test('六户四阶段共24条线路都按周历预约、真实地点与业务信号完成四节点并成功晋阶', async t => {
  for (const [线路, 文本] of Object.entries(全线路事件表)) {
    await t.test(线路, () => {
      const [门牌, 目标阶段字] = 线路.split('-');
      const 目标阶段 = Number(目标阶段字);
      const data = 建数据(门牌);
      设线路(data, 门牌, 目标阶段 - 1, 0, 0);

      for (const { 绝对时段, 事件: 原事件 } of 解析线路事件(文本)) {
        const 状态 = data.户[门牌].妻._阶段线路;
        const 节点定义 = 阶段审计矩阵.find(
          项 => 项.门牌 === 门牌 && 项.目标阶段 === 目标阶段 && 项.节点 === 状态.活跃节点,
        );
        assert.ok(节点定义, `${线路} 缺少第 ${状态.活跃节点 + 1} 节点定义`);
        const 事件 = { ...原事件 };
        if (事件.类型 === '地点') {
          assert.ok(状态.预约地点, `${线路} 第 ${状态.活跃节点 + 1} 节点没有地点预约`);
          assert.ok(状态.预约绝对时段 >= data.系统._绝对时段, `${线路} 的预约不能倒退时间`);
          data.系统._绝对时段 = 状态.预约绝对时段;
          事件.地点 = 状态.预约地点;
        } else {
          data.系统._绝对时段 = Math.max(data.系统._绝对时段, 绝对时段, 状态.节点起始楼 + (节点定义.至少等待时段 ?? 0));
        }
        const 消息 =
          事件.类型 === '时段经过'
            ? (() => {
                const 直接消息 = 上报时段推进(data, 事件.标识 ?? '');
                if (!data.系统._待发送事件.includes('【阶段线路演出:')) return 直接消息;
                const 演出消息 = 提交阶段线路演出事件(data, data.系统._待发送事件);
                data.系统._待发送事件 = '';
                return [...直接消息, ...演出消息];
              })()
            : 事件.类型 === '地点'
              ? 提交地点节点(data, 事件)
              : 上报阶段线路事件(data, 事件);
        assert.equal(消息.length, 1, `${线路} 未接住 ${JSON.stringify({ 绝对时段: data.系统._绝对时段, 事件 })}`);
      }

      if (线路 === '302-3') {
        data.系统._绝对时段 = 6;
        data.系统._母亲首夜第二幕 = true;
        assert.equal(提交母亲两幕事件(data, '【事件在场妻:302】【早饭桌】两幕均已提交').length, 1);
      }

      assert.equal(data.户[门牌].妻._阶段线路.活跃节点, 4);
      assert.equal(data.户[门牌].妻._阶段线路.完成位图, 15);

      const 完成线路 = data.户[门牌].妻._阶段线路;
      data.户[门牌].妻.堕落值 = 晋阶门槛[目标阶段];
      聊天变量 = { _场景: { 房间id: '错误地点' } };
      const 错场晋阶 = 请求晋阶(data, 门牌);
      assert.equal(错场晋阶.成功, false, `${线路} 不应允许从错误地点隔空晋阶`);
      assert.equal(data.户[门牌].妻.当前阶段, 目标阶段 - 1);
      聊天变量 = {
        _场景: { 房间id: 门牌 === '302' && 目标阶段 === 3 ? '302' : 完成线路.预约地点 },
      };
      const 晋阶 = 请求晋阶(data, 门牌);
      assert.equal(晋阶.成功, true, `${线路} 四节点完成后仍无法晋阶：${晋阶.消息}`);
      assert.equal(data.户[门牌].妻.当前阶段, 目标阶段);
    });
  }
});

