function 解析线路事件(文本) {
  return 文本.split(';').map(一项 => {
    const [类型, 绝对时段, 标识, 地点, 门牌] = 一项.split('~');
    return {
      绝对时段: Number(绝对时段),
      事件: {
        类型,
        ...(标识 ? { 标识 } : {}),
        ...(地点 ? { 地点 } : {}),
        ...(门牌 ? { 门牌 } : {}),
      },
    };
  });
}

