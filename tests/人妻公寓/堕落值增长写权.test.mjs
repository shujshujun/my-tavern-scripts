test('首稿作废按最终被采纳的稽查补权:首稿超限的补权不沿用', () => {
  const data = 建数据(['101', '102']);
  const 范围 = 构造AI可写变量范围(data, ['101', '102'], ['101', '102'], [], { 只读: false, 亲密场景: false });
  const 阶段表 = { '101': 1, '102': 1 };

  // 首稿:102 实际 3 超阶段上限 1 → 需重写
  const 首稿正文 = '正戏词。\n<尺度判定 模式="详">\n{"101":{"实际":1},"102":{"实际":3}}\n</尺度判定>';
  const 首稿稽查 = 输出稽查(首稿正文, ['101', '102'], 阶段表, '详');
  assert.equal(首稿稽查.状态, '需重写', '首稿超限触发重写');

  // 重写稿:102 降到实际 0,101 保持实际 1 → 通过
  const 重写正文 = '重写后的正文。\n<尺度判定 模式="详">\n{"101":{"实际":1},"102":{"实际":0}}\n</尺度判定>';
  const 重写稽查 = 输出稽查(重写正文, ['101', '102'], 阶段表, '详');
  assert.equal(重写稽查.状态, '通过', '重写稿通过');

  // 最终被采纳的是重写稽查 → 只补 101,不沿用首稿里 102 的实际 3
  const 逐角色实际 = Object.fromEntries(
    Object.entries(重写稽查.角色).map(([门牌号, 项]) => [门牌号, 项?.实际 ?? 0]),
  );
  const 扩展后 = 扩展精确亲密妻(范围, 逐角色实际);
  assert.deepEqual(扩展后.亲密妻, ['101'], '按最终稿补权,首稿权限不沿用');

  const ai = structuredClone(data);
  ai.户['101'].妻.堕落值 = 21;
  ai.户['102'].妻.堕落值 = 21;
  守护(data, ai, 扩展后, 8);
  assert.equal(ai.户['101'].妻.堕落值, 21, '最终稿参与者 +1 落地');
  assert.equal(ai.户['102'].妻.堕落值, 20, '首稿作废后 102 的 +1 不落地');
});

