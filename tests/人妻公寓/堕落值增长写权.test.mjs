/** 建一栋含若干户的存档；默认阶段 3、堕落 20（远低于阶段线路封顶 64）。 */
function 建数据(户, 阶段 = 3, 堕落 = 20) {
  const data = Schema.parse({ 户: Object.fromEntries(户.map(m => [m, 创建户节点(0)])) });
  for (const m of 户) {
    data.户[m].妻.当前阶段 = 阶段;
    data.户[m].妻.堕落值 = 堕落;
  }
  return data;
}

