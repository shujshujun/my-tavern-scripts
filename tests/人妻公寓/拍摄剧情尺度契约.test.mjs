test('首稿、二稿、资源结算与原生提交均接入同一契约源，不维护平行路线名单', () => {
  const 引擎 = readFileSync(new URL('../../src/人妻公寓/脚本/游戏逻辑/回合引擎.ts', import.meta.url), 'utf8');
  const 原生 = readFileSync(new URL('../../src/人妻公寓/脚本/游戏逻辑/index.ts', import.meta.url), 'utf8');
  const 快照 = readFileSync(new URL('../../src/人妻公寓/脚本/游戏逻辑/snapshotSystem.ts', import.meta.url), 'utf8');
  const 不再留门 = readFileSync(new URL('../../src/人妻公寓/脚本/游戏逻辑/不再留门系统.ts', import.meta.url), 'utf8');

  assert.match(引擎, /const 拍摄尺度契约 = 读取拍摄剧情尺度契约\(本楼事件\)/);
  assert.ok((引擎.match(/输出稽查\([\s\S]*?拍摄尺度契约[\s\S]*?\)/gu) ?? []).length >= 2);
  assert.doesNotMatch(引擎, /拍摄剧情尺度提示|拍摄尺度契约】|媒介契约】/u);
  assert.match(原生, /const 原生拍摄尺度契约 = .*读取拍摄剧情尺度契约\(本楼事件\)/);
  assert.match(原生, /应用拍摄剧情尺度契约\(原生原始尺度, 本轮有效正文, 原生拍摄尺度契约\)/);
  assert.match(原生, /const 尺度 = 原生尺度/);
  assert.doesNotMatch(原生, /拍摄剧情尺度提示|拍摄尺度契约】|媒介契约】/u);
  assert.doesNotMatch(快照, /拍摄剧情尺度提示|拍摄尺度契约】|媒介契约】|把本回合新发生的身体行为作为拍摄玩法/u);
  assert.match(快照, /4级无保护阴道内射\/肛交\/进阶玩法\/大胆场所\/拍摄，5级最深禁忌/u);
  assert.match(不再留门, /\\n本轮仅演这一拍。AI不改变状态/u);
  assert.equal((不再留门.match(/新增演出保持非露骨/gu) ?? []).length, 1, '旧句只保留在精确迁移匹配表');
  assert.match(不再留门, /清理不再留门旧尺度边界提示/u);
});
