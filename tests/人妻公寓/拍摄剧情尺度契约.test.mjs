test('不再留门、换掉和录像带V4共用设备语境维度，但保留各自结算边界', () => {
  const 用例们 = [
    { 事件: A7_1, 门牌: '202', 正文: '她检查待机画面、镜头和录制指示灯，设备仍在待机。', 模式: '简', 期望: 0 },
    { 事件: A9_1, 门牌: '202', 正文: '她停止录制，确认录像已转存，再把设备收好。', 模式: '简', 期望: 0 },
    { 事件: P1, 门牌: '301', 正文: '江辰举稳拍立得按下快门，第一张相纸从相机里吐出。', 模式: '详', 期望: 0 },
    { 事件: V4, 门牌: '102', 正文: '管理员室屏幕正在播放既有母带，三人只在观看。', 模式: '详', 期望: 0 },
  ];
  for (const 用例 of 用例们) {
    const 契约 = 读取拍摄剧情尺度契约(用例.事件);
    assert.ok(契约, 用例.事件);
    const 原文 = 带尺度(用例.门牌, 用例.正文, 4, 4, 用例.模式);
    const 原判定 = 解析尺度判定(原文);
    const 修正 = 应用拍摄剧情尺度契约(原判定, 用例.正文, 契约);
    assert.equal(修正?.角色[用例.门牌]?.实际, 用例.期望, 用例.事件);
    const 终审 = 输出稽查(原文, [用例.门牌], { [用例.门牌]: 5 }, 用例.模式, 契约.独立结算, 用例.正文, 契约);
    assert.equal(终审.状态, '通过', 用例.事件);
    assert.equal(终审.角色[用例.门牌]?.实际, 用例.期望, 用例.事件);
  }
  assert.equal(读取拍摄剧情尺度契约(V4)?.独立结算, true);
  const V4契约 = 读取拍摄剧情尺度契约(V4);
  assert.equal(推导拍摄契约行为尺度('屏幕关闭后，玩家在302与突然出现的人发生性关系。', V4契约).实际, 3);
});

