function 建数据({ 精力 = 5, 体力 = 4 } = {}) {
  const data = Schema.parse({ 户: { 101: 创建户节点(0) } });
  data.玩家资源.精力.当前值 = 精力;
  data.玩家资源.体力.当前值 = 体力;
  return data;
}

function 结算(data, 旧data, 覆盖 = {}) {
  return 结算成功现场楼(data, 旧data, {
    楼层: 10,
    行动: '和她聊聊',
    正文: '她坐下来回应。',
    本楼事件: '',
    妻在场: ['101'],
    实际尺度: { 101: 1 },
    资源计费: true,
    ...覆盖,
  });
}

