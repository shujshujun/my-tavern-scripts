function 建妻(覆盖 = {}) {
  const 基础 = {
    好感值: 10,
    堕落值: 30,
    当前阶段: 2,
    身体开发: { 小嘴: 0, 胸部: 0, 小屄: 0, 屁穴: 0 },
    _阶段线路: { 目标阶段: 3, 完成位图: 0, 活跃节点: 0 },
    _成长账: 创建成长账(0),
    _冷落余波: 创建余波账(),
  };
  return {
    ...基础,
    ...覆盖,
    身体开发: { ...基础.身体开发, ...(覆盖.身体开发 ?? {}) },
    _阶段线路: { ...基础._阶段线路, ...(覆盖._阶段线路 ?? {}) },
    _成长账: { ...基础._成长账, ...(覆盖._成长账 ?? {}) },
    _冷落余波: { ...基础._冷落余波, ...(覆盖._冷落余波 ?? {}) },
  };
}

function 建数据(户, 母亲入列 = false, 绝对时段 = 0) {
  return {
    户: Object.fromEntries(Object.entries(户).map(([门牌, 妻]) => [门牌, { 妻 }])),
    系统: { _母亲入列: 母亲入列, _绝对时段: 绝对时段 },
  };
}

