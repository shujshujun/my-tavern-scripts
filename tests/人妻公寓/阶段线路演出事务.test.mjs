test('24 条确认的剧情触发路径都只准备强演出票，正文提交后才推进一次', async t => {
  for (const [门牌, 目标阶段, 节点, 事件] of 应演出路径) {
    await t.test(`${门牌}-${目标阶段}-${节点}-${事件.类型}-${事件.标识 ?? ''}`, () => {
      const data = 建数据(门牌);
      设线路(data, 门牌, 目标阶段, 节点);
      const 位图前 = data.户[门牌].妻._阶段线路.完成位图;

      const 准备 = 准备阶段线路演出事件(data, 事件, { 近期正文: '上一楼已发生的正文。' });

      assert.equal(准备.成功, true);
      assert.match(准备.事件, new RegExp(`阶段线路演出:${门牌}:${目标阶段}:${节点}:`));
      assert.match(准备.事件, /本节点完成目标/);
      assert.match(准备.事件, /上一楼已发生的正文/);
      assert.equal(事件必须有正文(准备.事件), true, '阶段演出票必须由有效正文闸保护');
      assert.equal(data.户[门牌].妻._阶段线路.活跃节点, 节点, '准备阶段不得推进');
      assert.equal(data.户[门牌].妻._阶段线路.完成位图, 位图前, '准备阶段不得改位图');

      const 消息 = 提交阶段线路演出事件(data, 准备.事件);
      assert.equal(消息.length, 1);
      assert.equal(data.户[门牌].妻._阶段线路.活跃节点, 节点 + 1);
      assert.deepEqual(提交阶段线路演出事件(data, 准备.事件), [], '同票不得重复推进');
      assert.equal(data.户[门牌].妻._阶段线路.活跃节点, 节点 + 1);
    });
  }
});

