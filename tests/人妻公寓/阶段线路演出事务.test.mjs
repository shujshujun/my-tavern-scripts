test('地点剧情陈旧票失败时不得顺带补记其他角色', () => {
  const data = 建数据('101', '201');
  设线路(data, '101', 2, 2);
  const 地点时段 = data.户['101'].妻._阶段线路.预约绝对时段;
  设线路(data, '201', 5, 1, 地点时段);
  data.系统._已完成特殊场景.push('肉偿账本');

  const 到达 = { 类型: '地点', 门牌: '101', 地点: '大堂' };
  const 准备 = 构造阶段线路剧情事件(data, 到达);
  assert.equal(准备.成功, true);
  data.户['101'].妻._阶段线路.活跃节点 = 3;
  data.户['101'].妻._阶段线路.完成位图 = 7;

  assert.deepEqual(提交阶段线路剧情(data, 准备.事件, '大堂'), []);
  assert.equal(data.户['101'].妻._阶段线路.活跃节点, 3);
  assert.equal(data.户['201'].妻._阶段线路.活跃节点, 1, '失败地点票不得触发全局特殊场景补账副作用');
});

