test('多角色时段演出票先全量预检，任一票陈旧时所有角色都不推进', () => {
  const data = 建数据('102', '202');
  设线路(data, '102', 4, 2);
  设线路(data, '202', 4, 1);
  const 准备 = 准备阶段线路演出事件(data, { 类型: '时段经过', 标识: '歇一会儿' });
  assert.equal(准备.成功, true);
  assert.equal((准备.事件.match(/【阶段线路演出:/g) ?? []).length, 2);

  data.户['202'].妻._阶段线路.活跃节点 = 2;
  data.户['202'].妻._阶段线路.完成位图 = 3;
  assert.deepEqual(提交阶段线路演出事件(data, 准备.事件), []);
  assert.equal(data.户['102'].妻._阶段线路.活跃节点, 2, '另一张有效票也不得半提交');
  assert.equal(data.户['202'].妻._阶段线路.活跃节点, 2);
});

test('特殊时段节点排强事件，纯时间门槛仍直接推进', () => {
  const 剧情 = 建数据('102');
  设线路(剧情, '102', 4, 2);
  assert.deepEqual(上报时段推进(剧情, '歇一会儿'), []);
  assert.equal(剧情.户['102'].妻._阶段线路.活跃节点, 2);
  assert.match(剧情.系统._待发送事件, /阶段线路演出:102:4:2:/);
  assert.equal(提交阶段线路演出事件(剧情, 剧情.系统._待发送事件).length, 1);

  const 门槛 = 建数据('101');
  设线路(门槛, '101', 2, 1);
  assert.equal(上报时段推进(门槛, '歇一会儿').length, 1);
  assert.equal(门槛.户['101'].妻._阶段线路.活跃节点, 2);
  assert.equal(门槛.系统._待发送事件, '');
});

