function 建数据(...门牌们) {
  return Schema.parse({
    户: Object.fromEntries(门牌们.map(门牌 => [门牌, 创建户节点(0)])),
  });
}

function 设线路(data, 门牌, 目标阶段, 活跃节点, 绝对时段 = 20) {
  data.系统._绝对时段 = 绝对时段;
  const 妻 = data.户[门牌].妻;
  妻.当前阶段 = 目标阶段 - 1;
  妻._阶段线路 = {
    目标阶段,
    完成位图: (1 << 活跃节点) - 1,
    活跃节点,
    节点起始楼: 0,
    预约星期: '',
    预约时段: '',
    预约地点: '',
    预约绝对时段: -1,
    预约丈夫状态: '',
  };
  刷新阶段预约(data, 门牌);
}

