import type { SchemaType } from '../../schema';
import type { 时段名, 夫状态名, 门牌 } from '../../stageConfig';
import { 户静态表 } from '../../stageConfig';

/**
 * 伪时间:楼层=唯一时钟(2026-07-16 拍板)
 *
 * AI RP 里的日期时间是 AI 维护的必错变量——本作 AI 全程不碰日期,只把"第二天一早"演出来;
 * 账全在脚本手里:底层消息楼层照常累积 = 唯一可靠的单调计数器。
 *
 * 时段双层方案:
 *   AI 管"几月几号几点几分"(沉浸字符串,脚本永不回读,错了不影响任何机制);
 *   脚本管"几点档"(早/午/晚/深夜,按楼层推进,纯函数无游标——重roll/回档天然自洽),
 *   每轮注入快照「当前时段」,AI 写钟点须落在该档内;
 *   丈夫作息表/角色位置全挂时段、不挂 AI 的钟——永不自相矛盾。
 */

export const 时段列表: readonly 时段名[] = ['早上', '中午', '下午', '傍晚', '晚上', '深夜'];

/** 〔调参〕每个时段占几楼(6 档一轮=一天;3 楼/档 → 一天 18 楼,一个时段够演一场有来回的戏) */
export const 每时段楼数 = 3;

/** 纯函数:楼层 → 时段(无游标可漂移,防护11同理——同楼重roll结果不变) */
export function 当前时段(楼层: number): 时段名 {
  const 档 = Math.floor(Math.max(0, 楼层) / 每时段楼数) % 时段列表.length;
  return 时段列表[档];
}

/** 楼层 → 第几天(开局=第1天;快递"次日达"等机制换算用) */
export function 当前天数(楼层: number): number {
  return Math.floor(Math.max(0, 楼层) / (每时段楼数 * 时段列表.length)) + 1;
}

// ============================================
// 杀时间(2026-07-17 拍板:管理员室专属"歇一会儿",静默快进一个时段,不产楼不耗token)
// ============================================

/**
 * 快进一个时段:偏移写进 MVU `_时段偏移楼`——所有时间读数(时段/天数/作息/位置/垃圾周期/
 * 偷窥冷却)统一按"真实楼层+偏移"算,账面永不分裂;偏移随楼层快照走,回档/同楼重roll自洽。
 * 冷却:每真实楼层一次(连跳要先推进一楼)——一天 18 楼最快压到 5 楼上下,刷不动收租日,
 * 且快进天数同时在烧上交 deadline,自带平衡。
 * +3 楼恰好=一个整档:floor((x+3)/3)=floor(x/3)+1,任何落位都精准跳到下一时段。
 */
export function 杀时间(
  data: SchemaType,
  方式: string,
  真实楼层: number,
): { 提示: string; 事件?: string; 变动?: boolean } {
  if (data.系统._上次杀时间楼层 >= 真实楼层) {
    return { 提示: '刚消磨过一阵了——先去干点别的,回头再歇。' };
  }
  const 旧钟 = 真实楼层 + data.系统._时段偏移楼;
  data.系统._时段偏移楼 += 每时段楼数;
  data.系统._上次杀时间楼层 = 真实楼层;
  const 新钟 = 真实楼层 + data.系统._时段偏移楼;
  const 新段 = 当前时段(新钟);
  const 跨天 = 当前天数(新钟) > 当前天数(旧钟);
  const 行为 = 方式 === '看电视' ? '守着值班桌上那台小电视消磨了一阵子' : '在管理员室眯了一觉';
  return {
    提示: 跨天 ? `一觉到天亮——第 ${当前天数(新钟)} 天,${新段}。` : `时间悄悄溜走——已是${新段}。`,
    事件:
      `【时间流逝】刚才{{user}}${行为},${跨天 ? '一睁眼天已经亮了,新的一天' : `回过神已是${新段}`}。` +
      '上一场戏已经散了,请按当前时段的公寓光景自然开启本轮,不要把消磨时间之前的场面原样续下去',
    变动: true,
  };
}

// ============================================
// 楼层种子随机(防护11:金币/偷窃/碎片刷新/位置推算全用它,同楼重roll结果不变,天然防刷)
// ============================================

/** 确定性种子随机:同一组种子永远同一结果(mulberry32 变体) */
export function seededRandom(...seeds: (number | string)[]): number {
  let h = 1779033703 ^ seeds.length;
  for (const s of seeds) {
    const str = String(s);
    for (let i = 0; i < str.length; i++) {
      h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
      h = (h << 13) | (h >>> 19);
    }
  }
  h = Math.imul(h ^ (h >>> 16), 2246822507);
  h = Math.imul(h ^ (h >>> 13), 3266489909);
  return ((h ^= h >>> 16) >>> 0) / 4294967296;
}

// ============================================
// 丈夫位置推算(修道院"位置推算=纯函数种子轮换"直迁,进入种子换成"丈夫在家/不在家")
// ============================================

/**
 * 丈夫本楼状态:作息表按时段查基础档,楼层种子叠小概率扰动(早高峰晚走/临时外出)。
 * 纯函数——快照注入与结算读同一真值,永不自相矛盾;AI 只负责把它演出来。
 * 〔P5〕每户人设差分作息(202"晚间加班(?)"彩蛋)在 stageConfig 覆盖。
 */
export function 丈夫状态推算(门牌号: 门牌, 楼层: number): 夫状态名 {
  const 配 = 户静态表[门牌号];
  const 基础 = 配.夫作息[当前时段(楼层)];
  // 〔调参〕15% 扰动:在家↔外出对调(睡眠不扰动;302父亲长期不在场不扰动)
  if (门牌号 !== '302' && 基础 !== '睡眠' && seededRandom(楼层, 门牌号, '作息扰动') < 0.15) {
    return 基础 === '在家' ? '外出' : '在家';
  }
  return 基础;
}

/**
 * 妻位置推算:她此刻在哪(自己家门牌 or 公共区 or 外出)。
 * 纯函数楼层种子——玩家在房内期间用"进房末楼"冻结种子(修道院范式:
 * 否则楼号推进会把身边的人"传送"走,AI 只能圆成"她起身要走")。
 * 〔调参〕权重;〔P5〕每户人设差分(夏乔爱串门/沈静仪不出门)。
 */
export function 妻位置推算(门牌号: 门牌, 楼层: number): string {
  const 段 = 当前时段(楼层);
  const r = seededRandom(楼层, 门牌号, '妻位置');
  switch (段) {
    case '深夜':
      return 门牌号; // 深夜都在家
    case '早上': // 晾衣/扔垃圾的时段
      if (r < 0.65) return 门牌号;
      if (r < 0.8) return '天台';
      if (r < 0.9) return '垃圾房';
      return '大堂';
    case '中午': // 买菜/办事
      if (r < 0.55) return 门牌号;
      if (r < 0.75) return '外出';
      if (r < 0.9) return '大堂';
      return '天台';
    case '下午': // 一天里最容易不在家的时段
      if (r < 0.5) return 门牌号;
      if (r < 0.7) return '外出';
      if (r < 0.85) return '大堂';
      return '楼梯间';
    case '傍晚': // 做饭的黄金时段(丈夫还没到家)
      if (r < 0.75) return 门牌号;
      if (r < 0.9) return '垃圾房';
      return '楼梯间';
    case '晚上':
    default:
      if (r < 0.85) return 门牌号;
      if (r < 0.95) return '楼梯间';
      return '天台'; // 乘凉
  }
}
