export function 许曼君分居事件CG语义(data: unknown): string | null {
  const raw = 解包许曼君分居存档(data);
  const state = raw?.系统?._许曼君分居 ?? {};
  switch (state.当前场景) {
    case '第一幕初谈': return Number(state.当前拍) >= 2 ? '分居_A1_署名会面通知' : '分居_A1_工资卡入封套';
    case '第二幕摊牌': return Number(state.当前拍) >= 1 ? '分居_A3_工资卡归还' : '分居_A3_201三人同桌';
    case '第三幕独住后': return '201_分居_独住';
    case '共同夜晚开场': return '201_留宿_夜';
    case '第四幕取物提案': return '分居_A5_取物与修复';
    case '第四幕管理员室交接': return '分居_A6_钥匙柜前最终会面';
    default: return null;
  }
}

