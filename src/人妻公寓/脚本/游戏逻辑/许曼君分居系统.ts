function 硬互斥错误(data: SchemaType, 当前地点: string | null = null): string {
  if (!户(data)) return '201现在没有可承接《分居》的住户。';
  if (data.系统._坏结局) return '这一局已经结束，不能再开始或推进《分居》。';
  if (处于医院硬锁(data, '201')) return '许曼君正在医院待产或恢复，《分居》暂时冻结。';
  if (data.系统._性爱场景.状态 !== '空闲') return '先把当前亲密场景正常收束。';
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0) return '当前特殊现场尚未结束。';
  if (有普通场景剧情阻塞当前场景(data, 当前地点)) return '还有一段当前地点的场景剧情没有处理完。';
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态) return '先完成并挂断父亲电话。';
  if (丈夫登门需要处理(data, '201')) return '先完成已经排期的201丈夫登门事件，再继续《分居》。';
  return '';
}

