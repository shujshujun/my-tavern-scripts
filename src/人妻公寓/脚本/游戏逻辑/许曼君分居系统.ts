export function 读取201留宿可用状态(
  data: SchemaType,
  地点: string,
  预期绝对时段 = data.系统._绝对时段,
): 许曼君201留宿状态 {
  const 当前路线 = 路线(data);
  const 失败 = (原因: string): 许曼君201留宿状态 => ({ 已解锁: 当前路线.留宿201权限, 可执行: false, 原因 });
  if (data.系统._坏结局) return 失败('这一局已经结束，不能再在201留宿。');
  if (!当前路线.留宿201权限) return { 已解锁: false, 可执行: false, 原因: '先正常完成许曼君明确允许的第一次共同夜晚。' };
  if (当前路线.玩家最终关系选择 === '退出关系') return 失败('玩家已经退出这段关系，未来201留宿许可已撤销。');
  if (地点 !== '201') return 失败('必须实际在201才能留宿。');
  if (预期绝对时段 !== data.系统._绝对时段) return 失败('世界时间已经变化，请重新确认。');
  if (!是晚上(data)) return 失败('201留宿只在晚上或深夜开放。');
  if (处于医院硬锁(data, '201')) return 失败('许曼君正在医院待产或恢复。');
  if (!妻在201(data)) return 失败('许曼君此刻不在201。');
  if (!['临时外住', '待离婚交接', '正式退居'].includes(当前路线.钥匙用途)) return 失败('赵国强的201住户钥匙仍未进入外住或交接状态。');
  if (丈夫当前在201(data)) return 失败('赵国强此刻正在201。');
  if (睡醒前预约冲突(data)) return 失败('赵国强的预约会在睡醒前到期，今晚不能留宿。');
  if (data.系统._性爱场景.状态 !== '空闲') return 失败('先结束当前亲密场景。');
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0 || data.系统._场景剧情事务.id)
    return 失败('当前强制剧情尚未结束。');
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态) return 失败('先挂断父亲电话。');
  if (丈夫登门需要处理(data, '201')) return 失败('201还有一场已经排期的丈夫登门事件。');
  if (有普通场景剧情阻塞当前场景(data, 地点)) return 失败('201还有尚未演出的强制剧情。');
  if (data.系统._母亲首夜第二幕) return 失败('母亲首夜的次晨早餐必须从管理员室或302继续。');
  if (有其他丈夫待登门(data)) return 失败('今晚另有一位丈夫已经排期登门，先回管理员室或302处理。');
  return { 已解锁: true, 可执行: true, 原因: '' };
}

