/** 两个玩家答复点共用话语边界；不改变剧情正文的归一化或其他路线的决定规则。 */
function 分居玩家决定分句(value: unknown): string[] {
  const 原文 = String(value ?? '').normalize('NFKC').replace(/[^\S\n]+/gu, '').toLowerCase();
  const 文 = 原文.replace(/“[^”]*”|‘[^’]*’|「[^」]*」|『[^』]*』|"[^"]*"|'[^']*'|`[^`]*`/gu, (引用: string, 位置: number) => {
    const 前文 = 原文.slice(0, 位置).split(/[。！？!?；;\n，,]/u).at(-1) ?? '';
    const 后文 = 原文.slice(位置 + 引用.length).split(/[。！？!?；;\n，,]/u)[0];
    const 非本次答复 = /(?:昨天|以前|之前|刚才|过去|当时|曾经)|假设|举例|引用|收回|撤回|(?:没|没有|并未|不是|并非|不会).*(?:说|答应|决定)/u.test(前文);
    const 他人话语 = /^(?:但|而|可是|不过)?(?:她|他|你|许曼君|赵国强)(?:说|问|希望|要求|曾说|刚才说)/u.test(前文);
    const 引文说明 = /^(?:这句话|这句|只是|是|只是个).*(?:假设|举例|例子|原话|不是.*决定|不是.*答复)/u.test(后文);
    return 非本次答复 || 他人话语 || 引文说明 ? '' : 引用.slice(1, -1);
  });
  return (文.match(/[^。！？!?；;\n]+[。！？!?；;]?/gu) ?? []).flatMap(句 => {
    // 条件的作用域可跨逗号；问号仅约束自己的分句，不吞掉前一句明确决定。
    if (/如果|要是|假如|倘若|万一|除非|也许|或许|可能|或者|或是|要么/u.test(句)) return [];
    return 句.split(/[,，]|(?=但是|不过|而是|但现在)/u).filter(分句 =>
      !/[?？]|吗|么|是否|能不能|要不要|会不会|是不是/u.test(分句) &&
      !/(?:只是|是个|作为).*(?:假设|举例|例子)|不是.*(?:决定|答复)/u.test(分句),
    );
  });
}

function 读取分居玩家决定<T extends string>(value: unknown, 规则: readonly (readonly [T, RegExp])[]): T | '未决定' {
  const 决定 = new Set<T>();
  for (const 原分句 of 分居玩家决定分句(value)) {
    const 分句 = 原分句.replace(/^(?:但是|不过|可是|然而|而是|而且|但)/u, '');
    for (const [选择, 模式] of 规则) {
      for (const 匹配 of 分句.matchAll(new RegExp(模式.source, 'gu'))) {
        const 前文 = 分句.slice(0, 匹配.index);
        // 检查完整谓语之前的否定/转述，不把“不会退出”里的退出子串当新决定。
        if (/不是|并非|没有|并未|没|不|别|不能|考虑|想过|希望|要求|(?:你|她|他).*问/u.test(前文)) continue;
        if (/(?:昨天|以前|之前|刚才|过去|当时|曾经).*(?:说|想|决定|答应|选择|承诺)/u.test(前文)) continue;
        if (/^(?:她|他|你|许曼君|赵国强).*(?:说|问|认为|觉得|表示|声称|坚称|建议)/u.test(前文)) continue;
        决定.add(选择);
      }
    }
  }
  // 矛盾的并列答复不按关键词优先级替玩家裁决，复用已有重答检查点。
  return 决定.size === 1 ? [...决定][0] : '未决定';
}

