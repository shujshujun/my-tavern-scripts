function 取配置(门牌号: 门牌, 目标阶段: number): 线路配置 | null {
  if (目标阶段 < 2 || 目标阶段 > 5) return null;
  return 专属线路[门牌号]?.[目标阶段] ?? null;
}

function 预约键(门牌号: 门牌, 目标阶段: number, 节点号: number): string {
  return `${门牌号}:${目标阶段}:${节点号}`;
}

function 取节点预约(门牌号: 门牌, 目标阶段: number, 节点号: number): 阶段周历预约 | null {
  return 阶段周历预约表[预约键(门牌号, 目标阶段, 节点号)] ?? null;
}

function 下次周历预约绝对时段(起点: number, 预约: 阶段周历预约): number {
  const 星期序号 = 星期列表.indexOf(预约.星期);
  const 时段序号 = 六时段列表.indexOf(预约.时段);
  if (星期序号 < 0 || 时段序号 < 0) return -1;
  const 周内偏移 = 星期序号 * 六时段列表.length + 时段序号;
  const 本周起点 = Math.floor(Math.max(0, 起点) / 每周时段数) * 每周时段数;
  const 本周候选 = 本周起点 + 周内偏移;
  return 本周候选 >= 起点 ? 本周候选 : 本周候选 + 每周时段数;
}

function 清除阶段预约(妻: 户节点Type['妻']): void {
  妻._阶段线路.预约星期 = '';
  妻._阶段线路.预约时段 = '';
  妻._阶段线路.预约地点 = '';
  妻._阶段线路.预约绝对时段 = -1;
  妻._阶段线路.预约丈夫状态 = '';
}

function 投影当前节点预约(妻: 户节点Type['妻'], 门牌号: 门牌, 绝对时段: number): void {
  const 状态 = 妻._阶段线路;
  // 四节点完成后保留最后一场的预约，直到晋阶正戏成功；这样最终按钮不会脱离现场。
  if (状态.活跃节点 >= 4) return;
  const 配置 = 取配置(门牌号, 状态.目标阶段);
  const 当前节点 = 配置?.节点[状态.活跃节点];
  const 预约 = 取节点预约(门牌号, 状态.目标阶段, 状态.活跃节点);
  if (!当前节点?.事件类型.includes('地点') || !预约) {
    清除阶段预约(妻);
    return;
  }
  const 最早时段 = Math.max(绝对时段, 状态.节点起始楼 + (当前节点.至少等待时段 ?? 0));
  妻._阶段线路.预约星期 = 预约.星期;
  妻._阶段线路.预约时段 = 预约.时段;
  妻._阶段线路.预约地点 = 预约.地点;
  妻._阶段线路.预约绝对时段 = 下次周历预约绝对时段(最早时段, 预约);
  妻._阶段线路.预约丈夫状态 = 预约.丈夫状态;
}

/** 节点切换、晋阶或测试装配后的唯一预约投影入口。 */
export function 刷新阶段预约(data: SchemaType, 门牌号: 门牌): void {
  const 妻 = data.户[门牌号]?.妻;
  if (!妻) return;
  const 目标阶段 = Math.min(5, 妻.当前阶段 + 1);
  if (妻._阶段线路.目标阶段 !== 目标阶段) 同步阶段线路(妻, 取绝对时段(data), 门牌号);
  else 投影当前节点预约(妻, 门牌号, 取绝对时段(data));
}

