/** `节点起始楼` 是旧字段名；新局中只存 0-based 绝对时段。 */
export function 同步阶段线路(妻: 户节点Type['妻'], 绝对时段: number, 门牌号?: 门牌): void {
  const 目标阶段 = Math.min(5, 妻.当前阶段 + 1);
  if (妻.当前阶段 >= 5) {
    清除阶段预约(妻);
    return;
  }
  if (妻._阶段线路.目标阶段 === 目标阶段) return;
  妻._阶段线路 = {
    目标阶段,
    完成位图: 0,
    活跃节点: 0,
    节点起始楼: 绝对时段,
    预约星期: '',
    预约时段: '',
    预约地点: '',
    预约绝对时段: -1,
    预约丈夫状态: '',
  };
  if (门牌号) 投影当前节点预约(妻, 门牌号, 绝对时段);
}

