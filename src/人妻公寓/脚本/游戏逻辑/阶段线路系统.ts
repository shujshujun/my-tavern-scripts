function 取配置(门牌号: 门牌, 目标阶段: number): 线路配置 | null {
  if (目标阶段 < 2 || 目标阶段 > 5) return null;
  return 专属线路[门牌号]?.[目标阶段] ?? null;
}

export function 同步阶段线路(妻: 户节点Type['妻'], 楼层: number): void {
  const 目标阶段 = Math.min(5, 妻.当前阶段 + 1);
  if (妻._阶段线路.目标阶段 === 目标阶段) return;
  妻._阶段线路 = { 目标阶段, 完成位图: 0, 活跃节点: 0, 节点起始楼: 楼层, 预约时段: '', 预约地点: '' };
}

export function 线路已完成(妻: 户节点Type['妻']): boolean {
  if (妻.当前阶段 === 0 || 妻.当前阶段 >= 5) return true;
  return 妻._阶段线路.目标阶段 === 妻.当前阶段 + 1 && (妻._阶段线路.完成位图 & 15) === 15;
}

export function 上报阶段线路事件(data: SchemaType, 事件: 线路事件): string[] {
  const 消息: string[] = [];
  for (const [门牌字符串, 户] of Object.entries(data.户)) {
    const 门牌号 = 门牌字符串 as 门牌;
    if (!是本户(事件, 门牌号) || 户.妻.当前阶段 < 1 || 户.妻.当前阶段 >= 5) continue;
    同步阶段线路(户.妻, 事件.楼层);
    const 状态 = 户.妻._阶段线路;
    const 配置 = 取配置(门牌号, 状态.目标阶段);
    if (!配置 || 状态.活跃节点 >= 4) continue;
    const 当前 = 配置.节点[状态.活跃节点];
    const 已等待 = 状态.节点起始楼 < 0 || 事件.楼层 - 状态.节点起始楼 >= (当前.至少等待楼 ?? 0);
    if (!已等待 || !当前.匹配(事件)) continue;
    状态.完成位图 |= 1 << 状态.活跃节点;
    状态.活跃节点 += 1;
    状态.节点起始楼 = 事件.楼层;
    消息.push(`${阶段标题(户.妻.当前阶段, 门牌号)}关系线索有了新的变化（${状态.活跃节点}/4）`);
  }
  return 消息;
}

export function 应冻结堕落(妻: 户节点Type['妻']): number | null {
  if (妻.当前阶段 < 1 || 妻.当前阶段 >= 5 || 线路已完成(妻)) return null;
  return Math.max(0, (晋阶门槛[妻.当前阶段 + 1] ?? 100) - 1);
}

export interface 关系线索视图 {
  标题: string;
  侧写: string;
  进度: number;
  数值已冻结: boolean;
  线索: { 完成: boolean; 文案: string }[];
}

function 节点0侧写(data: SchemaType, 门牌号: 门牌, 配置: 线路配置): string {
  const 妻 = data.户[门牌号]?.妻;
  if (!妻) return 配置.侧写;
  const 身体尺度 = Math.max(...Object.values(妻.身体开发));
  const 已有特殊场景 = data.系统._已完成特殊场景.some(id => {
    if (id === '录像带') return false;
    const 场景 = 查特殊场景(id);
    if (!场景) return false;
    try {
      return 场景.参与(data as never).includes(门牌号);
    } catch {
      return false;
    }
  });
  if (已有特殊场景) return `已经发生过的事不会重演；现在要看的是，事后她会怎样选择。`;
  if (妻.当前阶段 >= 3 || 身体尺度 > 0) return `你们的距离早已不止试探；下一步不该退回身体上的“第一次”。`;
  if (妻.当前阶段 >= 2 && (妻.好感值 >= 35 || 妻.堕落值 >= 30)) {
    return `她并不陌生你的靠近；真正未回答的，是她愿意为这段关系改变什么。`;
  }
  if (妻.当前心理想法.trim()) return `她最近的心思已有变化，旧事只会留下余波，不会重新开始。`;
  return 配置.侧写;
}

export function 读取关系线索(data: SchemaType, 门牌号: 门牌): 关系线索视图 | null {
  const 妻 = data.户[门牌号]?.妻;
  if (!妻) return null;
  const 目标阶段 = 妻.当前阶段 + 1;
  const 配置 = 取配置(门牌号, 目标阶段);
  if (!配置) return null;
  const 状态 = 妻._阶段线路.目标阶段 === 目标阶段 ? 妻._阶段线路 : { 完成位图: 0, 活跃节点: 0 };
  const 进度 = Math.min(4, 状态.活跃节点);
  return {
    标题: `${阶段标题(妻.当前阶段, 门牌号)} → ${阶段标题(目标阶段, 门牌号)}`,
    侧写: 节点0侧写(data, 门牌号, 配置),
    进度,
    数值已冻结: 妻.堕落值 >= (晋阶门槛[目标阶段] ?? 999) - 1 && 进度 < 4,
    线索: 配置.节点.map((项, i) => ({ 完成: i < 进度, 文案: i < 进度 ? 项.完成事实 : 项.暗示 })),
  };
}
