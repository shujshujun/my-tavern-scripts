function 事件匹配文本(事件: 线路事件): string {
  const 道具 = 事件.标识 ? 查道具(事件.标识) : undefined;
  return `${事件.标识 ?? ''} ${事件.地点 ?? ''}${道具?.服饰 ? ' 服饰' : ''}`;
}

const 节点 = (
  暗示: string,
  完成事实: string,
  类型: 线路事件类型[],
  关键词?: RegExp,
  至少等待旧钟楼 = 0,
  允许时段?: readonly 时段名[],
): 节点配置 => ({
  暗示,
  完成事实,
  事件类型: 类型,
  至少等待时段: 旧钟楼跨度转时段(至少等待旧钟楼),
  允许时段,
  匹配: 事件 => 类型.includes(事件.类型) && (!关键词 || 关键词.test(事件匹配文本(事件))),
});

