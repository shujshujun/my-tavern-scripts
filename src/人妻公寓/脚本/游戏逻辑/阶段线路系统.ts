/**
 * 302 的 2→3 是唯一的两幕式线路节点，只接收回合引擎已经确认成功提交的冻结票据。
 * 第一幕只开启早餐；第二幕才完成节点4并解冻 39。普通地点/时段事件永远进不到这里。
 */
export function 提交母亲两幕事件(data: SchemaType, 已提交事件: string): string[] {
  if (!已提交事件.includes('【事件在场妻:302】')) return [];

  if (已提交事件.includes('【药物首夜】')) {
    if (是母亲首夜待第二幕线路(data)) {
      data.系统._母亲首夜第二幕 = true;
    }
    return [];
  }

  if (!已提交事件.includes('【早饭桌】') || !data.系统._母亲首夜第二幕) return [];

  // flag 是“首夜已提交、早餐未提交”的持久凭证，只能在早餐票据成功提交时清掉。
  data.系统._母亲首夜第二幕 = false;
  if (!是母亲首夜待第二幕线路(data)) return [];

  const 妻 = data.户['302']!.妻;
  妻._阶段线路.完成位图 |= 1 << 3;
  妻._阶段线路.活跃节点 = 4;
  妻._阶段线路.节点起始楼 = 取绝对时段(data);
  return [`${阶段标题(妻.当前阶段, '302')}关系线索有了新的变化（4/4）`];
}

function 当前节点可接收(data: SchemaType, 门牌号: 门牌, 事件: 内部线路事件): boolean {
  const 户 = data.户[门牌号];
  if (!户 || 户.妻.当前阶段 < 1 || 户.妻.当前阶段 >= 5) return false;

  const 目标阶段 = 户.妻.当前阶段 + 1;
  const 配置 = 取配置(门牌号, 目标阶段);
  if (!配置) return false;

  const 已同步 = 户.妻._阶段线路.目标阶段 === 目标阶段;
  const 活跃节点 = 已同步 ? 户.妻._阶段线路.活跃节点 : 0;
  if (活跃节点 >= 4) return false;
  if (事件.预期目标阶段 !== undefined && 事件.预期目标阶段 !== 目标阶段) return false;
  if (事件.预期节点 !== undefined && 事件.预期节点 !== 活跃节点) return false;
  if (事件.类型 === '时段经过' && 事件[时段推进授权] !== true) return false;

  const 当前 = 配置.节点[活跃节点];
  const 绝对时段 = 取绝对时段(data);
  const 节点起始时段 = 已同步 ? 户.妻._阶段线路.节点起始楼 : 绝对时段;
  const 已等待 = 节点起始时段 < 0 || 绝对时段 - 节点起始时段 >= (当前.至少等待时段 ?? 0);
  const 时段匹配 = !当前.允许时段 || 当前.允许时段.includes(当前时段(绝对时段));
  if (!已等待 || !时段匹配 || !当前.匹配(事件)) return false;

  if (事件.类型 === '地点') {
    if (!已同步) return false;
    const 状态 = 户.妻._阶段线路;
    const 标准地点 = (地点: string): string => {
      if (/大堂/.test(地点)) return '大堂';
      const 门牌匹配 = 地点.match(/(\d{3})/);
      return 门牌匹配?.[1] ?? 地点;
    };
    if (!状态.预约地点 || 标准地点(事件.地点 ?? '') !== 状态.预约地点) return false;
    if (妻位置推算(门牌号, 绝对时段, 户) !== 状态.预约地点) return false;
    if (状态.预约丈夫状态 && 丈夫在楼(户, 门牌号, 绝对时段) !== 状态.预约丈夫状态) return false;
  }
  return true;
}

/**
 * 列出当前事件在内容上能够推进的全部户。该函数不改变量，供界面在公共地点或全楼运作
 * 出现多个候选时展示明确的角色按钮。
 */
export function 列出阶段线路候选(data: SchemaType, 事件: 线路事件): 门牌[] {
  return 列出阶段线路候选详情(data, 事件).map(候选 => 候选.门牌);
}

export function 列出阶段线路候选详情(data: SchemaType, 事件: 线路事件): 阶段线路候选[] {
  const 门牌们 = 事件.门牌 ? [事件.门牌] : (Object.keys(data.户) as 门牌[]);
  return 门牌们.flatMap(门牌号 => {
    if (!当前节点可接收(data, 门牌号, 事件)) return [];
    const 妻 = data.户[门牌号]?.妻;
    if (!妻) return [];
    const 目标阶段 = 妻.当前阶段 + 1;
    const 节点 = 妻._阶段线路.目标阶段 === 目标阶段 ? 妻._阶段线路.活跃节点 : 0;
    return [{ 门牌: 门牌号, 目标阶段, 节点 }];
  });
}

/**
 * 决定一次上报最终归属哪些户：显式门牌只归本户；时间经过是合法广播；其他无门牌事件
 * 仅在候选唯一时自动归属。歧义时失败关闭，避免一次进大堂把多户关系线一起点亮。
 */
export function 找可推进门牌(data: SchemaType, 事件: 线路事件): 门牌[] {
  const 候选 = 列出阶段线路候选(data, 事件);
  if (事件.门牌 || 事件.类型 === '时段经过') return 候选;
  return 候选.length === 1 ? 候选 : [];
}

function 执行阶段线路事件(data: SchemaType, 事件: 内部线路事件): string[] {
  const 消息: string[] = [];
  const 绝对时段 = 取绝对时段(data);
  for (const 门牌号 of 找可推进门牌(data, 事件)) {
    const 户 = data.户[门牌号];
    if (!户) continue;
    同步阶段线路(户.妻, 绝对时段, 门牌号);
    const 状态 = 户.妻._阶段线路;
    const 配置 = 取配置(门牌号, 状态.目标阶段);
    if (!配置 || 状态.活跃节点 >= 4) continue;
    const 当前 = 配置.节点[状态.活跃节点];
    const 已等待 = 状态.节点起始楼 < 0 || 绝对时段 - 状态.节点起始楼 >= (当前.至少等待时段 ?? 0);
    const 时段匹配 = !当前.允许时段 || 当前.允许时段.includes(当前时段(绝对时段));
    if (!已等待 || !时段匹配 || !当前.匹配(事件)) continue;
    状态.完成位图 |= 1 << 状态.活跃节点;
    状态.活跃节点 += 1;
    状态.节点起始楼 = 绝对时段;
    if (事件.类型 !== '特殊场景' && 事件.类型 !== '性癖') 登记攻略风闻(data, 门牌号, '亲密');
    if (门牌号 === '302' && 状态.目标阶段 === 5 && 状态.活跃节点 === 1 && !data.背包.includes('哺育癖')) {
      data.背包.push('哺育癖');
    }
    投影当前节点预约(户.妻, 门牌号, 绝对时段);
    消息.push(`${阶段标题(户.妻.当前阶段, 门牌号)}关系线索有了新的变化（${状态.活跃节点}/4）`);
  }
  return 消息;
}

/** 普通业务事件入口；地点节点必须走“构造剧情→有效正文→提交票据”，到达本身永不登记。 */
export function 上报阶段线路事件(data: SchemaType, 事件: 线路事件): string[] {
  if (事件.类型 === '地点') return [];
  return 执行阶段线路事件(data, 事件);
}

/** 世界时间真正推进后的唯一线路入口；普通正文不得直接上报 `时段经过`。 */
export function 上报时段推进(data: SchemaType, 标识 = ''): string[] {
  return 执行阶段线路事件(data, { 类型: '时段经过', 标识, [时段推进授权]: true });
}

const 阶段线路剧情标记 = /【阶段线路剧情:(\d{3}):(\d+):(\d+):([^】]+)】/;

function 安全上下文(文本: string | undefined, 上限: number): string {
  if (!文本?.trim()) return '（无可用记录）';
  // 一次性事件以竖线分拍；外部记忆不得借字符碰撞拆出另一张事件票。
  return 文本
    .replace(/\|/g, '／')
    .replace(/【/g, '［')
    .replace(/】/g, '］')
    .split('\u0000')
    .join('')
    .trim()
    .slice(-上限);
}

