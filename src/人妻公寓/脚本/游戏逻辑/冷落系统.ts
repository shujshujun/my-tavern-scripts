function 转义正则(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * 无地图逃生路径不能把“想起她/谈她的事”当成当面见到她。地图物理在场直接成立；
 * 无地图时只接受明确称呼、走近、敲门或紧接上一段安抚对话的证据。
 */
export function 有余波当面证据(
  妻: Pick<冷落妻状态, '_冷落余波'>,
  参数: { 玩家文本: string; 正文楼: number; 有确定物理场景: boolean; 身份词: readonly string[] },
): boolean {
  if (参数.有确定物理场景) return true;

  const 上次正文楼 = 妻._冷落余波.上次安抚正文楼;
  const 正文楼 = 非负整数(参数.正文楼);
  const 间隔 = 正文楼 - 上次正文楼;
  if (妻._冷落余波.状态 === '安抚中' && 上次正文楼 >= 0 && 间隔 >= 0 && 间隔 <= 4) return true;

  const 文本 = String(参数.玩家文本 ?? '').replace(/\s+/g, '');
  const 身份词 = [
    ...new Set(
      参数.身份词
        .map(String)
        .map(词 => 词.replace(/\s+/g, ''))
        .filter(Boolean),
    ),
  ].sort((a, b) => b.length - a.length);
  if (!文本 || !身份词.length) return false;
  const 目标 = `(?:${身份词.map(转义正则).join('|')})`;
  if (new RegExp(`${目标}[，,:：！!？?]`).test(文本)) return true;

  const 靠近动词 =
    '(?:去找|来找|找到|走向|走到|来到|靠近|面对|看向|看着|望向|叫住|拦住|拉住|抱住|拥抱|握住|牵住|敲响|敲开|敲)';
  if (new RegExp(`${靠近动词}${目标}(?:的(?:门|房门|家门))?(?!的)`).test(文本)) return true;
  const 当面说话 = '(?:说|问|谈|聊|道歉|解释|保证|安慰|倾听)';
  if (new RegExp(`(?:对|向|跟|和|与)${目标}(?!的)${当面说话}`).test(文本)) return true;
  return new RegExp(`${目标}(?!的)(?:面前|门口|身边|跟前|说|问|道歉|解释|保证|抱住|拥抱|握住|牵住)`).test(文本);
}

/** 只判断玩家本轮行动是否在回应委屈；手机文本不会调用本函数。 */
export function 玩家行动是有效安抚(玩家文本: string): boolean {
  const 文本 = String(玩家文本 ?? '').replace(/\s+/g, '');
  if (!文本) return false;
  if (
    /不(?:想|会|肯|愿意|打算)?(?:道歉|解释|哄|安慰|改|听|原谅)|没(?:有)?(?:冷落|忽略|亏欠)|你想多了|不理|无视|敷衍|嘲讽|讥讽|辱骂|威胁|推开|甩开|转身离开|走开|滚开|闭嘴|烦死|懒得|别闹|别烦|不耐烦|打断她|让她闭嘴|(?:抱住|安慰|陪|向).{0,4}(?:别人|其他人)/.test(
      文本,
    )
  )
    return false;
  return /对不起|抱歉|我错|怪我|是我不好|(?:我|怪我|是我).{0,8}(?:冷落|忽略|亏欠|让你受?委屈)|让(?:你|她)受?委屈|弥补|补偿|赔罪|原谅|消消气|别生气|哄|安慰|在乎|重视|关心|理解|听她|听你|你说|说吧|愿意听|陪她|陪你|不会再|以后不再|改正|保证|承诺|抱住|拥抱|握住|牵住|擦泪|递纸|轻声|耐心|解释|询问.{0,8}(?:感受|心情|怎么|为什么)|问她.{0,8}(?:怎么|为什么)/.test(
    文本,
  );
}

function 空成长判定(): 有效成长判定 {
  return { 有效: false, 来源: [], 合法正候选来源: [] };
}

function 余波激活(妻: Pick<冷落妻状态, '_冷落余波'>): boolean {
  return 妻._冷落余波.状态 !== '无';
}

/** 冷落从阶段2开始；302在系统正式入列前始终只校准、不积欠账。 */
export function 冷落可参与(门牌号: 门牌, 妻: Pick<冷落妻状态, '当前阶段'>, 母亲入列: boolean): boolean {
  return 妻.当前阶段 >= 2 && (门牌号 !== '302' || 母亲入列);
}

/**
 * 余波只有仍具冷落资格（阶段≥2，302需入列）时才有冻结堕落效力；
 * 阶段1或未入列302的遗留余波不再冻结，等待冷落结算统一清理。
 */
export function 余波有冻结效力(
  门牌号: 门牌,
  妻: { 当前阶段: number; _冷落余波: { 状态: 余波账['状态'] } },
  母亲入列: boolean,
): boolean {
  return 冷落可参与(门牌号, 妻, 母亲入列) && 妻._冷落余波.状态 !== '无';
}

/**
 * 比较守护结束后的新旧妻状态。合法正候选由守护层提供，表示正向候选虽被合法上限截住，
 * 仍算玩家完成了一次有效成长行为。余波只屏蔽堕落轴，其他成长轴照常有效。
 * 冻结堕落由调用方按资格注入：阶段1或未入列302的遗留余波不再屏蔽堕落正候选。
 */
export function 检测有效成长(
  旧妻: Readonly<冷落妻状态>,
  新妻: Readonly<冷落妻状态>,
  合法正候选: readonly 数值成长来源[] = [],
  冻结堕落 = 旧妻.当前阶段 >= 2 && 余波激活(旧妻),
): 有效成长判定 {
  const 来源 = new Set<有效成长来源>();
  const 候选来源 = new Set<数值成长来源>();

  if (新妻.好感值 > 旧妻.好感值) 来源.add('好感值');
  if (!冻结堕落 && 新妻.堕落值 > 旧妻.堕落值) 来源.add('堕落值');
  if (身体开发字段.some(字段 => 新妻.身体开发[字段] > 旧妻.身体开发[字段])) 来源.add('身体开发');
  if (新妻.当前阶段 > 旧妻.当前阶段) 来源.add('阶段晋升');

  for (const 候选 of 合法正候选) {
    if (候选 === '堕落值' && 冻结堕落) continue;
    候选来源.add(候选);
    来源.add(候选);
  }

  return {
    有效: 来源.size > 0,
    来源: [...来源],
    合法正候选来源: [...候选来源],
  };
}

/** 对单妻记录一次本轮成长；多个轴同一正文增长也只推进一个成长轮次。 */
export function 记录本轮有效成长(
  门牌号: 门牌,
  旧妻: Readonly<冷落妻状态>,
  新妻: 冷落妻状态,
  当前绝对时段: number,
  母亲入列: boolean,
  合法正候选: readonly 数值成长来源[] = [],
): 妻成长记录结果 {
  // 攻略成长与冷落资格是两件事：阶段0/1不积冷落欠账，但真实成长仍须返回给风闻映射。
  const 判定 = 检测有效成长(旧妻, 新妻, 合法正候选, 余波有冻结效力(门牌号, 旧妻, 母亲入列));
  if (!冷落可参与(门牌号, 新妻, 母亲入列)) {
    新妻._成长账 = 校准成长账(旧妻._成长账, 当前绝对时段);
    return { 门牌: 门牌号, 资格校准: true, ...判定 };
  }

  if (判定.有效) 新妻._成长账 = 记录有效成长(旧妻._成长账, 当前绝对时段);
  return { 门牌: 门牌号, 资格校准: false, ...判定 };
}

/** 供主回合引擎与逃生舱路径共用，候选表直接接守护层的来源级返回值。 */
export function 记录全楼有效成长(
  旧数据: Readonly<冷落系统数据>,
  新数据: 冷落系统数据,
  合法正候选表: 合法正候选表 = {},
  当前时段覆盖?: number,
): 妻成长记录结果[] {
  const 脚本候选表 = 脚本正增长候选账.get(新数据);
  脚本正增长候选账.delete(新数据);
  const 本时段 = Number.isFinite(当前时段覆盖) ? Math.max(0, Math.floor(当前时段覆盖!)) : 当前绝对时段(新数据);
  const 结果: 妻成长记录结果[] = [];
  for (const [门牌字符串, 新节点] of Object.entries(新数据.户) as [门牌, 冷落户节点][]) {
    if (!新节点) continue;
    const 旧节点 = 旧数据.户[门牌字符串];
    if (!旧节点) {
      新节点.妻._成长账 = 校准成长账(新节点.妻._成长账, 本时段);
      结果.push({ 门牌: 门牌字符串, 资格校准: true, ...空成长判定() });
      continue;
    }
    const 本户候选 = new Set<数值成长来源>(合法正候选表[门牌字符串] ?? []);
    for (const 来源 of 脚本候选表?.get(门牌字符串) ?? []) 本户候选.add(来源);
    结果.push(记录本轮有效成长(门牌字符串, 旧节点.妻, 新节点.妻, 本时段, 新数据.系统._母亲入列, [...本户候选]));
  }
  return 结果;
}

/**
 * 静音会议等脚本全权管理的隔离场景不执行普通回合结算，但固定奖励仍须遵守余波冻结，
 * 并在同一提交对象上消费封顶正增长候选。这里不结算冷落、风闻或其他普通回合副作用。
 */
export function 结算隔离脚本成长(旧数据: Readonly<冷落系统数据>, 新数据: 冷落系统数据): 妻成长记录结果[] {
  冻结全楼余波堕落(旧数据, 新数据);
  return 记录全楼有效成长(旧数据, 新数据);
}

/**
 * 在守护完成后、成长检测前调用；仍具冻结效力的余波期间堕落候选无论升降都拍回本楼基准。
 * 冻结效力由调用方按资格注入：阶段1或未入列302的遗留余波不再冻结脚本正负堕落改写。
 */
export function 冻结余波堕落(
  旧妻: Readonly<冷落妻状态>,
  新妻: 冷落妻状态,
  冻结效力 = 旧妻.当前阶段 >= 2 && 余波激活(旧妻),
): boolean {
  if (!冻结效力 || 新妻.堕落值 === 旧妻.堕落值) return false;
  新妻.堕落值 = 旧妻.堕落值;
  return true;
}

export function 冻结全楼余波堕落(旧数据: Readonly<冷落系统数据>, 新数据: 冷落系统数据): 门牌[] {
  const 已冻结: 门牌[] = [];
  for (const [门牌字符串, 新节点] of Object.entries(新数据.户) as [门牌, 冷落户节点][]) {
    const 旧节点 = 旧数据.户[门牌字符串];
    if (
      旧节点 &&
      新节点 &&
      冻结余波堕落(旧节点.妻, 新节点.妻, 余波有冻结效力(门牌字符串, 旧节点.妻, 新数据.系统._母亲入列))
    )
      已冻结.push(门牌字符串);
  }
  return 已冻结;
}

function 空冷落结果(门牌号: 门牌, 妻: 冷落妻状态): 妻冷落结算结果 {
  return {
    门牌: 门牌号,
    参与: false,
    资格校准: false,
    首次校准: false,
    计划下降: 0,
    实际下降: 0,
    触发余波: false,
    余波状态: 妻._冷落余波.状态,
  };
}

/**
 * 单妻惰性冷落结算。该函数只接受绝对时段；-1 与资格外状态都只校准，不补历史下降。
 * 资格外妻（阶段<2或未入列302）若有遗留余波，一并清为 创建余波账()，不冻结、不下降。
 */
export function 结算妻冷落(门牌号: 门牌, 妻: 冷落妻状态, 当前绝对时段: number, 母亲入列: boolean): 妻冷落结算结果 {
  const 结果 = 空冷落结果(门牌号, 妻);
  if (!冷落可参与(门牌号, 妻, 母亲入列)) {
    妻._成长账 = 校准成长账(妻._成长账, 当前绝对时段);
    if (余波激活(妻)) 妻._冷落余波 = 创建余波账();
    return { ...结果, 资格校准: true, 余波状态: 妻._冷落余波.状态 };
  }

  结果.参与 = true;
  if (妻._成长账.上次有效成长钟楼 < 0) {
    妻._成长账 = 校准成长账(妻._成长账, 当前绝对时段);
    return { ...结果, 首次校准: true };
  }
  if (余波激活(妻)) return 结果;

  const 距上次成长钟楼 = Math.max(0, 非负整数(当前绝对时段) - 妻._成长账.上次有效成长钟楼);
  const 下降 = 结算冷落下降({
    当前堕落值: 妻.堕落值,
    当前阶段: 妻.当前阶段,
    已结算冷落日: 妻._成长账.已结算冷落日,
    距上次成长钟楼,
  });
  妻.堕落值 = 下降.堕落值;
  妻._成长账.已结算冷落日 = 下降.已结算冷落日;

  const 触发余波 = 下降.本次触底;
  if (触发余波) {
    妻._冷落余波 = {
      状态: '待诉苦',
      触发钟楼: 非负整数(当前绝对时段),
      需安抚楼: 计算余波所需楼数(距上次成长钟楼),
      已安抚楼: 0,
      上次安抚正文楼: -1,
      送礼安抚日: -1,
      当日送礼安抚次数: 0,
    };
  }

  return {
    ...结果,
    计划下降: 下降.计划下降,
    实际下降: 下降.实际下降,
    触发余波,
    余波状态: 妻._冷落余波.状态,
  };
}

export function 结算全楼冷落(数据: 冷落系统数据): 妻冷落结算结果[] {
  const 本时段 = 当前绝对时段(数据);
  const 结果: 妻冷落结算结果[] = [];
  for (const [门牌字符串, 节点] of Object.entries(数据.户) as [门牌, 冷落户节点][]) {
    if (节点) 结果.push(结算妻冷落(门牌字符串, 节点.妻, 本时段, 数据.系统._母亲入列));
  }
  return 结果;
}

/** 档5是“已经触底、等当面诉苦”的专用档；开始安抚后手机不再继续催促。 */
export function 计算妻冷落预警档(
  门牌号: 门牌,
  妻: Readonly<冷落妻状态>,
  当前绝对时段: number,
  母亲入列: boolean,
): 冷落微信档 {
  if (!冷落可参与(门牌号, 妻, 母亲入列)) return 0;
  if (妻._冷落余波.状态 === '待诉苦') return 5;
  if (妻._冷落余波.状态 === '安抚中' || 妻._成长账.上次有效成长钟楼 < 0) return 0;
  return 计算冷落预警档(非负整数(当前绝对时段) - 妻._成长账.上次有效成长钟楼);
}

