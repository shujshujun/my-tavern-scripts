/** 异步生成落库前复核此指纹，避免成长或余波状态已变化时写入过期消息。 */
export function 冷落语义指纹(数据: Readonly<冷落系统数据>, 门牌号: 门牌): 冷落语义指纹值 | null {
  const 妻 = 数据.户[门牌号]?.妻;
  if (!妻) return null;
  const 本时段 = 当前绝对时段(数据);
  const 有效余波 = 余波有冻结效力(门牌号, 妻, 数据.系统._母亲入列);
  return {
    成长轮次: 妻._成长账.成长轮次,
    当前档: 计算妻冷落预警档(门牌号, 妻, 本时段, 数据.系统._母亲入列),
    // 资格外遗留余波会在下一次结算清理；指纹提前归一为“无”，避免正常手机回复被旧状态误判失效。
    余波状态: 有效余波 ? 妻._冷落余波.状态 : '无',
    冷落钟楼数: 妻._成长账.上次有效成长钟楼 < 0 ? 0 : Math.max(0, 非负整数(本时段) - 妻._成长账.上次有效成长钟楼),
  };
}

export function 列出冷落预警候选(数据: Readonly<冷落系统数据>): 冷落预警候选[] {
  const 本时段 = 当前绝对时段(数据);
  const 候选: 冷落预警候选[] = [];
  for (const [门牌字符串, 节点] of Object.entries(数据.户) as [门牌, 冷落户节点][]) {
    if (!节点) continue;
    const 档 = 计算妻冷落预警档(门牌字符串, 节点.妻, 本时段, 数据.系统._母亲入列);
    if (档 === 0) continue;
    const 距 = Math.max(0, 非负整数(本时段) - 节点.妻._成长账.上次有效成长钟楼);
    候选.push({
      门牌: 门牌字符串,
      档,
      距上次成长钟楼: 距,
      成长轮次: 节点.妻._成长账.成长轮次,
      去重键: `冷落:${门牌字符串}:${节点.妻._成长账.成长轮次}:${档}`,
      方向: 取冷落微信方向(档),
    });
  }
  return 候选.sort((a, b) => b.档 - a.档 || b.距上次成长钟楼 - a.距上次成长钟楼 || a.门牌.localeCompare(b.门牌));
}

function 选择自然在场目标(
  数据: Readonly<冷落系统数据>,
  自然在场妻: readonly 门牌[],
  状态符合: (状态: 余波账['状态']) => boolean,
): 门牌 | null {
  const 候选 = [...new Set(自然在场妻)].filter(门牌号 => {
    const 妻 = 数据.户[门牌号]?.妻;
    return Boolean(妻 && 冷落可参与(门牌号, 妻, 数据.系统._母亲入列) && 状态符合(妻._冷落余波.状态));
  });
  候选.sort((a, b) => {
    const 妻A = 数据.户[a]!.妻;
    const 妻B = 数据.户[b]!.妻;
    return (
      妻A._冷落余波.触发钟楼 - 妻B._冷落余波.触发钟楼 ||
      妻A._成长账.上次有效成长钟楼 - 妻B._成长账.上次有效成长钟楼 ||
      a.localeCompare(b)
    );
  });
  return 候选[0] ?? null;
}

/** 候选列表必须由调用方按自然位置推算取得，事件强制在场或微信在线都不能传入。 */
export function 选择自然在场待诉苦目标(数据: Readonly<冷落系统数据>, 自然在场妻: readonly 门牌[]): 门牌 | null {
  return 选择自然在场目标(数据, 自然在场妻, 状态 => 状态 === '待诉苦');
}

/** 主回合持续注入入口：待诉苦与已经开始安抚的目标都必须能继续获得剧情方向。 */
export function 选择自然在场余波目标(数据: Readonly<冷落系统数据>, 自然在场妻: readonly 门牌[]): 门牌 | null {
  return 选择自然在场目标(数据, 自然在场妻, 状态 => 状态 !== '无');
}

/**
 * 只给正文模型当前这一拍的关系方向，不包含天数、扣点、门槛或安抚进度数值。
 */
export function 构造余波剧情指令(门牌号: 门牌, 妻: Readonly<冷落妻状态>): string {
  const 余波 = 妻._冷落余波;
  if (余波.状态 === '无') return '';
  if (余波.状态 === '待诉苦') {
    return (
      `【事件在场妻:${门牌号}】【关系余波·诉苦】她已经把近期受到的冷落压在心里。` +
      '本次当面对话必须由她按既有人设和当前关系讲出具体委屈或不满，内容从共同经历与近期落差中生长；' +
      '不要照抄微信，不要把她写成突然崩溃，也不要因玩家一句道歉立刻彻底和好。'
    );
  }

  const 还差 = Math.max(0, 余波.需安抚楼 - 余波.已安抚楼);
  if (还差 <= 1) {
    return (
      `【事件在场妻:${门牌号}】【关系余波·收束】她的防备已经接近松动。` +
      '本次根据玩家此前持续而具体的回应自然收束，让她重新愿意靠近；仍须服从既有人设，不写成系统任务完成。'
    );
  }
  if (余波.需安抚楼 > 0 && 余波.已安抚楼 * 2 >= 余波.需安抚楼) {
    return (
      `【事件在场妻:${门牌号}】【关系余波·回应】她开始因玩家持续的在场和回应而松动，但尚未完全释怀。` +
      '让本次交流承接先前谈过的具体事情，表现信任逐步恢复，不重复第一次诉苦。'
    );
  }
  return (
    `【事件在场妻:${门牌号}】【关系余波·延续】她仍带着没有消化的不满。` +
    '让玩家的当面陪伴产生一点真实回应，同时保留她的戒备，不重复宣泄，也不突然跳到彻底和好。'
  );
}

/**
 * 把一种已经通过自身成功门槛的安抚行动计入余波。礼物与正文共用完成语义：
 * 达标时解除余波并把完成时点记为一次有效成长，避免下一拍按旧跨度重新触发冷落。
 */
function 计入一次余波安抚(妻: 冷落妻状态, 当前绝对时段: number, 首次诉苦: boolean): 安抚推进结果 {
  if (首次诉苦) 妻._冷落余波.状态 = '安抚中';
  const 目标 = Math.max(1, 非负整数(妻._冷落余波.需安抚楼));
  妻._冷落余波.需安抚楼 = 目标;
  妻._冷落余波.已安抚楼 = Math.min(目标, 非负整数(妻._冷落余波.已安抚楼) + 1);

  if (妻._冷落余波.已安抚楼 >= 目标) {
    妻._成长账 = 记录有效成长(妻._成长账, 当前绝对时段);
    妻._冷落余波 = 创建余波账();
    return { 已推进: true, 首次诉苦, 已完成: true, 当前状态: '无' };
  }
  return { 已推进: true, 首次诉苦, 已完成: false, 当前状态: 妻._冷落余波.状态 };
}

/**
 * 成功送出的礼物可替代一楼后续安抚，但不能跳过首次当面诉苦，也不能让资格外遗留状态复活。
 * 一次调用对应商店已经实际消耗的一件礼物；每名角色每个世界日最多计三次。
 */
export function 推进送礼安抚(数据: 冷落系统数据, 门牌号: 门牌): 送礼安抚推进结果 {
  const 妻 = 数据.户[门牌号]?.妻;
  const 当前状态 = 妻?._冷落余波.状态 ?? '无';
  const 空结果: 送礼安抚推进结果 = {
    已推进: false,
    首次诉苦: false,
    已完成: false,
    当前状态,
    达到日上限: false,
    当日已计次数: 0,
  };
  if (!妻 || 当前状态 !== '安抚中' || !冷落可参与(门牌号, 妻, 数据.系统._母亲入列)) return 空结果;
  const 本时段 = 当前绝对时段(数据);
  const 本日 = 当前天数(本时段);
  const 账日 = Number.isFinite(妻._冷落余波.送礼安抚日) ? Math.floor(妻._冷落余波.送礼安抚日) : -1;
  const 当日已计次数 = 账日 === 本日 ? 非负整数(妻._冷落余波.当日送礼安抚次数) : 0;
  if (当日已计次数 >= 每日送礼安抚上限) {
    return { ...空结果, 达到日上限: true, 当日已计次数 };
  }

  const 本次后次数 = 当日已计次数 + 1;
  妻._冷落余波.送礼安抚日 = 本日;
  妻._冷落余波.当日送礼安抚次数 = 本次后次数;
  return {
    ...计入一次余波安抚(妻, 本时段, false),
    达到日上限: false,
    当日已计次数: 本次后次数,
  };
}

/**
 * 只在成功生成并落地的主线当面正文楼调用。首个诉苦楼本身计一次，同正文楼重复处理不计；
 * 完成时解除余波并把完成视为一次脚本成长，避免下一拍按旧跨度立即重新触发。
 */
export function 推进余波安抚(妻: 冷落妻状态, 参数: 安抚推进参数): 安抚推进结果 {
  const 当前状态 = 妻._冷落余波.状态;
  const 空结果: 安抚推进结果 = { 已推进: false, 首次诉苦: false, 已完成: false, 当前状态 };
  if (当前状态 === '无' || !参数.成功主线当面楼) return 空结果;

  const 正文楼 = 非负整数(参数.正文楼);
  if (妻._冷落余波.上次安抚正文楼 === 正文楼) return 空结果;

  const 首次诉苦 = 当前状态 === '待诉苦';
  if (!首次诉苦 && !参数.玩家有效回应) return 空结果;
  妻._冷落余波.上次安抚正文楼 = 正文楼;
  return 计入一次余波安抚(妻, 参数.当前绝对时段, 首次诉苦);
}
