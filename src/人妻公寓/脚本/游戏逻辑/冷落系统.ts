/**
 * 脚本奖励与随后发生的 MVU 写回共用同一个 data 对象。这里按对象身份暂存正向来源，
 * 使已经碰到数值上限的合法奖励仍可被成长账识别；消费一次即删除，失败或放弃的克隆由 GC 回收。
 */
const 脚本正增长候选账 = new WeakMap<object, Map<门牌, Set<数值成长来源>>>();

export function 登记脚本正增长候选(数据: object, 门牌号: 门牌, 来源: 数值成长来源 | readonly 数值成长来源[]): void {
  let 全楼 = 脚本正增长候选账.get(数据);
  if (!全楼) {
    全楼 = new Map();
    脚本正增长候选账.set(数据, 全楼);
  }
  let 本户 = 全楼.get(门牌号);
  if (!本户) {
    本户 = new Set();
    全楼.set(门牌号, 本户);
  }
  const 来源们: readonly 数值成长来源[] = typeof 来源 === 'string' ? [来源] : 来源;
  for (const 项 of 来源们) 本户.add(项);
}

