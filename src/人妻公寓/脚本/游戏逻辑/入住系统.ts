/** 世界书条目开启(酒馆助手 API;绑定的主世界书按妻/夫名匹配条目名) */
function 开启世界书条目(名们: string[]): void {
  void (async () => {
    try {
      const { primary } = getCharWorldbookNames('current');
      if (!primary) return;
      await updateWorldbookWith(primary, 条目们 => {
        for (const 条 of 条目们) {
          if (名们.some(名 => 条.name === 名)) 条.enabled = true;
        }
        return 条目们;
      });
      console.info(`[人妻公寓·入住] 世界书条目已开启:${名们.join('、')}`);
    } catch (e) {
      console.warn('[人妻公寓·入住] 世界书条目开启失败(须玩家手动开启):', e);
    }
  })();
}

/** 入住检测:回合结算里调用(排队事件通道;每楼最多一户) */
export function 入住检测(data: SchemaType, 楼层: number): void {
  if (data.系统._坏结局) return;
  if (data.系统._待发送事件) return; // 搬家戏必须独占登场

  const 阶段 = (m: 门牌) => data.户[m]?.妻.当前阶段 ?? -1;
  let 目标: 门牌 | null = null;
  if (!data.户['201'] && (阶段('101') >= 入住阶段门 || 阶段('102') >= 入住阶段门)) 目标 = '201';
  else if (!data.户['202'] && data.户['201'] && 楼层 - data.户['201']._入住楼层 >= 二批错开楼) 目标 = '202';
  else if (!data.户['301'] && (阶段('201') >= 入住阶段门 || 阶段('202') >= 入住阶段门)) 目标 = '301';

  if (目标) {
    const 节点 = 创建户节点(楼层);
    const 初始 = 户静态表[目标].初始;
    if (初始) {
      if (初始.外装) 节点.妻.外装 = 初始.外装;
      if (初始.妆容) 节点.妻.妆容 = 初始.妆容;
      if (初始.气质描述) 节点.妻.气质描述 = 初始.气质描述;
      if (初始.当前情绪) 节点.妻.当前情绪 = 初始.当前情绪;
    }
    data.户[目标] = 节点;
    镜像直写(目标, { 入住楼层: 楼层 });
    data.系统._待发送事件 = 搬家戏[目标] ?? `【新住户】${目标}室今天有人搬进来了。`;
    开启世界书条目([户静态表[目标].妻名, 户静态表[目标].夫名].filter(Boolean));
    console.info(`[人妻公寓·入住] ${目标} 入住(${户静态表[目标].妻名})@${楼层}楼`);
    return;
  }

  // 反转时点(spec 拍板):假BOSS 301 到阶段2 → 母亲头像亮起(入列本体在母亲线)
  if (!data.系统._母亲入列 && 阶段('301') >= 2) {
    data.系统._母亲入列 = true;
    data.系统._待发送事件 =
      '【那扇门】没有任何事件发生——只是从今天起,{{user}}路过302的门口时,会多看一眼。那是他家。妈在里面。本楼请照常演当前场景,只在某个不起眼的瞬间,让他与母亲有一次极寻常的照面(饭点的一声招呼/楼道里递来一袋水果),寻常得让人过后想起来会愣一下';
    console.info('[人妻公寓·入住] 母亲头像亮起(301达阶段2)');
  }
}
