/**
 * 按当前存档全量同步入住条目，而不是只做单向开启。
 * 世界书开关由酒馆全局持久化；新局、回档或切换聊天时必须同时把未入住角色关回去。
 */
export async function 同步入住世界书条目(
  data: Pick<SchemaType, '户'>,
  提交校验: () => boolean = () => true,
): Promise<void> {
  if (!提交校验()) return;
  const 启用状态 = new Map(世界书入住绑定.map(([条目名, 门牌号]) => [条目名, Boolean(data.户[门牌号])]));
  try {
    const { primary } = getCharWorldbookNames('current');
    if (!primary || !提交校验()) return;
    await updateWorldbookWith(primary, 条目们 => {
      if (!提交校验()) return 条目们;
      for (const 条 of 条目们) {
        const 应启用 = 启用状态.get(条.name);
        if (应启用 !== undefined) 条.enabled = 应启用;
      }
      return 条目们;
    });
    if (!提交校验()) return;
    const 已启用 = [...启用状态].filter(([, enabled]) => enabled).map(([name]) => name);
    console.info(`[人妻公寓·入住] 世界书入住条目已同步:${已启用.join('、')}`);
  } catch (e) {
    console.warn('[人妻公寓·入住] 世界书入住条目同步失败(游戏数据不受影响):', e);
  }
}

function 取严格入住预约(data: SchemaType, 事件: string): 入住登场预约 | null {
  if (!事件 || 读取队首场景剧情(data.系统._待发送事件)?.内容 !== 事件) return null;
  return 识别入住登场预约(事件);
}

/** 母亲第一次正式入列时结清此前撞见暗账；重复调用不再折算。 */
function 应用母亲首次入列(data: SchemaType): number {
  if (data.系统._母亲入列) return 0;
  data.系统._母亲入列 = true;
  const 节点 = data.户['302'];
  if (!节点) return 0;
  const 原值 = 节点.妻.堕落值;
  const 计划折算 = Math.min(16, data.系统._母亲撞见次数 * 4);
  节点.妻.堕落值 = _.clamp(原值 + 计划折算, 0, 100);
  return 节点.妻.堕落值 - 原值;
}

/**
 * 首次登场 prompt 专用投影。只有当前 pending 本身是严格入住预约时才补出演员；
 * 返回值始终是深克隆，调用方对它做焦点、快照或粘滞处理都不会污染真实存档。
 */
export function 构造入住登场演出态(data: SchemaType, 事件: string, _消息楼层: number): SchemaType {
  const 演出态 = _.cloneDeep(data) as SchemaType;
  const 预约 = 取严格入住预约(data, 事件);
  if (!预约) return 演出态;

  if (预约.类型 === '住户') {
    if (!演出态.户[预约.门牌]) {
      演出态.户[预约.门牌] = 创建配置户节点(预约.门牌, 取绝对时段(演出态));
    }
  } else {
    应用母亲首次入列(演出态);
  }
  return 演出态;
}

/**
 * 成功正文后的原子入住步骤。pending 必须仍与本楼冻结事件逐字相同，且含系统生成的严格预约标记；
 * 因此同楼重放、被替换的票和普通事件都无权创建节点。函数幂等，不重复创建已入住节点。
 */
export function 提交入住登场(data: SchemaType, 事件: string, 楼层: number): 入住登场预约 | null {
  const 预约 = 取严格入住预约(data, 事件);
  if (!预约) return null;

  if (预约.类型 === '住户') {
    const 现有节点 = data.户[预约.门牌];
    if (现有节点) return 预约;
    const 绝对时段 = 取绝对时段(data);
    data.户[预约.门牌] = 创建配置户节点(预约.门牌, 绝对时段);
    console.info(`[人妻公寓·入住] ${预约.门牌} 正式入住(${户静态表[预约.门牌].妻名})@${楼层}楼`);
    return 预约;
  }

  const 新提交 = !data.系统._母亲入列;
  const 计划折算 = Math.min(16, data.系统._母亲撞见次数 * 4);
  const 折算堕落 = 应用母亲首次入列(data);
  // 正式提交可能继承预演态里已经折算好的数值，因此不能再靠数值差或 `_母亲入列=false`
  // 判断候选；严格预约票本身就是本次提交权限，候选必须挂到最终写回对象上。
  if (计划折算 > 0 && data.户['302']) 登记脚本正增长候选(data, '302', '堕落值');
  if (新提交) {
    console.info(`[人妻公寓·入住] 母亲正式入列(撞见折算堕落+${折算堕落})@${楼层}楼`);
  }
  return 预约;
}

/** 入住检测:回合结算里调用(排队事件通道;每楼最多一户) */
export function 入住检测(data: SchemaType, 楼层: number, 持续人物数 = 0): void {
  if (data.系统._坏结局) return;
  if (有场景剧情阻塞(data)) return; // 搬家戏必须独占登场
  if (持续人物数 > 0) return;
  if (!入住登场当前场景可用(data, 楼层)) return; // 条件不会丢失，等玩家回到空闲公共场景再登场

  const 绝对时段 = 取绝对时段(data);
  const 阶段 = (m: 门牌) => data.户[m]?.妻.当前阶段 ?? -1;
  let 目标: 门牌 | null = null;
  if (!data.户['201'] && (阶段('101') >= 入住阶段门 || 阶段('102') >= 入住阶段门)) 目标 = '201';
  else if (!data.户['202'] && data.户['201'] && 绝对时段 - data.户['201']._入住时段 >= 二批错开时段数) 目标 = '202';
  else if (!data.户['301'] && (阶段('201') >= 入住阶段门 || 阶段('202') >= 入住阶段门)) 目标 = '301';

  const 目标场景 = 读场景().房间id ?? '';
  if (目标) {
    const 在场夫 = 目标 === '201' || 目标 === '202' ? [目标] : [];
    const 事件 =
      `${事件角色标记({ 在场妻: [目标], 在场夫 })}` + (搬家戏[目标] ?? `【新住户】${目标}室今天有人搬进来了。`);
    追加等待场景剧情(data, 事件, 目标场景, `${目标}室新住户搬入`);
    console.info(`[人妻公寓·入住] ${目标} 首次登场已预约(${户静态表[目标].妻名})@${楼层}楼`);
    return;
  }

  // 反转时点(spec 拍板):假BOSS 301 到阶段2 → 预约母亲首次照面；头像与攻略状态等正文成功后再开放。
  if (!data.系统._母亲入列 && 阶段('301') >= 2) {
    const 事件 =
      `${事件角色标记({ 在场妻: ['302'] })}【那扇门】没有任何事件发生——只是从今天起,{{user}}路过302的门口时,会多看一眼。` +
      '那是他家。妈在里面。本楼请照常演当前场景,只在某个不起眼的瞬间,让他与母亲有一次极寻常的照面(饭点的一声招呼/楼道里递来一袋水果),寻常得让人过后想起来会愣一下';
    追加等待场景剧情(data, 事件, 目标场景, '一次寻常照面');
    console.info(`[人妻公寓·入住] 母亲首次照面已预约(301达阶段2)@${楼层}楼`);
  }
}
