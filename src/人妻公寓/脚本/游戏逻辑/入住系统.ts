/** 按该户静态人设创建完整初始节点；首批开局与后续入住共用，避免新局仪容/情绪变空。 */
export function 创建配置户节点(门牌号: 门牌, 绝对时段: number): ReturnType<typeof 创建户节点> {
  const 节点 = 创建户节点(绝对时段);
  const 初始 = 户静态表[门牌号].初始;
  if (初始?.外装) 节点.妻.外装 = 初始.外装;
  if (初始?.妆容) 节点.妻.妆容 = 初始.妆容;
  if (初始?.当前情绪) 节点.妻.当前情绪 = 初始.当前情绪;
  return 节点;
}

