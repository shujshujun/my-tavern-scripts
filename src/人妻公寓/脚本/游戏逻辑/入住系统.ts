/**
 * 按当前存档全量同步入住条目，而不是只做单向开启。
 * 世界书开关由酒馆全局持久化；新局、回档或切换旧存档时必须同时把未入住角色关回去。
 */
export async function 同步入住世界书条目(data: Pick<SchemaType, '户'>): Promise<void> {
  const 启用状态 = new Map(世界书入住绑定.map(([条目名, 门牌号]) => [条目名, Boolean(data.户[门牌号])]));
  try {
    const { primary } = getCharWorldbookNames('current');
    if (!primary) return;
    await updateWorldbookWith(primary, 条目们 => {
      for (const 条 of 条目们) {
        const 应启用 = 启用状态.get(条.name);
        if (应启用 !== undefined) 条.enabled = 应启用;
      }
      return 条目们;
    });
    const 已启用 = [...启用状态].filter(([, enabled]) => enabled).map(([name]) => name);
    console.info(`[人妻公寓·入住] 世界书入住条目已同步:${已启用.join('、')}`);
  } catch (e) {
    console.warn('[人妻公寓·入住] 世界书入住条目同步失败(游戏数据不受影响):', e);
  }
}

/** 入住检测:回合结算里调用(排队事件通道;每楼最多一户) */
export function 入住检测(data: SchemaType, 楼层: number): void {
  if (data.系统._坏结局) return;
  if (data.系统._待发送事件) return; // 搬家戏必须独占登场

  // _入住楼层 统一存钟楼(2026-07-26 审计 H3):经济系统按钟楼算期号,旧版存真实楼,
  // 玩家杀时间攒下的偏移会让后续入住户开局倒欠/倒收 N 期房租(偏移75时 301 白拿 ¥6600)。
  // 二批错开判定同步改钟楼轴,两个读者同一单位。
  const 现钟 = 楼层 + data.系统._时段偏移楼;
  const 阶段 = (m: 门牌) => data.户[m]?.妻.当前阶段 ?? -1;
  let 目标: 门牌 | null = null;
  if (!data.户['201'] && (阶段('101') >= 入住阶段门 || 阶段('102') >= 入住阶段门)) 目标 = '201';
  else if (!data.户['202'] && data.户['201'] && 现钟 - data.户['201']._入住楼层 >= 二批错开楼) 目标 = '202';
  else if (!data.户['301'] && (阶段('201') >= 入住阶段门 || 阶段('202') >= 入住阶段门)) 目标 = '301';

  if (目标) {
    const 节点 = 创建配置户节点(目标, 现钟);
    data.户[目标] = 节点;
    镜像直写(目标, { 入住楼层: 现钟 });
    const 在场夫 = 目标 === '201' || 目标 === '202' ? [目标] : [];
    data.系统._待发送事件 =
      `${事件角色标记({ 在场妻: [目标], 在场夫 })}` + (搬家戏[目标] ?? `【新住户】${目标}室今天有人搬进来了。`);
    // 全量同步可同时修正酒馆全局残留的旧存档开关；专线丈夫仍由“丈夫焦点”关键字决定实际激活。
    void 同步入住世界书条目(data);
    console.info(`[人妻公寓·入住] ${目标} 入住(${户静态表[目标].妻名})@${楼层}楼`);
    return;
  }

  // 反转时点(spec 拍板):假BOSS 301 到阶段2 → 母亲头像亮起(入列本体在母亲线)
  if (!data.系统._母亲入列 && 阶段('301') >= 2) {
    data.系统._母亲入列 = true;
    // 撞见暗账折算(spec 拍板):她"看见过"的次数换算入列初始堕落(每次+4封顶16〔调参〕)
    const 折算 = Math.min(16, data.系统._母亲撞见次数 * 4);
    if (折算 > 0 && data.户['302']) {
      data.户['302'].妻.堕落值 = _.clamp(data.户['302'].妻.堕落值 + 折算, 0, 100);
      镜像直写('302', { 堕落: data.户['302'].妻.堕落值 });
    }
    data.系统._待发送事件 =
      `${事件角色标记({ 在场妻: ['302'] })}【那扇门】没有任何事件发生——只是从今天起,{{user}}路过302的门口时,会多看一眼。` +
      '那是他家。妈在里面。本楼请照常演当前场景,只在某个不起眼的瞬间,让他与母亲有一次极寻常的照面(饭点的一声招呼/楼道里递来一袋水果),寻常得让人过后想起来会愣一下';
    console.info(`[人妻公寓·入住] 母亲头像亮起(301达阶段2;撞见折算堕落+${折算})`);
  }
}
