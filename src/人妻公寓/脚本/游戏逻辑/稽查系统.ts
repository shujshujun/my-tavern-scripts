/** 中断卡文案(极简中性;她怎么拒绝的下一楼由 AI 按性格写,不给示例——教训7) */
export function 中断卡文案(妻名: string): string {
  return [
    '【这一楼没有发生】',
    `你越过了${妻名}此刻能接受的界线——她挣脱了。`,
    '(好感受损,楼里的空气紧了一分)',
  ].join('\n');
}

/**
 * 违规代价结算(直接改传入 data;调用方负责落库)。
 * 〔调参〕好感-3/风闻+1;连续3次→"她开始躲着你"事件。
 * 楼层去重(防护12):同楼重roll不重复扣。
 */
export function 结算违规代价(data: SchemaType, 门牌号: 门牌, 楼层: number): void {
  if (data.系统._上次违规楼层 === 楼层) return;
  data.系统._上次违规楼层 = 楼层;
  const 妻 = data.户[门牌号]?.妻;
  if (!妻) return;
  妻.好感值 = _.clamp(妻.好感值 - 3, 0, 100);
  data.风闻 = _.clamp(data.风闻 + 1, 0, 100);
  data.系统._连续违规 += 1;
  if (data.系统._连续违规 >= 3) {
    data.系统._连续违规 = 0;
    const 妻名 = 户静态表[门牌号].妻名;
    const 事件 = `【她开始躲着你】接连的越界让${妻名}对管理员起了戒心:本轮起她会主动避开与你独处的机会(错开时间、留着门、找人作陪),持续到你用她能接受的方式重新让她安心为止。以符合她性格的方式演,不要点破原因`;
    data.系统._待发送事件 = data.系统._待发送事件 ? `${data.系统._待发送事件}|${事件}` : 事件;
  }
  console.info(`[人妻公寓·稽查] 违规代价:${门牌号} 好感-3,风闻+1(连续${data.系统._连续违规})`);
}

/** 未遂余波指引(违规楼的下一楼注入;拒绝方式=人设展示位,由 AI 按性格写) */
export function 未遂余波指引(门牌号: 门牌): string {
  const 妻名 = 户静态表[门牌号].妻名;
  return `【未遂事件余波】上一幕里管理员对${妻名}做出了远超她能接受的举动,被她挣脱/拒绝了(具体如何拒绝的由你按她的性格与阶段补写,自然融入本轮开头,不要复述本提示)。这一楼她还带着那件事的余温:紧张、疏离或强作镇定,按人设演`;
}

/** 稽查通过后清零连续计数(只在"有焦点妻且未违规"的楼调用) */
export function 记违规清零(data: SchemaType): void {
  if (data.系统._连续违规 > 0) data.系统._连续违规 = 0;
}
