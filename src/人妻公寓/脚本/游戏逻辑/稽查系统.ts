function 去掉对白和控制块(正文: string): string {
  return String(正文 ?? '')
    .replace(/<尺度判定(?:\s+模式=["']?(?:简|详)["']?)?\s*>[\s\S]*?<\/尺度判定>/giu, ' ')
    .replace(/“[^”]*”|「[^」]*」|『[^』]*』|"[^"\n]*"/gu, ' ');
}

function 最后命中位置(文本: string, 模式: RegExp): number {
  const 全局 = new RegExp(模式.source, `${模式.flags.replace(/g/g, '')}g`);
  return [...文本.matchAll(全局)].at(-1)?.index ?? -1;
}

function 所在句起点(文本: string, 位置: number): number {
  for (let i = Math.max(0, 位置 - 1); i >= 0; i -= 1) if (句边界.test(文本[i])) return i + 1;
  return 0;
}

function 所在分句起点(文本: string, 位置: number): number {
  for (let i = Math.max(0, 位置 - 1); i >= 0; i -= 1) if (分句边界.test(文本[i])) return i + 1;
  return 0;
}

function 所在分句终点(文本: string, 位置: number): number {
  for (let i = Math.max(0, 位置); i < 文本.length; i += 1) if (分句边界.test(文本[i])) return i;
  return 文本.length;
}

function 本楼肯定事实位置们(文本: string, 模式: RegExp): number[] {
  const 位置们: number[] = [];
  const 全局 = new RegExp(模式.source, `${模式.flags.replace(/g/g, '')}g`);
  for (const 匹配 of 文本.matchAll(全局)) {
    const 位置 = 匹配.index ?? 0;
    const 句首 = 所在分句起点(文本, 位置);
    const 句尾 = 所在分句终点(文本, 位置 + 匹配[0].length);
    const 句前 = 文本.slice(句首, 位置);
    const 紧前 = 句前.slice(-24).replace(/(?:并非|并不是|不是)没有/gu, '已经');
    const 紧后 = 文本.slice(位置 + 匹配[0].length, Math.min(句尾, 位置 + 匹配[0].length + 24));
    const 历史位置 = 最后命中位置(句前, 历史或回放标记);
    const 当前位置 = 最后命中位置(句前, 当前事实重置标记);
    if (历史位置 > 当前位置) continue;
    if (直接否定或中止前缀.test(紧前) || 条件计划或疑问前缀.test(紧前) || 非事实后缀.test(紧后)) continue;
    if (文本[句尾] === '？' || 文本[句尾] === '?') continue;
    位置们.push(位置);
  }
  return 位置们;
}

function 同句相邻(文本: string, 左: number, 右: number, 最大距离 = 48): boolean {
  return 所在句起点(文本, 左) === 所在句起点(文本, 右) && Math.abs(左 - 右) <= 最大距离;
}

function 附近存在(文本: string, 位置: number, 模式: RegExp): boolean {
  const 句首 = 所在分句起点(文本, 位置);
  const 句尾 = 所在分句终点(文本, 位置);
  return 模式.test(文本.slice(句首, 句尾));
}

/**
 * 只在已识别的拍摄固定拍里使用。普通自由回合仍由通用标尺和模型裁决处理；这里仅把
 * “媒介存在／历史回顾”与“本楼新发生的身体行为”拆开，并对明确事实保持失败关闭。
 */
export function 推导拍摄契约行为尺度(正文: string, _契约: 拍摄剧情尺度契约): 拍摄契约行为尺度 {
  const 文本 = 去掉对白和控制块(正文);
  const 四级 = 本楼肯定事实位置们(文本, 显式四级身体事实);
  const 三级 = 本楼肯定事实位置们(文本, 三级身体事实);
  const 无保护 = 本楼肯定事实位置们(文本, 无保护标记);
  const 大胆场所 = 本楼肯定事实位置们(文本, 大胆场所标记);
  if (
    四级.length ||
    无保护.some(位置 => 三级.some(行为位置 => 同句相邻(文本, 位置, 行为位置))) ||
    大胆场所.some(位置 => 三级.some(行为位置 => 同句相邻(文本, 位置, 行为位置)))
  ) {
    return { 实际: 4, 有未决高尺度: false };
  }
  if (三级.length) return { 实际: 3, 有未决高尺度: false };
  if (本楼肯定事实位置们(文本, 二级身体事实).length) return { 实际: 2, 有未决高尺度: false };
  if (本楼肯定事实位置们(文本, 一级身体事实).length) return { 实际: 1, 有未决高尺度: false };
  const 有未决高尺度 = 本楼肯定事实位置们(文本, 未决身体高尺度词).some(
    位置 => !附近存在(文本, 位置, 媒介处理语境) && !附近存在(文本, 位置, 余波残留语境),
  );
  return { 实际: 0, 有未决高尺度 };
}

/**
 * 模型控制块仍是普通语义的主要来源；只有已识别的固定拍且模型把媒介／历史误报成3/4级时，
 * 才以本楼肯定身体事实纠正“实际”。请求等级和拒绝结果不改写，也不会给角色增加许可。
 */
export function 应用拍摄剧情尺度契约(
  判定: 尺度判定解析结果 | null,
  检词文本: string,
  契约: 拍摄剧情尺度契约 | null,
): 尺度判定解析结果 | null {
  if (!判定 || !契约) return 判定;
  const 本楼 = 推导拍摄契约行为尺度(检词文本, 契约);
  const 角色 = { ...判定.角色 };
  for (const 门牌号 of 契约.人物) {
    const 项 = 角色[门牌号];
    if (!项) continue;
    let 实际 = 项.实际;
    if (本楼.实际 >= 3) 实际 = 本楼.实际;
    else if (项.实际 >= 3 && !本楼.有未决高尺度) 实际 = 本楼.实际;
    else 实际 = Math.max(实际, 本楼.实际);
    角色[门牌号] = { ...项, 实际 };
  }
  return { ...判定, 角色 };
}

/** 原生备用链在写路线硬状态前复用同一身体事实契约；不依赖模型是否正确填写控制块。 */
export function 拍摄剧情尺度越界原因(正文: string, 契约: 拍摄剧情尺度契约 | null): string {
  if (!契约 || 契约.独立结算 || 契约.行为尺度上限 === null) return '';
  const 本楼 = 推导拍摄契约行为尺度(正文, 契约);
  if (本楼.实际 <= 契约.行为尺度上限 && !本楼.有未决高尺度) return '';
  const 门牌号 = 契约.人物[0];
  const 角色 = 门牌号 ? 户静态表[门牌号]?.妻名 ?? 门牌号 : 契约.线路;
  return 本楼.有未决高尺度
    ? `${角色}正文仍含无法确认为媒介或历史回顾的高尺度身体事实`
    : `${角色}本楼新发生行为尺度${本楼.实际}超过脚本上限${契约.行为尺度上限}`;
}

// 只用于“模型漏掉控制块”时阻止正文事实与结构化账本分叉，不参与正常玩家意图准入。
// 逐句排除明确否定/拒绝，避免“没有发生关系”反向触发重写。
const 正式性行为事实词 =
  /发生(?:了)?(?:性关系|关系)|共度(?:了)?春宵|行房|圆房|肌肤之亲|鱼水之欢|翻云覆雨|云雨一番|做爱|性交|交合|交媾|抽插|挺入|内射|中出/;
const 正式性行为否定词 = /没(?:有)?|并未|未曾|不愿|拒绝|制止|停下|到此为止|没有真的/;

function 正文明确发生正式性行为(正文: string): boolean {
  return 正文
    .split(/[。！？；;\n]/)
    .map(句 => 句.trim())
    .filter(Boolean)
    .some(句 => 正式性行为事实词.test(句) && !正式性行为否定词.test(句));
}

function 关键词命中(正文: string, 最低阶段: number, 免计词: ReadonlySet<string>): string[] {
  const 命中: string[] = [];
  if (最低阶段 < 3) 命中.push(...性行为词表.filter(词 => 正文.includes(词)));
  if (最低阶段 < 4) 命中.push(...进阶花样词表.filter(词 => !免计词.has(词) && 正文.includes(词)));
  return [...new Set(命中)];
}

