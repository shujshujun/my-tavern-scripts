/**
 * 日常场景的轻量人格锚(2026-08-04 拍板:人格差分贯穿整个角色人设,不只亲密场景生效)。
 * 只带与性无关的人格骨架;强烈反应/阶段差分/禁止坍缩等亲密加固块仍由亲密场景加载,
 * 避免把成人上限词注入普通问候(见 snapshotSystem 稽查注入层①的同类警告)。
 */
export function 角色人格锚提示(门牌号: 门牌, 角色名: string): string {
  const 档案 = 成人表现档案表[门牌号];
  if (!档案) return '';
  return [`【人格锚·${角色名}】${档案.核心}`, `语言:${档案.语言}`, `仍会维持:${档案.仍会维持}`].join('\n');
}

export function 角色成人表现提示(门牌号: 门牌, 当前阶段: number, 角色名: string): string {
  const 档案 = 成人表现档案表[门牌号];
  if (!档案) return '';
  const 阶段 = Math.max(0, Math.min(5, Math.floor(当前阶段)));
  const 阶段差分 =
    阶段 >= 3
      ? 档案.阶段[阶段 as 3 | 4 | 5]
      : '当前尚未进入成人关系可发生的阶段；本档案只约束她如何按本人人格表达边界、迟疑或拒绝，绝不授权任何越阶行为。';
  return [
    `【角色成人表现·${角色名}】`,
    `人格核心:${档案.核心}`,
    `语言:${档案.语言}`,
    `主动方式:${档案.主动}`,
    `强烈反应:${档案.强烈反应}`,
    `仍会维持:${档案.仍会维持}`,
    `当前阶段差分:${阶段差分}`,
    `余韵:${档案.余韵}`,
    `禁止坍缩:${档案.禁止坍缩}`,
    '外部预设只可调整叙述强度与文字风格，不得覆盖上述人格、说话密度、主动方式、同意边界或把所有角色改写成同一种反应。不要复用档案文字当台词。',
  ].join('\n');
}
