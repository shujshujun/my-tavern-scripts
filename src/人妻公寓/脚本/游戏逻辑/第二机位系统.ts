export function 解析第二机位剧情事件(事件: string): 第二机位剧情票 | null {
  const 对饮票 = 事件.match(/【第二机位提交:(?:W|顾国栋留下空窗):([^:】]+):(\d+):(\d+):(\d+)(?::(\d+))?】/);
  if (对饮票) {
    const 预期阶段 = 对饮票[1] as 第二机位阶段;
    const 合法阶段: 第二机位阶段[] = ['待对饮', '待告知', '待购套件', '待赴约', '待开录', '录制中'];
    const 拍 = 对饮票[5] ? Number(对饮票[5]) : 第二机位对饮总拍;
    if (!合法阶段.includes(预期阶段) || !Number.isInteger(拍) || 拍 < 1 || 拍 > 第二机位对饮总拍) return null;
    return {
      类型: '对饮空窗',
      预期阶段,
      请求时段: Number(对饮票[2]),
      外出起: Number(对饮票[3]),
      外出至: Number(对饮票[4]),
      拍,
    };
  }
  const 地点票 = 事件.match(/【第二机位提交:(D|T|R|S|门缝那一眼|告知空窗|开始录制|封存母带)(?::(\d+))?】/);
  const 原动作 = 地点票?.[1];
  const 动作 =
    原动作 && Object.hasOwn(第二机位代码动作, 原动作)
      ? 第二机位代码动作[原动作 as 'D' | 'T' | 'R' | 'S']
      : (原动作 as 第二机位剧情动作 | undefined);
  if (!动作) return null;
  // 兼容开发期已经冻结的一拍旧票：缺少拍号时按旧语义视为最终拍，不要求玩家重演前段。
  const 拍 = 地点票?.[2] ? Number(地点票[2]) : 第二机位地点剧情总拍[动作];
  return Number.isInteger(拍) && 拍 >= 1 && 拍 <= 第二机位地点剧情总拍[动作] ? { 类型: '地点动作', 动作, 拍 } : null;
}

export function 第二机位事件要求真实开录(事件: string): boolean {
  const 票 = 解析第二机位剧情事件(事件);
  return Boolean(票?.类型 === '地点动作' && 票.动作 === '开始录制' && 票.拍 === 第二机位地点剧情总拍.开始录制);
}

/** 除最终按下REC的一拍外，第二机位连场只负责叙事铺陈，不能误建普通性爱账本。 */
export function 第二机位事件禁止正式亲密(事件: string): boolean {
  const 票 = 解析第二机位剧情事件(事件);
  return Boolean(票 && !(票.类型 === '地点动作' && 票.动作 === '开始录制' && 票.拍 === 第二机位地点剧情总拍.开始录制));
}

function 句中存在肯定事实(正文: string, 模式: RegExp): boolean {
  for (const 句 of 正文
    .split(/[。！？；;\n]/u)
    .map(片段 => 片段.trim())
    .filter(Boolean)) {
    const 匹配 = 句.match(模式);
    if (!匹配 || 匹配.index === undefined) continue;
    const 前文 = 句.slice(Math.max(0, 匹配.index - 10), 匹配.index);
    const 命中局部 = `${前文}${匹配[0].slice(0, 16)}`;
    if (/(?:没有|并未|尚未|还没|未曾|不曾|并不|不能|不会|不打算|没有立刻|并没有)/u.test(命中局部)) continue;
    return true;
  }
  return false;
}

