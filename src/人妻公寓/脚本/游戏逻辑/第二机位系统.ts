/** 当前拍已经成功消费后调用；下一拍成为同场景队首，旧的远处等待剧情原顺序保留。 */
export function 排入第二机位后续剧情(data: SchemaType, 结果: 第二机位结果 | null | undefined): void {
  const 后续 = 结果?.后续剧情;
  if (!后续) return;
  const 后续票 = 解析第二机位剧情事件(后续.事件);
  const 已存在 =
    后续票 &&
    读取待发送事件队列(data.系统._待发送事件).some(item => {
      const 已有票 = 解析第二机位剧情事件(item);
      return Boolean(已有票 && JSON.stringify(已有票) === JSON.stringify(后续票));
    });
  if (已存在) return;
  追加等待场景剧情(data, 后续.事件, 后续.地点, 后续.标题, true);
}

/** 在对饮扣酒、加信任以前调用；null 表示本次仍是普通对饮。这里只冻结票，不改路线与作息。 */
export function 准备第二机位对饮(data: SchemaType): 第二机位结果 | null {
  const 当前阶段 = 路线(data).阶段;
  const 首次 = 当前阶段 === '待对饮' && 今日(data) >= 路线(data).最早继续日;
  const 录制断点 = 当前阶段 === '录制中' && !第二机位真实录制已绑定(data);
  const 重新安排 = (['待告知', '待购套件', '待赴约', '待开录'].includes(当前阶段) || 录制断点) && 预约已过期(data);
  if (!首次 && !重新安排) return null;
  const 错误 = 互斥错误(data, '102');
  if (错误) return { 成功: false, 提示: 错误 };
  const 起点 = 下一个预约起点(data);
  if (起点 < 0) return { 成功: false, 提示: '近期没有同时避开住院与既有预约的完整空窗，先不要消耗这瓶酒。' };
  const 终点 = 起点 + 3;
  return {
    成功: true,
    提示: '这次先是一顿普通酒。远差与过夜会在后续话题里自然露出来，完整酒局结束后才记下日期。',
    事件: 构造对饮剧情事件(当前阶段, data.系统._绝对时段, 起点, 终点, 1),
  };
}

