function 全局互斥错误(data: SchemaType, 当前地点: string | null = null): string {
  if (data.系统._性爱场景.状态 !== '空闲') return '先把当前亲密场景正常收束。';
  if (data.系统._特殊场景.id) return '当前特殊场景尚未结束。';
  if (有普通场景剧情阻塞当前场景(data, 当前地点)) return '还有一段当前地点的场景剧情没有处理完。';
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态) return '先完成并挂断父亲电话。';
  return '';
}

function 互斥错误(data: SchemaType, 当前地点: string | null = null): string {
  if (!data.户['102']) return '102现在没有可承接这条路线的住户。';
  const 全局错误 = 全局互斥错误(data, 当前地点);
  if (全局错误) return 全局错误;
  if (处于医院硬锁(data, '102')) return '沈静仪正在医院待产或恢复，《第二机位》暂时冻结。';
  return '';
}

/** 有效正文提交时允许当前场景剧情票存在，只排除真正互斥的世界状态。 */
function 剧情提交错误(data: SchemaType): string {
  if (!data.户['102']) return '102现在没有可承接这条路线的住户。';
  if (data.系统._特殊场景.id) return '当前特殊场景已经变化。';
  if (data.系统._性爱场景.状态 !== '空闲') return '另一场亲密场景已经抢先开始。';
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态) return '父亲电话状态已经变化。';
  if (处于医院硬锁(data, '102')) return '沈静仪已经进入医院硬锁。';
  return '';
}

