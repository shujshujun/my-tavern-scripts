  if (参数.在场妻?.length) 段.push(`【事件在场妻:${[...new Set(参数.在场妻)].join(',')}】`);
  if (参数.在场夫?.length) 段.push(`【事件在场夫:${[...new Set(参数.在场夫)].join(',')}】`);
  if (参数.关联妻?.length) 段.push(`【事件关联妻:${[...new Set(参数.关联妻)].join(',')}】`);
