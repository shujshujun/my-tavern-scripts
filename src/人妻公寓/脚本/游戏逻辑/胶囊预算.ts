/**
 * 胶囊预算纯函数（v0.74 第 8 项）。
 *
 * 三个胶囊（普通数据库记忆 / 私有微信进展 / 近期私聊）共用同一预算纪律：
 * 当前候选放不下剩余预算时，整条跳过并继续检查后续候选——不把一条语义记录裁成半句
 * 占满余量，也不因一条超长记录 break 掉后面的短记录。保留原顺序、闭合标签与总字符上限。
 * 本模块不依赖任何浏览器全局，纯 Node 可测。
 */

/**
 * 按总字符上限挑选应保留的候选行（不含前缀/后缀，由调用方自行拼装闭合标签）。
 *
 * @param 开头 固定前缀（计入预算）
 * @param 结尾 固定后缀（计入预算）
 * @param 候选 已格式化好的候选行，按原顺序
 * @param 总上限 开头+候选行们+结尾 的总字符上限
 * @param 最多保留 最多保留多少条（普通数据库记忆为 8；无上限传 Number.POSITIVE_INFINITY）
 */
export function 胶囊预算选择(
  开头: string,
  结尾: string,
  候选: readonly string[],
  总上限: number,
  最多保留 = Number.POSITIVE_INFINITY,
): string[] {
  const 保留: string[] = [];
  for (const 项 of 候选) {
    // 条数硬上限已满时没有更多席位，直接结束；这不是“单条放不下”的跳过路径。
    if (保留.length >= 最多保留) break;
    // 当前候选整条放不下剩余预算 → 跳过该完整候选，继续检查后续更短的候选。
    if (开头.length + [...保留, 项].join('\n').length + 结尾.length > 总上限) continue;
    保留.push(项);
  }
  return 保留;
}
