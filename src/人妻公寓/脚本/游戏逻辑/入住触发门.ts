export interface 入住登场场景状态 {
  房间id?: string;
  房间类型?: '户' | '公共';
  /** 当前场景中会延续到下一轮的全部人物（妻、夫、赴约及其他自然演员）。 */
  持续人物数?: number;
  特殊场景中?: boolean;
  荣耀洞进行中?: boolean;
}

/**
 * 搬家与首次照面只能发生在公寓入口、楼内通道或管理员室。公园、健身房、天台、
 * 垃圾房和洗手间虽然同属“公共”类型，却不是住户搬家或路过 302 的现实现场。
 */
const 入住登场地点 = new Set(['公寓外部', '大堂', '信箱区', '管理员室', '楼梯间']);

/** 首次登场属于延后强制事件：只能在没有连续对戏占用的合法公寓公共场景启动。 */
export function 入住登场场景可用(状态: 入住登场场景状态): boolean {
  return (
    状态.房间类型 === '公共' &&
    入住登场地点.has(状态.房间id ?? '') &&
    (状态.持续人物数 ?? 0) === 0 &&
    !状态.特殊场景中 &&
    !状态.荣耀洞进行中
  );
}

export type 入住登场预约 = { 类型: '住户'; 门牌: '201' | '202' | '301' } | { 类型: '母亲'; 门牌: '302' };

/**
 * 只接受入住系统自己生成的“剧情标记 + 对应妻角色标记”。
 * 普通对白里偶然提到“新住户”或房号，不能获得创建住户节点的权限。
 */
export function 识别入住登场预约(事件: string): 入住登场预约 | null {
  if (!事件) return null;
  const 新住户标记数 = 事件.match(/【新住户】/g)?.length ?? 0;
  const 母亲标记数 = 事件.match(/【那扇门】/g)?.length ?? 0;
  if (新住户标记数 + 母亲标记数 !== 1) return null;

  const 妻标记组 = [...事件.matchAll(/【事件在场妻:([\d,]+)】/g)];
  if (妻标记组.length !== 1) return null;
  const 妻门牌 = 妻标记组[0][1].split(',').filter(Boolean);
  if (妻门牌.length !== 1) return null;

  if (母亲标记数 === 1 && 妻门牌[0] === '302') {
    return { 类型: '母亲', 门牌: '302' };
  }

  const 门牌 = 妻门牌[0];
  if (新住户标记数 === 1 && /^(?:201|202|301)$/.test(门牌)) {
    return { 类型: '住户', 门牌: 门牌 as '201' | '202' | '301' };
  }
  return null;
}

/** 新住户搬家与母亲首次入列共用同一延后规则；真正的来电、撞见仍可按设计打断。 */
export function 是入住登场事件(事件: string): boolean {
  return 识别入住登场预约(事件) !== null;
}

export type 本轮事件来源 = '重放' | '待发送' | '入住延期' | '场景延期' | '无';

export interface 本轮事件冻结 {
  楼层: number;
  内容: string;
  来源: 本轮事件来源;
  /** prompt 构造时看到的 pending；提交时必须逐字仍相同。 */
  待发送快照: string;
}

export interface 本轮事件选择输入 {
  楼层: number;
  已注入?: { 楼层?: number; 内容?: string } | null;
  待发送?: string;
  /** 已持久激活的普通场景事务内容；与队首一致时拥有首次正文冻结权。 */
  活动事务内容?: string;
  入住场景可用: boolean;
}

/**
 * 这里只需要冻结队首逻辑票，不能为了一个纯门函数反向依赖完整场景事务模块：
 * 部分 Node 测试以原生 ESM 直接加载本文件，扩展名解析与浏览器打包器不同。
 */
function 读取队首场景剧情内容(value: string): string {
  const items = String(value ?? '')
    .split('|')
    .map(item => item.trim())
    .filter(Boolean);
  if (!items.length) return '';
  const 取ID = (item: string) => item.match(/【场景剧情:v1:([^:】]*):[^】]*】/)?.[1] ?? '';
  const firstID = 取ID(items[0]);
  let count = 1;
  if (firstID) {
    while (count < items.length && 取ID(items[count]) === firstID) count += 1;
  }
  return items.slice(0, count).join('|');
}

/**
 * 在 prompt 构造前冻结唯一事件来源。新活动事务优先；没有活动事务时，同楼重掷才优先于 pending。
 */
export function 选择本轮事件(输入: 本轮事件选择输入): 本轮事件冻结 {
  const 待发送 = 输入.待发送 ?? '';
  const 已注入楼层 = 输入.已注入?.楼层 ?? -1;
  const 已注入内容 = 输入.已注入?.内容 ?? '';
  const 队首 = 读取队首场景剧情内容(待发送);
  const 活动事务内容 = String(输入.活动事务内容 ?? '').trim();

  // 新活动事务代表已经完成业务结算、正等待首次正文的确定性票。只要它仍与持久队首
  // 精确一致，就必须优先于同楼旧 `_已注入事件`；后者只属于没有新活动事务的真实重掷。
  if (活动事务内容 && 队首 === 活动事务内容) {
    return {
      楼层: 输入.楼层,
      内容: 活动事务内容,
      来源: '待发送',
      待发送快照: 待发送,
    };
  }

  if (已注入楼层 >= 输入.楼层 && 已注入内容) {
    return {
      楼层: 输入.楼层,
      内容: 已注入内容,
      来源: '重放',
      待发送快照: 待发送,
    };
  }

  if (!待发送) {
    return { 楼层: 输入.楼层, 内容: '', 来源: '无', 待发送快照: '' };
  }

  if (是入住登场事件(队首) && !输入.入住场景可用) {
    return {
      楼层: 输入.楼层,
      内容: '',
      来源: '入住延期',
      待发送快照: 待发送,
    };
  }

  return {
    楼层: 输入.楼层,
    内容: 队首,
    来源: '待发送',
    待发送快照: 待发送,
  };
}

/**
 * 阶段主题开幕票只凭稳定结构标记识别，不校验主题是否真实有效：
 * 新机器票据【阶段性癖票:门牌:主题】或旧“名称+对象”格式【性癖开幕·主题】都要求正文。
 * 未知、已下线或门牌与主题不符的残留/伪造票也宁可保留到有正文后，由
 * `解析阶段性癖开幕事件` / `提交阶段性癖开幕` 拒绝结算，不能因空响应被静默消费。
 */
function 带阶段性癖开幕标记(事件: string): boolean {
  return /【阶段性癖票:[^】]+】/.test(事件) || /【性癖开幕·[^】]+】/.test(事件);
}

/** 这些确定性剧情只有真正生成可显示正文后才能消费，空响应和纯标签都必须保留票据重试。 */
export function 事件必须有正文(事件: string): boolean {
  return (
    是入住登场事件(事件) ||
    带阶段性癖开幕标记(事件) ||
    /【(?:特殊场景·|丈夫登门:|转折正戏】|药物首夜】|早饭桌】|破墙】|场景行动】)/.test(事件) ||
    /【阶段线路剧情:\d{3}:\d+:\d+:[^】]+】/.test(事件) ||
    /【阶段线路演出:\d{3}:\d+:\d+:[^:】]*:[^】]*】/.test(事件)
  );
}

/**
 * 事件只有在“确实由 pending 注入、楼层一致、票未被换掉”时才可提交。
 * 确定性强剧情还要求清洗后的正文非空；普通事件沿用成功回合即可消费的旧语义。
 */
export function 本轮事件可提交(冻结: 本轮事件冻结, 当前待发送: string, 实际楼层: number, 有效正文: boolean): boolean {
  if (冻结.来源 !== '待发送') return false;
  if (冻结.楼层 !== 实际楼层) return false;
  if (!冻结.待发送快照) return false;
  const 当前队首 = 读取队首场景剧情内容(当前待发送);
  if (!当前队首 || 当前队首 !== 冻结.内容) return false;
  return !事件必须有正文(冻结.内容) || 有效正文;
}
