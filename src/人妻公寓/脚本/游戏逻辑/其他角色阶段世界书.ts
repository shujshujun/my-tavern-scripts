import type { SchemaType } from '../../schema';
import { 户静态表 } from '../../stageConfig';
import { 借种结局已完成, 是借种受孕场次 } from './借种结局状态';
import { 录像带结局后效已开启, 读取周小满承接生活事实 } from './结局后生活社交语义';
import { 录像带V4固定日常结果摘要 } from './录像带V4状态';
import type { 阶段世界书投影 } from './阶段世界书同步器';

export const 其他角色阶段条目名 = {
  '101': '[人妻公寓]101家庭与生活阶段',
  '102': '[人妻公寓]102关系与生活阶段',
  '202': '[人妻公寓]202关系与生活阶段',
} as const;

export function 读取其他角色游戏阶段(data: SchemaType, room: keyof typeof 其他角色阶段条目名): string {
  if (!data.户[room]) return '未入住';
  if (room === '101') {
    if (借种结局已完成(data)) return '结局后自由生活';
    if (data.系统._特殊场景.id === '借种' || 是借种受孕场次(data.系统._性爱场景.场次标识)) return '结局进行中';
    if (data.系统._家庭计划.阶段 === '已完成') return '承接完成';
    return data.系统._家庭计划.阶段 === '未开始' || data.系统._家庭计划.阶段 === '待安装' ? '关系发展中' : '承接进行中';
  }
  if (录像带结局后效已开启(data)) return '结局后自由生活';
  if (data.系统._录像带V4.阶段 !== '未开始') return data.系统._录像带V4.录像带已使用 ? '结局进行中' : '结局筹备中';
  const route = room === '102' ? data.系统._第二机位 : data.系统._不再留门;
  const name = room === '102' ? '第二机位' : '不再留门';
  if (route.阶段 === '已完成' || data.系统._已完成特殊场景.includes(name)) return '承接完成';
  return room === '102'
    ? (['未开始', '待门缝'].includes(route.阶段) ? '关系发展中' : '承接进行中')
    : (data.系统._不再留门.道具已使用 ? '承接进行中' : '关系发展中');
}

export function 构造其他角色阶段世界书投影(data: SchemaType): 阶段世界书投影[] {
  return (Object.keys(其他角色阶段条目名) as (keyof typeof 其他角色阶段条目名)[]).map(room => {
    const phase = 读取其他角色游戏阶段(data, room);
    const name = 户静态表[room].妻名;
    const lines = [`${name}当前游戏阶段：${phase}。`];
    if (phase === '结局后自由生活') {
      if (room === '101') {
        lines.push('《借种》结局已经完成。夏乔、陆嘉明与玩家已经建立知情的三人家庭安排，陆嘉明继续参与家庭生活。',
          '当前孕产阶段、孩子和合照以存档中的已发生记录为准；后续生活延续既有家庭关系。照片公开与群内知情按玩家的实际选择和已发送消息承接。');
      } else {
        lines.push('共享《录像带》结局已经完成。',
          data.系统._录像带V4.阶段 === '已完成' ? 录像带V4固定日常结果摘要 : '此存档保留共享结局完成记录，未记录的拍次与物件细节仍按现有历史承接。',
          room === '102'
            ? '沈静仪与玩家延续已经成立的关系，顾国栋保留对既成事实的知情；102继续现有日常、见面与时间安排。'
            : '周小满与玩家延续已经成立的关系，何俊生保留对既成事实的知情；' +
              (读取周小满承接生活事实(data).停止默认等待
                ? '周小满不再默认留饭守门，按自己的时间与约定生活。'
                : '周小满按当下的真实安排与约定继续生活。'),
          '日常层承接已完成结果，当前游戏阶段已经越过首次调查、对质与观看；公开群聊仍以真正发送过的消息确定知情范围。');
      }
    } else if (phase !== '未入住') {
      if (room === '101') lines.push(`家庭计划当前进度：${data.系统._家庭计划.阶段}。家庭计划完成只开放《借种》，正式结局由成功的结局收尾签发。`);
      else lines.push(`${room === '102' ? '《第二机位》' : '《不再留门》'}的当前完成事实只属于本户；共享《录像带》的筹备、观看和最终交接仍按实际进度推进。`);
      lines.push('尚未提交的结局步骤继续由玩家推进，当前关系按已经发生的个人剧情承接。');
    }
    return { 名称: 其他角色阶段条目名[room], 内容: lines.join('\n'), 启用: Boolean(data.户[room]),
      允许建书: !['未入住', '关系发展中'].includes(phase), 顺序: room === '101' ? 104 : room === '102' ? 105 : 106,
      元数据: { rqgy角色阶段投影版本: 1, 门牌: room, 游戏阶段: phase } };
  });
}
