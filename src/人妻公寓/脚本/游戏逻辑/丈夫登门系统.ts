import type { SchemaType } from '../../schema';
import { 户静态表, 门牌列表, type 门牌 } from '../../stageConfig';
import { 读取世界时间 } from './楼层时钟';
import { 处于医院硬锁 } from './生产系统';
import { 降低风闻 } from './风闻系统';

export const 丈夫登门触发疑心 = 50;
export const 喜讯奖励 = { 疑心降低: 20, 信任提高: 10, 风闻降低: 15 } as const;
export const 夏乔感谢补偿 = 1200;

export type 丈夫登门变体 = '对质' | '喜讯' | string;

export interface 丈夫登门操作结果 {
  成功: boolean;
  提示: string;
  变动?: boolean;
  事件?: string;
  门牌?: 门牌;
}

function 是门牌(value: string): value is 门牌 {
  return 门牌列表.includes(value as 门牌);
}

function 夹取(value: number): number {
  return Math.min(100, Math.max(0, Math.round(value)));
}

function 登门账(data: SchemaType, 门牌号: 门牌) {
  return data.户[门牌号]?.妻._怀孕.丈夫登门;
}

/**
 * 后续丈夫结局只需在这里返回新的稳定变体标识，并在构造节拍处分派对应演出。
 * 当前不擅自把“观众席／哑巴亏”等尚未设计完成的轨道解释成感谢事件。
 */
export function 解析丈夫特殊登门变体(data: SchemaType, 门牌号: 门牌): string {
  if (门牌号 !== '101') return '';
  const 生产 = data.户['101']?.妻._生产;
  if (!生产?.家庭计划知情) return '';
  if (生产.本胎序号 === 1) return '夏乔感谢';
  if (生产.本胎序号 === 2) return '夏乔带酒';
  if (生产.本胎序号 === 3) return '夏乔不登门';
  return '';
}

/** 孕情微信已送达、已经曝光且疑心达到门槛时登记睡前强制访问；重复扫描无副作用。 */
export function 同步丈夫登门排期(data: SchemaType): 门牌[] {
  const 新排期: 门牌[] = [];
  const 绝对时段 = 读取世界时间(data).绝对时段;
  for (const 门牌号 of Object.keys(data.户) as 门牌[]) {
    if (门牌号 === '302') continue;
    const 节点 = data.户[门牌号];
    if (!节点 || 节点.妻._怀孕.状态 !== '已告知') continue;
    const 特殊 = 解析丈夫特殊登门变体(data, 门牌号);
    if (特殊 === '夏乔不登门') continue;
    if (!特殊 && (!节点.妻._怀孕.已曝光 || 节点.夫.疑心值 < 丈夫登门触发疑心)) continue;
    const 账 = 节点.妻._怀孕.丈夫登门;
    if (账.状态 !== '无') continue;
    账.状态 = '待触发';
    账.排期绝对时段 = 绝对时段;
    账.变体标识 = '';
    账.当前拍 = 0;
    账.已结算 = false;
    新排期.push(门牌号);
  }
  return 新排期;
}

export function 安眠药可圆场(data: SchemaType, 门牌号: 门牌): boolean {
  if (门牌号 === '302') return false;
  if (处于医院硬锁(data, 门牌号)) return false;
  // 夏乔知情家庭计划的三胎全部由专属语义接管，安眠药不能把感谢／带酒／不上门改写成通用喜讯。
  if (门牌号 === '101' && data.户['101']?.妻._生产.家庭计划知情) return false;
  const 账 = 登门账(data, 门牌号);
  return !!账 && 账.状态 === '待触发' && !账.隐藏圆场;
}

export function 丈夫登门药物窗口已开启(data: SchemaType): boolean {
  return (Object.keys(data.户) as 门牌[]).some(门牌号 => 安眠药可圆场(data, 门牌号));
}

/** 只记录妻子已经收下并自行圆场；不生成或描写实际用药过程。 */
export function 交付圆场安眠药(data: SchemaType, 原门牌: string): 丈夫登门操作结果 {
  if (!是门牌(原门牌) || 原门牌 === '302') {
    return { 成功: false, 提示: '这不是拿来当普通礼物送出的。' };
  }
  if (!安眠药可圆场(data, 原门牌)) {
    return { 成功: false, 提示: '现在还没有需要她提前圆场的丈夫登门事件。' };
  }
  const 账 = 登门账(data, 原门牌)!;
  账.隐藏圆场 = true;
  return {
    成功: true,
    提示: `${户静态表[原门牌].妻名}把东西收了起来，没有多说。她似乎已经想好了该怎么解释。`,
    变动: true,
    门牌: 原门牌,
  };
}

function 解析当前变体(data: SchemaType, 门牌号: 门牌): 丈夫登门变体 {
  const 特殊 = 解析丈夫特殊登门变体(data, 门牌号).trim();
  if (特殊) return 特殊;
  return 登门账(data, 门牌号)?.隐藏圆场 ? '喜讯' : '对质';
}

function 节拍总数(变体: 丈夫登门变体): number {
  return ['喜讯', '夏乔感谢', '夏乔带酒'].includes(变体) ? 2 : 3;
}

function 构造丈夫登门节拍(data: SchemaType, 门牌号: 门牌, 地点: string, 拍: number): string {
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  const 变体 = 节点.妻._怀孕.丈夫登门.变体标识 || '对质';
  const 标记 = `【丈夫登门:${门牌号}:${变体}:${拍}】【事件在场夫:${门牌号}】【事件关联妻:${门牌号}】`;
  const 共通 =
    `地点始终是${地点}。${配.夫名}亲自来找{{user}}，${配.妻名}不在现场。` +
    '这是独立的丈夫登门连续剧情，不得插入其他住户、手机消息、随机事件或额外数值结算。';

  if (变体 === '夏乔感谢') {
    if (拍 === 1) {
      return (
        `${标记}${共通}这是家庭计划知情后的第一胎。陆嘉明清楚是{{user}}帮助夏乔怀孕，也清楚这是夫妻双方已经同意的借种计划。` +
        '他深夜来访是郑重道谢，不是试探、对质或索赔；演出他的局促、释然与真诚感谢，然后停下来等玩家回应。'
      );
    }
    return (
      `${标记}${共通}先自然回应玩家上一轮的话，再让陆嘉明把准备好的1200金币补偿交给{{user}}，说明这是感谢而非封口费。` +
      '他明确接受这个孩子和既定家庭计划，郑重告别离开；不得翻脸、怀疑身世、索要赔偿或追加惩罚。金币只由脚本在本拍有效收尾后结算一次。'
    );
  }

  if (变体 === '夏乔带酒') {
    if (拍 === 1) {
      return (
        `${标记}${共通}这是夏乔第二胎。陆嘉明刚刚得知她又怀孕，带着一瓶酒来找{{user}}；他清楚这次仍是{{user}}让夏乔怀孕。` +
        '演出他想庆祝却笑不出来的复杂状态：嫉妒、失落、现实压力与某种认命同时存在，但他不是来翻案或惩罚玩家；倒酒后停下来等回应。'
      );
    }
    return (
      `${标记}${共通}先具体回应玩家的话，再让陆嘉明承认第二个孩子已经是家庭计划延续出的现实。` +
      '他把酒喝完，带着仍然复杂但不再挣扎的情绪离开；不得索赔、扣钱、降低关系、诉诸暴力或把这次演成普通对质。'
    );
  }

  if (变体 === '喜讯') {
    if (拍 === 1) {
      return (
        `${标记}${共通}${配.夫名}满脸压不住的喜色，主动告诉{{user}}妻子已经怀孕，把孩子坚定地当作自己的。` +
        '他是来分享喜事，不是试探或对质；演出他的兴奋、笨拙期待与对管理员的信任，然后停下来等待玩家回应。'
      );
    }
    return (
      `${标记}${共通}先自然回应玩家上一轮的话，再让${配.夫名}继续分享一点将为人父的打算。` +
      '他真诚告别并离开，必须明确本次喜讯登门已经结束；不得突然翻脸、怀疑孩子身世或索要赔偿。'
    );
  }

  if (变体 !== '对质') {
    return (
      `${标记}${共通}这是预留给丈夫特殊结局“${变体}”的登门端口；当前只按已注册的特殊剧情事实演出本拍，` +
      '不得退回普通对质，也不得自行发明尚未登记的永久结局。'
    );
  }
  if (拍 === 1) {
    return (
      `${标记}${共通}${配.夫名}已经听说妻子怀孕，疑心压不住，深夜堵到门前要求{{user}}把话说清楚。` +
      `按他当前疑心${节点.夫.疑心值}、信任${节点.夫.信任值}和本人性格演出第一轮质问；只建立压力与具体矛盾，停下来等玩家澄清。`
    );
  }
  if (拍 === 2) {
    return (
      `${标记}${共通}先针对玩家上一轮的解释作出具体反应。${配.夫名}不会被一句空话轻易说服，` +
      '继续追问并把冲突推到赔偿条件，但本拍不能动手、不能离开，也不能提前完成赔偿结算；结尾再次把回应权交给玩家。'
    );
  }
  return (
    `${标记}${共通}先回应玩家最后一次澄清，再让${配.夫名}接受以玩家现有全部现金作为赔偿的收口。` +
    '他带着仍未完全消散的怀疑离开，必须明确本次对质已经结束；不得追加暴力、报警、离婚或其他未设计结局。'
  );
}

export function 读取待触发丈夫登门(data: SchemaType): 门牌 | null {
  return (
    (Object.keys(data.户) as 门牌[])
      .filter(门牌号 => 门牌号 !== '302' && 登门账(data, 门牌号)?.状态 === '待触发')
      .filter(门牌号 => !处于医院硬锁(data, 门牌号))
      .sort((a, b) => {
        const 时差 = (登门账(data, a)?.排期绝对时段 ?? -1) - (登门账(data, b)?.排期绝对时段 ?? -1);
        return 时差 || a.localeCompare(b);
      })[0] ?? null
  );
}

/** 睡眠按钮在真正推进时间前调用；返回事件即拦截本次睡眠并立即开演第一拍。 */
export function 准备睡前丈夫登门(data: SchemaType, 地点: string): 丈夫登门操作结果 | null {
  同步丈夫登门排期(data);
  const 门牌号 = 读取待触发丈夫登门(data);
  if (!门牌号) return null;
  const 账 = 登门账(data, 门牌号)!;
  账.状态 = '进行中';
  账.变体标识 = 解析当前变体(data, 门牌号);
  账.当前拍 = 1;
  const 事件 = 构造丈夫登门节拍(data, 门牌号, 地点, 1);
  data.系统._待发送事件 = 事件;
  return {
    成功: true,
    提示: `刚准备休息，${户静态表[门牌号].夫名}却找上了门。今晚得先处理这次登门。`,
    变动: true,
    事件,
    门牌: 门牌号,
  };
}

/** 成功演完一拍后调用；中途失败、取消或重掷不会消费，也不会提前结算。 */
export function 推进丈夫登门(data: SchemaType, 已演事件: string, 地点 = '管理员室'): 丈夫登门操作结果 | null {
  const 匹配 = 已演事件.match(/【丈夫登门:(\d{3}):([^:】]+):(\d+)】/);
  if (!匹配 || !是门牌(匹配[1])) return null;
  const 门牌号 = 匹配[1];
  const 账 = 登门账(data, 门牌号);
  if (!账 || 账.状态 !== '进行中' || 账.变体标识 !== 匹配[2] || 账.当前拍 !== Number(匹配[3])) return null;

  const 总拍 = 节拍总数(账.变体标识);
  if (账.当前拍 < 总拍) {
    账.当前拍 += 1;
    const 事件 = 构造丈夫登门节拍(data, 门牌号, 地点, 账.当前拍);
    data.系统._待发送事件 = 事件;
    return { 成功: true, 提示: '丈夫登门事件仍在继续。', 变动: true, 事件, 门牌: 门牌号 };
  }

  let 提示 = '';
  if (!账.已结算) {
    const 节点 = data.户[门牌号];
    if (账.变体标识 === '喜讯') {
      const 原疑心 = 节点.夫.疑心值;
      const 原信任 = 节点.夫.信任值;
      节点.夫.疑心值 = 夹取(原疑心 - 喜讯奖励.疑心降低);
      节点.夫.信任值 = 夹取(原信任 + 喜讯奖励.信任提高);
      const 风闻降低 = 降低风闻(data, 喜讯奖励.风闻降低);
      提示 = `喜讯登门结束：疑心 -${原疑心 - 节点.夫.疑心值}，信任 +${节点.夫.信任值 - 原信任}，风闻 -${风闻降低}。`;
    } else if (账.变体标识 === '对质') {
      const 赔偿 = Math.max(0, Math.round(data.现金));
      data.现金 = 0;
      提示 = `丈夫对质结束：已支付全部现金作为赔偿（${赔偿} 金币）。`;
    } else if (账.变体标识 === '夏乔感谢') {
      data.现金 += 夏乔感谢补偿;
      提示 = `陆嘉明的感谢登门结束：已收到 ${夏乔感谢补偿} 金币补偿。`;
    } else if (账.变体标识 === '夏乔带酒') {
      提示 = '陆嘉明带酒上门的谈话已经结束；没有奖励、赔偿或惩罚。';
    } else {
      提示 = `丈夫特殊登门“${账.变体标识}”已经结束。`;
    }
    账.已结算 = true;
  }
  账.状态 = '已完成';
  return { 成功: true, 提示, 变动: true, 门牌: 门牌号 };
}
