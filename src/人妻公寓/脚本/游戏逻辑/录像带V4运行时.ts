function 是房间(值: unknown): 值 is 录像带V4房间 {
  return 值 === '102' || 值 === '202';
}

function 文件名(路径: string): string {
  return (
    String(路径 ?? '')
      .split(/[\\/]/u)
      .at(-1) ?? ''
  );
}

/**
 * V4候选尚未正式接受或安装，生产包不得静态导入38张PNG。只有本地验收环境显式提供
 * `__RQGY_VTR_V4_CANDIDATE_BASE__`（或调用方传入基址）时才生成图片URL；正式环境为空时
 * 舞台显示带REC/CAM/时间码的监控占位，不会偷请求未发布标签。
 */
export function 读取录像带V4候选基址(): string {
  return String((globalThis as Record<string, unknown>).__RQGY_VTR_V4_CANDIDATE_BASE__ ?? '')
    .trim()
    .replace(/\/+$/u, '');
}

export function 录像带V4候选图片地址(候选: 录像带V4候选记录 | undefined, 基址 = 读取录像带V4候选基址()): string {
  const 根 = String(基址 ?? '')
    .trim()
    .replace(/\/+$/u, '');
  const 名 = 候选 ? 文件名(候选.output) : '';
  if (!根 || !/^VTR-V4-(?:102|202)-B(?:0[1-9]|1[0-9])(?:-draw\d+)?\.png$/u.test(名)) return '';
  return `${根}/${encodeURIComponent(名)}`;
}

function 从画面键解析(键: string): { 房间: 录像带V4房间; 幕次: number } | null {
  const 匹配 = /^VTR-V4-(102|202)-B(0[1-9]|1[0-9])$/u.exec(String(键 ?? ''));
  if (!匹配 || !是房间(匹配[1])) return null;
  return { 房间: 匹配[1], 幕次: Number(匹配[2]) };
}

/**
 * 滚动摘要不进入主stat；每次生成前仅从已提交画面键与冻结卡的 runtimeOutcome 临时重建。
 * 这样VTR可获得跨幕连续性，普通日常状态却永远看不到AI原文或专用软摘要。
 */
export function 构造录像带V4房间摘要(data: SchemaType): { '102': string; '202': string } {
  const 结果: { '102': string[]; '202': string[] } = { '102': [], '202': [] };
  for (const 键 of data.系统._录像带V4.场景.已提交画面键) {
    const 身份 = 从画面键解析(键);
    if (!身份) continue;
    const 卡 = 读取录像带V4镜头卡(身份.房间, 身份.幕次);
    if (!卡) continue;
    const 收束 = String(卡.runtimeOutcome ?? '').trim();
    const 硬事实 = 收束 || `${卡.title}已经按停止边界完成。`;
    结果[身份.房间].push(`B${String(身份.幕次).padStart(2, '0')}：${硬事实}`);
  }
  return {
    '102': 结果['102'].slice(-8).join('\n') || 'CAM-102尚无已提交画面。',
    '202': 结果['202'].slice(-8).join('\n') || 'CAM-202尚无已提交画面。',
  };
}

