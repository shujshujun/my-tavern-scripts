function 录像带V4句中存在肯定事实(正文: string, 模式: RegExp): boolean {
  const flags = [...new Set(`${模式.flags.replace(/[gy]/gu, '')}g`)].join('');
  for (const 句 of String(正文 ?? '')
    .split(/[。！？；;，,：:\n]/u)
    .map(片段 => 片段.trim())
    .filter(Boolean)) {
    const 搜索 = new RegExp(模式.source, flags);
    let 匹配: RegExpExecArray | null;
    while ((匹配 = 搜索.exec(句))) {
      const 动作前 = 句.slice(Math.max(0, 匹配.index - 22), 匹配.index);
      if (
        /(?:没有|并未|尚未|还没|仍未|不曾|未曾|不能|不得|不要|不准|不许|绝不|并不|准备|打算|将要|即将|下一步|稍后|待会|是否|能否|可否|要不要|问(?:他|她)?).{0,18}$/u.test(
          动作前,
        )
      ) {
        if (!匹配[0]) 搜索.lastIndex += 1;
        continue;
      }
      return true;
    }
  }
  return false;
}

