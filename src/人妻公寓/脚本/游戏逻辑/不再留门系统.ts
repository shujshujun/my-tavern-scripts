function 下一动作(data: SchemaType): 不再留门动作ID | null {
  const r = data.系统._不再留门;
  if (不再留门已完成(data)) return null;
  if (r.当前场景) return '继续现场';
  const 表: Partial<Record<路线['阶段'], 不再留门动作ID>> = {
    未开始: '使用道具',
    待目击: '观察街对面',
    可拍: r.可拍时段 === data.系统._绝对时段 ? '拍照' : '观察街对面',
    持有照片: '出示照片',
    待交付: '交付副本',
    待决定: '听她决定',
    待准备: r.设备位置 === '202' ? '开始录制' : '安装套件',
    待开录: '开始录制',
    待转存: '转存记录',
    待封存: '检查记录',
    待归档: '归档母带',
  };
  return 表[r.阶段] ?? null;
}

export function 不再留门动作阻断(data: SchemaType, 动作: 不再留门动作ID, 原地点: string): string {
  const 地点 = 地点规范(原地点);
  const r = data.系统._不再留门;
  if (动作 === '暂缓' || 动作 === '撤回许可') {
    if (!r.实例 || r.阶段 === '已完成') return '当前没有可暂停的本线现场。';
    if (r.阶段 === '录制中' && 动作 === '暂缓') return '请先使用普通场次的停止或收尾操作。';
    if (动作 === '撤回许可' && r.许可 !== '同意本次') return '当前没有已生效的录制许可。';
    return '';
  }
  if (动作 === '确认当前决定')
    return 本线正在前台(data) && 不再留门明确回应(data)
      ? 互斥错误(data, 地点, true) || 人物错误(data, 地点)
      : '请先处理当前前台剧情。';
  if (动作 === '使用道具' && !r.道具已使用 && r.当前场景 === 'A1' && data.背包.includes(不再留门任务ID)) {
    if (有普通场景剧情阻塞当前场景(data, 地点) && !本线正在前台(data)) return '请先处理当前前台剧情。';
    if (data.户['202']?.妻.当前阶段 < 5 || data.户['202']?.妻.阶段性癖 !== '独占印记') return '开场前置已经变化。';
    return 互斥错误(data, 地点, true) || 人物错误(data, 地点);
  }
  const 互斥 = 互斥错误(data, 地点);
  if (互斥) return 互斥;
  if (动作 !== 下一动作(data)) return '进度已经变化，请查看当前可做的一步。';
  if (!data.背包.includes(不再留门任务ID)) return '《不再留门》剧情道具不在背包中。';
  if (动作 === '归档母带') {
    if (地点 !== '302') return '请携带母带到302资料柜。';
    if (!记录有效(r) || r.母带.位置 !== '玩家背包' || !data.背包.includes(不再留门母带ID) || !r.照片.副本持有人)
      return '封存母带或照片交付凭据不完整。';
    return '';
  }
  const 外部 = 动作 === '观察街对面' || 动作 === '拍照' || (动作 === '继续现场' && r.当前场景 === 'A2');
  if (外部) {
    if (地点 !== '公寓外部') return '请到梧桐里公寓外。';
    return 目击窗口错误(data);
  }
  const 人物 = 人物错误(data, 地点);
  if (人物) return 人物;
  if (动作 === '使用道具') {
    if (r.道具已使用 || data.户['202'].妻.当前阶段 < 5 || data.户['202'].妻.阶段性癖 !== '独占印记')
      return '开场资格不符，或道具已在使用中。';
  }
  if (['出示照片', '交付副本', '听她决定'].includes(动作) && (!照片有效(r) || !data.背包.includes(不再留门照片ID)))
    return '照片原件凭据不完整。';
  if (动作 === '安装套件' && (r.设备位置 !== '背包' || !data.背包.includes(不再留门套件ID) || r.许可 !== '同意本次'))
    return '请先在商店购买便携录制套件。';
  if (动作 === '开始录制' || (动作 === '继续现场' && r.当前场景 === 'A7')) return 录制窗口错误(data);
  if (动作 === '转存记录' && (!记录有效(r) || r.记录.位置 !== '手机')) return '没有可转存的完整绑定记录。';
  if ((动作 === '检查记录' || (动作 === '继续现场' && r.当前场景 === 'A9')) && (!记录有效(r) || r.记录.位置 !== '介质'))
    return '先将这次完整记录转存到独立介质。';
  return '';
}

/** 只列当前位置的下一步；等待理由与档案、背包共用同一判定。 */
export function 不再留门地点动作(data: SchemaType, 原地点: string): 不再留门动作视图[] {
  const r = data.系统._不再留门;
  if (!r) return [];
  if (!r.道具已使用 && !data.背包.includes(不再留门任务ID)) return [];
  const 地点 = 地点规范(原地点);
  const 动作 = 下一动作(data);
  const 目标 = r.阶段 === '待归档' ? '302' : ['待目击', '目击中', '可拍'].includes(r.阶段) ? '公寓外部' : '202';
  const ids: 不再留门动作ID[] = [];
  if (动作 && 地点 === 目标 && !当前本线票(data)) ids.push(动作);
  if (当前本线票(data) && 地点 === 目标 && 不再留门明确回应(data)) ids.push('确认当前决定');
  if (当前本线票(data)) ids.push('暂缓');
  if (r.许可 === '同意本次' && r.阶段 !== '已完成' && 地点 === '202') ids.push('撤回许可');
  return ids.map(id => {
    const 原因 = 不再留门动作阻断(data, id, 地点);
    return { id, kicker: '不再留门', icon: 'camera', 文案: 标签[id], 可执行: !原因, 原因 };
  });
}

