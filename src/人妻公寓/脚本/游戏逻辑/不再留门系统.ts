export function 不再留门购买阻断(data: SchemaType): string {
  const h = data.户['202'];
  if (!h) return '202目前没有周小满。';
  if (h.妻.当前阶段 < 5 || h.妻.阶段性癖 !== '独占印记') return '周小满需达到L5并完成《独占印记》。';
  if (data.系统._坏结局 || h.夫._居住模式 !== '普通作息') return '202当前居住或结局状态不能开展这条承接。';
  if (丈夫登门需要处理(data, '202')) return '先完成已经排期的202丈夫登门事件。';
  const v = data.系统._录像带V4;
  if (
    v.录像带已使用 ||
    v.场景.场次标识 ||
    Object.values(v.赠锁).some(g => g.已接收) ||
    data.系统._已完成特殊场景.some(id => id === '录像带' || id === '录像带结局')
  )
    return '202已进入共享结局，请从既有进度继续。';
  if (不再留门已完成(data)) return '周小满母带已归档。';
  if (data.系统._不再留门.道具已使用) return '这条承接已在进行，请从当前断点继续。';
  if (data.背包.includes(不再留门任务ID)) return '《不再留门》已在背包中。';
  return '';
}

