function 参与者仍在场(项: 性爱参与项 | undefined): 项 is 性爱参与项 {
  return !!项 && 项.已退出 !== true;
}

function 读取参与者有效楼数(场景: 性爱场景账本, 项: 性爱参与项): number {
  const 原值 = Number(项.有效楼数);
  return Number.isFinite(原值) && 原值 >= 0 ? Math.floor(原值) : Math.max(0, Math.floor(场景.有效楼数));
}

/** 旧档只有全场楼数；第一次继续操作时把它冻结进每名既有参与者，之后再逐人累计。 */
function 规范参与者有效楼数(场景: 性爱场景账本): void {
  for (const 项 of Object.values(场景.参与者)) 项.有效楼数 = 读取参与者有效楼数(场景, 项);
}

function 活跃性爱参与者(场景: 性爱场景账本): 门牌[] {
  return (Object.keys(场景.参与者) as 门牌[]).filter(门牌号 => 参与者仍在场(场景.参与者[门牌号]));
}

/** 只读取得当前有效焦点，避免审计旧快照时为“规范化”反向修改基准。 */
function 读取性爱主焦点(场景: 性爱场景账本): 门牌 | null {
  const 活跃 = 活跃性爱参与者(场景);
  if (!活跃.length) return null;
  return 活跃.includes(场景.主焦点门牌 as 门牌) ? (场景.主焦点门牌 as 门牌) : 活跃[0];
}

