export interface 角色性爱结果判定 {
  时长评价: 性爱时长评价;
  结局态度: string;
}

export function 判定角色性爱结果(
  门牌号: 门牌,
  输入: { 满意度: number; 满意目标: number; 有效楼数: number; 结束方式: 性爱结束方式 },
): 角色性爱结果判定 {
  const 档案 = 角色性爱档案表[门牌号];
  const 最短 = Math.max(1, 输入.满意目标 + 档案.时长偏移.最短);
  const 最长 = Math.max(最短, 输入.满意目标 + 档案.时长偏移.最长);
  let 时长评价: 性爱时长评价;
  if (输入.结束方式 === '体力耗尽') 时长评价 = '失控';
  else if (输入.结束方式 === '突然离场') 时长评价 = '太短';
  else if (输入.结束方式 === '角色中止') 时长评价 = '太短';
  else if (输入.有效楼数 < 最短 || 输入.满意度 < 输入.满意目标) 时长评价 = '太短';
  else if (输入.有效楼数 > 最长) 时长评价 = '过久';
  else 时长评价 = '合适';

  const 结局态度 =
    输入.结束方式 === '突然离场'
      ? 档案.突然离场态度
      : 输入.结束方式 === '角色中止'
        ? 档案.角色中止态度
        : 档案.态度[时长评价];
  return { 时长评价, 结局态度 };
}

