    const 满体比例 = 开始体力 / Math.max(1, 资源上限(data, '体力'));
    const 本场等级加成 = 满体比例 >= 0.6 ? (等级 === 5 ? 2 : 等级 >= 3 ? 1 : 0) : 0;
