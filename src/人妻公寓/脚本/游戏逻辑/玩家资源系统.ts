function 角色明确中止(正文: string, 参与门牌: readonly 门牌[]): boolean {
  const 文本 = 正文.replace(/\s+/g, ' ');
  const 实名 = 参与门牌.map(门牌号 => 户静态表[门牌号]?.妻名).filter((名称): 名称 is string => !!名称);
  const 主语 = ['她', '对方', '妻子', '女人', '母亲', '妈妈', '妈', ...实名].map(转义正则文本).join('|');
  const 明确停止 = new RegExp(
    `(?:${主语})[^。！？\\n]{0,36}(?:推开(?:了)?(?:你|我)|制止(?:了)?(?:你|我)|喊停|要求(?:你|我)?(?:停下|停止)|(?:说|喊)[^。！？\\n]{0,12}(?:停下|住手|不要继续|不行)|(?:明确|坚决|直接)(?:地)?结束(?:了)?(?:这次|本次|当前)?(?:亲密互动|性行为))`,
  );
  const 全局拒绝 = new RegExp(
    `(?:${主语})[^。！？\\n]{0,32}(?:` +
      `(?:明确|坚决|直接)?拒绝(?:了)?(?:这次|本次)(?:亲密)?请求|` +
      `(?:明确|坚决|直接)?拒绝(?:了)?(?:你|我)?(?:继续)?(?:这次|本次|当前)?(?:亲密互动|性行为|做爱|性交)|` +
      `(?:明确|坚决|直接)?拒绝继续(?:下去)?(?=$|[，,；;])` +
      `)`,
  );
  const 请求继续 = /(?:不要|别|不许|不能|无需|不用)(?:再)?停(?:下|止)?/g;
  const 被否定的中止 =
    /(?:没有|并未|并没有|未曾|不曾|不再)(?:明确|坚决|直接|真的)?(?:拒绝(?:继续)?|推开(?:了)?(?:你|我)?|制止(?:了)?(?:你|我)?|喊停|要求(?:你|我)?停下|(?:说|喊)[^，。！？\n]{0,10}(?:停下|住手|不要继续|不行)|结束(?:了)?(?:这次|本次|当前)?(?:亲密互动|性行为))/g;

  // 否定只消除它直接修饰的动作，不能用一句“没有拒绝”吞掉后半句后来发生的喊停。
  return 文本
    .split(/[。！？\n]/)
    .map(句 => 句.replace(请求继续, '').replace(被否定的中止, ''))
    .some(句 => 明确停止.test(句) || 全局拒绝.test(句));
}

