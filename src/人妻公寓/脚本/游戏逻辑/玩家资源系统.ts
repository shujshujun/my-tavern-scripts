function 推断行为(文本: string, 旧行为: SchemaType['系统']['_性爱场景']['当前行为'], 行动文本?: string) {
  // 定向修正：玩具进入前穴/后穴必须先识别为“玩具”，不能让后面的“插入/后穴”词
  // 先把它抢记为阴茎插入；同时必须按片段配对，不能把主焦点的“阴道插入”和另一名
  // 角色的“拿起玩具”跨句拼成一次玩具插入。普通未插入玩具仍走 玩具/其他。
  const 玩具词 = /玩具|振动棒|按摩棒|假阳具|跳蛋|倒模/;
  const 进入词 = /插(?:入|进)|塞进|放进|送入|进入|捅进|弄进/;
  // 玩家行动是主焦点的权威行为证据：行动里的完整玩具插入片段即使排在口交/乳交等
  // 明确行为之后也必须判为“玩具”，不能因“首片段已有明确行为”被全文级插入正则
  // 抢记为阴茎插入。正文/本人片段仍走下方按片段配对的旧规则，避免把另一名角色的
  // 拿玩具或自插玩具写成主焦点行为。
  if (行动文本) {
    const 行动玩具进入 = 行动文本
      .split(/[。！？；;\n]/)
      .map(项 => 项.trim())
      .filter(Boolean)
      .find(项 => 玩具词.test(项) && 进入词.test(项));
    if (行动玩具进入) {
      if (/肛|屁穴|后穴|后庭|菊穴/.test(行动玩具进入)) return { 行为: '玩具' as const, 部位: '屁穴' as const };
      return { 行为: '玩具' as const, 部位: '小屄' as const };
    }
  }
  const 片段 = 文本
    .split(/[。！？；;\n]/)
    .map(项 => 项.trim())
    .filter(Boolean);
  const 首片段 = 片段[0] ?? '';
  const 首片段已有明确行为 =
    /肛交|肛门|屁穴|后庭|阴道|小穴|小屄|肉穴|插入|抽插|进入她|口交|含住|嘴里|吞吐|乳交|胸部|乳沟|双乳/.test(
      首片段,
    );
  const 玩具进入片段 = 片段.find(
    (项, index) => (index === 0 || !首片段已有明确行为) && 玩具词.test(项) && 进入词.test(项),
  );
  if (玩具进入片段) {
    if (/肛|屁穴|后穴|后庭|菊穴/.test(玩具进入片段)) return { 行为: '玩具' as const, 部位: '屁穴' as const };
    return { 行为: '玩具' as const, 部位: '小屄' as const };
  }
  if (/肛交|肛门|屁穴|后庭/.test(文本)) return { 行为: '肛门插入' as const, 部位: '屁穴' as const };
  if (/阴道|小穴|小屄|肉穴|插入|抽插|进入她/.test(文本)) return { 行为: '阴道插入' as const, 部位: '小屄' as const };
  if (/口交|含住|嘴里|吞吐/.test(文本)) return { 行为: '口交' as const, 部位: '嘴' as const };
  if (/乳交|胸部|乳沟|双乳/.test(文本)) return { 行为: '乳交' as const, 部位: '胸部' as const };
  if (/玩具|振动棒|按摩棒/.test(文本)) return { 行为: '玩具' as const, 部位: '其他' as const };
  if (/手交|摩擦|抚弄|爱抚/.test(文本)) return { 行为: '无插入' as const, 部位: '其他' as const };
  const 部位表 = {
    口交: '嘴',
    乳交: '胸部',
    阴道插入: '小屄',
    肛门插入: '屁穴',
    玩具: '其他',
    无插入: '无',
    其他: '其他',
  } as const;
  return { 行为: 旧行为, 部位: 部位表[旧行为] };
}

/**
 * 多人行动里只把主焦点本人相关或未点名的玩家动作交给主账本。明确只点到其他参与者的
 * 命令（含后续“自己”承接句）归对方，不能把她的玩具行为记到主焦点身上。
 */
function 提取主焦点行动片段(行动: string, 主焦点: 门牌 | null, 参与者: readonly 门牌[]): string {
  if (!主焦点 || 参与者.length <= 1) return 行动;
  const 主名 = 户静态表[主焦点]?.妻名;
  if (!主名) return 行动;
  const 其他名 = 参与者
    .filter(门牌号 => 门牌号 !== 主焦点)
    .map(门牌号 => 户静态表[门牌号]?.妻名)
    .filter((名称): 名称 is string => !!名称);
  let 当前归属: '主焦点' | '其他' | '未定' = '未定';
  const 保留: string[] = [];
  for (const 原片段 of 行动.split(/[，,。！？；;\n]/)) {
    const 片段 = 原片段.trim();
    if (!片段) continue;
    const 点到主焦点 = 片段.includes(主名);
    const 点到其他 = 其他名.some(名称 => 片段.includes(名称));
    if (点到主焦点) 当前归属 = '主焦点';
    else if (点到其他) 当前归属 = '其他';
    else if (/^(?:我|玩家|继续|随后我|然后我)/.test(片段)) 当前归属 = '主焦点';

    if (当前归属 === '其他' && !点到主焦点) continue;
    保留.push(片段);
  }
  return 保留.join('。');
}

