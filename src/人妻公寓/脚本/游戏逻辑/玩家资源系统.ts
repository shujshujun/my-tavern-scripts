function 夹取整数(值: number, 下限: number, 上限: number): number {
  return Math.min(上限, Math.max(下限, Math.round(Number.isFinite(值) ? 值 : 下限)));
}

export function 玩家当前日(data: SchemaType): number {
  return Math.floor(data.系统._绝对时段 / 6) + 1;
}

export function 资源等级(训练经验: number): 1 | 2 | 3 | 4 | 5 {
  for (let 等级 = 5; 等级 >= 2; 等级 -= 1) {
    if (训练经验 >= 资源等级门槛[等级]) return 等级 as 2 | 3 | 4 | 5;
  }
  return 1;
}

export function 资源上限(data: SchemaType, 种类: 资源种类): number {
  const 资源 = data.玩家资源[种类];
  const 等级 = 资源等级(资源.训练经验);
  const 基础 = 种类 === '精力' ? 精力等级上限[等级] : 体力等级上限[等级];
  return 基础 + 资源.永久上限加成;
}

export function 距离下级经验(训练经验: number): { 等级: number; 当前: number; 下级门槛: number | null } {
  const 等级 = 资源等级(训练经验);
  return { 等级, 当前: 训练经验, 下级门槛: 等级 >= 5 ? null : 资源等级门槛[等级 + 1] };
}

/** 防手改、坏数据与等级下降污染；调用不会凭空补充资源。 */
export function 规范玩家资源(data: SchemaType): void {
  data.玩家资源.精力.当前值 = 夹取整数(data.玩家资源.精力.当前值, 0, 资源上限(data, '精力'));
  data.玩家资源.体力.当前值 = 夹取整数(data.玩家资源.体力.当前值, 0, 资源上限(data, '体力'));
}

export function 完全恢复玩家资源(data: SchemaType): void {
  data.玩家资源.精力.当前值 = 资源上限(data, '精力');
  data.玩家资源.体力.当前值 = 资源上限(data, '体力');
}

export function 玩家资源已满(data: SchemaType): boolean {
  return data.玩家资源.精力.当前值 >= 资源上限(data, '精力') && data.玩家资源.体力.当前值 >= 资源上限(data, '体力');
}

function 恢复但不回满(data: SchemaType, 种类: 资源种类, 数量: number): number {
  const 资源 = data.玩家资源[种类];
  const 上限 = 资源上限(data, 种类);
  const 原值 = 资源.当前值;
  资源.当前值 = Math.min(Math.max(0, 上限 - 1), 原值 + Math.max(0, Math.round(数量)));
  return 资源.当前值 - 原值;
}

export function 校验玩家时间活动(data: SchemaType, 活动: 玩家时间活动, 地点: string): { 成功: boolean; 提示: string } {
  const 今日 = 玩家当前日(data);
  if (活动 === '晨跑') {
    if (地点 !== '晨跑公园') return { 成功: false, 提示: '先到晨跑公园再开始训练。' };
    if (data.系统._绝对时段 % 6 !== 0) return { 成功: false, 提示: '晨跑只在早上开放。' };
    if (data.玩家资源._晨跑训练日 === 今日) return { 成功: false, 提示: '今天已经晨跑过了。' };
  }
  if (活动 === '健身') {
    if (地点 !== '健身房') return { 成功: false, 提示: '先进入健身房再开始锻炼。' };
    if (data.玩家资源._体力训练日 === 今日) return { 成功: false, 提示: '今天的常规体力训练收益已经取得。' };
  }
  if (活动 === '小憩') {
    if (地点 !== '管理员室' && 地点 !== '302') return { 成功: false, 提示: '只能在管理员室或 302 小憩。' };
    if (data.玩家资源._小憩日 === 今日) return { 成功: false, 提示: '今天已经小憩过一次了。' };
    const 精力可回 = data.玩家资源.精力.当前值 < Math.max(0, 资源上限(data, '精力') - 1);
    const 体力可回 = data.玩家资源.体力.当前值 < Math.max(0, 资源上限(data, '体力') - 1);
    if (!精力可回 && !体力可回) return { 成功: false, 提示: '现在不需要小憩；真正睡一觉才能完全回满。' };
  }
  return { 成功: true, 提示: '' };
}

/** 时间已经由中央事务推进后再结算，失败时整份候选会被丢弃。 */
export function 结算玩家时间活动(data: SchemaType, 活动: 玩家时间活动, 起始日: number): string {
  if (活动 === '晨跑') {
    data.玩家资源.精力.训练经验 += 1;
    data.玩家资源._晨跑训练日 = 起始日;
    return `晨跑完成：精力训练经验 +1（当前 LV${资源等级(data.玩家资源.精力.训练经验)}）。`;
  }
  if (活动 === '健身') {
    data.玩家资源.体力.训练经验 += 1;
    data.玩家资源._体力训练日 = 起始日;
    return `健身完成：体力训练经验 +1（当前 LV${资源等级(data.玩家资源.体力.训练经验)}）。`;
  }
  const 精力恢复 = 恢复但不回满(data, '精力', Math.max(2, Math.ceil(资源上限(data, '精力') * 0.35)));
  const 体力恢复 = 恢复但不回满(data, '体力', 1);
  data.玩家资源._小憩日 = 起始日;
  return `小憩结束：精力 +${精力恢复}，体力 +${体力恢复}；完整恢复仍需睡到次日早晨。`;
}

/** 普通等待只恢复少量状态；小憩仍是更有效、每日一次的主动休息。 */
export function 结算普通等待恢复(data: SchemaType): string {
  const 精力恢复 = 恢复但不回满(data, '精力', 1);
  const 体力恢复 = 恢复但不回满(data, '体力', 1);
  return `这段空闲让你稍微缓了口气：精力 +${精力恢复}，体力 +${体力恢复}。`;
}

