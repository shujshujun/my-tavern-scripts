export function 默认失控位置(data: SchemaType): string {
  const 场景 = data.系统._性爱场景;
  if (场景.保护状态 === '安全套') return '安全套内';
  const 允许无保护体内 = 亲密主焦点阶段(data) >= 4;
  if (场景.当前行为 === '阴道插入') return 允许无保护体内 ? '小屄' : '体外';
  if (场景.当前行为 === '肛门插入') return 允许无保护体内 ? '后穴' : '体外';
  if (场景.当前行为 === '口交') return '小嘴';
  if (场景.当前行为 === '乳交') return '胸部';
  return 场景.当前接触部位 === '无' ? '体外' : `${场景.当前接触部位}附近`;
}

