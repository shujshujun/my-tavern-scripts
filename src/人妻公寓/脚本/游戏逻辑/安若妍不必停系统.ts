/**
 * 预约夜必须落在安若妍按当前硬状态真实位于301的夜间档；例如周三晚上她在天台，
 * 就顺延到同一夜的深夜，而不是让地图动作与剧情演员真值互相矛盾。
 */
function 最近可用301夜间(data: SchemaType, 起点: number): number {
  const 户 = data.户['301'];
  const start = Math.max(0, Math.floor(起点));
  for (let offset = 0; offset < 42; offset += 1) {
    const candidate = start + offset;
    if (!在晚上窗口(candidate)) continue;
    if (妻位置推算('301', candidate, 户) === '301') return candidate;
  }
  return start;
}

function 指定后续日预约夜(data: SchemaType, 绝对时段: number, 后续天数: number): number {
  return 最近可用301夜间(data, 指定后续日晚上(绝对时段, 后续天数));
}

