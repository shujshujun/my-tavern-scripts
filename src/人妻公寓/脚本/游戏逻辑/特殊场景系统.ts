export function 通过静音会议互动(
  data: SchemaType,
  载荷: { id?: unknown; 目标妻?: unknown; 模式?: unknown },
  使用补偿 = false,
): 特殊场景操作结果 {
  const 场 = data.系统._特殊场景;
  if (场.id !== '静音会议' || !['A', 'B', 'C'].includes(String(载荷.id ?? ''))) {
    return { 成功: false, 提示: '当前没有这项会议操作。' };
  }
  const id = String(载荷.id) as 静音会议互动ID;
  if (场.交互.id !== id) return { 成功: false, 提示: '控制步骤与当前会议拍不匹配。' };

  // AI 续拍失败后的重放：交互结果已经冻结，不重复改变目标、模式或失败计数。
  if (场.交互.状态 === '等待AI') {
    准备当前特殊场景节拍(data);
    return { 成功: true, 提示: '控制结果保持不变，正在重新生成固定续拍。' };
  }
  if (场.交互.状态 !== '待操作') return { 成功: false, 提示: '这项操作当前不能提交。' };
  if (使用补偿 && !场.交互.补偿可用) return { 成功: false, 提示: '还没有达到自动通过条件。' };

  if (id === 'B') {
    if (!是静音会议候选门牌(载荷.目标妻) || !场.参与妻.includes(载荷.目标妻)) {
      return { 成功: false, 提示: '请先选择一位本场参与妻作为第二档目标。' };
    }
    场.重点妻 = 载荷.目标妻;
  }
  if (id === 'C') {
    if (载荷.模式 !== '集中' && 载荷.模式 !== '同步') {
      return { 成功: false, 提示: '请选择“集中一人”或“全体同步”。' };
    }
    if (载荷.模式 === '集中' && !场.重点妻) {
      return { 成功: false, 提示: '集中模式缺少此前冻结的重点目标。' };
    }
    场.峰值模式 = 载荷.模式;
  }
  场.交互.状态 = '等待AI';
  准备当前特殊场景节拍(data);
  return { 成功: true, 提示: 使用补偿 ? '系统已自动完成操作。' : '控制信号已确认。' };
}

export function 请求结束静音会议(data: SchemaType): 特殊场景操作结果 {
  const 场 = data.系统._特殊场景;
  if (场.id !== '静音会议') return { 成功: false, 提示: '当前没有静音会议。' };
  if (场.阶段 === '收尾') {
    准备当前特殊场景节拍(data);
    return { 成功: true, 提示: '正在重新生成最终收尾。' };
  }
  if (!场.阶段.includes('自由') || 场.当前拍 < 15) {
    return { 成功: false, 提示: '至少完成第 15 拍后，才能主动结束本次会议。' };
  }
  const 待重试自由标记 = `【特殊场景·静音会议·自由·${场.自由循环次数 + 1}】`;
  if (data.系统._待发送事件.includes(待重试自由标记)) {
    // 自由拍生成失败后事件会保留以便原拍重试；玩家此时改选“结束”，必须撤销这条
    // 尚未成功的自由拍，否则第一次收尾请求会错误地再生成一轮会后内容。
    移除待发送节拍(data, 待重试自由标记);
  }
  场.阶段 = '收尾';
  场.交互 = { id: '', 类型: '', 状态: '', 失败次数: 0, 补偿可用: false };
  准备当前特殊场景节拍(data);
  return { 成功: true, 提示: '正在生成最终收尾；成功落地后才会结算和清场。' };
}

