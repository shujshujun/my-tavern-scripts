export function 推进特殊场景(data: SchemaType, 已演事件: string): void {
  const 场 = data.系统._特殊场景;
  if (!场.id) return;

  if (场.id === '静音会议') {
    const 固定 = 已演事件.match(/【特殊场景·静音会议·(\d{1,2})】/);
    const 自由 = 已演事件.match(/【特殊场景·静音会议·自由·(\d+)】/);
    const 收尾 = 已演事件.includes('【特殊场景·静音会议·收尾】');
    if (!固定 && !自由 && !收尾) return;

    // 标记与阶段必须双向匹配：尤其不能让重放/乱序的旧第 15 拍把“收尾”退回自由阶段。
    if (收尾) {
      if (场.阶段 !== '收尾') return;
    } else if (自由) {
      if (!场.阶段.includes('自由')) return;
    } else if (固定) {
      const 拍 = Number(固定[1]);
      const 阶段匹配 =
        (场.阶段 === '正文' && 拍 >= 1 && 拍 <= 11) ||
        (场.阶段 === '散会选择' && 拍 === 12) ||
        (场.阶段 === '会后' && 拍 >= 13 && 拍 <= 15);
      if (!阶段匹配) return;
    }
    if (
      自由 &&
      (场.当前拍 !== 15 || Number(自由[1]) !== 场.自由循环次数 + 1)
    ) {
      return;
    }
    if (固定 && Number(固定[1]) !== 场.当前拍) return;

    // 摘要只供紧邻的下一条成功正文使用；失败时本函数不会运行，因而自然保留。
    场.会场私聊摘要 = {};
    场.会场私聊摘要楼层 = -1;

    if (收尾) {
      const 原参与 = [...场.参与妻].filter(是静音会议候选门牌);
      for (const 门牌号 of 原参与) {
        const 妻 = data.户[门牌号]?.妻;
        if (妻) {
          登记脚本正增长候选(data, 门牌号, '堕落值');
          妻.堕落值 = Math.min(100, 妻.堕落值 + 2);
        }
      }
      if (!data.系统._已完成特殊场景.includes('静音会议')) {
        data.系统._已完成特殊场景.push('静音会议');
      }
      清空特殊场景(data);
      return;
    }

    if (自由) {
      场.自由循环次数 += 1;
      return;
    }

    const 拍 = Number(固定![1]);
    const 清互动 = () => {
      场.交互 = { id: '', 类型: '', 状态: '', 失败次数: 0, 补偿可用: false };
    };
    switch (拍) {
      case 1:
      case 2:
        场.阶段 = '正文';
        场.当前拍 = 拍 + 1;
        break;
      case 3:
        场.阶段 = '正文';
        场.当前拍 = 4;
        场.交互 = { id: 'A', 类型: '单击', 状态: '待操作', 失败次数: 0, 补偿可用: false };
        break;
      case 4:
      case 5:
      case 6:
        清互动();
        场.阶段 = '正文';
        场.当前拍 = 拍 + 1;
        break;
      case 7:
        场.阶段 = '正文';
        场.当前拍 = 8;
        场.交互 = { id: 'B', 类型: '长按', 状态: '待操作', 失败次数: 0, 补偿可用: false };
        break;
      case 8:
      case 9:
        清互动();
        场.阶段 = '正文';
        场.当前拍 = 拍 + 1;
        break;
      case 10:
        场.阶段 = '正文';
        场.当前拍 = 11;
        场.交互 = { id: 'C', 类型: '连点', 状态: '待操作', 失败次数: 0, 补偿可用: false };
        break;
      case 11:
        清互动();
        场.阶段 = '散会选择';
        场.当前拍 = 12;
        break;
      case 12:
        清互动();
        场.阶段 = '会后';
        场.当前拍 = 13;
        场.演出妻 = [...场.会后妻];
        场.演出夫 = [];
        break;
      case 13:
      case 14:
        场.阶段 = '会后';
        场.当前拍 = 拍 + 1;
        break;
      case 15:
        场.阶段 = '自由';
        场.当前拍 = 15;
        场.自由循环次数 = 0;
        break;
    }
    return;
  }

  const 前置 = 已演事件.match(/【特殊前置·录像带·(102|202)·([12])】/);
  if (场.id === '录像带前置' && 前置) {
    const 门牌号 = 前置[1] as '102' | '202';
    const 拍 = Number(前置[2]);
    if (场.阶段 !== `${门牌号}-${拍}`) return;
    if (拍 === 1) {
      场.阶段 = `${门牌号}-2`;
    } else {
      const 键 = 录像带前置键(门牌号);
      if (!data.系统._特殊场景前置.includes(键)) data.系统._特殊场景前置.push(键);
      清空特殊场景(data);
    }
    return;
  }

  const 正式 = 已演事件.match(/【特殊场景·录像带·(102|202)-([123])】/);
  if (场.id !== '录像带' || !正式) return;
  const 房 = 正式[1] as '102' | '202';
  const 拍 = Number(正式[2]);
  if (场.阶段 !== `${房}-${拍}`) return;
  if (房 === '102' && 拍 < 3) 场.阶段 = `102-${拍 + 1}`;
  else if (房 === '102') 场.阶段 = '等待202';
  else if (拍 < 3) 场.阶段 = `202-${拍 + 1}`;
  else {
    for (const 门牌号 of ['102', '202'] as const) {
      const 妻 = data.户[门牌号]?.妻;
      if (妻) {
        登记脚本正增长候选(data, 门牌号, '堕落值');
        妻.堕落值 = Math.min(100, 妻.堕落值 + 2);
      }
    }
    if (!data.系统._已完成特殊场景.includes('录像带')) data.系统._已完成特殊场景.push('录像带');
    清空特殊场景(data);
  }
}
