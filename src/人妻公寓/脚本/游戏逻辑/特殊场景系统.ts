export function 启动静音会议(
  data: SchemaType,
  原参与妻: unknown,
  原议题: unknown,
  当前地点: string,
  当前楼层: number,
): 特殊场景操作结果 {
  const 场 = data.系统._特殊场景;
  const 亲密阻断 = 特殊场景启动亲密门(data);
  if (亲密阻断) return { 成功: false, 提示: 亲密阻断 };
  if (场.id !== '静音会议' || 场.阶段 !== '筹备') {
    return { 成功: false, 提示: '请先从背包打开静音会议筹备表。' };
  }
  if (当前地点 !== '管理员室') return { 成功: false, 提示: '会议只能从管理员室开始。' };
  if (data.系统._待发送事件) return { 成功: false, 提示: '眼下还有一段剧情没有演完。' };
  if (data.系统._已完成特殊场景.includes('静音会议')) {
    return { 成功: false, 提示: '这场静音会议已经完成过了。' };
  }
  const 票位 = data.背包.indexOf('静音会议');
  if (票位 < 0) return { 成功: false, 提示: '会议票已经不在背包里。' };
  const 参与妻 = 规范静音会议妻名单(原参与妻);
  if (!参与妻 || 参与妻.length < 2 || 参与妻.length > 3) {
    return { 成功: false, 提示: '必须亲自选择 2—3 位不同的候选妻。' };
  }
  const 合资格 = new Set(静音会议合资格妻(data));
  if (!参与妻.every(门牌号 => 合资格.has(门牌号))) {
    return { 成功: false, 提示: '候选资格已经变化，请返回重新选择。' };
  }
  if (typeof 原议题 !== 'string' || !(静音会议议题 as readonly string[]).includes(原议题)) {
    return { 成功: false, 提示: '请选择一项真实的楼务会议议题。' };
  }

  // 只有最终确认通过后才消耗票；启动楼层指向即将创建的第一条场景用户楼。
  data.背包.splice(票位, 1);
  data.系统._特殊场景 = {
    ...空特殊场景状态(),
    id: '静音会议',
    阶段: '正文',
    地点: '管理员室',
    参与妻: [...参与妻],
    演出妻: [...参与妻],
    演出夫: [...参与妻],
    启动楼层: Math.max(0, Math.round(当前楼层) + 1),
    当前拍: 1,
    议题: 原议题,
  };
  准备当前特殊场景节拍(data);
  return { 成功: true, 提示: '通知已经发出，所选夫妻正陆续进入管理员室。' };
}

export function 静音会议玩家行动许可(data: SchemaType): 特殊场景操作结果 {
  const 场 = data.系统._特殊场景;
  if (场.id !== '静音会议' || 场.阶段 === '筹备') {
    return { 成功: true, 提示: '' };
  }
  if (场.交互.状态 === '待操作') return { 成功: false, 提示: '请先完成当前会议控制操作。' };
  if (场.交互.状态 === '等待AI') return { 成功: false, 提示: '请先重新生成交互后的固定续拍。' };
  if (场.阶段 === '收尾') return { 成功: false, 提示: '最终收尾尚未成功，请使用收尾重试按钮。' };
  if (场.阶段 === '散会选择' || 场.当前拍 === 12) {
    return { 成功: false, 提示: '第 12 拍必须先选择会后留下的妻子。' };
  }
  if (场.阶段 === '正文') {
    // 第 1 拍正常由确认按钮自动发起；若生成失败，保留的固定事件允许玩家从输入框重试。
    const 自由拍 = [1, 2, 3, 5, 6, 7, 9, 10] as const;
    return 自由拍.includes(场.当前拍 as (typeof 自由拍)[number])
      ? { 成功: true, 提示: '' }
      : { 成功: false, 提示: '这一拍由固定轨道自动续写，不能另发普通行动。' };
  }
  if (场.阶段 === '会后' && 场.当前拍 >= 13 && 场.当前拍 <= 15) {
    return { 成功: true, 提示: '' };
  }
  if (场.阶段.includes('自由') && 场.当前拍 >= 15) return { 成功: true, 提示: '' };
  return { 成功: false, 提示: '当前静音会议状态不能提交普通行动。' };
}

