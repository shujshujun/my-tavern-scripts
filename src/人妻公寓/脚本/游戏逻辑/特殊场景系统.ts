/** `_待发送事件` 是 `|` 分隔的稳定队列；特殊场景只能替换自己的精确节拍。 */
function 读待发送事件队列(data: SchemaType): string[] {
  return String(data.系统._待发送事件 ?? '')
    .split('|')
    .filter(Boolean);
}

function 写待发送事件队列(data: SchemaType, 队列: string[]): void {
  data.系统._待发送事件 = 队列.filter(Boolean).join('|');
}

function 移除待发送节拍(data: SchemaType, 精确标记: string): void {
  写待发送事件队列(
    data,
    读待发送事件队列(data).filter(事件 => !事件.includes(精确标记)),
  );
}

function 追加待发送节拍(data: SchemaType, 精确标记: string, 正文: string): void {
  const 队列 = 读待发送事件队列(data);
  if (队列.some(事件 => 事件.includes(精确标记))) return;
  队列.push(正文);
  写待发送事件队列(data, 队列);
}

function 是静音会议候选门牌(值: unknown): 值 is 静音会议候选门牌 {
  return typeof 值 === 'string' && 静音会议候选门牌顺序.includes(值 as 静音会议候选门牌);
}

function 规范静音会议妻名单(原值: unknown): 静音会议候选门牌[] | null {
  if (!Array.isArray(原值) || 原值.length < 1) return null;
  const 门牌们 = 原值.filter(是静音会议候选门牌);
  if (门牌们.length !== 原值.length || new Set(门牌们).size !== 门牌们.length) return null;
  return [...门牌们].sort(
    (左, 右) => 静音会议候选门牌顺序.indexOf(左) - 静音会议候选门牌顺序.indexOf(右),
  );
}

export function 静音会议合资格妻(data: SchemaType): 静音会议候选门牌[] {
  return 静音会议候选门牌顺序.filter(门牌号 => {
    const 妻 = data.户[门牌号]?.妻;
    return !!妻 && 妻.当前阶段 >= 4 && 妻.特殊.some(项 => 项.includes('遥控跳蛋'));
  });
}

export function 静音会议正式运行中(data: SchemaType): boolean {
  const 场 = data.系统._特殊场景;
  return 场.id === '静音会议' && 场.阶段 !== '筹备';
}

