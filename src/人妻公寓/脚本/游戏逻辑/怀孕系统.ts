/** 每名角色固定一个易孕日；周日留空，避免六人的窗口完全重叠。 */
export const 易孕星期表: Readonly<Record<门牌, 星期名>> = {
  '101': '星期一',
  '102': '星期二',
  '201': '星期三',
  '202': '星期四',
  '301': '星期五',
  '302': '星期六',
};

export const 受孕概率阶梯 = [0.6, 0.8, 1] as const;
export const 怀孕告知延迟时段 = 每周时段数;

export interface 受孕判定输入 {
  场次标识: string;
  结束方式: string;
  最终位置: string;
  收尾对象门牌: string;
  保护状态: string;
  当前行为: string;
}

export type 受孕判定结果 = '不符合' | '非易孕日' | '今日已判定' | '未受孕' | '已受孕';

function 是门牌(value: string): value is 门牌 {
  return 门牌列表.includes(value as 门牌);
}

/** 只在普通玩家亲密场景真实收尾后调用；不输出提示，确保受孕后一周完全隐藏。 */
export function 判定受孕(data: SchemaType, 输入: 受孕判定输入): 受孕判定结果 {
  const 门牌号 = 输入.收尾对象门牌;
  if (
    !输入.场次标识 ||
    !是门牌(门牌号) ||
    (输入.结束方式 !== '主动收尾' && 输入.结束方式 !== '体力耗尽') ||
    输入.最终位置 !== '小屄' ||
    输入.保护状态 !== '未使用' ||
    输入.当前行为 !== '阴道插入'
  ) {
    return '不符合';
  }

  const 妻 = data.户[门牌号]?.妻;
  if (!妻 || 妻.当前阶段 < 3 || 妻._怀孕.状态 !== '未孕') return '不符合';
  if (当前星期(data) !== 易孕星期表[门牌号]) return '非易孕日';

  const 时间 = 读取世界时间(data);
  if (妻._怀孕.上次判定日 === 时间.天数) return '今日已判定';
  妻._怀孕.上次判定日 = 时间.天数;

  const 失败次数 = Math.min(2, Math.max(0, 妻._怀孕.连续未中次数));
  const 概率 = 受孕概率阶梯[失败次数];
  const 命中 = seededRandom('怀孕', 输入.场次标识, 门牌号, 时间.天数) < 概率;
  if (!命中) {
    妻._怀孕.连续未中次数 = Math.min(2, 失败次数 + 1);
    return '未受孕';
  }

  妻._怀孕 = {
    状态: '已受孕',
    受孕绝对时段: 时间.绝对时段,
    预计告知绝对时段: 时间.绝对时段 + 怀孕告知延迟时段,
    告知绝对时段: -1,
    受孕场次标识: 输入.场次标识,
    上次判定日: 时间.天数,
    连续未中次数: 0,
    告知文案: '',
    已曝光: false,
    丈夫登门: {
      状态: '无',
      排期绝对时段: -1,
      变体标识: '',
      当前拍: 0,
      隐藏圆场: false,
      已结算: false,
    },
  };
  return '已受孕';
}

/** 告知文案在一周期满时按当时关系冻结；之后数值变化不得改写已经发出的消息。 */
export function 编译怀孕告知文案(data: SchemaType, 门牌号: 门牌): string {
  const 节点 = data.户[门牌号];
  if (!节点) return '';
  const { 妻, 夫 } = 节点;

  const 阶段句 =
    妻.当前阶段 <= 3
      ? '我反复确认过了……我怀孕了。现在脑子很乱，你先别过来。'
      : 妻.当前阶段 === 4
        ? '我反复确认过了，是怀孕。我很害怕，但不想一个人扛着，想先告诉你。'
        : '结果已经确认，我怀孕了。我想清楚了一些事，接下来需要和你认真谈谈。';

  const 关系句 =
    妻.好感值 < 40
      ? '我还不知道该不该完全相信你，所以先别替我做决定。'
      : 妻.好感值 >= 70 && 妻.堕落值 >= 65
        ? '我第一时间想到的人还是你，这件事我希望我们一起面对。'
        : 妻.堕落值 >= 75
          ? '我没有把那天当成错误，只是事情来得比想象中更快。'
          : '你先听我把话说完，别急着给答案。';

  const 风险句 =
    data.风闻 >= 风闻阈值.盯防
      ? '楼里的风声已经不对了，这条消息也未必还只在我们之间。'
      : 夫.疑心值 >= 70
        ? `${户静态表[门牌号].夫名 || '他'}最近已经在留意我，我们说话必须更小心。`
        : 妻.婚姻值 >= 70
          ? `一想到${户静态表[门牌号].夫名 || '他'}，我就不知道该怎么开口。`
          : 夫.信任值 >= 70
            ? `${户静态表[门牌号].夫名 || '他'}那么信任你，反而让我更不安。`
            : 妻.婚姻值 <= 30
              ? '我和他的关系早就回不到从前，这一次我不想再逃避。'
              : '这件事现在只能先由我们两个人知道。';

  return `${阶段句}${关系句}${风险句}`.slice(0, 150);
}

export interface 怀孕送达凭据 {
  门牌: 门牌;
  场次标识: string;
}

export function 怀孕微信键(门牌号: 门牌, 场次标识: string): string {
  return `怀孕:${门牌号}:${场次标识}`;
}

export function 列出待告知孕情(data: SchemaType): 怀孕送达凭据[] {
  return (Object.keys(data.户) as 门牌[]).flatMap(门牌号 => {
    const 账 = data.户[门牌号]?.妻._怀孕;
    return 账?.状态 === '待告知' && 账.受孕场次标识 ? [{ 门牌: 门牌号, 场次标识: 账.受孕场次标识 }] : [];
  });
}

/** 时间事务只把状态推进到待告知；立绘、头像与 AI 认知仍保持隐藏，直到微信真正落库。 */
export function 推进怀孕告知(data: SchemaType): 门牌[] {
  const 当前绝对时段 = 读取世界时间(data).绝对时段;
  const 到期: 门牌[] = [];
  for (const 门牌号 of Object.keys(data.户) as 门牌[]) {
    const 妻 = data.户[门牌号]?.妻;
    if (!妻 || 妻._怀孕.状态 !== '已受孕' || 当前绝对时段 < 妻._怀孕.预计告知绝对时段) continue;
    妻._怀孕.状态 = '待告知';
    妻._怀孕.告知文案 = 编译怀孕告知文案(data, 门牌号);
    到期.push(门牌号);

    // 盯防档代表私密关系已经处于公开调查边缘。孕情到期会形成不可辩驳的硬证据，
    // 把风闻推入既有 100 点危机，再由原有父亲来电、胜任通牒和坏结局链统一收口。
    if (data.风闻 >= 风闻阈值.盯防) {
      妻._怀孕.已曝光 = true;
      登记风闻事件(data, {
        id: `怀孕曝光:${门牌号}:${妻._怀孕.受孕场次标识}`,
        类型: '怀孕曝光',
        目标增量: 100,
        门牌: 门牌号,
        地点: `${门牌号}室`,
        摘要: `${户静态表[门牌号].妻名}的怀孕消息成为公开关系证据`,
        迹象: '硬证据',
        投诉: '严重',
      });
    }
  }
  return 到期;
}

/** 手机消息已经存在于当前分支后才公开状态；重复确认与过期凭据均无副作用。 */
export function 确认怀孕微信已送达(data: SchemaType, 凭据们: readonly 怀孕送达凭据[]): 门牌[] {
  const 已确认: 门牌[] = [];
  for (const 凭据 of 凭据们) {
    if (!是门牌(凭据.门牌)) continue;
    const 账 = data.户[凭据.门牌]?.妻._怀孕;
    if (!账 || 账.状态 !== '待告知' || 账.受孕场次标识 !== 凭据.场次标识) continue;
    账.状态 = '已告知';
    账.告知绝对时段 = 读取世界时间(data).绝对时段;
    已确认.push(凭据.门牌);
  }
  if (已确认.length) 同步丈夫登门排期(data);
  return 已确认;
}

/** 所有表现层与 AI 感知只能调用这一口，避免隐藏期从任一支路泄露。 */
export function 怀孕已公开(data: SchemaType, 门牌号: 门牌): boolean {
  return data.户[门牌号]?.妻._怀孕.状态 === '已告知';
}

export interface 孕情初见配对 {
  观察者: 门牌;
  孕妇: 门牌;
  键: string;
}

export interface 孕情初见计划 {
  配对: 孕情初见配对[];
  提示: string;
}

const 孕情初见提交票正则 = /【孕情初见提交票\|([^】]+)】/u;

function 孕情初见配对键(data: SchemaType, 观察者: 门牌, 孕妇: 门牌): string {
  const 场次标识 = data.户[孕妇]?.妻._怀孕.受孕场次标识 ?? '';
  return `${观察者}>${孕妇}>${encodeURIComponent(场次标识)}`;
}

function 已完成孕情初见(data: SchemaType, 键: string, 当前楼层: number): boolean {
  const 成功楼 = data.系统._孕情初见评价楼[键];
  // 同楼 swipe/重掷必须重放同一提示；只有进入后续楼，才把这张票视为已经消费。
  return Number.isFinite(成功楼) && 成功楼 >= 0 && 成功楼 < 当前楼层;
}

/**
 * 普通正文的软上下文：未孕或自身孕情已公开的在场角色，只在第一次当面看见某一次已公开孕情时评价。
 * “已受孕/待告知”仍处于隐藏生命周期，既不能作为孕妇目标，也不能以孕妇身份参与评价。
 * 姐妹群是否已聊过由手机数据层传入；这里不读取手机库，保持配对与消费规则可独立测试。
 */
export function 规划孕情初见(
  data: SchemaType,
  在场妻: readonly 门牌[],
  当前楼层: number,
  姐妹群已聊过: (孕妇: 门牌, 场次标识: string) => boolean = () => false,
): 孕情初见计划 {
  const 在场 = [...new Set(在场妻)].filter(门牌号 => !!data.户[门牌号]);
  if (在场.length < 2) return { 配对: [], 提示: '' };

  const 孕妇们 = 在场.filter(门牌号 => {
    const 账 = data.户[门牌号].妻._怀孕;
    return 怀孕已公开(data, 门牌号) && !!账.受孕场次标识 && !姐妹群已聊过(门牌号, 账.受孕场次标识);
  });
  const 观察者们 = 在场.filter(门牌号 => {
    const 状态 = data.户[门牌号].妻._怀孕.状态;
    return 状态 === '未孕' || 状态 === '已告知';
  });
  const 配对 = 观察者们.flatMap(观察者 =>
    孕妇们.flatMap(孕妇 => {
      if (观察者 === 孕妇) return [];
      const 键 = 孕情初见配对键(data, 观察者, 孕妇);
      return 已完成孕情初见(data, 键, 当前楼层) ? [] : [{ 观察者, 孕妇, 键 }];
    }),
  );
  if (!配对.length) return { 配对: [], 提示: '' };

  const 画像 = 配对.map(({ 观察者, 孕妇 }) => {
    const 妻 = data.户[观察者].妻;
    const 配 = 户静态表[观察者];
    const 自身孕情 = 妻._怀孕.状态 === '已告知' ? '自身孕情也已公开' : '自身未孕';
    return (
      `- ${配.妻名} → ${户静态表[孕妇].妻名}：` +
      `观察者处于阶段${妻.当前阶段}「${阶段标题(妻.当前阶段, 观察者)}」，` +
      `好感${妻.好感值}、堕落${妻.堕落值}、婚姻${妻.婚姻值}；` +
      `${自身孕情}；性格与说话底色:${配.初始?.气质描述 ?? '沿用既有人设'}；` +
      `群体互动习惯:${配.雌竞 ?? '按既有人设'}。`
    );
  });
  const 票 = 配对.map(({ 键 }) => encodeURIComponent(键)).join(',');
  return {
    配对,
    提示: [
      '【孕情初见·一次性现场反应】',
      '这是下列角色第一次当面看见对应角色已经明显怀孕。她们通过眼前的孕肚现场得知，属于“亲眼看见”的认知，不受此前“其他人不得凭空知道”限制。',
      ...画像,
      '本轮正文中，每名观察者都必须主动、自然地对对应孕妇提起并评价一次，至少有一句直接面向她的台词，不能只用旁白带过。具体是祝福、关切、惊讶、羡慕、酸涩、警惕还是调侃，必须按观察者自己的当前阶段、三项数值强弱、性格和既有关系判断；不得把所有人写成同一种反应。',
      '若观察者自己也已公开怀孕，可按她的性格表现同感、比较、关心、提醒或玩笑，但不得捏造双方的孕周、检查结果或身体症状。数值与阶段只作表演依据，正文不得念出数字、阶段名、系统或提示词。不得借机泄露受孕经过、孩子父亲或其他未公开事实；孕妇可按自身状态回应，但不得让不在上述配对中的角色凭空知情。此反应只服务当前现场，不得挤掉本轮原有主线行动。',
      `【孕情初见提交票|${票}】`,
    ].join('\n'),
  };
}

export function 提取孕情初见提交票(提示: string): string[] {
  const 原 = 提示.match(孕情初见提交票正则)?.[1] ?? '';
  if (!原) return [];
  return [...new Set(原.split(',').flatMap(项 => {
    try {
      return [decodeURIComponent(项)];
    } catch {
      return [];
    }
  }))];
}

/** 只在有效正文即将提交时调用；失败、取消与空正文没有提交点，因此不会提前消耗。 */
export function 提交孕情初见评价(data: SchemaType, 已注入提示: string, 楼层: number): string[] {
  const 已提交: string[] = [];
  for (const 键 of 提取孕情初见提交票(已注入提示)) {
    const 匹配 = 键.match(/^(\d{3})>(\d{3})>(.+)$/u);
    if (!匹配 || !是门牌(匹配[1]) || !是门牌(匹配[2])) continue;
    const [, 观察者, 孕妇] = 匹配;
    if (!data.户[观察者] || !data.户[孕妇] || 孕情初见配对键(data, 观察者, 孕妇) !== 键) continue;
    data.系统._孕情初见评价楼[键] = 楼层;
    已提交.push(键);
  }
  return 已提交;
}

function 已当面知情角色(data: SchemaType, 孕妇: 门牌, 当前楼层: number): string[] {
  const 场次后缀 = `>${孕妇}>${encodeURIComponent(data.户[孕妇]?.妻._怀孕.受孕场次标识 ?? '')}`;
  return Object.entries(data.系统._孕情初见评价楼).flatMap(([键, 成功楼]) => {
    if (!键.endsWith(场次后缀) || !Number.isFinite(成功楼) || 成功楼 < 0 || 成功楼 >= 当前楼层) return [];
    const 观察者 = 键.slice(0, 3);
    return 是门牌(观察者) && data.户[观察者] ? [户静态表[观察者].妻名] : [];
  });
}

/** 给正文/手机 AI 的唯一孕情认知语；从不暴露受孕日、易孕日或内部状态名。 */
export function 怀孕认知提示(data: SchemaType, 门牌号: 门牌, 当前楼层 = Number.POSITIVE_INFINITY): string {
  if (!怀孕已公开(data, 门牌号)) return '';
  const 已曝光 = data.户[门牌号]?.妻._怀孕.已曝光 === true;
  if (已曝光) return '她已经确认怀孕并告诉了{{user}}；这件事又成为楼内调查中的硬证据，不能再当作只有两人知道。';
  const 当面知情 = [...new Set(已当面知情角色(data, 门牌号, 当前楼层))];
  return 当面知情.length
    ? `她已经确认怀孕并通过微信告诉了{{user}}；${当面知情.join('、')}此前已当面看见孕肚并明确知情，除此之外丈夫与其他人不得凭空知道。`
    : '她已经确认怀孕并通过微信告诉了{{user}}；目前只有她和{{user}}明确知情，丈夫与其他人不得凭空知道。';
}
