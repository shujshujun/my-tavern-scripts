// ============================================

export function 读信揭晓(data: SchemaType, 门牌号: 门牌): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  if (!节点 || !配) return { 提示: '没有可读的东西。' };
  if (节点.妻.裂缝.碎片进度 < 4) return { 提示: '线索还没凑齐。' };
  if (节点.妻.裂缝.已确认) return { 提示: '你已经读过了。' };
  节点.妻.裂缝.已确认 = true;
  const 提交镜像 = () => 镜像直写(门牌号, { 裂缝确认: true });
  const 妻名 = 户静态表[门牌号].妻名;
  // 揭晓物是一次性的拼合成果：读完即归档，不再占背包格。
  const 揭晓物 = new Set(['拼合的信', '观察笔记', '考古辑录', '街坊札记', '酒后真言'].map(名 => `${名}·${妻名}`));
  data.背包 = data.背包.filter(id => !揭晓物.has(id));
  return {
    提示: `${妻名}的裂缝,你看清了。`,
    事件: `【心照不宣】{{user}}已经看清了${妻名}生活里的裂缝(他自己拼出来的,她并不知情)。从本楼起你(AI)也知道了她的隐痛(见快照),演出照旧克制:她不知道他知道,他也不会说破`,
    碎片到手: true,
    提交后: 提交镜像,
  };
}

