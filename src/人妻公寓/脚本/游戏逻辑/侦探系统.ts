function 监控稳定短签名(text: string): string {
  let hash = 0x811c9dc5;
  for (const 字符 of text) {
    hash ^= 字符.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
}

