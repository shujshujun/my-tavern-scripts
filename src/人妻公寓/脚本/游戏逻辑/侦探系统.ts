/**
 * 侦探系统(P2:翻垃圾+摄像头两渠道;打听/丈夫/动态广场留接口归 P5)
 *
 * 硬门(spec 拍板):每户只吃专属渠道,错渠道 100% 无产出;
 * 错渠道刷 2~3 次后给死路风味提示——解谜的死路必须可识别。
 * 4 张碎片全部由专属渠道产出;集齐=信自动拼合,读信=揭晓时刻(玩家动作,有仪式感)。
 *
 * 软计数(死路次数/垃圾软保底/偷窥冷却)存 chat 变量 `_侦探`:
 * 回档丢了也无害(碎片进度本账在 stat_data.裂缝 + 晋阶镜像里,防重roll打回)。
 */

// 〔调参〕
const 垃圾出货概率 = 0.7; // 2026-07-18 用户拍板 0.45→0.7(碎片而已,不该太非酋);测试期曾临时 1.0
const 垃圾软保底次数 = 2; // 连续 N 次空手后下次必出(玩家无感知防非酋)
const 垃圾同周期锁 = 旧钟楼跨度转时段(3); // 同户每个世界时段最多翻一袋
const 垃圾零钱概率 = 0.3; // 任何袋子几率翻出 5~20 元零钱(2026-07-17 用户提案;空手安慰奖+P3 公共区金币先遣)
const 偷窥冷却时段数 = 旧钟楼跨度转时段(3);

// ── 软计数(chat 变量) ──

interface 侦探计数 {
  垃圾空手: Record<string, number>; // 门牌 → 连续空手次数(软保底)
  垃圾上次: Record<string, number>; // 门牌 → 上次翻到东西/判定的绝对时段(周期锁)
  死路: Record<string, number>; // `${渠道}:${门牌}` → 错渠道次数(死路提示分档)
  偷窥上次: Record<string, number>; // 门牌 → 上次偷窥绝对时段(冷却)
  偷窥待选: { 门牌: string; 拍: number } | null; // 本场偷窥的"你注意到了什么"挂起态
  打听上次: Record<string, number>; // P5:门牌 → 上次打听绝对时段(冷却)
  对饮上次: Record<string, number>; // P5:门牌 → 上次对饮绝对时段(冷却)
}

function 读计数(): 侦探计数 {
  const v = (_.get(getVariables({ type: 'chat' }), '_侦探') ?? {}) as Partial<侦探计数>;
  return {
    垃圾空手: v.垃圾空手 ?? {},
    垃圾上次: v.垃圾上次 ?? {},
    死路: v.死路 ?? {},
    偷窥上次: v.偷窥上次 ?? {},
    偷窥待选: v.偷窥待选 ?? null,
    打听上次: v.打听上次 ?? {},
    对饮上次: v.对饮上次 ?? {},
  };
}

function 写计数(c: 侦探计数): void {
  // Promise.resolve 包一层(2026-07-17 实测事故):insertOrAssignVariables 在部分酒馆助手版本
  // 是同步函数不返回 Promise——写入已成功,裸链 .catch 却在 undefined 上炸,把调用方后半段
  // (落库+提示)全炸没="翻垃圾没反应但锁记上了"的真凶
  void Promise.resolve(insertOrAssignVariables({ _侦探: c }, { type: 'chat' })).catch((e: unknown) =>
    console.error('[人妻公寓·侦探] 计数写入失败', e),
  );
}

// ── 结果类型(index 接线用:提示给 toast,事件排队进下一楼叙事) ──

export interface 侦探结果 {
  提示: string; // toast 短句
  事件?: string; // 排队进 _待发送事件 的叙事指令(可空=纯 UI 反馈)
  变动?: boolean; // 非碎片状态发生变化（例如风闻）时也必须落库
  碎片到手?: boolean; // 变量有改动,需要落库+刷新
  集齐?: boolean; // 第 4 张到手(背包加信,等玩家读信揭晓)
  /** 已通过冷却/在场等硬校验并完成一次有效调查；供裂缝确认后的阶段线路稳定记账。 */
  线路动作成功?: boolean;
}

/** 母亲特例双拼前半:入列后完成前两次父亲通话,各归档一条线索。 */
export function 母亲来电线索(data: SchemaType): 侦探结果 | null {
  const 门牌号: 门牌 = '302';
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  if (!data.系统._母亲入列 || !节点 || 配?.渠道 !== '特例双拼' || 节点.妻.裂缝.已确认) return null;
  const 进度 = 节点.妻.裂缝.碎片进度;
  const 拍 = 进度 < 2 ? 配.来电?.[进度] : undefined;
  if (!拍) return null;
  节点.妻.裂缝.碎片进度 = 进度 + 1;
  镜像直写(门牌号, { 碎片: 进度 + 1 });
  return {
    提示: `【母亲线索 ${进度 + 1}/4】${拍.碎片文案}`,
    事件: `【母亲裂缝·父亲来电】${拍.场景种子}。这只是{{user}}注意到的细节,妈不知道他已经把它当成线索`,
    碎片到手: true,
  };
}

/** 错渠道死路:计数分档出文案(1~2 次含糊,3 次起定性) */
function 死路反馈(渠道: 户配置['渠道'], 门牌号: 门牌, c: 侦探计数): 侦探结果 {
  const key = `${渠道}:${门牌号}`;
  c.死路[key] = (c.死路[key] ?? 0) + 1;
  写计数(c);
  if (c.死路[key] < 3) {
    const 含糊: Partial<Record<户配置['渠道'], string>> = {
      翻垃圾: '什么都没翻到。',
      摄像头: '画面里没什么特别的。',
      动态广场: '翻了很久,眼睛都酸了,没看出什么。',
      打听: '街坊客气地收了礼,聊的全是家长里短,没什么有用的。',
    };
    return { 提示: 含糊[渠道] ?? '似乎没什么收获。' };
  }
  const 定性 = 查裂缝(门牌号)?.死路提示[渠道];
  return { 提示: 定性 ?? '这条路上似乎什么都没有。' };
}

