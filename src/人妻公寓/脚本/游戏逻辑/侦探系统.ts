// 考古(双层广场硬编码层;动态广场渠道户出题,错渠道=能翻但永不出题=硬门)
// ============================================

/** 考古关键动态判定(选错可重试不罚,难度在找不在罚;关键条按碎片进度顺序解锁) */
export function 考古选细节(data: SchemaType, 门牌号: 门牌, 动态序: number, 选项下标: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  const 条 = 查考古(门牌号)[动态序];
  if (!节点 || !条?.关键) return { 提示: '……看不出什么特别的。' };
  const 是动态渠道 = 配?.渠道 === '动态广场';
  const 是母亲双拼 = 门牌号 === '302' && 配?.渠道 === '特例双拼' && data.系统._母亲入列;
  if ((!是动态渠道 && !是母亲双拼) || 节点.妻.裂缝.已确认) return { 提示: '……好像也就是寻常的一条。' };
  const 关键序 = 查考古(门牌号)
    .filter(x => x.关键)
    .indexOf(条);
  const 应到进度 = 是母亲双拼 ? 关键序 + 2 : 关键序;
  if (应到进度 !== 节点.妻.裂缝.碎片进度) return { 提示: '哪里不太对,但现在还串不起来。' };
  if (选项下标 !== 条.关键.正确) return { 提示: '……好像也没什么不对。也许换个角度再看。' };
  节点.妻.裂缝.碎片进度 += 1;
  const 提交镜像 = () => 镜像直写(门牌号, { 碎片: 节点.妻.裂缝.碎片进度 });
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`考古辑录·${妻名}`)) data.背包.push(`考古辑录·${妻名}`);
  return { 提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${条.关键.碎片文案}`, 碎片到手: true, 集齐,
    提交后: 提交镜像 };
}

/**
 * 考古翻到底(2026-07-18 用户拍板混排流版:考古直接发生在朋友圈众人动态里,无个人相册)——
 * 楼里有动态广场渠道的题没做完=提醒答案在漏看的条里;否则计全局死路,3次起把各家定性一并给
 */
export function 考古到底(data: SchemaType): 侦探结果 {
  const 有题在身 = (Object.keys(data.户) as 门牌[]).some(
    m => 查裂缝(m)?.渠道 === '动态广场' && !data.户[m].妻.裂缝.已确认,
  );
  if (有题在身) return { 提示: '翻到底了。答案不在更早——在你漏看的那几条里。' };
  const c = 读计数();
  const key = '动态广场:混排';
  c.死路[key] = (c.死路[key] ?? 0) + 1;
  写计数(c);
  if (c.死路[key] < 3) return { 提示: '翻到底了。这几年谁把日子过成什么样,都晒在上面了。' };
  const 定性 = (Object.keys(data.户) as 门牌[])
    .map(m => 查裂缝(m)?.死路提示['动态广场'])
    .filter((x): x is string => Boolean(x));
  return { 提示: 定性.length ? 定性.join('\n') : '这条路上似乎什么都没有。' };
}

