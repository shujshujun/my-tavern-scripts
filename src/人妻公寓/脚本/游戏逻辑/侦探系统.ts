// 打听(201 专属,P5):四张嘴按顺序撬,伴手礼盒当弹药;从大堂出门找街坊
// ============================================

const 打听冷却时段数 = 旧钟楼跨度转时段(3); // 〔调参〕一个时段最多跑一趟街坊

export function 打听(data: SchemaType, 门牌号: 门牌, _消息楼层?: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 提示: '这户还空着,街坊嘴里没有它的话。' };
  const 配 = 查裂缝(门牌号);
  const c = 读计数();
  const 妻名 = 户静态表[门牌号].妻名;

  const 绝对时段 = 取绝对时段(data);
  // 冷却(回档陷阱同款:记录停在未来=作废)
  const 上次记录 = c.打听上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 绝对时段 ? -999 : 上次记录;
  if (绝对时段 - 上次 < 打听冷却时段数) return { 提示: '刚打听过一圈——街坊也要过日子,别把嘴撬秃了。' };

  // 弹药:伴手礼盒(人情页签)
  const i = data.背包.indexOf('伴手礼盒');
  if (i < 0) return { 提示: '空着手打听不出真话——先去商店备一份伴手礼盒。' };

  // 零收益分支前置(2026-07-26 审计 低危10):已确认/进度走完再打听是纯无收益,
  // 旧版照扣礼盒照记冷却=白烧钱。错渠道死路仍消耗(硬门代价,礼盒照送话打不开)。
  const 是打听渠道 = !!配 && 配.渠道 === '打听';
  if (是打听渠道 && 节点.妻.裂缝.已确认) {
    return { 提示: `街坊还是那些话——关于${妻名},你要知道的已经知道了。礼盒先留着吧。` };
  }
  const 进度 = 节点.妻.裂缝.碎片进度;
  const 拍 = 是打听渠道 ? 配!.打听?.[进度] : undefined;
  if (是打听渠道 && (!拍 || 进度 >= 4)) {
    return { 提示: '这一圈不会有新话头了——礼盒先留着吧。' };
  }

  c.打听上次[门牌号] = 绝对时段;
  data.背包.splice(i, 1);
  const 风闻事件ID = `打听:${Math.floor(Math.max(0, 绝对时段) / 每天时段数)}:${门牌号}`;
  const 已打听过本日 = data.系统._风闻账.最近事件.some(event => event.id === 风闻事件ID);
  登记风闻事件(data, {
    id: 风闻事件ID,
    类型: '打听隐私',
    目标增量: 已打听过本日 ? 6 : 3,
    门牌: 门牌号,
    地点: '楼外街坊',
    摘要: '有人向街坊反复打听住户私事',
    迹象: '可疑痕迹',
  });

  // 硬门:非打听渠道户=礼盒照送,话打不开
  if (!是打听渠道 || !拍) {
    const 死 = 死路反馈('打听', 门牌号, c);
    return { ...死, 碎片到手: true }; // 背包变了要落库
  }
  写计数(c);
  节点.妻.裂缝.碎片进度 = 进度 + 1;
  镜像直写(门牌号, { 碎片: 进度 + 1 });
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`街坊札记·${妻名}`)) data.背包.push(`街坊札记·${妻名}`);
  return {
    提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${拍.碎片文案}`,
    事件: `【打听】{{user}}提着伴手礼盒出门找${拍.对象}打听了${妻名}家的事。演出这场对话戏(信息如下,按对方的身份口吻自然铺开,{{user}}回楼即本轮场景):${拍.场景种子}。严禁替{{user}}解读这些话的含义`,
    碎片到手: true,
    集齐,
  };
}

// ============================================
// 对饮(202 专属渠道=丈夫;对任何在家的丈夫都可用=信任值资源轴,唯 202 会漏酒话)
// ============================================

const 对饮冷却时段数 = 旧钟楼跨度转时段(3); // 〔调参〕
const 对饮信任加 = 8; // 〔调参〕一顿酒的交情

export function 对饮(data: SchemaType, 门牌号: 门牌, _消息楼层?: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 户配 = 户静态表[门牌号];
  if (!节点 || !户配?.夫名 || 门牌号 === '302') return { 提示: '这家没有能陪你喝的人。' };
  const c = 读计数();
  const 绝对时段 = 取绝对时段(data);

  // UI 只负责展示按钮；陈旧界面事件或手工 eventEmit 仍必须在业务层复核。
  // 统一走 丈夫在楼，确保夜班/出差运作窗口也能挡住对饮。
  if (丈夫在楼(节点, 门牌号, 绝对时段) !== '在家') return { 提示: `${户配.夫名}这会儿不在家,酒先留着。` };

  const 上次记录 = c.对饮上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 绝对时段 ? -999 : 上次记录;
  if (绝对时段 - 上次 < 对饮冷却时段数) return { 提示: `${户配.夫名}上一顿还没醒透,改天再约。` };

  const i = data.背包.indexOf('好酒');
  if (i < 0) return { 提示: '空手请人喝酒?先去商店拎一瓶好酒。' };

  c.对饮上次[门牌号] = 绝对时段;
  写计数(c);
  data.背包.splice(i, 1);
  const 夫 = 节点.夫;
  夫.信任值 = _.clamp(夫.信任值 + 对饮信任加, 0, 100);

  // 202 专属:信任到节点,他酒后漏话
  const 配 = 查裂缝(门牌号);
  const 进度 = 节点.妻.裂缝.碎片进度;
  const 拍 = 配?.渠道 === '丈夫' && !节点.妻.裂缝.已确认 && 进度 < 4 ? 配.夫漏?.[进度] : undefined;
  if (拍 && 夫.信任值 >= 拍.信任门槛) {
    节点.妻.裂缝.碎片进度 = 进度 + 1;
    镜像直写(门牌号, { 碎片: 进度 + 1 });
    const 妻名 = 户配.妻名;
    const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
    if (集齐 && !data.背包.includes(`酒后真言·${妻名}`)) data.背包.push(`酒后真言·${妻名}`);
    return {
      提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${拍.碎片文案}`,
      事件: `【对饮】{{user}}拎着好酒约${户配.夫名}喝了一顿。演出这场酒局(信息如下,按他的性格与醉意自然铺开):${拍.场景种子}。严禁替{{user}}解读这些话`,
      碎片到手: true,
      集齐,
    };
  }
  // 通用:交情涨了(信任=资源轴,对谁都有用);202 未到节点=他有话没说透
  const 欲言 =
    配?.渠道 === '丈夫' && !节点.妻.裂缝.已确认 && 进度 < 4 ? '他几次话到嘴边又咽回去——交情还没到那个份上。' : '';
  return {
    提示: `和${户配.夫名}喝了一顿,交情近了些。${欲言}`,
    事件: `【对饮】{{user}}拎着好酒约${户配.夫名}喝了一顿,聊些男人间的闲篇(球赛/工作/楼里琐事)。演出这场酒局的松弛感${欲言 ? ',他偶尔欲言又止,但没说什么要紧的' : ''}`,
    碎片到手: true,
  };
}

export type 丈夫礼物 = '香烟' | '球赛票';

const 丈夫礼物信任加: Record<丈夫礼物, number> = {
  香烟: 3,
  球赛票: 10,
};

/** 两种非酒类丈夫礼物只经营信任轴，不替代 202 对饮漏话的专属调查渠道。 */
export function 赠礼丈夫(data: SchemaType, 门牌号: 门牌, 道具id: 丈夫礼物): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 户配 = 户静态表[门牌号];
  if (!节点 || !户配?.夫名 || 门牌号 === '302') return { 提示: '这家没有可以收下这份礼物的丈夫。' };
  if (!(道具id in 丈夫礼物信任加)) return { 提示: '这件东西不适合作为丈夫礼物。' };
  const 绝对时段 = 取绝对时段(data);
  if (丈夫在楼(节点, 门牌号, 绝对时段) !== '在家') return { 提示: `${户配.夫名}这会儿不在家，礼物先留着。` };
  const 背包序 = data.背包.indexOf(道具id);
  if (背包序 < 0) return { 提示: `背包里没有「${道具id}」。` };

  data.背包.splice(背包序, 1);
  const 加成 = 丈夫礼物信任加[道具id];
  节点.夫.信任值 = _.clamp(节点.夫.信任值 + 加成, 0, 100);
  const 是球票 = 道具id === '球赛票';
  return {
    提示: 是球票 ? `${户配.夫名}收下两张连座票，认真和你约好了看球的日子。` : `${户配.夫名}接过烟，楼道里多聊了几句。`,
    事件:
      事件角色标记({ 在场夫: [门牌号], 关联妻: [门牌号] }) +
      `【丈夫礼物】对象=${户配.夫名}；礼物=${道具id}；信任变化方向=增加；互动性质=${
        是球票 ? '一次明确的共同出行约定，交情提升较大' : '短促的楼道社交，交情小幅提升'
      }。按他的性格与当时家庭气氛自然演出收礼反应；不要念出数值，也不要凭空生成妻子的裂缝线索。`,
    碎片到手: true,
  };
}

// ============================================
// 考古(双层广场硬编码层;动态广场渠道户出题,错渠道=能翻但永不出题=硬门)
// ============================================

/** 考古关键动态判定(选错可重试不罚,难度在找不在罚;关键条按碎片进度顺序解锁) */
export function 考古选细节(data: SchemaType, 门牌号: 门牌, 动态序: number, 选项下标: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  const 条 = 查考古(门牌号)[动态序];
  if (!节点 || !条?.关键) return { 提示: '……看不出什么特别的。' };
  const 是动态渠道 = 配?.渠道 === '动态广场';
  const 是母亲双拼 = 门牌号 === '302' && 配?.渠道 === '特例双拼' && data.系统._母亲入列;
  if ((!是动态渠道 && !是母亲双拼) || 节点.妻.裂缝.已确认) return { 提示: '……好像也就是寻常的一条。' };
  const 关键序 = 查考古(门牌号)
    .filter(x => x.关键)
    .indexOf(条);
  const 应到进度 = 是母亲双拼 ? 关键序 + 2 : 关键序;
  if (应到进度 !== 节点.妻.裂缝.碎片进度) return { 提示: '哪里不太对,但现在还串不起来。' };
  if (选项下标 !== 条.关键.正确) return { 提示: '……好像也没什么不对。也许换个角度再看。' };
  节点.妻.裂缝.碎片进度 += 1;
  镜像直写(门牌号, { 碎片: 节点.妻.裂缝.碎片进度 });
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`考古辑录·${妻名}`)) data.背包.push(`考古辑录·${妻名}`);
  return { 提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${条.关键.碎片文案}`, 碎片到手: true, 集齐 };
}

/**
 * 考古翻到底(2026-07-18 用户拍板混排流版:考古直接发生在朋友圈众人动态里,无个人相册)——
 * 楼里有动态广场渠道的题没做完=提醒答案在漏看的条里;否则计全局死路,3次起把各家定性一并给
 */
export function 考古到底(data: SchemaType): 侦探结果 {
  const 有题在身 = (Object.keys(data.户) as 门牌[]).some(
    m => 查裂缝(m)?.渠道 === '动态广场' && !data.户[m].妻.裂缝.已确认,
  );
  if (有题在身) return { 提示: '翻到底了。答案不在更早——在你漏看的那几条里。' };
  const c = 读计数();
  const key = '动态广场:混排';
  c.死路[key] = (c.死路[key] ?? 0) + 1;
  写计数(c);
  if (c.死路[key] < 3) return { 提示: '翻到底了。这几年谁把日子过成什么样,都晒在上面了。' };
  const 定性 = (Object.keys(data.户) as 门牌[])
    .map(m => 查裂缝(m)?.死路提示['动态广场'])
    .filter((x): x is string => Boolean(x));
  return { 提示: 定性.length ? 定性.join('\n') : '这条路上似乎什么都没有。' };
}

