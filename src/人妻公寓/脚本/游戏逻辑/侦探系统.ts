// ============================================

/**
 * 已布设名单存 stat `_摄像头布设`(2026-07-17 从 chat 变量迁入):布设的"消耗"(背包扣道具)
 * 随楼层快照走,布设记录必须同账——重掷/撤回删楼时两者一起回滚,否则道具复活+已装仍在=无限摄像头。
 * 旧局的 chat 变量 `_摄像头` 只读兼容(在测玩家已装的不作废),新写入只进 stat。
 */
export function 已布设(data: SchemaType, 门牌号: string): boolean {
  if (data.系统._摄像头布设[门牌号]) return true;
  const legacy = (_.get(getVariables({ type: 'chat' }), '_摄像头') ?? {}) as Record<string, boolean>;
  return !!legacy[门牌号];
}

/** 布设摄像头(客户端已校验:在该户房内+背包有货;这里做最终校验+消耗;消耗与布设记录同写 stat=同一本账) */
export function 布设摄像头(data: SchemaType, 门牌号: 门牌): 侦探结果 {
  if (!data.户[门牌号]) return { 提示: '这户还空着,装了也只能看灰。' };
  const i = data.背包.indexOf('针孔摄像头');
  if (i < 0) return { 提示: '背包里没有摄像头。' };
  if (已布设(data, 门牌号)) return { 提示: '这里已经装过一个了。' };
  data.背包.splice(i, 1);
  data.系统._摄像头布设[门牌号] = true;
  return {
    提示: '装好了。烟雾报警器的外壳严丝合缝——从今晚起,这个家没人看着的时候,你看着。',
    碎片到手: true, // 背包变了,需要落库
  };
}

/**
 * 查看摄像头:排队本拍偷窥场景(场景种子注入,AI 演出),回合完成后客户端弹细节选项。
 * 返回 null = 不可看(未布设/冷却/她不在家/已确认),提示给 toast。
 */
export function 查看摄像头(
  data: SchemaType,
  门牌号: 门牌,
  楼层: number,
): { 事件: string; 拍: number } | 侦探结果 {
  const 节点 = data.户[门牌号];
  if (!节点 || !已布设(data, 门牌号)) return { 提示: '那边没有你的眼睛。' };
  const 配 = 查裂缝(门牌号);
  const c = 读计数();
  const 妻名 = 户静态表[门牌号].妻名;

  // 回档陷阱同翻垃圾:冷却记录停在"未来"楼层=作废,否则回档后监控永久哑火
  const 上次记录 = c.偷窥上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 楼层 ? -999 : 上次记录;
  if (楼层 - 上次 < 偷窥冷却楼数) return { 提示: '画面里她刚才那会儿的样子你还记得——过阵子再看吧。' };
  if (妻位置推算(门牌号, 楼层) !== 门牌号) return { 提示: `画面里空无一人——${妻名}这会儿不在家。` };

  c.偷窥上次[门牌号] = 楼层;

  // 硬门:非摄像头渠道户=死路(拍到的全是正常日常)
  if (!配 || 配.渠道 !== '摄像头' || 节点.妻.裂缝.已确认) {
    c.偷窥待选 = null;
    写计数(c);
    if (节点.妻.裂缝.已确认) return { 提示: '画面里是你已经读懂的那个她。' };
    return 死路反馈('摄像头', 门牌号, c);
  }

  const 拍 = 节点.妻.裂缝.碎片进度;
  const 本拍 = 配.偷窥?.[拍];
  if (!本拍) {
    c.偷窥待选 = null;
    写计数(c);
    return { 提示: '画面里没有新东西了。' };
  }
  c.偷窥待选 = { 门牌: 门牌号, 拍 };
  写计数(c);
  return {
    事件:
      `【摄像头画面】本轮{{user}}正通过针孔摄像头偷看${门牌号}室——他人在302自己屋里,看的是屏幕里的画面。` +
      `画面里${妻名}独自在家,不知道被看:${本拍.场景种子}。` +
      `以偷窥视角演出这一楼(画面的颗粒感、无声、他的心跳),她的部分只演画面里发生的事,严禁解读她行为背后的原因,严禁让两人产生任何互动`,
    拍,
  };
}

/** "你注意到了什么?"——静态选项判定(1 真;选错=本场白看,冷却后重看) */
export function 偷窥选细节(data: SchemaType, 门牌号: 门牌, 选项下标: number): 侦探结果 {
  const c = 读计数();
  const 挂起 = c.偷窥待选;
  c.偷窥待选 = null;
  写计数(c);
  if (!挂起 || 挂起.门牌 !== 门牌号) return { 提示: '画面已经过去了。' };
  const 节点 = data.户[门牌号];
  const 本拍 = 查裂缝(门牌号)?.偷窥?.[挂起.拍];
  if (!节点 || !本拍 || 节点.妻.裂缝.碎片进度 !== 挂起.拍) return { 提示: '画面已经过去了。' };

  if (选项下标 !== 本拍.正确) {
    return { 提示: '……好像也没什么特别的。也许下次再看看。' };
  }
  节点.妻.裂缝.碎片进度 = 挂起.拍 + 1;
  镜像直写(门牌号, { 碎片: 挂起.拍 + 1 });
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`观察笔记·${妻名}`)) data.背包.push(`观察笔记·${妻名}`);
  return {
    提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${本拍.碎片文案}`,
    碎片到手: true,
    集齐,
  };
}

/**
 * 清挂起的偷窥待选(2026-07-17 BUG:偷窥回合生成失败(403等)没有正文,挂起态却已写入,
 * 过后选择卡凭空弹出)——回合失败时调用,画面没演成就没有"你注意到了什么"。
 */
export function 清偷窥挂起(): void {
  const c = 读计数();
  if (!c.偷窥待选) return;
  c.偷窥待选 = null;
  写计数(c);
}

/** 偷窥挂起态(客户端回合完成后查询,弹选项卡) */
export function 取偷窥待选(): { 门牌: string; 拍: number; 选项: string[] } | null {
  const 挂起 = 读计数().偷窥待选;
  if (!挂起) return null;
  const 本拍 = 查裂缝(挂起.门牌 as 门牌)?.偷窥?.[挂起.拍];
  return 本拍 ? { ...挂起, 选项: 本拍.选项 } : null;
}

// ============================================
// 读信揭晓(集齐 4 张后,玩家点开信=揭晓时刻;裂缝确认+情报可见,单向)
// ============================================

export function 读信揭晓(data: SchemaType, 门牌号: 门牌): 侦探结果 {
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  if (!节点 || !配) return { 提示: '没有可读的东西。' };
  if (节点.妻.裂缝.碎片进度 < 4) return { 提示: '线索还没凑齐。' };
  if (节点.妻.裂缝.已确认) return { 提示: '你已经读过了。' };
  节点.妻.裂缝.已确认 = true;
  节点.妻.情报可见 = true;
  镜像直写(门牌号, { 裂缝确认: true, 情报可见: true });
  const 妻名 = 户静态表[门牌号].妻名;
  return {
    提示: `${妻名}的裂缝,你看清了。`,
    事件: `【心照不宣】{{user}}已经看清了${妻名}生活里的裂缝(他自己拼出来的,她并不知情)。从本楼起你(AI)也知道了她的隐痛(见快照),演出照旧克制:她不知道他知道,他也不会说破`,
    碎片到手: true,
  };
}

/** 读信正文(客户端读信 modal 用) */
export function 取信全文(门牌号: 门牌): string {
  return 查裂缝(门牌号)?.信全文 ?? '';
}
