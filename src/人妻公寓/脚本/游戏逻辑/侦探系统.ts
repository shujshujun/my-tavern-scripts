// 翻垃圾(101 专属;垃圾房按户分袋,翻哪户=选择)
// ============================================

export function 翻垃圾(data: SchemaType, 门牌号: 门牌, _消息楼层?: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 提示: '这户还空着,垃圾房里没有它的袋子。' };
  const 配 = 查裂缝(门牌号);
  const c = 读计数();
  const 绝对时段 = 取绝对时段(data);

  // 周期锁(2026-07-17 提前到所有袋子统一:垃圾一个时段一袋;也堵住错渠道袋无冷却刷零钱)
  // 回档陷阱(2026-07-17 用户实测"101从来翻不出"根因):软计数不随存档回滚,回档后记录停在
  // "未来"绝对时段,锁永远打不开——记录>当前绝对时段一律视为作废
  const 上次记录 = c.垃圾上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 绝对时段 ? -999 : 上次记录;
  if (绝对时段 - 上次 < 垃圾同周期锁) {
    return { 提示: '这袋你翻过了,还是那些东西。等她再扔一袋吧。' };
  }
  c.垃圾上次[门牌号] = 绝对时段;
  const 风闻结果 = 登记风闻事件(data, {
    id: `翻垃圾:${绝对时段}:${门牌号}`,
    类型: '翻垃圾',
    目标增量: 1,
    门牌: 门牌号,
    地点: '垃圾房',
    摘要: '垃圾房里留下了可疑翻找痕迹',
    迹象: '可疑痕迹',
  });

  // 零钱奖励(2026-07-17 用户提案:任何袋子几率翻出零钱;绝对时段种子防刷)〔调参〕
  let 零钱 = 0;
  if (seededRandom(绝对时段, 门牌号, '垃圾零钱') < 垃圾零钱概率) {
    零钱 = 5 + Math.floor(seededRandom(绝对时段, 门牌号, '零钱额') * 16); // 5~20 元
    data.现金 += 零钱;
  }
  const 零钱语 = 零钱 ? ` 袋底还压着几张皱巴巴的零钱(+¥${零钱})。` : '';

  // 已确认:垃圾恢复成普通垃圾
  if (节点.妻.裂缝.已确认) {
    写计数(c);
    return {
      提示: '都是些寻常的生活垃圾——你要知道的,已经知道了。' + 零钱语,
      变动: 风闻结果.变动,
      碎片到手: 零钱 > 0,
      线路动作成功: true,
    };
  }

  // 硬门:裂缝确认前，非垃圾渠道户=死路(死路计数照记;零钱照捡)
  if (!配 || 配.渠道 !== '翻垃圾') {
    const 死 = 死路反馈('翻垃圾', 门牌号, c);
    return { 提示: 死.提示 + 零钱语, 变动: 风闻结果.变动, 碎片到手: 零钱 > 0 };
  }

  // 几率+软保底(绝对时段种子:同时段重roll结果不变,防刷)
  const 出货 = c.垃圾空手[门牌号] >= 垃圾软保底次数 || seededRandom(绝对时段, 门牌号, '翻垃圾') < 垃圾出货概率;
  if (!出货) {
    c.垃圾空手[门牌号] = (c.垃圾空手[门牌号] ?? 0) + 1;
    写计数(c);
    return {
      提示: '一袋普通的生活垃圾:外卖盒、零食袋、快递纸箱。今天没有线索。' + 零钱语,
      变动: 风闻结果.变动,
      碎片到手: 零钱 > 0,
    };
  }
  c.垃圾空手[门牌号] = 0;
  写计数(c);

  // 出碎片
  const 进度 = 节点.妻.裂缝.碎片进度;
  if (进度 >= 4) {
    return { 提示: '袋子里没有新东西了。' + 零钱语, 变动: 风闻结果.变动, 碎片到手: 零钱 > 0 };
  }
  const 文案 = 配.碎片信?.[进度] ?? '一张看不清的碎纸。';
  节点.妻.裂缝.碎片进度 = 进度 + 1;
  镜像直写(门牌号, { 碎片: 进度 + 1 });
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`拼合的信·${妻名}`)) data.背包.push(`拼合的信·${妻名}`);
  return {
    提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${文案}${零钱语}`,
    事件: `【翻垃圾的收获】{{user}}在垃圾房${妻名}家的垃圾袋里翻到了一样东西:${文案}。若本轮场景在垃圾房,可自然演出这次翻找(紧张、楼道脚步声、塑料袋的响动);其他场景则不必提及。严禁替{{user}}解读这条线索的含义`,
    碎片到手: true,
    变动: 风闻结果.变动,
    集齐,
  };
}

