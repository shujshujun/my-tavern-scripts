/**
 * 查看摄像头：家庭计划、裂缝调查和当前阶段线路属于硬内容；裂缝确认后的日常观察只是
 * 低优先级状态反馈。阶段线路票一旦就绪，必须绕过日常观察的冷却与已见历史，避免软内容
 * 反向饿死晋阶任务。
 */
export function 查看摄像头(
  data: SchemaType,
  门牌号: 门牌,
  _消息楼层?: number,
  选项: 查看摄像头选项 = {},
): { 事件: string; 拍: number } | 监控日常观察结果 | 家庭计划监控结果 | 侦探结果 {
  const 节点 = data.户[门牌号];
  if (!节点 || !已布设(data, 门牌号)) return { 提示: '那边没有你的眼睛。' };
  const 配 = 查裂缝(门牌号);
  const c = 读计数();
  const 妻名 = 户静态表[门牌号].妻名;
  const 绝对时段 = 取绝对时段(data);

  // 回档陷阱同翻垃圾：软冷却停在未来绝对时段时视为无效，不能令回档后的监控永久哑火。
  const 上次记录 = c.偷窥上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 绝对时段 ? -999 : 上次记录;

  // 家庭计划是独立硬剧情，保持既有第一优先级；成功观看也压住当天的普通日常观察。
  const 家庭计划 = 准备家庭计划监控(data, 门牌号);
  if (家庭计划 && !('提示' in 家庭计划)) {
    if (绝对时段 - 上次 < 偷窥冷却时段数) return { 提示: '这路画面刚看过，过阵子再打开监控。' };
    c.偷窥上次[门牌号] = 绝对时段;
    c.偷窥待选 = null;
    记录监控日常软冷却(c, 门牌号, 绝对时段);
    写计数(c);
    return 家庭计划;
  }

  // 当前阶段线路票已就绪时先走硬任务：不读取普通观察冷却与已见历史，也不依赖旧偷窥冷却。
  // AI 失败时外层隔离事务会把这里写入的软计数一并精确回滚。
  if (节点.妻.裂缝.已确认 && 选项.关系线路优先) {
    if (妻位置推算(门牌号, 绝对时段, 节点) !== 门牌号) {
      return { 提示: `画面里空无一人——${妻名}这会儿不在家。` };
    }
    c.偷窥待选 = null;
    记录监控日常软冷却(c, 门牌号, 绝对时段);
    写计数(c);
    return { 提示: '这次画面优先承接当前关系任务。', 线路动作成功: true };
  }

  // 家庭计划当前只有“尚未到日／丈夫未就绪”等提示时，不得反向压住已经就绪的关系票；
  // 没有关系票时仍保留原提示，避免玩家误以为家庭计划条件已经满足。
  if (家庭计划) return 家庭计划;

  // 裂缝确认前维持原调查冷却与专属四拍，不让普通状态观察抢走解谜入口。
  if (!节点.妻.裂缝.已确认 && 绝对时段 - 上次 < 偷窥冷却时段数) {
    return { 提示: '画面里她刚才那会儿的样子你还记得——过阵子再看吧。' };
  }
  if (妻位置推算(门牌号, 绝对时段, 节点) !== 门牌号) {
    return { 提示: `画面里空无一人——${妻名}这会儿不在家。` };
  }

  if (节点.妻.裂缝.已确认) {
    const 日常上次记录 = c.监控日常上次?.[门牌号] ?? -999;
    const 日常上次 = 日常上次记录 > 绝对时段 ? -999 : 日常上次记录;
    if (绝对时段 - 日常上次 < 监控日常观察冷却时段数) {
      return { 提示: '今天已经看过她的一段独处状态了；关系任务准备好时仍会优先出现。' };
    }

    const 观察 = 构造监控日常观察(data, 门牌号);
    if (!观察) return { 提示: '当前没有可安全呈现的新状态。' };
    const 原历史 = c.监控日常已见?.[门牌号];
    const 历史 = Array.isArray(原历史)
      ? 原历史.filter(
          项 => 项 && typeof 项.签名 === 'string' && Number.isInteger(项.时) && 项.时 >= 0 && 项.时 <= 绝对时段,
        )
      : [];
    const 历史已清理 = Array.isArray(原历史) && 历史.length !== 原历史.length;
    if (历史.some(项 => 项.签名 === 观察.观察签名)) {
      c.偷窥待选 = null;
      if (历史已清理) {
        (c.监控日常已见 ??= {})[门牌号] = 历史;
        写计数(c);
      }
      return { 提示: '这组阶段与数值状态已经看过；等她出现实质变化后，镜头才会给出新的独处片段。' };
    }

    c.偷窥待选 = null;
    记录监控日常软冷却(c, 门牌号, 绝对时段);
    (c.监控日常已见 ??= {})[门牌号] = [...历史, { 签名: 观察.观察签名, 时: 绝对时段 }].slice(-监控日常观察历史上限);
    写计数(c);
    return 观察;
  }

  c.偷窥上次[门牌号] = 绝对时段;

  // 硬门：裂缝确认前，非摄像头渠道户仍是死路，不能借日常观察提前泄露裂缝。
  if (!配 || 配.渠道 !== '摄像头') {
    c.偷窥待选 = null;
    写计数(c);
    return 死路反馈('摄像头', 门牌号, c);
  }

  const 拍 = 节点.妻.裂缝.碎片进度;
  const 本拍 = 配.偷窥?.[拍];
  if (!本拍) {
    c.偷窥待选 = null;
    写计数(c);
    return { 提示: '画面里没有新东西了。' };
  }
  c.偷窥待选 = { 门牌: 门牌号, 拍 };
  写计数(c);
  return {
    事件:
      `【摄像头画面】本轮{{user}}正通过针孔摄像头偷看${门牌号}室——他人在302自己屋里,看的是屏幕里的画面。` +
      `画面里${妻名}独自在家,不知道被看:${本拍.场景种子}。` +
      `以偷窥视角演出这一楼(画面的颗粒感、无声、他的心跳),她的部分只演画面里发生的事,严禁解读她行为背后的原因,严禁让两人产生任何互动`,
    拍,
  };
}

/** "你注意到了什么?"——静态选项判定(1 真;选错=本场白看,冷却后重看) */
export function 偷窥选细节(data: SchemaType, 门牌号: 门牌, 选项下标: number): 侦探结果 {
  const 挂起 = 读计数().偷窥待选;
  const 清当前挂起 = () => {
    const 最新 = 读计数();
    if (!挂起 || !最新.偷窥待选) return;
    if (最新.偷窥待选.门牌 !== 挂起.门牌 || 最新.偷窥待选.拍 !== 挂起.拍) return;
    最新.偷窥待选 = null;
    写计数(最新);
  };
  if (!挂起 || 挂起.门牌 !== 门牌号) {
    if (挂起) 清当前挂起();
    return { 提示: '画面已经过去了。' };
  }
  const 节点 = data.户[门牌号];
  const 配 = 查裂缝(门牌号);
  const 本拍 = 配?.渠道 === '摄像头' ? 配.偷窥?.[挂起.拍] : undefined;
  if (!节点 || !本拍 || 节点.妻.裂缝.碎片进度 !== 挂起.拍) {
    清当前挂起();
    return { 提示: '画面已经过去了。' };
  }

  if (选项下标 !== 本拍.正确) {
    清当前挂起();
    return { 提示: '……好像也没什么特别的。也许下次再看看。' };
  }
  const 新进度 = 挂起.拍 + 1;
  节点.妻.裂缝.碎片进度 = 新进度;
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`观察笔记·${妻名}`)) data.背包.push(`观察笔记·${妻名}`);
  return {
    提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${本拍.碎片文案}`,
    碎片到手: true,
    集齐,
    提交后: () => {
      清当前挂起();
      镜像直写(门牌号, { 碎片: 新进度 });
    },
  };
}

/**
 * 清挂起的偷窥待选(2026-07-17 BUG:偷窥回合生成失败(403等)没有正文,挂起态却已写入,
 * 过后选择卡凭空弹出)——回合失败时调用,画面没演成就没有"你注意到了什么"。
 */
export function 清偷窥挂起(): void {
  const c = 读计数();
  if (!c.偷窥待选) return;
  // 画面没演成,这次查看等于没看:冷却一并退还,否则玩家白等一轮冷却什么都没看到。
  // 挂起态存在即说明冷却是本次查看刚写入的(更早的记录必然已过期才可能通过冷却门),
  // 直接删键就是精确退款(2026-08-03 审计 L2)
  delete c.偷窥上次[c.偷窥待选.门牌];
  c.偷窥待选 = null;
  写计数(c);
}

/** 偷窥挂起态(客户端回合完成后查询,弹选项卡) */
export function 取偷窥待选(): { 门牌: string; 拍: number; 选项: string[] } | null {
  const 挂起 = 读计数().偷窥待选;
  if (!挂起) return null;
  const 本拍 = 查裂缝(挂起.门牌 as 门牌)?.偷窥?.[挂起.拍];
  return 本拍 ? { ...挂起, 选项: 本拍.选项 } : null;
}

