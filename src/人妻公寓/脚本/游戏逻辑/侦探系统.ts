import type { SchemaType } from '../../schema';
import type { 门牌 } from '../../stageConfig';
import { 户静态表, 查裂缝 } from '../../stageConfig';
import { seededRandom, 妻位置推算 } from './楼层时钟';
import { 镜像直写 } from './守护系统';

/**
 * 侦探系统(P2:翻垃圾+摄像头两渠道;打听/丈夫/动态广场留接口归 P5)
 *
 * 硬门(spec 拍板):每户只吃专属渠道,错渠道 100% 无产出;
 * 错渠道刷 2~3 次后给死路风味提示——解谜的死路必须可识别。
 * 4 张碎片全部由专属渠道产出;集齐=信自动拼合,读信=揭晓时刻(玩家动作,有仪式感)。
 *
 * 软计数(死路次数/垃圾软保底/偷窥冷却)存 chat 变量 `_侦探`:
 * 回档丢了也无害(碎片进度本账在 stat_data.裂缝 + 晋阶镜像里,防重roll打回)。
 */

// 〔调参〕
const 垃圾出货概率 = 1; // 〔测试临时 2026-07-17〕P2 测裂缝流程拉满;正式 rq0.18 改 0.7(用户拍板:0.45 太低,毕竟只是碎片)
const 垃圾软保底次数 = 2; // 连续 N 次空手后下次必出(玩家无感知防非酋)
const 垃圾同周期锁 = 3; // 同户翻过后隔 N 楼才再判(=一个时段一袋;2026-07-17 用户反馈 8 楼集齐要近三天,8→3 与偷窥冷却对齐)
const 垃圾零钱概率 = 0.3; // 任何袋子几率翻出 5~20 元零钱(2026-07-17 用户提案;空手安慰奖+P3 公共区金币先遣)
const 偷窥冷却楼数 = 3; // 同户两拍之间隔 N 楼(2026-07-17 用户反馈 6 太久,6→3=一个时段)

// ── 软计数(chat 变量) ──

interface 侦探计数 {
  垃圾空手: Record<string, number>; // 门牌 → 连续空手次数(软保底)
  垃圾上次: Record<string, number>; // 门牌 → 上次翻到东西/判定的楼层(周期锁)
  死路: Record<string, number>; // `${渠道}:${门牌}` → 错渠道次数(死路提示分档)
  偷窥上次: Record<string, number>; // 门牌 → 上次偷窥楼层(冷却)
  偷窥待选: { 门牌: string; 拍: number } | null; // 本场偷窥的"你注意到了什么"挂起态
}

function 读计数(): 侦探计数 {
  const v = (_.get(getVariables({ type: 'chat' }), '_侦探') ?? {}) as Partial<侦探计数>;
  return {
    垃圾空手: v.垃圾空手 ?? {},
    垃圾上次: v.垃圾上次 ?? {},
    死路: v.死路 ?? {},
    偷窥上次: v.偷窥上次 ?? {},
    偷窥待选: v.偷窥待选 ?? null,
  };
}

function 写计数(c: 侦探计数): void {
  // Promise.resolve 包一层(2026-07-17 实测事故):insertOrAssignVariables 在部分酒馆助手版本
  // 是同步函数不返回 Promise——写入已成功,裸链 .catch 却在 undefined 上炸,把调用方后半段
  // (落库+提示)全炸没="翻垃圾没反应但锁记上了"的真凶
  void Promise.resolve(insertOrAssignVariables({ _侦探: c }, { type: 'chat' })).catch((e: unknown) =>
    console.error('[人妻公寓·侦探] 计数写入失败', e),
  );
}

// ── 结果类型(index 接线用:提示给 toast,事件排队进下一楼叙事) ──

export interface 侦探结果 {
  提示: string; // toast 短句
  事件?: string; // 排队进 _待发送事件 的叙事指令(可空=纯 UI 反馈)
  碎片到手?: boolean; // 变量有改动,需要落库+刷新
  集齐?: boolean; // 第 4 张到手(背包加信,等玩家读信揭晓)
}

/** 错渠道死路:计数分档出文案(1~2 次含糊,3 次起定性) */
function 死路反馈(渠道: '翻垃圾' | '摄像头', 门牌号: 门牌, c: 侦探计数): 侦探结果 {
  const key = `${渠道}:${门牌号}`;
  c.死路[key] = (c.死路[key] ?? 0) + 1;
  写计数(c);
  if (c.死路[key] < 3) {
    return { 提示: 渠道 === '翻垃圾' ? '什么都没翻到。' : '画面里没什么特别的。' };
  }
  const 定性 = 查裂缝(门牌号)?.死路提示[渠道];
  return { 提示: 定性 ?? '这条路上似乎什么都没有。' };
}

// ============================================
// 翻垃圾(101 专属;垃圾房按户分袋,翻哪户=选择)
// ============================================

export function 翻垃圾(data: SchemaType, 门牌号: 门牌, 楼层: number): 侦探结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 提示: '这户还空着,垃圾房里没有它的袋子。' };
  const 配 = 查裂缝(门牌号);
  const c = 读计数();

  // 周期锁(2026-07-17 提前到所有袋子统一:垃圾一个时段一袋;也堵住错渠道袋无冷却刷零钱)
  // 回档陷阱(2026-07-17 用户实测"101从来翻不出"根因):软计数不随楼回滚,回档后记录停在
  // "未来"楼层,锁永远打不开——记录>当前楼一律视为作废
  const 上次记录 = c.垃圾上次[门牌号] ?? -999;
  const 上次 = 上次记录 > 楼层 ? -999 : 上次记录;
  if (楼层 - 上次 < 垃圾同周期锁) {
    return { 提示: '这袋你翻过了,还是那些东西。等她再扔一袋吧。' };
  }
  c.垃圾上次[门牌号] = 楼层;

  // 零钱奖励(2026-07-17 用户提案:任何袋子几率翻出零钱;楼层种子防刷)〔调参〕
  let 零钱 = 0;
  if (seededRandom(楼层, 门牌号, '垃圾零钱') < 垃圾零钱概率) {
    零钱 = 5 + Math.floor(seededRandom(楼层, 门牌号, '零钱额') * 16); // 5~20 元
    data.现金 += 零钱;
  }
  const 零钱语 = 零钱 ? ` 袋底还压着几张皱巴巴的零钱(+¥${零钱})。` : '';

  // 硬门:非垃圾渠道户=死路(死路计数照记;零钱照捡)
  if (!配 || 配.渠道 !== '翻垃圾') {
    const 死 = 死路反馈('翻垃圾', 门牌号, c);
    return { 提示: 死.提示 + 零钱语, 碎片到手: 零钱 > 0 };
  }

  // 已确认:垃圾恢复成普通垃圾
  if (节点.妻.裂缝.已确认) {
    写计数(c);
    return { 提示: '都是些寻常的生活垃圾——你要知道的,已经知道了。' + 零钱语, 碎片到手: 零钱 > 0 };
  }

  // 几率+软保底(楼层种子:同楼重roll结果不变,防刷)
  const 出货 =
    c.垃圾空手[门牌号] >= 垃圾软保底次数 || seededRandom(楼层, 门牌号, '翻垃圾') < 垃圾出货概率;
  if (!出货) {
    c.垃圾空手[门牌号] = (c.垃圾空手[门牌号] ?? 0) + 1;
    写计数(c);
    return {
      提示: '一袋普通的生活垃圾:外卖盒、零食袋、快递纸箱。今天没有线索。' + 零钱语,
      碎片到手: 零钱 > 0,
    };
  }
  c.垃圾空手[门牌号] = 0;
  写计数(c);

  // 出碎片
  const 进度 = 节点.妻.裂缝.碎片进度;
  if (进度 >= 4) return { 提示: '袋子里没有新东西了。' + 零钱语, 碎片到手: 零钱 > 0 };
  const 文案 = 配.碎片信?.[进度] ?? '一张看不清的碎纸。';
  节点.妻.裂缝.碎片进度 = 进度 + 1;
  镜像直写(门牌号, { 碎片: 进度 + 1 });
  const 妻名 = 户静态表[门牌号].妻名;
  const 集齐 = 节点.妻.裂缝.碎片进度 >= 4;
  if (集齐 && !data.背包.includes(`拼合的信·${妻名}`)) data.背包.push(`拼合的信·${妻名}`);
  return {
    提示: `【线索 ${节点.妻.裂缝.碎片进度}/4】${文案}${零钱语}`,
    事件: `【翻垃圾的收获】{{user}}在垃圾房${妻名}家的垃圾袋里翻到了一样东西:${文案}。若本轮场景在垃圾房,可自然演出这次翻找(紧张、楼道脚步声、塑料袋的响动);其他场景则不必提及。严禁替{{user}}解读这条线索的含义`,
    碎片到手: true,
    集齐,
  };
}

