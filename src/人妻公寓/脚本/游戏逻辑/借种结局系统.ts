function 查找可拍借种产后家庭合照(
  data: SchemaType,
  当前地点: string,
  夏乔在场: boolean,
  陆嘉明在场: boolean,
): 借种产后家庭合照凭据 | null {
  const 妻 = data.户['101']?.妻;
  if (!妻 || !夏乔在场 || !陆嘉明在场) return null;
  for (const 凭据 of 列出借种产后家庭合照待拍凭据(data)) {
    if (借种产后家庭合照已拍(data, 凭据.场次标识, 凭据.胎次)) continue;
    const 有对应孩子 = data.系统._家庭文档.孩子.some(
      孩子 =>
        孩子.母亲门牌 === '101' &&
        孩子.胎次 === 凭据.胎次 &&
        孩子.出生场次标识 === 凭据.场次标识,
    );
    if (!有对应孩子) continue;
    if (当前地点 === '医院') {
      const 是当前住院胎 =
        妻._生产.状态 === '住院中' &&
        妻._生产.本胎序号 === 凭据.胎次 &&
        妻._怀孕.受孕场次标识 === 凭据.场次标识;
      const 已有现场资格 = 妻._生产.产后看望 || (妻._生产.结果 === '陪产' && 妻._生产.生产叙事已完成);
      if (是当前住院胎 && 已有现场资格) return 凭据;
      continue;
    }
    if (当前地点 === '101' && !读取医院内容策略(data, '101').医院中) return 凭据;
  }
  return null;
}

