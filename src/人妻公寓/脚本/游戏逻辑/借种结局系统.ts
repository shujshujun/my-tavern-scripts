/**
 * 复用安装摄像头的同一本账。角色位置与撬门事实由调用层现场复核后传入，
 * 本函数仍再次校验票、路线、布设与大型场景状态，避免旧UI或手工事件绕过。
 */
export function 拆除借种摄像头(
  data: SchemaType,
  当前地点: string,
  通过撬门进入: boolean,
  目标房无人: boolean,
): 借种操作结果 {
  if (借种结局已完成(data)) return { 成功: false, 提示: '借种结局已经完成，摄像头可以按普通流程处理。' };
  if (data.系统._家庭计划.阶段 !== '已完成') return { 成功: false, 提示: '家庭计划还没有走到拆除观察点这一步。' };
  if (!借种票在背包(data)) return { 成功: false, 提示: '先在特殊场景货架买下「借种」。' };
  if (data.系统._特殊场景.id) return { 成功: false, 提示: '当前特殊场景尚未结束，不能同时拆除101观察点。' };
  if (当前地点 !== '101') return { 成功: false, 提示: '必须亲自进入101，才能找到原来的安装位置。' };
  if (!通过撬门进入) return { 成功: false, 提示: '不能当面拆除。等101无人后，从撬开的门进去处理。' };
  if (!目标房无人) return { 成功: false, 提示: '101里还有人，现在不能拆。' };
  if (data.系统._摄像头布设['101'] !== true) {
    if (借种摄像头已拆(data)) return { 成功: true, 提示: '101观察点已经拆下；回302确认无信号。' };
    return { 成功: false, 提示: '101当前没有可拆除的针孔摄像头。' };
  }

  data.系统._摄像头布设['101'] = false;
  // 真正的 true → false 每次都返还一枚；背包里已有其他摄像头也不能吞掉本枚设备。
  data.背包.push('针孔摄像头');
  记录借种前置(data, 借种摄像头已拆键);
  移除借种前置(data, 借种断线已确认键);
  return {
    成功: true,
    变动: true,
    提示: '针孔摄像头已经从101拆下并收回背包。现在回302，亲眼确认CAM-101已经断线。',
  };
}

export function 确认借种监控断线(data: SchemaType, 当前地点: string): 借种操作结果 {
  if (借种结局已完成(data)) return { 成功: false, 提示: '借种结局已经完成。' };
  if (!借种票在背包(data)) return { 成功: false, 提示: '背包里没有「借种」场景票。' };
  if (当前地点 !== '302') return { 成功: false, 提示: '只有回到302，才能从自己的监控台确认信号。' };
  if (!借种摄像头已拆(data)) return { 成功: false, 提示: '101观察点还没有拆除。' };
  if (data.系统._摄像头布设['101'] === true) return { 成功: false, 提示: 'CAM-101仍有信号，观察点并没有真正移除。' };
  if (借种断线已确认(data)) return { 成功: true, 提示: 'CAM-101的断线状态已经确认。' };

  记录借种前置(data, 借种断线已确认键);
  return {
    成功: true,
    变动: true,
    提示: 'CAM-101 / NO SIGNAL。观察点已经确认移除；星期一晚上带着场景票去101。',
  };
}

