/** 商店的唯一借种票购买口；调用前商店层仍会复核商品确实在当前货架。 */
export function 购买借种场景票(data: SchemaType, 价格: number): 借种操作结果 {
  const 妻 = data.户['101']?.妻;
  if (data.系统._家庭计划.阶段 !== '已完成') return { 成功: false, 提示: '先完成夏乔的家庭计划。' };
  if (!妻 || 妻.当前阶段 < 5) return { 成功: false, 提示: '夏乔还没有走到这项家庭安排的最终阶段。' };
  if (借种结局已完成(data)) return { 成功: false, 提示: '夏乔的「借种」结局已经完成。' };
  if (借种票在背包(data) || 借种场景运行中(data)) {
    return { 成功: false, 提示: '「借种」场景票已经购买或正在使用。' };
  }
  if (data.系统._特殊场景.id) return { 成功: false, 提示: '眼下已有一场特殊事件正在进行。' };
  if (data.系统._待发送事件) return { 成功: false, 提示: '眼下已有一桩事在发生——过一楼再来。' };
  if (!Number.isFinite(价格) || 价格 <= 0) return { 成功: false, 提示: '「借种」商品价格配置无效。' };
  if (data.现金 < 价格) return { 成功: false, 提示: '钱不够。' };
  data.现金 -= 价格;
  data.背包.push(借种场景ID);
  return {
    成功: true,
    变动: true,
    提示: '「借种」场景票已放入背包。正式开始前，必须先亲自清理101的观察点。',
  };
}

