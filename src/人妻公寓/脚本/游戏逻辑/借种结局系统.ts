export function 借种启动条件提示(data: SchemaType, 当前地点: string): string {
  const 妻 = data.户['101']?.妻;
  const 亲密阻断 = 特殊场景启动亲密门(data);
  if (亲密阻断) return 亲密阻断;
  if (借种结局已完成(data)) return '这条借种结局已经完成。';
  if (data.系统._家庭计划.阶段 !== '已完成') return '家庭计划尚未完成。';
  if (!妻 || 妻.当前阶段 < 5) return '夏乔还没有走到可以完成这项家庭安排的阶段。';
  if (!借种票在背包(data)) return '背包里没有「借种」场景票。';
  if (!借种摄像头已拆(data)) return '先等101无人，撬门进去拆下针孔摄像头。';
  if (!借种断线已确认(data)) return '先回302，从监控台确认CAM-101已经无信号。';
  if (data.系统._摄像头布设['101'] === true) return '101观察点已经重新上线，今晚不能开始。';
  if (当前地点 !== '101') return '请亲自前往101。';
  if (当前星期(data) !== '星期一') return '只能在夏乔的固定易孕日星期一开始。';
  if (!['晚上', '深夜'].includes(当前时段(data.系统._绝对时段))) return '只能在星期一晚上或深夜开始。';
  if (妻._怀孕.状态 !== '未孕') return '夏乔当前已经处在怀孕流程中。';
  if (已达生产上限(data, '101')) return '夏乔已经达到当前设计的生产上限。';
  if (!读取医院内容策略(data, '101').允许成人特殊场景) return '夏乔正在医院待产或恢复。';
  if (data.系统._特殊场景.id) return '眼下已有一场特殊事件正在进行。';
  if (data.系统._场景剧情事务.id || data.系统._待发送事件) return '还有一段场景剧情没有处理完。';
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态) return '请先完成并挂断父亲电话。';
  return '';
}

export function 启动借种结局(data: SchemaType, 当前地点: string, 当前楼层: number): 借种操作结果 {
  const 阻断 = 借种启动条件提示(data, 当前地点);
  if (阻断) return { 成功: false, 提示: 阻断 };
  const 票位 = data.背包.indexOf(借种场景ID);
  if (票位 < 0) return { 成功: false, 提示: '场景票已经不在背包里。' };

  data.背包.splice(票位, 1);
  // 借种不把此前拆封的保护准备带进本场；避免场景目标与普通保护状态互相冲突。
  data.玩家资源.保护准备 = false;
  data.系统._特殊场景 = {
    ...空特殊场景(),
    id: 借种场景ID,
    阶段: '开场',
    地点: '101',
    参与妻: ['101'],
    演出妻: ['101'],
    演出夫: ['101'],
    启动楼层: Math.max(0, Math.round(当前楼层) + 1),
    当前拍: 1,
  };
  return {
    成功: true,
    变动: true,
    提示: '101的观察点已经断线。夏乔和陆嘉明都在等你进门。',
  };
}

