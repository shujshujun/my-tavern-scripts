export function 推进借种开场(data: SchemaType): boolean {
  const 场 = data.系统._特殊场景;
  if (场.id !== 借种场景ID || 场.阶段 !== '开场' || 场.当前拍 !== 1) return false;
  场.阶段 = '亲密';
  场.当前拍 = 2;
  场.演出妻 = ['101'];
  // 陆嘉明仍在101的家庭关系里，但不进入卧室现场，也不参与后续成人演出。
  场.演出夫 = [];
  return true;
}

export function 停止借种结局(data: SchemaType, 当前地点: string): 借种操作结果 {
  if (!借种场景运行中(data)) return { 成功: false, 提示: '当前没有正在进行的借种场景。' };
  if (当前地点 !== '101') return { 成功: false, 提示: '必须留在101现场停止这次安排。' };
  if (data.系统._性爱场景.状态 !== '空闲') {
    return { 成功: false, 提示: '亲密场景已经开始，请使用亲密面板里的「停下并收尾」。' };
  }
  恢复借种票(data);
  data.系统._特殊场景 = 空特殊场景();
  return {
    成功: true,
    变动: true,
    提示: '这次安排已经停下；场景票已恢复，摄像头拆除和302断线确认仍然保留。',
  };
}

export function 借种玩家行动许可(data: SchemaType, 当前地点: string): 借种操作结果 {
  const 场 = data.系统._特殊场景;
  if (场.id !== 借种场景ID) return { 成功: true, 提示: '' };
  if (当前地点 !== '101') return { 成功: false, 提示: '借种场景已经开始，必须留在101完成或停止。' };
  // 开场由同一张固定节拍票接管；首次自动生成失败时，玩家可以从输入区直接重试该拍。
  if (场.阶段 === '开场') return { 成功: true, 提示: '' };
  if (场.阶段 !== '亲密') return { 成功: false, 提示: '当前借种阶段不能提交普通行动。' };
  return { 成功: true, 提示: '' };
}

