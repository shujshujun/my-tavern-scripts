/**
 * 普通亲密系统结束时的唯一借种接管口。有效体内完成会在同一对象内原子写入怀孕、
 * 完成事实和清场；停止、角色中止或任何不合法收尾都恢复票据并保留已完成的拆机前置。
 */
export function 结算借种亲密收尾(
  data: SchemaType,
  结果: SchemaType['系统']['_上次性爱结果'],
): 借种亲密结算结果 {
  if (!借种场景运行中(data)) return { 接管: false, 完成: false, 受孕: '未处理', 提示: '' };

  const 场 = data.系统._特殊场景;
  const 有效完成 = 场.阶段 === '亲密' && 借种完成收尾事实有效(结果);

  if (!有效完成) {
    恢复借种票(data);
    data.系统._特殊场景 = 空特殊场景();
    return {
      接管: true,
      完成: false,
      受孕: '未处理',
      提示: '本次借种已经安全停止；场景票已恢复，拆机与断线确认仍然有效。',
    };
  }

  const 受孕 = 保证夏乔借种受孕(data, 结果.场次标识);
  if (受孕 !== '已受孕') {
    恢复借种票(data);
    data.系统._特殊场景 = 空特殊场景();
    return {
      接管: true,
      完成: false,
      受孕,
      提示: '借种完成条件在最终提交时已经变化；没有登记结局或怀孕，场景票已恢复。',
    };
  }

  if (!data.系统._已完成特殊场景.includes(借种场景ID)) data.系统._已完成特殊场景.push(借种场景ID);
  清除借种临时前置(data);
  data.系统._特殊场景 = 空特殊场景();
  return {
    接管: true,
    完成: true,
    受孕,
    提示: '夏乔「借种」结局已经完成；受孕结果已由脚本确定，当前仍处于尚未能确认的隐藏期。',
  };
}
