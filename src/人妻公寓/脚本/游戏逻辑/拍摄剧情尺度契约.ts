import type { 门牌 } from '../../stageConfig';
import {
  第二机位事件禁止正式亲密,
  解析第二机位剧情事件,
} from './第二机位系统';
import {
  不再留门事件禁止正式亲密,
  解析不再留门剧情事件,
} from './不再留门系统';
import { 解析安若妍换掉剧情事件 } from './安若妍换掉系统';

export type 拍摄剧情线路 = '第二机位' | '不再留门' | '换掉' | '录像带V4';

/**
 * 拍摄题材固定拍的权威尺度维度。
 *
 * “行为尺度上限”只约束本楼新发生的身体行为；录像、镜头、照片、母带与回放属于
 * 独立的场景媒介维度。当前拍任务和禁止提前事实仍由各线路原有解析器／验收器负责，
 * 本契约不复制第二套路线名单，也不替代专属节拍验收。
 */
export interface 拍摄剧情尺度契约 {
  线路: 拍摄剧情线路;
  场景ID: string;
  当前拍: number | null;
  人物: readonly 门牌[];
  地点: string;
  行为尺度上限: number | null;
  允许录制语境: true;
  只计本楼新增行为: true;
  独立结算: boolean;
  冻结事件: string;
  必须完成事实: string;
  禁止提前事实: string;
}

function 录像带V4契约(事件: string): 拍摄剧情尺度契约 | null {
  const 匹配 = 事件.match(/【特殊场景·(录像带前置|录像带|录像带双承接)(?:·([^】]+))?】/u);
  if (!匹配) return null;
  const 节点 = 匹配[2] ?? '';
  const 房 = 节点.match(/^(102|202)-/u)?.[1] as 门牌 | undefined;
  return {
    线路: '录像带V4',
    场景ID: `${匹配[1]}${节点 ? `:${节点}` : ''}`,
    当前拍: Number(nodePart(节点)) || null,
    人物: 房 ? [房] : ['102', '202'],
    地点: '管理员室',
    行为尺度上限: null,
    允许录制语境: true,
    只计本楼新增行为: true,
    独立结算: true,
    冻结事件: 事件,
    必须完成事实: '只演冻结事件指定的当前录像／母带节点与管理员室观看反应。',
    禁止提前事实: '不得把屏幕内容冒充管理员室本楼身体行为；节点推进服从录像带独立状态机。',
  };
}

function nodePart(节点: string): string {
  return 节点.match(/-(\d+)$/u)?.[1] ?? '';
}

export function 读取拍摄剧情尺度契约(原事件: unknown): 拍摄剧情尺度契约 | null {
  const 事件 = String(原事件 ?? '');
  if (!事件) return null;

  const 第二机位票 = 解析第二机位剧情事件(事件);
  if (第二机位票) {
    const 场景ID =
      第二机位票.类型 === '对饮空窗'
        ? `对饮空窗:${第二机位票.预期阶段}`
        : 第二机位票.动作;
    return {
      线路: '第二机位',
      场景ID,
      当前拍: 第二机位票.拍,
      人物: ['102'],
      地点: '102',
      行为尺度上限: 第二机位事件禁止正式亲密(事件) ? 2 : null,
      允许录制语境: true,
      只计本楼新增行为: true,
      独立结算: false,
      冻结事件: 事件,
      必须完成事实: '只完成冻结的《第二机位》当前拍；具体末帧服从事件票。',
      禁止提前事实: '不得提前进入下一拍、母带流转或共享结局；最终仍由《第二机位》专属验收器裁决。',
    };
  }

  const 不再留门票 = 解析不再留门剧情事件(事件);
  if (不再留门票) {
    return {
      线路: '不再留门',
      场景ID: 不再留门票.场景,
      当前拍: 不再留门票.拍,
      人物: ['202'],
      地点: 不再留门票.场景 === 'A2' ? '公寓外部' : '202',
      行为尺度上限: 不再留门事件禁止正式亲密(事件) ? 2 : null,
      允许录制语境: true,
      只计本楼新增行为: true,
      独立结算: false,
      冻结事件: 事件,
      必须完成事实: '只完成冻结的《不再留门》当前拍；照片、许可、设备或录制事实服从事件票。',
      禁止提前事实: '不得替玩家作出许可、提前开录、停录、交带或归档；最终仍由《不再留门》专属验收器裁决。',
    };
  }

  const 换掉票 = 解析安若妍换掉剧情事件(事件);
  if (换掉票) {
    return {
      线路: '换掉',
      场景ID: 换掉票.场景,
      当前拍: null,
      人物: ['301'],
      地点: ['A1', 'B1', 'B2', 'C1', 'C2', 'H1', 'P1', 'P2', 'H10', 'H11', 'H12'].includes(换掉票.场景)
        ? '301'
        : '',
      // 《换掉》H1及同一场次拥有自己的亲密账本；这里不另造一个全线“非露骨”上限。
      行为尺度上限: null,
      允许录制语境: true,
      只计本楼新增行为: true,
      独立结算: false,
      冻结事件: 事件,
      必须完成事实: '只完成冻结的《换掉》当前场景；拍立得、镜头、照片和显影均是场景媒介事实。',
      禁止提前事实: '不得把拍照本身当成新身体行为，也不得提前换照、发群消息或完成结局。',
    };
  }

  return 录像带V4契约(事件);
}
