  const 行: string[] = ['<公寓快照>'];

  // 时段(楼层时钟:脚本管"几点档",AI 管钟点但须落在档内;杀时间偏移统一吃进时间读数)
  const 偏移 = data.系统._时段偏移楼;
  行.push(`【当前时段】${当前时段(楼层 + 偏移)}`);

  // 场景(地图模式:房间氛围+进入方式;位置种子在房内期间冻结,与检测焦点同一真值)
