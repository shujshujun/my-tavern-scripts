/** 罪恶感 = 堕落跑在防线崩塌前面的差值(修道院螺旋换皮:防线轴从信仰值换成婚姻值) */
export function 罪恶感(妻: { 堕落值: number; 婚姻值: number }): number {
  return Math.max(0, 妻.堕落值 - (100 - 妻.婚姻值));
}

