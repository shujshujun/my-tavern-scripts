/** 玩家当前场景(客户端地图写 chat 变量;走动零成本纯 UI 不产楼) */
export function 读场景(): { 房间id?: string; 破门?: boolean; 进房末楼?: number } {
  return (_.get(getVariables({ type: 'chat' }), '_场景') ?? {}) as {
    房间id?: string;
    破门?: boolean;
    进房末楼?: number;
  };
}

/**
 * 检测焦点户:
 *   地图模式(_场景.房间id)→ 按妻位置推算比对:她真在这个房间才算焦点(公共区偶遇同理);
 *   她不在但这是她家且丈夫在家 → 这户仍是焦点(丈夫应门:陪酒/打听戏走这条道)。
 *   进房期间用"进房末楼"冻结位置种子(修道院范式:否则楼号推进会把身边的人"传送"走)。
 *   无场景(原生玩法)→ 文本扫描妻/夫名,首中=焦点,其余=在场
 * 母亲(302)系统级隐身:入列前不进焦点候选(叙事在场由 AI 自由演,无记账块)。
 */
export function 检测焦点(
  chat: { role: string; content: string }[],
  data: SchemaType,
  楼层: number,
): { 焦点: 门牌[]; 在场: 门牌[] } {
  const 候选 = (Object.keys(data.户) as 门牌[]).filter(m => !户静态表[m]?.隐身);

  const { 房间id, 进房末楼 } = 读场景();
  if (房间id) {
    const 种子楼 = 进房末楼 ?? 楼层;
    const 在此 = 候选.filter(m => {
      if (妻位置推算(m, 种子楼) === 房间id) return true;
      return m === 房间id && 丈夫状态推算(m, 种子楼) !== '外出';
    });
    return { 焦点: 在此.slice(0, 1), 在场: 在此.slice(1, 3) };
  }

  const 尾部 = chat.slice(-4).reverse(); // 末条优先
  const 命中: 门牌[] = [];
  for (const 楼 of 尾部) {
    for (const m of 候选) {
      if (命中.includes(m)) continue;
      const { 妻名, 夫名 } = 户静态表[m];
      if (楼.content.includes(妻名) || (夫名 && 楼.content.includes(夫名))) 命中.push(m);
    }
  }
  return { 焦点: 命中.slice(0, 1), 在场: 命中.slice(1, 3) };
}

/** 妻位置 → 一句人话(焦点块"她不在场"警示用) */
function 位置感知(位置: string): string {
  if (位置 === '外出') return '出门在外了';
  const 房 = 查房间(位置);
  return 房 ? `这会儿在${房.名称}` : '不在附近';
}

