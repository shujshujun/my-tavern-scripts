/**
 * 对话粘滞(2026-07-18 用户拍板:聊着天的人不许被楼层时钟传送走,玩家离开才解除)。
 * 组快照注入 每轮把"当场的人"钉在当场;读取自校验:位置对不上(玩家换了地方)=不生效,
 * 楼戳在未来(回档过)=作废——粘滞天然随玩家脚步失效,不需要显式清理。
 */
export interface 粘滞状态 {
  位置?: string;
  楼?: number;
  们?: 门牌[];
  离场?: 门牌[];
}

export function 读粘滞状态(): 粘滞状态 | null {
  return (_.get(getVariables({ type: 'chat' }), '_粘滞') ?? null) as 粘滞状态 | null;
}

export function 读粘滞(楼层: number, 房间id: string): 门牌[] {
  const p = 读粘滞状态();
  if (!p || p.位置 !== 房间id || (p.楼 ?? 0) > 楼层) return [];
  return p.们 ?? [];
}

/**
 * 读赴约(2026-07-18 用户提案:微信"+"约出来):应约期间她的位置=玩家的位置。
 * 起楼在未来=回档过→作废;过了至楼=有效期(2个时段)结束,她回归作息。
 */
export function 读赴约(楼层: number): { m: 门牌; 至楼: number } | null {
  const p = (_.get(getVariables({ type: 'chat' }), '_赴约') ?? null) as {
    m?: 门牌;
    起楼?: number;
    至楼?: number;
  } | null;
  if (!p?.m || (p.起楼 ?? 0) > 楼层 || (p.至楼 ?? -1) < 楼层) return null;
  return { m: p.m, 至楼: p.至楼 ?? 楼层 };
}

/**
 * 微信渠道人物状态包(2026-07-18 用户拍板:微信与正文同源感知,治"现实冷漠微信热情"的口吻断裂)。
 * 内容=正文快照同一套感知语(好感/阶段基调/罪恶)+AI自己写的情绪与心理——全是演出语,无裸数值无机制。
 */
export function 妻状态包(m: 门牌, data: SchemaType): string {
  const 节点 = data.户[m];
  if (!节点) return '';
  const 妻 = 节点.妻;
  const 段 = [好感感知(妻.好感值), 阶段行为基调[妻.当前阶段]];
  const 罪 = 罪恶感知(罪恶感(妻));
  if (罪) 段.push(罪);
  return (
    `她此刻的真实状态(口吻必须据此拿捏):${段.join(';')}` +
    (妻.当前情绪 ? `;情绪:${妻.当前情绪}` : '') +
    (妻.当前心理想法 ? `;心里正想着:${妻.当前心理想法}` : '') +
    '。'
  );
}

export interface 事件角色绑定 {
  在场妻: 门牌[];
  在场夫: 门牌[];
  关联妻: 门牌[];
  关联夫: 门牌[];
}

const 解析门牌串 = (值: string | undefined): 门牌[] =>
  _.uniq(
    (值 ?? '')
      .split(',')
      .map(x => x.trim())
      .filter((x): x is 门牌 => /^\d{3}$/.test(x)),
  );

/**
 * 强制事件角色绑定协议：
 * - 在场：临时事件演员，不服从日常作息，进入焦点并取得可写状态。
 * - 关联：只给事件所需的状态，不把人传送到玩家当前位置，也不开放变量更新。
 * - 旧版【事件妻:门牌】继续视为单妻在场。
 * 没有显式元数据的旧事件会按角色姓名补出“关联”状态，避免只有剧情文案、没有人物变量。
 */
export function 解析事件角色绑定(事件: string, data: SchemaType): 事件角色绑定 {
  const 取 = (标签: string) => 解析门牌串(事件.match(new RegExp(`【${标签}:([\\d,]+)】`))?.[1]);
  const 旧妻 = 解析门牌串(事件.match(/【事件妻:(\d{3})】/)?.[1]);
  const 在场妻 = _.uniq([...旧妻, ...取('事件在场妻')]);
  const 在场夫 = 取('事件在场夫');
  const 关联妻 = _.uniq([...在场妻, ...取('事件关联妻')]);
  const 关联夫 = _.uniq([...在场夫, ...取('事件关联夫')]);

  for (const m of Object.keys(data.户) as 门牌[]) {
    const 配 = 户静态表[m];
    if (!配) continue;
    if (配.妻名 && 事件.includes(配.妻名)) 关联妻.push(m);
    if (配.夫名 && 事件.includes(配.夫名)) 关联夫.push(m);
  }
  if (data.户['302'] && /(?:妈|母亲)/.test(事件)) 关联妻.push('302');
  if (data.户['302'] && /(?:父亲|爸爸|爸的|越洋来电)/.test(事件)) 关联夫.push('302');

  // 0.45 旧存档可能已经排着没有元数据的强制事件。按事件类别补“实际在场”，
  // 让升级后的第一楼也能读取正确变量；普通回响不在此列，避免凭空传送。
  if (!在场妻.length && !在场夫.length) {
    if (/【(?:转折正戏|药物首夜|破墙|首穿|性癖开幕(?:·[^】]+)?|重燃|新住户|早饭桌|那扇门)】/.test(事件)) {
      在场妻.push(...关联妻);
      if (/【新住户】/.test(事件)) 在场夫.push(...关联夫);
    }
    if (/【(?:被看见了|她看见了,然后)】/.test(事件)) {
      在场妻.push(...关联妻);
      if (data.户['302']) 在场妻.push('302');
    }
    if (/【门缝那一眼】/.test(事件)) {
      在场妻.push('102');
      在场夫.push('102');
    }
    if (/【哑巴亏】/.test(事件)) 在场夫.push('202');
    const 特殊名 = 事件.match(/【特殊场景·([^】]+)】/)?.[1];
    const 特殊 = 特殊名 ? 查特殊场景(特殊名) : undefined;
    if (特殊) {
      const 参与妻 = 特殊.参与(data as never);
      在场妻.push(...(特殊.演出妻?.(data as never) ?? 参与妻));
      在场夫.push(...(特殊.演出夫?.(data as never) ?? []));
    }
  }

  return {
    在场妻: _.uniq(在场妻).filter(m => !!data.户[m]),
    在场夫: _.uniq(在场夫).filter(m => !!data.户[m]),
    关联妻: _.uniq(关联妻).filter(m => !!data.户[m]),
    关联夫: _.uniq(关联夫).filter(m => !!data.户[m]),
  };
}

export function 事件角色标记(参数: Partial<事件角色绑定>): string {
  const 段: string[] = [];
  if (参数.在场妻?.length) 段.push(`【事件在场妻:${_.uniq(参数.在场妻).join(',')}】`);
  if (参数.在场夫?.length) 段.push(`【事件在场夫:${_.uniq(参数.在场夫).join(',')}】`);
  if (参数.关联妻?.length) 段.push(`【事件关联妻:${_.uniq(参数.关联妻).join(',')}】`);
  if (参数.关联夫?.length) 段.push(`【事件关联夫:${_.uniq(参数.关联夫).join(',')}】`);
  return 段.join('');
}

const 清事件角色标记 = (文本: string): string =>
  文本.replace(/【事件(?:妻|在场妻|在场夫|关联妻|关联夫):[\d,]+】/g, '');

/**
 * 检测焦点户:
 *   地图模式(_场景.房间id)→ 按妻位置推算比对:她真在这个房间才算焦点(公共区偶遇同理);
 *   她不在但这是她家且丈夫在家 → 这户仍是焦点(丈夫应门:陪酒/打听戏走这条道)。
 *   进房期间用"进房末楼"冻结位置种子(修道院范式:否则楼号推进会把身边的人"传送"走)。
 *   无场景(原生玩法)→ 文本扫描妻/夫名,首中=焦点,其余=在场
 * 母亲(302)系统级隐身:入列前不进焦点候选(叙事在场由 AI 自由演,无记账块)。
 */
export function 检测焦点(
  chat: { role: string; content: string }[],
  data: SchemaType,
  楼层: number,
): { 焦点: 门牌[]; 在场: 门牌[]; 妻在场: 门牌[]; 夫在场: 门牌[] } {
  // 存在性守卫(审计 低危13):`!undefined?.隐身` 为 true,脏档野门牌会一路放行到解构裸取
  const 候选 = (Object.keys(data.户) as 门牌[]).filter(
    m => 户静态表[m] && (!户静态表[m].隐身 || data.系统._母亲入列),
  );
  // 临时登场事件不服从日常作息位置。旧版冷落探访只在事件文案中写“她来找你”，
  // 地图焦点仍按作息判断，导致来访者没有状态包，AI 会脱离阶段/情绪自由脑补。
  const 事件绑定 = 解析事件角色绑定(取本轮事件文本(data, 楼层), data);
  const 应用事件演员 = (结果: { 焦点: 门牌[]; 在场: 门牌[]; 妻在场: 门牌[]; 夫在场: 门牌[] }) => {
    const 事件妻 = 事件绑定.在场妻.filter(m => 候选.includes(m));
    const 事件夫户 = 事件绑定.在场夫.filter(m => 候选.includes(m));
    const 事件焦点 = _.uniq([...事件妻, ...事件夫户]);
    if (!事件焦点.length) return 结果;
    const 原焦点 = 结果.焦点.filter(m => !事件焦点.includes(m));
    return {
      焦点: [...事件焦点, ...原焦点],
      在场: _.uniq([...原焦点, ...结果.在场]).filter(m => !事件焦点.includes(m)).slice(0, 2),
      妻在场: _.uniq([...事件妻, ...结果.妻在场]),
      夫在场: _.uniq([...事件夫户, ...结果.夫在场]),
    };
  };

  const { 房间id, 进房末楼 } = 读场景();
  if (房间id) {
    // 杀时间偏移一并吃进种子:进房期间偏移不可能变(杀时间只在管理员室),冻结语义不破
    const 种子楼 = (进房末楼 ?? 楼层) + data.系统._时段偏移楼;
    const 粘 = 读粘滞(楼层, 房间id);
    const 赴约 = 读赴约(楼层);
    const 粘态 = 读粘滞状态();
    // 离场带过期(审计 低危16):她因连续反感离场后,若玩家一直赖在她家不走,深夜按作息
    // 她"必回自己家"也被永久排除——离场标记只在最近 6 楼(两个时段)内生效
    const 已离场 = new Set(
      粘态?.位置 === 房间id && 楼层 - (粘态?.楼 ?? 0) <= 6 ? (粘态.离场 ?? []) : [],
    );
    const 妻在场 = 候选.filter(
      m => !已离场.has(m) && (粘.includes(m) || 妻位置推算(m, 种子楼) === 房间id),
    );
    const 夫在场 = 候选.filter(m => m === 房间id && 丈夫在楼(data.户[m], m, 种子楼) !== '外出');
    const 在此 = _.uniq([...妻在场, ...夫在场]);
    // 赴约妻:她的位置=玩家的位置(微信约出来的),排焦点首位
    const 约 = 赴约;
    if (约 && 候选.includes(约.m)) {
      if (!妻在场.includes(约.m)) 妻在场.push(约.m);
      const i = 在此.indexOf(约.m);
      if (i >= 0) 在此.splice(i, 1);
      在此.unshift(约.m);
    }
    return 应用事件演员({ 焦点: 在此.slice(0, 1), 在场: 在此.slice(1, 3), 妻在场, 夫在场 });
  }

  // 无地图文本扫描兜底(2026-07-26 审计 M10 加固):
  // (a) 302 的名字是通用词("母亲""父亲"),游戏自己生产的"父亲来电/跟父亲通话"文本会
  //     误把 302 判成焦点在场→AI 收到"她本人在场"凭空传送——302 不进文本扫描候选
  //     (地图路径按房间号精确匹配,302 交互不受影响);
  // (b) UI 生成的行动模板自带角色名(打听/对饮:"向街坊打听夏乔家的事"),提到≠在场——
  //     玩家消息剥掉开头的括号系统段再扫;
  // (c) 同条消息多人命中按出现位置排序(旧版按门牌序,注释说"首中"实现却永远选 101);
  // (d) 扫描起点跳过 0 楼(固定 0 楼=客户端 HTML,不是剧情)——起点由 近楼对话 保证,
  //     此处对 chat 数组尾 4 条扫描不变。
  const 尾部 = chat.slice(-4).reverse(); // 末条优先
  const 扫描候选 = 候选.filter(m => m !== '302');
  const 命中: 门牌[] = [];
  const 妻在场: 门牌[] = [];
  const 夫在场: 门牌[] = [];
  for (const 楼 of 尾部) {
    const 文 = 楼.role === 'user' ? 楼.content.replace(/^[((][^))]*[))]/, '') : 楼.content;
    const 本条: { m: 门牌; 位: number; 妻: boolean; 夫: boolean }[] = [];
    for (const m of 扫描候选) {
      const { 妻名, 夫名 } = 户静态表[m];
      const 妻位 = 文.indexOf(妻名);
      const 夫位 = 夫名 ? 文.indexOf(夫名) : -1;
      if (妻位 < 0 && 夫位 < 0) continue;
      const 位 = Math.min(...[妻位, 夫位].filter(x => x >= 0));
      本条.push({ m, 位, 妻: 妻位 >= 0, 夫: 夫位 >= 0 });
    }
    本条.sort((a, b) => a.位 - b.位);
    for (const { m, 妻, 夫 } of 本条) {
      if (妻 && !妻在场.includes(m)) 妻在场.push(m);
      if (夫 && !夫在场.includes(m)) 夫在场.push(m);
      if (!命中.includes(m)) 命中.push(m);
    }
  }
  return 应用事件演员({ 焦点: 命中.slice(0, 1), 在场: 命中.slice(1, 3), 妻在场, 夫在场 });
}

