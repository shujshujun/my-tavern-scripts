      '【特殊场景·独立结算】本轮人物状态只供演出，拍次、成长和最终结果只服从特殊场景脚本；不得创建或推进普通亲密账本，无需输出普通尺度控制块。录像、屏幕、回忆与转述中的行为不是管理员室现场行为。',
