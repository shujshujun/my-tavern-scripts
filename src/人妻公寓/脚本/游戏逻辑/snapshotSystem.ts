/**
 * 完整提示只在必要时刷新；其余成功正文使用最小内核。节拍存于 stat_data，只有回合
 * 成功提交后才推进，所以取消、失败、重掷与两条不同楼号路径都不会扰乱循环。
 */
export function 规划快照刷新(
  data: SchemaType,
  本楼事件: string,
  人物: 快照人物态,
): 快照刷新票 {
  const 场 = 读场景();
  const 性爱 = data.系统._性爱场景;
  const 特殊 = data.系统._特殊场景;
  const 场景签名 = JSON.stringify([
    场.房间id ?? '',
    场.进房末楼 ?? -1,
    Boolean(场.破门),
    Boolean(场.非法进入),
    data.系统._绝对时段,
    性爱.状态,
    性爱.场次标识,
    性爱.主焦点门牌,
    性爱.当前行为,
    性爱.当前接触部位,
    性爱.保护状态,
    Object.keys(性爱.参与者).sort(),
    特殊.id,
    特殊.阶段,
    特殊.当前拍,
  ]);
  const 焦点签名 = JSON.stringify([人物.焦点, 人物.在场, 人物.妻在场, 人物.夫在场]);
  const 角色签名 = JSON.stringify(
    人物.焦点.map(m => {
      const 妻 = data.户[m]?.妻;
      return 妻
        ? [m, 妻.当前阶段, 妻.婚姻值 < 25 ? 1 : 0, 妻.裂缝.已确认 ? 1 : 0, [...妻.性癖装载].sort()]
        : [m, '无妻节点'];
    }),
  );
  const 旧 = data.系统._提示刷新态;
  const 原因们: string[] = [];
  if (!旧.场景签名 || !旧.焦点签名) 原因们.push('首次');
  if (旧.场景签名 && 旧.场景签名 !== 场景签名) 原因们.push('场景或亲密状态变化');
  if (旧.焦点签名 && 旧.焦点签名 !== 焦点签名) 原因们.push('在场或焦点变化');
  if (旧.角色签名 && 旧.角色签名 !== 角色签名) 原因们.push('角色边界变化');
  if (本楼事件) 原因们.push('本楼事件');
  if (!原因们.length && 旧.距完整楼数 >= 2) 原因们.push('三楼刷新');
  const 完整 = 原因们.length > 0;
  return {
    模式: 完整 ? '完整' : '最小',
    原因: 原因们.join('、') || '连续场景最小内核',
    下一态: {
      版本: 1,
      场景签名,
      焦点签名,
      角色签名,
      距完整楼数: 完整 ? 0 : Math.min(2, 旧.距完整楼数 + 1),
    },
  };
}

