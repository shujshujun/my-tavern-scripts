export function 组公寓快照(chat: { role: string; content: string }[], data: SchemaType, 楼层: number): string {
  // 坏结局已锁定:只注入终局指引,其余系统块全部停止(单向锁防 AI 演活)
  if (data.系统._坏结局) {
    return [
      '<公寓快照>',
      `【坏结局·已锁定】${data.系统._坏结局}:考验已经失败,一切都结束了。`,
      '请演绎终局篇章的余波——收拾、离开、无可挽回,不再开启新的剧情线。',
      '</公寓快照>',
    ].join('\n');
  }

  const { 焦点, 在场 } = 检测焦点(chat, data, 楼层);
  const 行: string[] = ['<公寓快照>'];

  // 时段(楼层时钟:脚本管"几点档",AI 管钟点但须落在档内)
  行.push(`【当前时段】${当前时段(楼层)}`);

  // 场景(地图模式:房间氛围+进入方式;位置种子在房内期间冻结,与检测焦点同一真值)
  const { 房间id, 破门, 进房末楼 } = 读场景();
  const 种子楼 = 房间id ? (进房末楼 ?? 楼层) : 楼层;
  if (房间id) {
    const 房 = 查房间(房间id);
    行.push(`【当前位置】${房 ? `${房.名称}——${房.氛围}` : 房间id}`);
    if (破门) 行.push('【进入方式】这扇门不是被打开的,是被撬开的——没人知道你进来过,除非你留下痕迹');
    if (房?.类型 === '户' && 房间id !== '302') {
      if (!data.户[房间id as 门牌]) {
        行.push('【屋内】这间屋子还空着,没有住户,家具蒙着防尘布');
      } else if (!焦点.length && !在场.length) {
        行.push(
          破门
            ? '【屋内】屋里空无一人——这家人此刻都不在。别让任何人在这一楼凭空回家,除非剧情事件另有指示'
            : '【屋内】敲门没有人应,门里没有动静——这户此刻家里没人。你还站在门外',
        );
      }
    }
    // 母亲底色:脚本藏发不进世界书(2026-07-17 用户拍板——隐藏BOSS的底牌玩家翻卡看不到,
    // 且可按状态梯度揭示;P5 母亲线全套在此扩展)。302 场景才注入,只给公开层。
    if (房间id === '302') {
      行.push(
        '【妈】302 也是你妈住的地方——她五十多岁,操心唠叨型,饭点掐得准,楼里街坊都熟;' +
          '爸常年在海外,她一个人把这个家守成了老样子。对你嘴上嫌弃、手上疼爱。' +
          '她的更多面目由系统在剧情节点注入——在那之前只演一位寻常的母亲,严禁自行编造她的过去、秘密或异样',
      );
    }
  }

  // 在场与相识纪律(分批引出:未入住的户在数据世界里不存在,名字都不该出现)
  const 相识 = (Object.keys(data.户) as 门牌[])
    .flatMap(m => {
      const 配 = 户静态表[m];
      return 配 ? [配.妻名, 配.夫名].filter(Boolean) : [];
    })
    .join('、');
  行.push(
    `【在场与相识纪律】管理员迄今在这栋楼里认识的人只有:${相识}。名单之外的住户尚未出现在他的生活里——严禁让任何名单外的角色登场、传话或被提及名字。` +
      `此刻能与管理员对话的只有【焦点】列出的在场者;不在场的人不得凭空现身,玩家点名要找不在场的人时,如实告知"她此刻不在这里"。`,
  );

  // 焦点户:全量注入(记账通道只开 好感/堕落 两轴,其余全感知语)
  if (焦点.length) {
    行.push('【焦点】(仅以下人物的数值可做小步更新,其余一律禁改)');
    for (const m of 焦点) {
      const 配 = 户静态表[m];
      const { 妻, 夫 } = data.户[m];
      const 夫状态 = 丈夫状态推算(m, 种子楼);
      const 妻位置 = 妻位置推算(m, 种子楼);
      const 感知段 = [好感感知(妻.好感值), 阶段行为基调[妻.当前阶段], 婚姻感知(妻.婚姻值)];
      const 罪 = 罪恶感知(罪恶感(妻));
      if (罪) 感知段.push(罪);
      行.push(
        `◆ ${配.妻名}(${m}室)|阶段:${妻.阶段标题}`,
        `  记账:好感值${妻.好感值} 堕落值${妻.堕落值}(仅供变量更新计算,严禁写进正文)`,
        `  感知:${感知段.join(';')}`,
        妻.当前心理想法 ? `  心理:${妻.当前心理想法}` : '',
        `  情绪:${妻.当前情绪}${妻.气质描述 ? `|气质:${妻.气质描述}` : ''}`,
        [妻.外装, 妻.内衣, 妻.妆容, ...妻.特殊].filter(x => x && x !== '素颜').length
          ? `  着装:${[妻.外装, 妻.妆容 !== '素颜' ? 妻.妆容 : '', ...妻.特殊].filter(Boolean).join('|')}`
          : '',
        `  她的丈夫${配.夫名 ? `(${配.夫名})` : ''}:此刻${夫状态}。${信任感知(配.夫名, 夫.信任值)}`,
      );
      const 疑 = 疑心感知(配.夫名, 夫.疑心值);
      if (疑) 行.push(`  ⚠ ${疑}`);
      // 裂缝双态注入:确认前=只许埋淡淡违和感(内容不给,AI 不知道就不可能泄底);
      // 确认后=隐痛补丁常驻(裂缝+渗进日常+对症±5 红利;演出铁律:她自己永远不说破)
      const 缝 = 查裂缝(m);
      if (缝) {
        行.push(妻.裂缝.已确认 ? `  ${缝.确认后注入}` : `  ${缝.确认前违和感}`);
      }
      // 丈夫应门戏:她本人不在这个房间时明说,防 AI 让她凭空登场
      if (房间id && 妻位置 !== 房间id) {
        行.push(`  ⚠ ${配.妻名}本人此刻不在这里(${位置感知(妻位置)}),眼前应对你的是她丈夫——不要让她凭空出现在这一楼`);
      }
    }
  } else {
    行.push('【焦点】本轮无(任何住户的数值都不得更新)');
  }

  // 在场户:一行存在感(AI 只许情绪位置文本,轻逻辑)
  if (在场.length) {
    行.push('【在场】(每人至多一句掠影,不抢戏,数值禁改)');
    for (const m of 在场) {
      const { 妻 } = data.户[m];
      行.push(`· ${户静态表[m].妻名}:${妻.阶段标题}|${好感感知(妻.好感值)}`);
    }
  }

  // 楼内空气(风闻,替代警戒度)
  行.push(`【楼内空气】${风闻感知(data.风闻)}`);

  // 一次性剧情事件(同楼重roll由 index 决定重放内容,此处只渲染)
  const 事件 = 取本轮事件文本(data, 楼层);
  if (事件) {
    行.push('【本轮剧情事件(一次性,请自然融入演绎,不要复述本提示)】');
    for (const ev of 事件.split('|').filter(Boolean)) 行.push(`  · ${ev}`);
  }

  // 演出规则按场景裁剪:表现通道每轮必带;有人登场才带人格防线;多于一人才带认知隔离
  行.push(表现通道规则);
  if (焦点.length) 行.push(人格防线规则);
  if (焦点.length + 在场.length > 1) 行.push(认知隔离规则);

  // 稽查注入层①:尺度白名单+软失败话术,注入末尾=末位权重最高(写成"她的心理现实",不是系统禁令)
  for (const m of 焦点) {
    const 妻 = data.户[m].妻;
    行.push(`【${户静态表[m].妻名}的界线】${阶段接受上限[_.clamp(Math.floor(妻.当前阶段), 0, 5)]}`);
  }
  if (焦点.length) 行.push(越界应对话术);

  // 输出格式约定(每轮必带:标签协议是稽查的眼睛,选项块是前端按钮的料)
  行.push(行动选项要求, 行为等级自报要求);

  行.push('</公寓快照>');
  return 行.filter(Boolean).join('\n');
}

/**
 * 一次性事件重放判定(防护10:转存重放制,秦璐 v0.25 范式)
 * - 同楼重roll(转存楼层 ≥ 本次生成楼层):重放转存内容,忽略待发送(那是为下一楼产出的)
 * - 正常过楼:注入待发送
 */
export function 取本轮事件文本(data: SchemaType, 楼层: number): string {
  const 已注入 = data.系统._已注入事件;
  if (已注入.内容 && 已注入.楼层 >= 楼层) {
    console.info(`[人妻公寓] 同楼重roll,重放已消费事件(楼层${已注入.楼层})`);
    return 已注入.内容;
  }
  return data.系统._待发送事件;
}
