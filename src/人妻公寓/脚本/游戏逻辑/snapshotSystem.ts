function 好感感知(v: number): string {
  if (v >= 60) return '她眼里已经有你的位置';
  if (v >= 30) return '她愿意和你多说几句';
  if (v >= 12) return '她开始对你另眼相看';
  return '她对你保持着邻里的分寸';
}

function 婚姻感知(v: number): string {
  if (v >= 75) return '这段婚姻在外人眼里还看不出裂缝';
  if (v >= 50) return '她提起丈夫时,语气里有些说不清的东西';
  if (v >= 25) return '那个家对她来说越来越像一间旅馆';
  return '婚姻只剩一层没人戳破的壳';
}

function 罪恶感知(v: number): string {
  if (v >= 30) return '她最近对丈夫好得刻意,像在偿还什么';
  if (v >= 15) return '她偶尔会在丈夫面前突然沉默';
  if (v > 0) return '有些瞬间,她不敢和丈夫对视';
  return '';
}

/** 疑心阶梯(30/60/90):AI 只演态度,数值脚本管(秦璐范式) */
function 疑心感知(夫名: string, v: number): string | null {
  const 称 = 夫名 || '她丈夫';
  if (v >= 90) return `${称}的猜疑已近爆发:阴沉、冷淡、暗中留意,一触即发`;
  if (v >= 60) return `${称}明显起了疑心:盘问变多,留意她的行踪与手机`;
  if (v >= 30) return `${称}隐约觉得妻子最近有点不对劲,但还愿意相信家人`;
  return null;
}

function 信任感知(夫名: string, v: number): string {
  const 称 = 夫名 || '她丈夫';
  if (v >= 60) return `${称}拿你当自己人,钥匙都放心交给你`;
  if (v >= 30) return `${称}对你这个管理员印象不错`;
  return `${称}对你只是点头之交`;
}

function 风闻感知(v: number): string {
  if (v >= 75) return '楼里的闲话已经压不住,有人开始在走廊上交换眼神';
  if (v >= 50) return '阳台对望的目光变多了,几位太太聊天时会突然压低声音';
  if (v >= 25) return '楼里有人开始留意管理员的行踪';
  return '楼里风平浪静';
}

