/**
 * 对话粘滞(2026-07-18 用户拍板:聊着天的人不许被楼层时钟传送走,玩家离开才解除)。
 * 组快照注入 每轮把"当场的人"钉在当场;读取自校验:位置对不上(玩家换了地方)=不生效,
 * 楼戳在未来(回档过)=作废——粘滞天然随玩家脚步失效,不需要显式清理。
 */
export interface 粘滞状态 {
  位置?: string;
  楼?: number;
  们?: 门牌[];
  夫们?: 门牌[];
  离场?: 门牌[];
  /** 离场冷却的原始楼戳；不能随每轮粘滞心跳刷新。 */
  离场楼?: number;
}

export function 读粘滞状态(): 粘滞状态 | null {
  return (_.get(getVariables({ type: 'chat' }), '_粘滞') ?? null) as 粘滞状态 | null;
}

export function 读粘滞(楼层: number, 房间id: string): 门牌[] {
  const p = 读粘滞状态();
  if (!p || p.位置 !== 房间id || (p.楼 ?? 0) > 楼层) return [];
  return p.们 ?? [];
}

export function 读粘滞夫(楼层: number, 房间id: string): 门牌[] {
  const p = 读粘滞状态();
  if (!p || p.位置 !== 房间id || (p.楼 ?? 0) > 楼层) return [];
  return p.夫们 ?? [];
}

/** 离场冷却只认当前房间、非未来的粘滞/离场楼戳，并在六楼后自动失效。 */
export function 离场标记仍有效(粘滞: 粘滞状态 | null, 房间id: string | undefined, 楼层: number): boolean {
  if (!房间id || !粘滞 || 粘滞.位置 !== 房间id || (粘滞.楼 ?? 0) > 楼层) return false;
  const 已过楼 = 楼层 - (粘滞.离场楼 ?? 粘滞.楼 ?? 0);
  return 已过楼 >= 0 && 已过楼 <= 6;
}

/** 新住户首次登场的公共场景硬门；排队与真正注入前各检查一次。 */
export function 入住登场当前场景可用(data: SchemaType, 楼层: number, 额外持续人物数 = 0): boolean {
  const 房间id = 读场景().房间id;
  const 粘滞 = 读粘滞状态();
  const 粘滞有效 = !!房间id && 粘滞?.位置 === 房间id && (粘滞.楼 ?? 0) <= 楼层;
  const 离场仍有效 = 离场标记仍有效(粘滞, 房间id, 楼层);
  const 离场 = new Set(离场仍有效 ? (粘滞?.离场 ?? []) : []);
  const 粘滞妻人数 = 粘滞有效 ? (粘滞?.们 ?? []).filter(m => !离场.has(m)).length : 0;
  const 粘滞夫人数 = 粘滞有效 ? (粘滞?.夫们 ?? []).length : 0;
  const 赴约人数 = 读赴约(楼层) ? 1 : 0;
  return 入住登场场景可用({
    房间id,
    房间类型: 房间id ? 查房间(房间id)?.类型 : undefined,
    持续人物数: 粘滞妻人数 + 粘滞夫人数 + 赴约人数 + Math.max(0, 额外持续人物数),
    特殊场景中: !!data.系统._特殊场景.id,
    荣耀洞进行中: data.系统._荣耀洞拍 >= 0,
  });
}

