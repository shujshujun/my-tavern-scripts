      // 主对手(焦点[0])=全量;副焦点=骨架数据——裂缝补丁全文/性癖感知这类长文只给主对手,
      // 多妻同台(特殊场景/雌竞撞场)时快照不随人数线性爆炸
      const 主对手 = 妻同场 && m === 焦点[0];
