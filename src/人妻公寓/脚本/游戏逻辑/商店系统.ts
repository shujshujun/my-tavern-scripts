/**
 * 商店系统(P2:工具+礼物两页签起步;八页签全量框架/次日达快递箱归 P3)
 *
 * 裂缝三拍的第②③拍在这里:信是题目,货架是选择题——
 * 礼物页签在任一裂缝解锁后出现,一大排里只有对症几件有效,错误项全是"似是而非";
 * 送对=开门正戏+阶段0解封(晋阶0→1)+完整状态栏解锁;送错=礼貌收下/钱白花/可重试。
 */

export interface 商店结果 {
  成功: boolean;
  提示: string;
  事件?: string; // 排队进 _待发送事件
  变动?: boolean; // 变量有改动,需要落库
}

// ============================================
// 货架(页签可见性=进度条:礼物页签挂"任一裂缝已确认")
// ============================================

export function 礼物页签已解锁(data: SchemaType): boolean {
  return Object.values(data.户).some(节点 => 节点.妻.裂缝.已确认);
}

/** 全楼最高阶段(服饰货架上架档位=全局进度奖励,spec 拍板) */
export function 全楼最高阶段(data: SchemaType): number {
  return Math.max(0, ...Object.values(data.户).map(节点 => 节点.妻.当前阶段));
}

/** 当前可见页签的货架(动态亮起=商店自己就是进度条;P5 服饰上架) */
export function 取货架(data: SchemaType): { 页签: string; 商品: (typeof 道具表)[string][] }[] {
  const 全部 = Object.values(道具表).filter(d => (d.价格 ?? 0) > 0);
  const 架: { 页签: string; 商品: (typeof 道具表)[string][] }[] = [
    { 页签: '工具', 商品: 全部.filter(d => d.类别 === '工具') },
    { 页签: '人情', 商品: 全部.filter(d => d.类别 === '人情') },
    { 页签: '运作', 商品: 全部.filter(d => d.类别 === '运作') },
  ];
  if (礼物页签已解锁(data)) {
    架.push({ 页签: '礼物', 商品: 全部.filter(d => d.类别 === '礼物') });
  }
  // 服饰(P5):任一妻 L2 亮页签;货架只上"≤全楼最高阶段+1"档的货(进度奖励,买得到的永远比走到的多一档)
  const 最高 = 全楼最高阶段(data);
  if (最高 >= 2) {
    架.push({
      页签: '服饰',
      商品: 全部.filter(d => d.类别 === '服饰' && (d.服饰?.档 ?? 9) <= Math.min(5, 最高 + 1)),
    });
  }
  return 架;
}

// ============================================
// 购买(P2 即时入包;P3 升级"次日达"快递箱=楼层时钟到货)
// ============================================

export function 购买(data: SchemaType, 道具id: string): 商店结果 {
  const 配 = 查道具(道具id);
  if (!配 || !(配.价格 ?? 0)) return { 成功: false, 提示: '货架上没有这件东西。' };
  if (配.类别 === '礼物' && !礼物页签已解锁(data)) return { 成功: false, 提示: '这个柜台还没开。' };
  if (配.常驻 && data.背包.includes(道具id)) return { 成功: false, 提示: `「${配.名称}」已经在背包里。` };
  if (data.现金 < 配.价格!) return { 成功: false, 提示: '钱不够。' };

  // 特殊场景(P5):买下即触发定制正戏,不入背包(男用贞操带等无场景配置的照常入包)
  const 场景 = 查特殊场景(道具id);
  if (场景) {
    if (!场景.前置(data as never)) return { 成功: false, 提示: '这场戏的人还没到齐。' };
    if (data.系统._待发送事件) return { 成功: false, 提示: '眼下已有一桩事在发生——过一楼再来。' };
    data.现金 -= 配.价格!;
    data.系统._待发送事件 = 场景.剧情;
    // 结算:参与妻堕落+2(spec:自洽小戏,不触疑心/摊牌,不影响正文其他进展)
    for (const m of 场景.参与(data as never)) {
      const 妻 = data.户[m]?.妻;
      if (妻) 妻.堕落值 = _.clamp(妻.堕落值 + 2, 0, 100);
    }
    return { 成功: true, 提示: `「${配.名称}」——开演。`, 变动: true };
  }

  data.现金 -= 配.价格!;
  data.背包.push(道具id);
  return { 成功: true, 提示: `买下了「${配.名称}」。`, 变动: true };
}

// ============================================
// 送礼(须当面;对症判定→开门正戏/似是而非→礼貌收下/开门后→普通赠礼)
// ============================================

export async function 送礼(data: SchemaType, 道具id: string, 门牌号: 门牌): Promise<商店结果> {
  const 配 = 查道具(道具id);
  const 节点 = data.户[门牌号];
  if (!配 || !节点) return { 成功: false, 提示: '送不出去。' };
  const i = data.背包.indexOf(道具id);
  if (i < 0) return { 成功: false, 提示: '背包里没有这件东西。' };
  if (配.常驻) return { 成功: false, 提示: '这是吃饭的家伙,送不得。' };
  const 妻名 = 户静态表[门牌号].妻名;
  const 裂缝 = 查裂缝(门牌号);

  // ── 送衣流程(P5;服饰SKU走专属分支) ──
  if (配.服饰) {
    const 妻 = 节点.妻;

    // 档位判定前置(2026-07-19 用户改拍:不够档=系统退回不消耗,不再"藏衣柜钱白花";
    // 302阶段0走破墙分支不受此门)
    if (!(门牌号 === '302' && 妻.当前阶段 === 0) && 妻.当前阶段 < 配.服饰.档) {
      return { 成功: false, 提示: `${妻名}现在的阶段,还接受不了这件东西——先收回来吧。` };
    }
    data.背包.splice(i, 1);

    // 破妈妈墙(spec 隐藏机制,UI零提示):阶段0的母亲+外装/妆容类+档≤3 → 破墙正戏
    if (门牌号 === '302' && 妻.当前阶段 === 0) {
      if ((配.服饰.类 === '外装' || 配.服饰.类 === '妆容') && 配.服饰.档 <= 3) {
        const 撞见次数 = data.系统._母亲撞见次数;
        const 差分 =
          撞见次数 >= 3
            ? '她哭到一半忽然自己说破了:"我不是没看见……你和楼里的事,妈都看见了。我是不知道该用什么身份说你。"她亲口承认,早就没法只用"妈"的身份看你了'
            : 撞见次数 >= 1
              ? '她哭的时候多说了一句话——那句话让你意识到,楼里的那些事,她其实早就知道了'
              : '';
        妻.当前阶段 = 1;
        妻.阶段标题 = 阶段标题(1);
        镜像直写(门牌号, { 阶段: 1 });
        data.系统._待发送事件 =
          `【破墙】{{user}}把「${配.名称}」递给了妈——不是保健品,不是按摩仪,是一件给"女人"买的东西。` +
          `她第一反应是笑着骂"这是买给哪个小姑娘的",笑到一半停住了——她反应过来这是买给她的。二十年了,` +
          `第一次有人把她当女人而不是当妈看。演出她从错愕到眼眶失守的完整过程,她转过身去很久没说话。${差分}。` +
          `这是那堵叫"妈妈"的墙裂开的一楼,张力给足,不要一笔带过`;
        return { 成功: true, 提示: '妈半天没说话。有什么东西,不一样了。', 变动: true };
      }
      // 不过分档位判定失败/内衣制服特殊/L4+ = 打回(钱白花容错,风味=她没往自己身上想)
      return {
        成功: true,
        提示: `"这是买给哪个小姑娘的?妈帮你包起来。"她没往自己身上想。东西被原样包好收进了柜子`,
        变动: true,
      };
    }

    // 肯穿:写槽+穿戴锁+穿着SKU(立绘差分接线)+首穿正戏+换装余波
    const 槽 = 配.服饰.槽;
    妻[槽 === '特殊' ? '外装' : 槽] = 槽 === '特殊' ? 妻.外装 : 配.服饰.穿着描述;
    if (槽 === '特殊') {
      if (!妻.特殊.includes(配.服饰.穿着描述) && 妻.特殊.length < 4) 妻.特殊.push(配.服饰.穿着描述);
    }
    if (!妻._穿戴锁.includes(槽) && 槽 !== '特殊') 妻._穿戴锁.push(槽);
    妻._穿着SKU[槽] = 道具id;
    // 立绘跟随最后一次实际换上的衣服；妆容与小配件不抢整张衣装差分。
    if (槽 === '外装' || 槽 === '内衣') 妻._穿着SKU._立绘 = 道具id;
    if (配.外显) await 记余波(门牌号, `${妻名}${配.外显}`);
    else if (配.私密外显 && 妻.当前阶段 >= 4) await 记余波(门牌号, `${妻名}${配.私密外显}`, true);
    const 事件 =
      `【首穿】{{user}}把「${配.名称}」(${配.描述})当面送给了${妻名},而她收下了——按她的阶段与性格,这一次她会穿上它。` +
      `演出完整的首穿:拆包时的神情、${配.服饰.档 >= 4 ? '换上它前后的心理落差、见到{{user}}反应时藏不住的那点得意与羞' : '试穿后在镜子前多站的那一会儿'}。` +
      `从此她穿着它(着装已更新),正文里不要让她随意换下`;
    data.系统._待发送事件 = data.系统._待发送事件 ? `${data.系统._待发送事件}|${事件}` : 事件;
    return { 成功: true, 提示: `${妻名}收下了「${配.名称}」——这一次,她会穿上它。`, 变动: true };
  }

  data.背包.splice(i, 1);

  // 开门时刻:裂缝已确认+还在阶段0+送中对症 → 三拍走完
  if (节点.妻.裂缝.已确认 && 节点.妻.当前阶段 === 0 && 裂缝?.对症礼物.includes(道具id)) {
    const 晋 = 请求晋阶(data, 门牌号); // 0→1:裂缝确认即资格,镜像直写在内
    if (晋.成功) {
      const 事件 = 裂缝.开门正戏;
      data.系统._待发送事件 = data.系统._待发送事件 ? `${data.系统._待发送事件}|${事件}` : 事件;
      return { 成功: true, 提示: `送对了。${妻名}的门,开了。`, 变动: true };
    }
  }

  // 阶段0送错(含未读信就乱送):礼貌收下,钱白花,可重试
  if (节点.妻.当前阶段 === 0) {
    const 事件 =
      `【送礼】{{user}}把「${配.名称}」送给了${妻名}。这份礼物没送进她心里——她客气地收下,` +
      `按她的性格演出这次"礼貌的收下"(得体的感谢/一点不易察觉的失落或困惑),关系不会因此推进,也不损害什么`;
    data.系统._待发送事件 = data.系统._待发送事件 ? `${data.系统._待发送事件}|${事件}` : 事件;
    return { 成功: true, 提示: `${妻名}收下了,客客气气的。好像不是这个。`, 变动: true };
  }

  // 开门后的普通赠礼:AI 演,好感 AI 自己给
  const 事件 =
    `【送礼】{{user}}当面把「${配.名称}」(${配.描述})送给了${妻名}。演出这次赠与:她按当前阶段与性格接下它,` +
    `礼物落进她的生活(用上/收好/佩戴)。反应的分寸由她此刻的心决定`;
  data.系统._待发送事件 = data.系统._待发送事件 ? `${data.系统._待发送事件}|${事件}` : 事件;
  // 换装余波:外显件人人看得见;私密件她阶段≥4(沉沦)才"藏不住春光"(2026-07-19 用户追拍)
  if (配.外显) await 记余波(门牌号, `${妻名}${配.外显}`);
  else if (配.私密外显 && 节点.妻.当前阶段 >= 4) await 记余波(门牌号, `${妻名}${配.私密外显}`, true);
  return { 成功: true, 提示: `把「${配.名称}」送给了${妻名}。`, 变动: true };
}
