import type { 许曼君离婚动作ID, 许曼君离婚地点动作视图 } from './许曼君离婚系统';

/**
 * 宿主收到客户端动作意图后，只能接受当前地点动作快照中仍然可见的动作。
 * 长按失败补偿只存在于选项的 `短按动作`，也必须纳入同一份活快照校验，
 * 否则客户端确实发出意图后会在宿主边界被误判为过期动作。
 */
export function 查找许曼君离婚事件候选(
  动作组: readonly 许曼君离婚地点动作视图[],
  动作: 许曼君离婚动作ID,
): 许曼君离婚地点动作视图 | undefined {
  return 动作组.find(
    候选 => 候选.id === 动作 || 候选.选项?.some(选项 => 选项.id === 动作 || 选项.短按动作 === 动作),
  );
}
