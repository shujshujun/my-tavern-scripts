import type { SchemaType } from '../../schema';
import { 户静态表 } from '../../stageConfig';
import { 录像带结局后效已开启 } from './结局后生活社交语义';
import { 取绝对时段, 妻位置推算 } from './楼层时钟';
import { 读取医院内容策略 } from './生产系统';
import { 场景剧情占用前台生成 } from './场景剧情事务';

export type 录像带结局角色 = '102' | '202';
export type 录像带结局后开场选择 = '由我开始' | '让她开始';

export function 录像带结局后亲密阻断(data: SchemaType, 门牌号: 录像带结局角色, 地点: string): string {
  if (data.系统._坏结局) return '本次故事已经结束。';
  const 户 = data.户[门牌号];
  if (!户 || !录像带结局后效已开启(data)) return '请先完成《录像带》。';
  if (地点 !== 门牌号) return `请先进入${门牌号}。`;
  if (!读取医院内容策略(data, 门牌号).允许成人特殊场景) return '她当前正在医院，请等她恢复回家。';
  if (妻位置推算(门牌号, 取绝对时段(data), 户) !== 地点) return `${户静态表[门牌号].妻名}现在不在这里。`;
  if (场景剧情占用前台生成(data, 地点)) return '请先完成当前这段剧情。';
  if (data.系统._父亲通话.状态) return '请先结束正在进行的通话。';
  if (data.系统._性爱场景.状态 !== '空闲') return '请继续或结束当前相处，再开始下一场。';
  if (户.妻.当前阶段 < 3) return '当前关系阶段尚不支持这项行动。';
  if (data.玩家资源.体力.当前值 <= 0) return '体力不足，请先休息。';
  return '';
}

export function 录像带结局后亲密可用(data: SchemaType, 门牌号: 录像带结局角色, 地点: string): boolean {
  return !录像带结局后亲密阻断(data, 门牌号, 地点);
}

export function 录像带结局后亲密行动(门牌号: 录像带结局角色, 选择: 录像带结局后开场选择): string {
  const 开场 = 门牌号 === '102'
    ? 选择 === '由我开始' ? '玩家向沈静仪靠近，她克制而明确地回应此刻的亲近' : '沈静仪放下眼前的事，主动向玩家靠近，清楚表达自己的意思'
    : 选择 === '由我开始' ? '玩家向周小满靠近，她说出此刻的心情并回应玩家' : '周小满主动说出想与玩家亲近的意愿，按自己的节奏走近';
  return `【${门牌号}结局后亲密开场】【${选择}】（${开场}。承接已经成立的关系；本楼完成开场，将下一步留给玩家。）`;
}

export function 解析录像带结局后亲密行动(行动: string): { 门牌: 录像带结局角色; 选择: 录像带结局后开场选择 } | null {
  const 结果 = /^【(102|202)结局后亲密开场】【(由我开始|让她开始)】/u.exec(行动.trim());
  return 结果 ? { 门牌: 结果[1] as 录像带结局角色, 选择: 结果[2] as 录像带结局后开场选择 } : null;
}
