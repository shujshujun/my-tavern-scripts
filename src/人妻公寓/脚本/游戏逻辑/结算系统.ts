// 惰性结算:被触碰时一口气补算被动账
// ============================================

/**
 * 惰性结算一户(进门/收租日/事件触碰时调用)。
 * @param 绝对时段 当前 0-based 世界时段。首见(_上次结算楼层<0)只校准不补发历史。
 *   `_上次结算楼层` 是旧字段名；新局只保存绝对时段。
 */
export function 惰性结算户(节点: 户节点Type, 绝对时段: number): void {
  const 妻 = 节点.妻;
  if (妻._上次结算楼层 < 0) {
    妻._上次结算楼层 = 绝对时段;
    return;
  }
  const 经过 = 绝对时段 - 妻._上次结算楼层;
  if (经过 <= 0) return;
  妻._上次结算楼层 = 绝对时段;

  // 婚姻值自然阴跌(裂缝已确认漏得更快)。
  // 阶段0-1 不阴跌(2026-07-17 用户拍板:还没越界,她的婚姻不该白掉)——从阶段2(拥吻,
  // 墙缝真的开了)起才开始滑坡;这也让罪恶感公式对齐:堕落开始涨的同时婚姻才开始掉
  if (妻.当前阶段 >= 2) {
    const 阴跌率 = 妻.裂缝.已确认 ? 婚姻阴跌每时段_裂缝已确认 : 婚姻阴跌每时段;
    妻.婚姻值 = _.clamp(妻.婚姻值 - 阴跌率 * 经过, 0, 100);
  }

  // 疑心自然回落(不破下限棘轮)
  const 下限 = 疑心下限(妻.堕落值);
  const 夫 = 节点.夫;
  if (夫.疑心值 > 下限) {
    夫.疑心值 = Math.max(下限, 夫.疑心值 - 疑心回落每时段 * 经过);
  }
}

/** 全户惰性结算(上交日全楼刷一遍,经济结算接线——审计 低危8:此前从无调用者;日常只结算焦点户) */
export function 惰性结算全楼(data: SchemaType, _旧钟楼?: number): void {
  const 绝对时段 = 取绝对时段(data);
  for (const 节点 of Object.values(data.户)) {
    惰性结算户(节点, 绝对时段);
  }
}

