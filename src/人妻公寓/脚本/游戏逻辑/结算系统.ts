// 〔调参〕深夜到访每楼代价(戏每多演一楼,代价多记一笔——赖着不走=越陷越深)
const 夜访疑心每楼 = 4;

/**
 * 深夜到访结算(每 AI 楼一次,主路径与逃生舱都挂):
 * 玩家深夜站在低阶段(<2)住户门口(敲门/串门,非破门)且屋里有人 → 丈夫疑心+/楼内风闻+。
 * 阶段≥2 不走此账(深夜私会的风险由疑心主通道与丈夫在家状态自管);破门=无声潜入,另一套风险。
 * 快照侧的【夜访纪律】【深夜纪律】负责演出层,这里负责账面压力,两层同一份判定条件。
 */
export function 夜访结算(data: SchemaType, 楼层: number): void {
  const { 房间id, 破门, 非法进入, 进房末楼 } = 读场景();
  if (!房间id || 非法进入 || 破门 || 房间id === '302') return;
  const 节点 = data.户[房间id as 门牌];
  if (!节点 || 节点.妻.当前阶段 >= 2) return;
  // 真实消息楼只校验场景连续性；作息与冻结窗口一律读取当前绝对时段。
  if (进房末楼 != null && 进房末楼 > 楼层) return;
  const 绝对时段 = 取绝对时段(data);
  if (当前时段(绝对时段) !== '深夜') return;
  const 有人 =
    妻位置推算(房间id as 门牌, 绝对时段, 节点) === 房间id ||
    丈夫在楼(节点, 房间id as 门牌, 绝对时段) !== '外出';
  if (!有人) return;
  // 疑心冻结窗口内不涨疑心(审计 M9);风闻是楼道里的耳朵,与丈夫状态无关照记
  if (!疑心冻结中(节点.夫, 绝对时段)) {
    节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 夜访疑心每楼, 0, 100);
  }
  const 风闻 = 登记风闻事件(data, {
    // 逐成功正文楼收费；楼层进入稳定 ID 后，同楼重掷仍幂等，继续赖在门外的新楼则独立记账。
    id: `深夜夜访:${绝对时段}:${房间id}:${楼层}`,
    类型: '深夜夜访',
    目标增量: 2,
    门牌: 房间id,
    地点: `${房间id}门外`,
    摘要: `深夜频繁出现在${房间id}门外`,
    迹象: '可疑痕迹',
  });
  console.info(
    `[人妻公寓·结算] 深夜夜访 ${房间id}:疑心+${夜访疑心每楼}(${节点.夫.疑心值}) 风闻+${风闻.实际增加}(${data.风闻})`,
  );
}

