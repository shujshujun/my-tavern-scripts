/** 婚姻值自然阴跌:裂缝=婚姻值的漏点,不处理自然阴跌(裂缝已确认的户漏得更快) */
const 婚姻阴跌每时段 = 0.3;
const 婚姻阴跌每时段_裂缝已确认 = 0.75;
/** 疑心值自然回落:无新增的时段自然回落,但不破下限棘轮(下限=堕落值×系数) */
const 疑心回落每时段 = 0.9;
const 疑心下限系数 = 0.2;

/** 疑心下限棘轮:看见了就无法当没看见(堕落越深,回落触底越高) */
function 疑心下限(妻堕落: number): number {
  return 妻堕落 * 疑心下限系数;
}

// ============================================
// 焦点户主动结算(每楼:好感/堕落增量→疑心;婚姻关键事件走独立接口)
// ============================================

const 疑心涨_每2堕落 = 0.5; // 堕落度每 +2 → 疑心 +1(攻略本身就是暴露)
const 疑心单楼上限 = 2; // 本楼最多 +2,超出部分直接豁免(不进位,无续收字段)

/**
 * 疑心主通道(焦点户,水位线制,镜像秦璐范式):
 * 堕落增量折算疑心涨点,按"当前堕落 vs 快照堕落"的本楼真实增量结算。
 * - Math.floor(审计 低危6):最高频档位是增量1,旧版 Math.round(0.5)=1 让"每2堕落→1疑心"翻倍
 * - 疑心冻结窗口(审计 M9):钓鱼团购券买的清净期此前只挡打断/要钱/偷窃,主通道照涨=钱白花
 */
export function 结算焦点疑心(节点: 户节点Type, 门牌号: 门牌, 本楼堕落增量: number, 现钟: number): void {
  if (本楼堕落增量 <= 0) return;
  if (疑心冻结中(节点.夫, 现钟)) return;
  const collect = Math.min(Math.floor(本楼堕落增量 * 疑心涨_每2堕落), 疑心单楼上限);
  if (collect <= 0) return;
  节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + collect, 0, 100);
  console.info(`[人妻公寓·结算] ${门牌号} 堕落+${本楼堕落增量} → 疑心+${collect}(${节点.夫.疑心值})`);
}

