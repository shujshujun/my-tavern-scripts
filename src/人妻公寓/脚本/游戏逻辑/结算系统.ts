/**
 * 结算系统:户级运行时的惰性结算 + 派生轴脚本结算(变量分工表:婚姻值/丈夫双轴全脚本)
 *
 * 惰性结算(放置游戏离线收益算法):后台户被动账不每楼 tick——每户存 _上次结算楼层,
 * 被触碰时(进门/收租日/事件)一口气结算 经过楼数×被动速率。每楼计算量=1焦点户+到期事件,
 * 不随户数膨胀。〔调参〕所有速率待货币平衡波统一定。
 */

// ============================================
// 被动速率(每楼;惰性一次性折算 经过楼数×速率)
// ============================================

/** 婚姻值自然阴跌:裂缝=婚姻值的漏点,不处理自然阴跌(裂缝已确认的户漏得更快) */
const 婚姻阴跌每楼 = 0.1;
const 婚姻阴跌每楼_裂缝已确认 = 0.25;
/** 疑心值自然回落:无新增的楼每楼回落,但不破下限棘轮(下限=堕落值×系数) */
const 疑心回落每楼 = 0.3;
const 疑心下限系数 = 0.2;

/** 疑心下限棘轮:看见了就无法当没看见(堕落越深,回落触底越高) */
function 疑心下限(妻堕落: number): number {
  return 妻堕落 * 疑心下限系数;
}

// ============================================
// 焦点户主动结算(每楼:好感/堕落增量→疑心;婚姻关键事件走独立接口)
// ============================================

const 疑心涨_每2堕落 = 0.5; // 堕落度每 +2 → 疑心 +1(攻略本身就是暴露)
const 疑心单楼上限 = 2; // 本楼最多 +2,超出部分直接豁免(不进位,无续收字段)

/**
 * 疑心主通道(焦点户,水位线制,镜像秦璐范式):
 * 堕落增量折算疑心涨点,按"当前堕落 vs 快照堕落"的本楼真实增量结算。
 * - Math.floor(审计 低危6):最高频档位是增量1,旧版 Math.round(0.5)=1 让"每2堕落→1疑心"翻倍
 * - 疑心冻结窗口(审计 M9):钓鱼团购券买的清净期此前只挡打断/要钱/偷窃,主通道照涨=钱白花
 */
export function 结算焦点疑心(节点: 户节点Type, 门牌号: 门牌, 本楼堕落增量: number, 现钟: number): void {
  if (本楼堕落增量 <= 0) return;
  if (节点.夫._疑心冻结至 >= 现钟) return;
  const collect = Math.min(Math.floor(本楼堕落增量 * 疑心涨_每2堕落), 疑心单楼上限);
  if (collect <= 0) return;
  节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + collect, 0, 100);
  console.info(`[人妻公寓·结算] ${门牌号} 堕落+${本楼堕落增量} → 疑心+${collect}(${节点.夫.疑心值})`);
}

// ============================================
// 夜访代价(2026-07-18 用户拍板"软门+代价"):低阶段深夜杵在人家门口,楼道听得见
// ============================================

// 〔调参〕深夜到访每楼代价(戏每多演一楼,代价多记一笔——赖着不走=越陷越深)
const 夜访疑心每楼 = 4;
const 夜访风闻每楼 = 2;

/**
 * 深夜到访结算(每 AI 楼一次,主路径与逃生舱都挂):
 * 玩家深夜站在低阶段(<2)住户门口(敲门/串门,非破门)且屋里有人 → 丈夫疑心+/楼内风闻+。
 * 阶段≥2 不走此账(深夜私会的风险由疑心主通道与丈夫在家状态自管);破门=无声潜入,另一套风险。
 * 快照侧的【夜访纪律】【深夜纪律】负责演出层,这里负责账面压力,两层同一份判定条件。
 */
export function 夜访结算(data: SchemaType, 楼层: number): void {
  const { 房间id, 破门, 进房末楼 } = 读场景();
  if (!房间id || 破门 || 房间id === '302') return;
  const 节点 = data.户[房间id as 门牌];
  if (!节点 || 节点.妻.当前阶段 >= 2) return;
  // 未来作废守卫(审计 低危11):酒馆原生 UI 删末楼后 chat 变量不回滚,进房末楼可能停在"未来"
  const 进房 = 进房末楼 != null && 进房末楼 <= 楼层 ? 进房末楼 : 楼层;
  const 钟 = 进房 + data.系统._时段偏移楼;
  if (当前时段(钟) !== '深夜') return;
  const 有人 = 妻位置推算(房间id as 门牌, 钟) === 房间id || 丈夫在楼(节点, 房间id as 门牌, 钟) !== '外出';
  if (!有人) return;
  // 疑心冻结窗口内不涨疑心(审计 M9);风闻是楼道里的耳朵,与丈夫状态无关照记
  if (节点.夫._疑心冻结至 < 钟) {
    节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 夜访疑心每楼, 0, 100);
  }
  data.风闻 = _.clamp(data.风闻 + 夜访风闻每楼, 0, 100);
  console.info(
    `[人妻公寓·结算] 深夜夜访 ${房间id}:疑心+${夜访疑心每楼}(${节点.夫.疑心值}) 风闻+${夜访风闻每楼}(${data.风闻})`,
  );
}

// ============================================
// 惰性结算:被触碰时一口气补算被动账
// ============================================

/**
 * 惰性结算一户(进门/收租日/事件触碰时调用)。
 * @param 钟楼 当前钟楼(真实楼+杀时间偏移;2026-07-26 审计 低危7:收租/冷却/作息全按钟楼,
 *   被动账若按真实楼走,杀时间=用 1/3 婚姻代价换整期房租)。首见(_上次结算楼层<0)只校准不补发历史。
 *   旧档存的是真实楼水位,切轴后首次结算会多补一段(至多一次杀时间总偏移),一次性迁移成本。
 */
export function 惰性结算户(节点: 户节点Type, 钟楼: number): void {
  const 妻 = 节点.妻;
  if (妻._上次结算楼层 < 0) {
    妻._上次结算楼层 = 钟楼;
    return;
  }
  const 经过 = 钟楼 - 妻._上次结算楼层;
  if (经过 <= 0) return;
  妻._上次结算楼层 = 钟楼;

  // 婚姻值自然阴跌(裂缝已确认漏得更快)。
  // 阶段0-1 不阴跌(2026-07-17 用户拍板:还没越界,她的婚姻不该白掉)——从阶段2(拥吻,
  // 墙缝真的开了)起才开始滑坡;这也让罪恶感公式对齐:堕落开始涨的同时婚姻才开始掉
  if (妻.当前阶段 >= 2) {
    const 阴跌率 = 妻.裂缝.已确认 ? 婚姻阴跌每楼_裂缝已确认 : 婚姻阴跌每楼;
    妻.婚姻值 = _.clamp(妻.婚姻值 - 阴跌率 * 经过, 0, 100);
  }

  // 疑心自然回落(不破下限棘轮)
  const 下限 = 疑心下限(妻.堕落值);
  const 夫 = 节点.夫;
  if (夫.疑心值 > 下限) {
    夫.疑心值 = Math.max(下限, 夫.疑心值 - 疑心回落每楼 * 经过);
  }
}

/** 全户惰性结算(上交日全楼刷一遍,经济结算接线——审计 低危8:此前从无调用者;日常只结算焦点户) */
export function 惰性结算全楼(data: SchemaType, 钟楼: number): void {
  for (const 节点 of Object.values(data.户)) {
    惰性结算户(节点, 钟楼);
  }
}

// ============================================
// 晋阶(资格+正戏,不自动;UI 按钮触发,镜像直写)
// ============================================

export interface 晋阶结果 {
  成功: boolean;
  消息: string;
}

/** 检查晋阶资格(达标只是资格) */
export function 可晋阶(妻: 户节点Type['妻']): boolean {
  const 下阶 = 妻.当前阶段 + 1;
  if (下阶 > 5) return false;
  if (下阶 === 1) return 妻.裂缝.已确认; // 0→1:送对症礼开门(裂缝三拍第三拍)
  return 妻.堕落值 >= (晋阶门槛[下阶] ?? 999);
}

/**
 * 请求晋阶(脚本结算:阶段+1,派生标题重算,镜像直写)。
 * 晋阶正戏(第一夜等)由回合引擎注入事件承载,本函数只动机制。
 * 返回结果供 UI 反馈;调用方负责落库。
 */
export function 请求晋阶(data: SchemaType, 门牌号: 门牌): 晋阶结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 成功: false, 消息: '这户还没入住' };
  const 妻 = 节点.妻;
  if (!可晋阶(妻)) {
    return { 成功: false, 消息: 妻.当前阶段 === 0 ? '还没找到打开她的方式' : '她还没到能更进一步的时候' };
  }
  // 母亲药物首夜门(P5②,spec拍板):她的2→3那道坎清醒时绝不会迈——必须持有安眠药(首个既成事实装置)
  if (门牌号 === '302' && 妻.当前阶段 === 2) {
    const i = data.背包.indexOf('安眠药');
    if (i < 0) return { 成功: false, 消息: '那道坎,她清醒着绝不会迈过去。也许需要一场谁都没打算发生的"意外"。' };
    data.背包.splice(i, 1);
  }
  妻.当前阶段 += 1;
  妻.阶段标题 = 阶段标题(妻.当前阶段);
  镜像直写(门牌号, { 阶段: 妻.当前阶段 });
  return { 成功: true, 消息: `${户静态表[门牌号].妻名}进入了「${妻.阶段标题}」` };
}

