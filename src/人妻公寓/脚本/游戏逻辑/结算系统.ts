function 母亲首夜前三节点已完成(data: SchemaType): boolean {
  const 妻 = data.户['302']?.妻;
  return Boolean(
    妻?.当前阶段 === 2 &&
    妻._阶段线路.目标阶段 === 3 &&
    妻._阶段线路.活跃节点 === 3 &&
    (妻._阶段线路.完成位图 & 7) === 7,
  );
}

/** UI 只用它决定按钮状态；真正请求仍由脚本重读存档时钟与 chat 场景后再校验。 */
export function 可启动母亲药物首夜(data: SchemaType, 当前地点?: string | null): boolean {
  const 妻 = data.户['302']?.妻;
  if (!妻 || !母亲首夜前三节点已完成(data)) return false;
  if (!读取医院内容策略(data, '302').允许普通阶段推进) return false;
  const 时段 = 当前时段(取绝对时段(data));
  return (
    妻.堕落值 >= (晋阶门槛[3] ?? 40) - 1 &&
    (时段 === '晚上' || 时段 === '深夜') &&
    当前地点 === '302' &&
    data.背包.includes('安眠药') &&
    !data.系统._母亲首夜第二幕 &&
    !有场景剧情阻塞(data)
  );
}

/** 检查晋阶资格(达标只是资格) */
export function 可晋阶(妻: 户节点Type['妻']): boolean {
  const 下阶 = 妻.当前阶段 + 1;
  if (下阶 > 5) return false;
  if (下阶 === 1) return 妻.裂缝.已确认; // 0→1:送对症礼开门(裂缝三拍第三拍)
  return 妻.堕落值 >= (晋阶门槛[下阶] ?? 999) && 线路已完成(妻);
}

/** 普通五户的 2→3 是“第一夜”，只能从晚上启动；302 由两幕专用门单独判定。 */
export function 普通首夜时段已满足(data: SchemaType, 门牌号: 门牌): boolean {
  const 妻 = data.户[门牌号]?.妻;
  return !妻 || 门牌号 === '302' || 妻.当前阶段 !== 2 || 当前时段(取绝对时段(data)) === '晚上';
}

/**
 * 晋阶按钮必须仍处在最后一个关系节点的周历现场。线路预约负责精确星期、时段、地点与
 * 丈夫状态；事件演员标记只负责演出，不再允许玩家从档案页隔空升阶。
 */
export function 晋阶预约现场已满足(data: SchemaType, 门牌号: 门牌, 当前地点 = 读场景().房间id): boolean {
  const 节点 = data.户[门牌号];
  if (!节点) return false;
  if (!读取医院内容策略(data, 门牌号).允许普通阶段推进) return false;
  const 妻 = 节点.妻;
  if (妻.当前阶段 === 0) return true;
  if (!线路已完成(妻)) return false;

  // 母亲 2→3 的最终节点是睡眠后的早餐正文，不属于普通地点预约；晋阶仍须留在睡醒地点。
  if (门牌号 === '302' && 妻.当前阶段 === 2) return 当前地点 === '管理员室' || 当前地点 === '302';

  const 状态 = 妻._阶段线路;
  const 绝对时段 = 取绝对时段(data);
  if (!当前地点 || 当前地点 !== 状态.预约地点 || !阶段预约当前有效(状态, 绝对时段)) return false;
  if (妻位置推算(门牌号, 绝对时段, 节点) !== 当前地点) return false;
  return !状态.预约丈夫状态 || 丈夫在楼(节点, 门牌号, 绝对时段) === 状态.预约丈夫状态;
}

export function 晋阶预约现场提示(data: SchemaType, 门牌号: 门牌): string {
  const 妻 = data.户[门牌号]?.妻;
  if (!妻) return '这户还没入住';
  if (门牌号 === '302' && 妻.当前阶段 === 2) return '请留在管理员室或 302，等早餐这一幕真正收束后再晋阶。';
  const 预约 = 妻._阶段线路;
  if (!预约.预约地点) return '最后一项关系任务还没有形成可用的见面预约。';
  const 地点名 = 查房间(预约.预约地点)?.名称 ?? 预约.预约地点;
  return `请在${预约.预约星期}${预约.预约时段}到${地点名}，当面完成这次晋阶。`;
}

/**
 * 请求晋阶(脚本候选:阶段+1,派生标题重算；镜像只在核心写入成功后的提交钩子执行)。
 * 普通晋阶正戏由回合引擎注入；302 两幕特例在尚未升阶时原子消费药物并排首夜票据。
 * 返回结果供 UI 反馈;调用方负责落库。
 */
function 请求晋阶核心(data: SchemaType, 门牌号: 门牌, 允许阶段0开门: boolean): 晋阶结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 成功: false, 消息: '这户还没入住', 动作: '无变化' };
  if (!读取医院内容策略(data, 门牌号).允许普通阶段推进) {
    return { 成功: false, 消息: '她正在医院待产或恢复，普通关系阶段暂停，出院后再继续。', 动作: '无变化' };
  }
  const 妻 = 节点.妻;

  // 阶段0的裂缝确认只是资格；只有商店核验过的对症礼物能调用开门入口。
  if (妻.当前阶段 === 0 && !允许阶段0开门) {
    return { 成功: false, 消息: '要把真正对症的礼物当面送给她，才能打开这道门。', 动作: '无变化' };
  }

  // 302 的 2→3 先用同一个晋阶入口启动首夜，但此时绝不提前改阶段或完成节点4。
  // 地点从脚本侧 chat 真值读取，时段只读 MVU `_绝对时段`；UI 不提供任何可伪造的授权载荷。
  if (门牌号 === '302' && 母亲首夜前三节点已完成(data)) {
    if (data.系统._母亲首夜第二幕) {
      return { 成功: false, 消息: '第一幕已经发生了。先让时间走到第二天早饭桌。', 动作: '无变化' };
    }
    if (data.系统._待发送事件.trim()) {
      return { 成功: false, 消息: '眼下还有一幕没有演完。', 动作: '无变化' };
    }
    if (妻.堕落值 < (晋阶门槛[3] ?? 40) - 1) {
      return { 成功: false, 消息: '她还没到能更进一步的时候', 动作: '无变化' };
    }
    const 当前地点 = 读场景().房间id;
    if (当前地点 !== '302') {
      return { 成功: false, 消息: '这件事只能在 302 发生。', 动作: '无变化' };
    }
    const 时段 = 当前时段(取绝对时段(data));
    if (时段 !== '晚上' && 时段 !== '深夜') {
      return { 成功: false, 消息: '还没到这个夜晚。', 动作: '无变化' };
    }
    const 药物索引 = data.背包.indexOf('安眠药');
    if (药物索引 < 0) {
      return {
        成功: false,
        消息: '那道坎,她清醒着绝不会迈过去。也许需要一场谁都没打算发生的"意外"。',
        动作: '无变化',
      };
    }
    data.背包.splice(药物索引, 1);
    data.系统._待发送事件 = 母亲药物首夜事件;
    return { 成功: true, 消息: '这个夜晚已经开始。', 动作: '母亲首夜' };
  }

  if (!可晋阶(妻)) {
    if (妻.当前阶段 === 0) return { 成功: false, 消息: '还没找到打开她的方式', 动作: '无变化' };
    if (妻.堕落值 >= (晋阶门槛[妻.当前阶段 + 1] ?? 999) && !线路已完成(妻)) {
      return {
        成功: false,
        消息: '她似乎还有一件事没有想明白。去关系线索里看看最近留下的变化。',
        动作: '无变化',
      };
    }
    return { 成功: false, 消息: '她还没到能更进一步的时候', 动作: '无变化' };
  }
  if (!普通首夜时段已满足(data, 门牌号)) {
    return { 成功: false, 消息: '这是她的第一夜，要等到晚上才能跨过这道界线。', 动作: '无变化' };
  }
  if (!晋阶预约现场已满足(data, 门牌号)) {
    return { 成功: false, 消息: 晋阶预约现场提示(data, 门牌号), 动作: '无变化' };
  }
  const 是母亲两幕后晋阶 = 门牌号 === '302' && 妻.当前阶段 === 2;
  妻.当前阶段 += 1;
  同步阶段线路(妻, 取绝对时段(data), 门牌号);
  登记攻略风闻(data, 门牌号, '晋阶');
  const 新阶段标题 = 阶段标题(妻.当前阶段, 门牌号);
  const 新阶段 = 妻.当前阶段;
  return {
    成功: true,
    消息: `${户静态表[门牌号].妻名}进入了「${新阶段标题}」`,
    动作: 是母亲两幕后晋阶 ? '母亲两幕后晋阶' : '晋阶',
    提交后: () => 镜像直写(门牌号, { 阶段: 新阶段 }),
  };
}

