// 绿帽双线(P5⑥;spec拍板:仅2户开放,其余锁死)——
// 102顾国栋=愿者线「观众席」:拥有不碰拧成观赏欲,"门缝那一眼"=正式开线关键事件
// 202何俊生=苦主线「哑巴亏」:出轨在先没资格掀桌,被自己的把柄堵住嘴,眼睁睁两头落空
// 结局轨道字段=开线标记(全脚本,AI不可见);后续内容(衣柜/寝取展示)以轨道为前置
// ============================================

export function 绿帽线检测(data: SchemaType, 楼层: number): void {
  if (data.系统._待发送事件) return;
  const 钟 = 楼层 + data.系统._时段偏移楼;

  // 102 观众席:「门缝那一眼」——妻阶段≥4且信任≥60,他"提前回家"的某个傍晚(种子档判定)
  {
    const 节点 = data.户['102'];
    if (节点 && !节点.夫.结局轨道 && 节点.妻.当前阶段 >= 4 && 节点.夫.信任值 >= 60) {
      const 档号 = Math.floor(钟 / 每时段楼数);
      if (seededRandom(档号, '102', '门缝') < 0.25) {
        节点.夫.结局轨道 = '观众席';
        data.系统._待发送事件 =
          `${事件角色标记({ 在场妻: ['102'], 在场夫: ['102'] })}【门缝那一眼】这个傍晚,顾国栋比往常早到家——门虚掩着一条缝,他在门外站住了。他看见了。` +
          '他没有推门,没有出声,在门外站了很久很久,然后退了出去,把门缝留在原样。' +
          '本楼从屋内视角演:沈静仪不知道(或知道?她的性癖会替她选),{{user}}或许瞥见门缝暗了一瞬。' +
          '这一眼改变的东西,不在今晚爆发';
        console.info('[人妻公寓·绿帽] 102 观众席开线(门缝那一眼)');
        return;
      }
    }
  }

  // 202 哑巴亏:妻阶段≥3且丈夫疑心≥70——他察觉了,但出轨在先的人掀不了桌
  {
    const 节点 = data.户['202'];
    if (节点 && !节点.夫.结局轨道 && 节点.妻.当前阶段 >= 3 && 节点.夫.疑心值 >= 70) {
      节点.夫.结局轨道 = '哑巴亏';
      data.系统._待发送事件 =
        `${事件角色标记({ 在场夫: ['202'], 关联妻: ['202'] })}【哑巴亏】何俊生知道了——不是证据确凿的知道,是丈夫的直觉那种知道。他在楼道里迎面撞上{{user}},` +
        '拳头握紧了,又松开。掀桌的话到了喉咙口,被他自己咽了回去:他兜里的手机还亮着那朵花的备注。' +
        '演出这次擦肩:他眼里的东西{{user}}看得懂,他知道{{user}}看得懂,谁都没说话。' +
        '出轨在先的人没资格掀桌——从今天起他是这栋楼里最沉默的人';
      console.info('[人妻公寓·绿帽] 202 哑巴亏开线');
    }
  }
}

// ============================================
// 冷落计时器(修道院范式:排队"她主动来找你";P1 落接口,事件文案 P5 精修)
// ============================================

/** 〔调参〕冷落阈值:超过 N 楼没互动的已攻略户会主动来找你 */
const 冷落阈值 = 25;

/**
 * 冷落检测:找出最久没互动、且阶段≥2 的一户,注入"她主动来找你"事件(一次一人)。
 * 调用方负责落库。
 */
export function 冷落检测(data: SchemaType, 楼层: number): void {
  if (data.系统._待发送事件) return; // 已有事件排队,不叠
  let 最久: { 门牌号: 门牌; 距: number } | null = null;
  for (const [门牌号, 节点] of Object.entries(data.户) as [门牌, 户节点Type][]) {
    if (户静态表[门牌号]?.隐身) continue; // 母亲不走通用冷落
    if (节点.妻.当前阶段 < 2) continue;
    const 距 = 楼层 - 节点.妻.上次互动楼层;
    if (距 >= 冷落阈值 && (!最久 || 距 > 最久.距)) 最久 = { 门牌号, 距 };
  }
  if (!最久) return;
  const 妻名 = 户静态表[最久.门牌号].妻名;
  const 事件 = `【事件妻:${最久.门牌号}】【她来找你了】${妻名}好些天没见到管理员,主动找了个由头下楼来(报修/还东西/顺路——按她的性格与当前场景自然生成)。本轮让她自然出现,理由从日常里长出来,不要凭空发明道具；她的态度、情绪强度和关系距离必须服从本轮焦点状态，不得仅因久未互动擅自写成绝望、崩溃或孤注一掷`;
  data.系统._待发送事件 = 事件;
  // 她主动来找=一次互动,计时器就地清零(2026-07-26 审计 M1):旧版不落任何已发标记,
  // 事件通道下一楼开头就被转存清空,同一户每个 AI 楼重新排队;玩家待在管理员室等
  // 妻位置推算 覆盖不到的房间时,上次互动楼层 永远无人推进,事件无限循环
  data.户[最久.门牌号]!.妻.上次互动楼层 = 楼层;
  console.info(`[人妻公寓·冷落] ${最久.门牌号}(距${最久.距}楼)排队主动来找`);
}
