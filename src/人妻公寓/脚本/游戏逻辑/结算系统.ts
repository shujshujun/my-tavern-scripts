import type { SchemaType, 户节点Type } from '../../schema';
import type { 门牌 } from '../../stageConfig';
import { 户静态表, 晋阶门槛, 阶段标题 } from '../../stageConfig';
import { 镜像直写 } from './守护系统';

/**
 * 结算系统:户级运行时的惰性结算 + 派生轴脚本结算(变量分工表:婚姻值/丈夫双轴全脚本)
 *
 * 惰性结算(放置游戏离线收益算法):后台户被动账不每楼 tick——每户存 _上次结算楼层,
 * 被触碰时(进门/收租日/事件)一口气结算 经过楼数×被动速率。每楼计算量=1焦点户+到期事件,
 * 不随户数膨胀。〔调参〕所有速率待货币平衡波统一定。
 */

// ============================================
// 被动速率(每楼;惰性一次性折算 经过楼数×速率)
// ============================================

/** 婚姻值自然阴跌:裂缝=婚姻值的漏点,不处理自然阴跌(裂缝已确认的户漏得更快) */
const 婚姻阴跌每楼 = 0.1;
const 婚姻阴跌每楼_裂缝已确认 = 0.25;
/** 疑心值自然回落:无新增的楼每楼回落,但不破下限棘轮(下限=堕落值×系数) */
const 疑心回落每楼 = 0.3;
const 疑心下限系数 = 0.2;

/** 疑心下限棘轮:看见了就无法当没看见(堕落越深,回落触底越高) */
function 疑心下限(妻堕落: number): number {
  return 妻堕落 * 疑心下限系数;
}

// ============================================
// 焦点户主动结算(每楼:好感/堕落增量→疑心;婚姻关键事件走独立接口)
// ============================================

const 疑心涨_每2堕落 = 0.5; // 堕落度每 +2 → 疑心 +1(攻略本身就是暴露)
const 疑心单楼上限 = 2; // 分期补收:本楼最多 +2,余账下楼续收(总量守恒)

/**
 * 疑心主通道(焦点户,水位线制,镜像秦璐范式):
 * 堕落增量折算疑心涨点,以 _上次结算楼层 之外的独立水位线跟踪。
 * 这里复用 妻._上次结算楼层 附近逻辑不够——疑心水位需独立字段,P1 先用现算差值近似:
 * 用镜像堕落作水位不便,改为每次触碰时按"当前堕落 vs 快照堕落"的本楼真实增量结算。
 */
export function 结算焦点疑心(节点: 户节点Type, 门牌号: 门牌, 本楼堕落增量: number): void {
  if (本楼堕落增量 <= 0) return;
  const collect = Math.min(Math.round(本楼堕落增量 * 疑心涨_每2堕落), 疑心单楼上限);
  if (collect <= 0) return;
  节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + collect, 0, 100);
  console.info(`[人妻公寓·结算] ${门牌号} 堕落+${本楼堕落增量} → 疑心+${collect}(${节点.夫.疑心值})`);
}

// ============================================
// 惰性结算:被触碰时一口气补算被动账
// ============================================

/**
 * 惰性结算一户(进门/收租日/事件触碰时调用)。
 * @param 楼层 当前楼;首见(_上次结算楼层<0)只校准不补发历史。
 */
export function 惰性结算户(节点: 户节点Type, 楼层: number): void {
  const 妻 = 节点.妻;
  if (妻._上次结算楼层 < 0) {
    妻._上次结算楼层 = 楼层;
    return;
  }
  const 经过 = 楼层 - 妻._上次结算楼层;
  if (经过 <= 0) return;
  妻._上次结算楼层 = 楼层;

  // 婚姻值自然阴跌(裂缝已确认漏得更快)
  const 阴跌率 = 妻.裂缝.已确认 ? 婚姻阴跌每楼_裂缝已确认 : 婚姻阴跌每楼;
  妻.婚姻值 = _.clamp(妻.婚姻值 - 阴跌率 * 经过, 0, 100);

  // 疑心自然回落(不破下限棘轮)
  const 下限 = 疑心下限(妻.堕落值);
  const 夫 = 节点.夫;
  if (夫.疑心值 > 下限) {
    夫.疑心值 = Math.max(下限, 夫.疑心值 - 疑心回落每楼 * 经过);
  }
}

/** 全户惰性结算(收租日/大事件时全楼刷一遍;日常只结算焦点户) */
export function 惰性结算全楼(data: SchemaType, 楼层: number): void {
  for (const [门牌号, 节点] of Object.entries(data.户)) {
    void 门牌号;
    惰性结算户(节点, 楼层);
  }
}

// ============================================
// 晋阶(资格+正戏,不自动;UI 按钮触发,镜像直写)
// ============================================

export interface 晋阶结果 {
  成功: boolean;
  消息: string;
}

/** 检查晋阶资格(达标只是资格) */
export function 可晋阶(妻: 户节点Type['妻']): boolean {
  const 下阶 = 妻.当前阶段 + 1;
  if (下阶 > 5) return false;
  if (下阶 === 1) return 妻.裂缝.已确认; // 0→1:送对症礼开门(裂缝三拍第三拍)
  return 妻.堕落值 >= (晋阶门槛[下阶] ?? 999);
}

/**
 * 请求晋阶(脚本结算:阶段+1,派生标题重算,镜像直写)。
 * 晋阶正戏(第一夜等)由回合引擎注入事件承载,本函数只动机制。
 * 返回结果供 UI 反馈;调用方负责落库。
 */
export function 请求晋阶(data: SchemaType, 门牌号: 门牌): 晋阶结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 成功: false, 消息: '这户还没入住' };
  const 妻 = 节点.妻;
  if (!可晋阶(妻)) {
    return { 成功: false, 消息: 妻.当前阶段 === 0 ? '还没找到打开她的方式' : '她还没到能更进一步的时候' };
  }
  妻.当前阶段 += 1;
  妻.阶段标题 = 阶段标题(妻.当前阶段);
  镜像直写(门牌号, { 阶段: 妻.当前阶段 });
  return { 成功: true, 消息: `${户静态表[门牌号].妻名}进入了「${妻.阶段标题}」` };
}

// ============================================
// 冷落计时器(修道院范式:排队"她主动来找你";P1 落接口,事件文案 P5 精修)
// ============================================

/** 〔调参〕冷落阈值:超过 N 楼没互动的已攻略户会主动来找你 */
const 冷落阈值 = 25;

/**
 * 冷落检测:找出最久没互动、且阶段≥2 的一户,注入"她主动来找你"事件(一次一人)。
 * 调用方负责落库。
 */
export function 冷落检测(data: SchemaType, 楼层: number): void {
  if (data.系统._待发送事件) return; // 已有事件排队,不叠
  let 最久: { 门牌号: 门牌; 距: number } | null = null;
  for (const [门牌号, 节点] of Object.entries(data.户) as [门牌, 户节点Type][]) {
    if (户静态表[门牌号]?.隐身) continue; // 母亲不走通用冷落
    if (节点.妻.当前阶段 < 2) continue;
    const 距 = 楼层 - 节点.妻.上次互动楼层;
    if (距 >= 冷落阈值 && (!最久 || 距 > 最久.距)) 最久 = { 门牌号, 距 };
  }
  if (!最久) return;
  const 妻名 = 户静态表[最久.门牌号].妻名;
  const 事件 = `【她来找你了】${妻名}好些天没见到管理员,主动找了个由头下楼来(报修/还东西/顺路——按她的性格与当前场景自然生成)。本轮让她自然出现,理由从日常里长出来,不要凭空发明道具`;
  data.系统._待发送事件 = 事件;
  console.info(`[人妻公寓·冷落] ${最久.门牌号}(距${最久.距}楼)排队主动来找`);
}
