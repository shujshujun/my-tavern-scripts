/**
 * 一个成功 AI 剧情段原子提交一组旧档兼容节点。102 第三段只推进到核验；202 第三段完成后，
 * 两户的最终交接在同一事务中提交，保证任一失败都不会留下半批节点。
 */
export function 提交录像带双承接剧情阶段(
  data: SchemaType,
  场次标识: string,
  房间: 录像带双承接房间,
  阶段: 1 | 2 | 3,
): 录像带双承接剧情阶段结果 {
  const 路线备份 = 复制路线状态(data.系统._录像带双承接);
  const 完成备份 = [...data.系统._已完成特殊场景];
  const 节点们: { 房间: 录像带双承接房间; 节点: 录像带双承接节点 }[] =
    录像带双承接剧情节点表[阶段].map(节点 => ({ 房间, 节点 }));
  if (房间 === '202' && 阶段 === 3) {
    节点们.push(
      { 房间: '102', 节点: { 轨道: '外层', 序号: 9 } },
      { 房间: '202', 节点: { 轨道: '外层', 序号: 9 } },
    );
  }

  for (const 项 of 节点们) {
    const 结果 = 提交录像带双承接节点(data, {
      路线: 录像带双承接兼容路线ID,
      版本: 录像带双承接兼容版本,
      场次标识,
      房间: 项.房间,
      ...项.节点,
    } as 录像带双承接节点提交);
    if (!结果.成功 || !结果.变动) {
      data.系统._录像带双承接 = 路线备份;
      data.系统._已完成特殊场景 = 完成备份;
      return { 成功: false, 变动: false, 提示: `旧档剧情第 ${阶段} 段提交失败：${结果.提示}` };
    }
  }
  return {
    成功: true,
    变动: true,
    提示: `${房间} 旧档剧情第 ${阶段} 段已提交。`,
    全场完成: data.系统._录像带双承接.状态 === '已完成',
  };
}

function 重新计算全场状态(路线: 录像带双承接路线状态): void {
  const 房间状态 = 录像带双承接房间顺序.map(房间 => 路线.房间[房间]);
  if (房间状态.every(状态 => 状态.状态 === '已结算')) {
    路线.状态 = '已完成';
    return;
  }
  if (房间状态.some(状态 => 状态.状态 === '待复锁')) {
    路线.状态 = '待安全收束';
    return;
  }
  if (房间状态.some(状态 => 状态.状态 === '已安全中断')) {
    路线.状态 = '已安全中断';
    return;
  }
  if (房间状态.every(状态 => 状态.硬状态 === 'visually-verified' || 状态.硬状态 === 'settled')) {
    路线.状态 = '待双路结算';
    return;
  }
  路线.状态 = 房间状态.some(状态 => 状态.状态 !== '未开始') ? '进行中' : '未开始';
}

function 成功结果(全场完成: boolean, 提示: string): 录像带双承接状态结果 {
  return {
    成功: true,
    变动: true,
    提示,
    全场完成,
  };
}

function 失败(提示: string): 录像带双承接状态结果 {
  return { 成功: false, 变动: false, 提示 };
}

function 提交安全收束节点(
  路线: 录像带双承接路线状态,
  提交: 录像带双承接节点提交,
  房间状态: 录像带双承接房间状态,
  键: string,
): 录像带双承接状态结果 {
  if (提交.轨道 !== '外层') return 失败('场次已经中断，平板播放已冻结；必须先由丈夫本人复锁并完成目视核验。');
  if (提交.序号 === 7 && ['self-unlocked', 'full-tape-playing', 'husband-completed'].includes(房间状态.硬状态)) {
    房间状态.硬状态 = 'self-relocked';
    房间状态.外层序号 = Math.max(房间状态.外层序号, 7);
  } else if (提交.序号 === 8 && 房间状态.硬状态 === 'self-relocked') {
    房间状态.硬状态 = 'visually-verified';
    房间状态.外层序号 = Math.max(房间状态.外层序号, 8);
    房间状态.状态 = '已安全中断';
  } else {
    return 失败('安全收束顺序不成立：只能先提交本人复锁，再提交陪看人无接触目视核验。');
  }
  房间状态.已提交键.push(键);
  房间状态.最近提交键 = 键;
  重新计算全场状态(路线);
  return 成功结果(
    false,
    提交.序号 === 7 ? '本人复锁已提交；还需目视核验才能安全离场。' : '目视核验已提交；本场已安全中断，不产生结局结算。',
  );
}

function 普通节点错误(路线: 录像带双承接路线状态, 房间状态: 录像带双承接房间状态, 提交: 录像带双承接节点提交): string {
  const { 轨道, 序号 } = 提交;
  if (轨道 === '平板') {
    if (序号 !== 房间状态.平板序号 + 1) return `平板必须连续播放；下一拍应为 ${房间状态.平板序号 + 1}。`;
    if (序号 === 1 && (房间状态.硬状态 !== 'locked' || 房间状态.外层序号 !== 1)) {
      return '片头只能在丈夫仍锁定且外层锁定镜头已提交后播放。';
    }
    if (序号 === 2 && (房间状态.硬状态 !== 'self-unlocked' || 房间状态.外层序号 !== 3)) {
      return '第二拍只能在授权成立且丈夫本人解锁后播放。';
    }
    if (序号 >= 3 && 序号 <= 4 && 房间状态.硬状态 !== 'full-tape-playing') {
      return '母带中段只能在正式连续播放状态推进。';
    }
    if (序号 >= 5 && 序号 <= 9 && (房间状态.硬状态 !== 'full-tape-playing' || 房间状态.外层序号 < 4)) {
      return '先提交观看初段反应，再继续母带第五至第九拍。';
    }
    if (序号 === 10 && (房间状态.硬状态 !== 'full-tape-playing' || 房间状态.外层序号 < 5)) {
      return '先顺序播放至第九拍并提交观看升档，才能播放片尾。';
    }
    return '';
  }

  if (序号 !== 房间状态.外层序号 + 1) return `外层必须按生命周期推进；下一拍应为 ${房间状态.外层序号 + 1}。`;
  if (序号 === 1 && (房间状态.状态 !== '未开始' || 房间状态.硬状态 !== 'idle'))
    return '本户已经开始，不能重复建立锁定起点。';
  if (序号 === 2 && (房间状态.硬状态 !== 'opening-playing-locked' || 房间状态.平板序号 !== 1)) {
    return '必须先在锁定状态完整播放片头，才能提交临时授权。';
  }
  if (序号 === 3 && 房间状态.硬状态 !== 'authorized') return '丈夫尚未明确接受本次授权，不能提交本人解锁。';
  if (序号 === 4 && (房间状态.硬状态 !== 'full-tape-playing' || 房间状态.平板序号 !== 4)) {
    return '观看初段反应必须承接平板第二至第四拍。';
  }
  if (序号 === 5 && (房间状态.硬状态 !== 'full-tape-playing' || 房间状态.平板序号 !== 9)) {
    return '观看升档必须承接平板第五至第九拍。';
  }
  if (序号 === 6 && (房间状态.硬状态 !== 'full-tape-playing' || 房间状态.平板序号 !== 10)) {
    return '丈夫完成只能在第十拍可见后提交。';
  }
  if (序号 === 7 && 房间状态.硬状态 !== 'husband-completed') return '丈夫完成清理前不能提交本人复锁。';
  if (序号 === 8 && 房间状态.硬状态 !== 'self-relocked') return '陪看人只能在丈夫本人复锁后进行无接触目视核验。';
  if (序号 === 9) {
    if (房间状态.硬状态 !== 'visually-verified') return '回执或钥匙交接必须在目视核验后发生。';
    const 另一户 = 路线.房间[提交.房间 === '102' ? '202' : '102'];
    if (另一户.硬状态 !== 'visually-verified' && 另一户.硬状态 !== 'settled') {
      return '另一户尚未完成复锁与目视核验，双路最终交接暂不能提交。';
    }
  }
  return '';
}

function 应更新的硬状态(提交: 录像带双承接节点提交): 录像带双承接房间状态['硬状态'] | null {
  if (提交.轨道 === '平板') {
    if (提交.序号 === 1) return 'opening-playing-locked';
    if (提交.序号 === 2) return 'full-tape-playing';
    return null;
  }
  const 状态表: Partial<Record<number, 录像带双承接房间状态['硬状态']>> = {
    1: 'locked',
    2: 'authorized',
    3: 'self-unlocked',
    6: 'husband-completed',
    7: 'self-relocked',
    8: 'visually-verified',
    9: 'settled',
  };
  return 状态表[提交.序号] ?? null;
}

/**
 * 原子提交一个旧档兼容节点。失败、超时、取消与重复事件都不得留下半提交硬状态。
 */
export function 提交录像带双承接节点(data: SchemaType, 提交: 录像带双承接节点提交): 录像带双承接状态结果 {
  if (录像带V4已占用(data)) return 失败('录像带V4已经购买或运行，旧双承接节点已拒绝。');
  if (提交.路线 !== 录像带双承接兼容路线ID || 提交.版本 !== 录像带双承接兼容版本)
    return 失败('不是录像带旧档兼容节点。');
  if (!提交.场次标识.trim()) return 失败('正式场次标识不能为空。');
  if (!录像带双承接房间顺序.includes(提交.房间) || !是正式序号(提交.轨道, 提交.序号))
    return 失败('录像带节点范围无效。');

  const 路线 = data.系统._录像带双承接;
  const 是起点 = 提交.轨道 === '外层' && 提交.序号 === 1;
  if (路线.状态 === '已安全中断' && 是起点 && 路线.场次标识 !== 提交.场次标识) {
    重置正式场次(路线, 提交.场次标识);
  }
  if (!路线.场次标识) {
    if (!是起点) return 失败('正式场次只能从本户外层锁定镜头开始。');
    重置正式场次(路线, 提交.场次标识);
  }
  if (路线.场次标识 !== 提交.场次标识) return 失败('场次标识已经变化，旧节点不能写入当前时间线。');
  if (路线.状态 === '已完成') return 失败('录像带双承接已经完成，不能重复结算。');

  const 房间状态 = 路线.房间[提交.房间];
  const 键 = 节点键(提交);
  if (房间状态.已提交键.includes(键)) {
    return { 成功: true, 变动: false, 重复: true, 提示: '该房间、轨道、版本与序号已经提交；本次重复事件已忽略。' };
  }
  if (路线.状态 === '待安全收束') {
    if (房间状态.状态 !== '待复锁') return 失败('全场正在安全收束，本户没有新的播放或结算节点。');
    return 提交安全收束节点(路线, 提交, 房间状态, 键);
  }
  if (路线.状态 === '已安全中断') return 失败('本场已经安全中断；必须使用新的场次标识从外层第一拍重新开始。');

  const 错误 = 普通节点错误(路线, 房间状态, 提交);
  if (错误) return 失败(错误);

  if (提交.轨道 === '平板') 房间状态.平板序号 = 提交.序号;
  else 房间状态.外层序号 = 提交.序号;
  const 下一硬状态 = 应更新的硬状态(提交);
  if (下一硬状态) 房间状态.硬状态 = 下一硬状态;
  房间状态.状态 = 房间状态.硬状态 === 'settled' ? '已结算' : '进行中';
  房间状态.已提交键.push(键);
  房间状态.最近提交键 = 键;
  重新计算全场状态(路线);

  const 全场完成 = 录像带双承接房间顺序.every(房间 => 路线.房间[房间].状态 === '已结算');
  if (全场完成) 路线.状态 = '已完成';
  if (全场完成 && !data.系统._已完成特殊场景.includes(录像带双承接完成ID)) {
    data.系统._已完成特殊场景.push(录像带双承接完成ID);
  }
  return 成功结果(
    全场完成,
    全场完成
      ? '两户均已复锁、核验并完成交接；《录像带》正式结局已提交。'
      : `${提交.房间} ${提交.轨道}第 ${提交.序号} 拍已提交。`,
  );
}

/**
 * 取消、正文失败或超时发生在本人解锁后时，两户播放与结算一起冻结；
 * 已解锁房间必须依次提交外层 7、8，未解锁房间可直接安全退出。
 */
export function 请求录像带双承接中断(
  data: SchemaType,
  场次标识: string,
  原因: 录像带双承接中断原因,
): 录像带双承接状态结果 {
  const 路线 = data.系统._录像带双承接;
  if (!路线.场次标识 || 路线.场次标识 !== 场次标识.trim()) return 失败('场次已经变化，本次中断请求没有写入。');
  if (路线.状态 === '已完成') return 失败('场次已经完整结算，不能再按中断处理。');
  if (路线.状态 === '已安全中断') return { 成功: true, 变动: false, 重复: true, 提示: '本场已经安全中断。' };

  let 需要复锁 = false;
  for (const 房间 of 录像带双承接房间顺序) {
    const 状态 = 路线.房间[房间];
    if (状态.状态 === '已结算') continue;
    状态.中断原因 = 原因;
    if (['self-unlocked', 'full-tape-playing', 'husband-completed', 'self-relocked'].includes(状态.硬状态)) {
      状态.状态 = '待复锁';
      需要复锁 = true;
    } else {
      状态.状态 = '已安全中断';
    }
  }
  重新计算全场状态(路线);
  return {
    成功: true,
    变动: true,
    提示: 需要复锁
      ? `场次因${原因}冻结；已解锁房间必须先由丈夫本人复锁，再完成无接触目视核验。`
      : `场次因${原因}在解锁前取消，未产生结局结算。`,
  };
}
