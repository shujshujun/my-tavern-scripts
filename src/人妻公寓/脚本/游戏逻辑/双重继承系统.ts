export function 双重继承商店已上架(data: SchemaType): boolean {
  return (
    !data.系统._坏结局 &&
    回国前置完成(data) &&
    路线(data).阶段 === '未开始' &&
    !data.背包.includes(双重继承场景票ID) &&
    !双重继承已完成(data)
  );
}

