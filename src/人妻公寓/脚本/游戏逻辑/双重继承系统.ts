export function 购买双重继承场景票(data: SchemaType, 价格: number): 双重继承结果 {
  if (!双重继承商店已上架(data)) {
    return { 成功: false, 提示: '《双重继承》尚未开放、已经购买、已经启动或已经完成。' };
  }
  if (!Number.isFinite(价格) || 价格 <= 0) return { 成功: false, 提示: '《双重继承》的价格配置无效。' };
  if (data.现金 < 价格) return { 成功: false, 提示: '钱不够。' };
  data.现金 -= 价格;
  data.背包.push(双重继承场景票ID);
  const 当前路线 = 路线(data);
  当前路线.阶段 = '待使用双重继承';
  当前路线.最早父亲到楼时段 = -1;
  当前路线.已检查公共区域 = [];
  return {
    成功: true,
    变动: true,
    提示: '《双重继承》的正式交接材料已经放进背包。去管理员室使用，由你决定什么时候开始结局。',
  };
}

