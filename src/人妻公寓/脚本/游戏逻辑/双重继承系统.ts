function 今日(data: SchemaType): number {
  return Math.max(0, Math.floor(data.系统._绝对时段 / 每天时段数));
}

function 对齐当前或下一个下午(绝对时段: number): number {
  const 当前 = Math.max(0, Math.floor(绝对时段));
  const 序号 = ((当前 % 每天时段数) + 每天时段数) % 每天时段数;
  const 下午序号 = 2;
  const 偏移 = 序号 <= 下午序号 ? 下午序号 - 序号 : 每天时段数 - 序号 + 下午序号;
  return 当前 + 偏移;
}

function 同一双重继承剧情票(左: string, 右: string): boolean {
  const 左票 = 解析双重继承剧情事件(左);
  const 右票 = 解析双重继承剧情事件(右);
  return Boolean(
    左票 &&
      右票 &&
      左票.动作 === 右票.动作 &&
      左票.预期阶段 === 右票.预期阶段 &&
      左票.请求时段 === 右票.请求时段 &&
      左票.拍 === 右票.拍,
  );
}

/** 候选／执行不允许任何普通强剧情；提交端只放行当前回调自己的《双重继承》票。 */
function 双重继承普通强剧情冲突(data: SchemaType, 当前事件 = ''): boolean {
  const 活动 = data.系统._场景剧情事务;
  if (活动.id && (!当前事件 || !活动.内容 || !同一双重继承剧情票(活动.内容, 当前事件))) return true;
  const 队首 = 读取队首场景剧情(data.系统._待发送事件);
  if (队首 && (!当前事件 || !同一双重继承剧情票(队首.内容, 当前事件))) return true;
  return false;
}

function 双重继承父亲强交互占用(data: SchemaType): boolean {
  const 通话 = data.系统._父亲通话;
  const 视频 = data.系统._母亲视频通话终幕;
  const 自有视频已收尾 =
    路线(data).阶段 === '待总钥匙归位' &&
    视频.标识 === 双重继承完成ID &&
    视频.状态 === '已完成' &&
    通话.标识 === 双重继承完成ID &&
    通话.模式 === 母亲视频通话模式 &&
    通话.状态 === '收尾中';
  return data.系统._待接来电.期 >= 0 || (!自有视频已收尾 && Boolean(通话.标识 || 通话.状态));
}

function 强剧情占用(data: SchemaType): boolean {
  if (data.系统._坏结局) return true;
  if (data.系统._性爱场景.状态 !== '空闲') return true;
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0) return true;
  if (双重继承普通强剧情冲突(data)) return true;
  if (双重继承父亲强交互占用(data)) return true;
  if (处于医院硬锁(data, '302')) return true;
  return false;
}

function 地点操作错误(data: SchemaType): string {
  if (data.系统._坏结局) return '当前结局已经锁定。';
  if (data.系统._性爱场景.状态 !== '空闲') return '先把当前亲密场景正常收束。';
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0) return '当前特殊场景尚未结束。';
  if (双重继承普通强剧情冲突(data)) return '还有一段强剧情没有完成。';
  if (双重继承父亲强交互占用(data)) return '先处理当前父亲电话。';
  if (处于医院硬锁(data, '302')) return '母亲正在医院待产或恢复，《双重继承》从当前步骤顺延。';
  return '';
}

function 剧情提交错误(data: SchemaType, 当前事件: string): string {
  if (data.系统._坏结局) return '当前结局已经锁定。';
  if (data.系统._性爱场景.状态 !== '空闲') return '另一场亲密场景已经抢先开始。';
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0) return '当前特殊场景已经变化。';
  if (双重继承普通强剧情冲突(data, 当前事件)) return '另一段强剧情已经抢先开始。';
  if (双重继承父亲强交互占用(data)) return '父亲电话状态已经变化。';
  if (处于医院硬锁(data, '302')) return '母亲已经进入医院硬锁。';
  return '';
}

export function 使用双重继承场景票(data: SchemaType, 当前地点: string, 当前楼层 = -1): 双重继承结果 {
  const 当前路线 = 路线(data);
  if (当前路线.阶段 !== '待使用双重继承' || !data.背包.includes(双重继承场景票ID)) {
    return { 成功: false, 提示: '背包里没有当前可用的《双重继承》交接材料。' };
  }
  if (当前地点 !== '管理员室') return { 成功: false, 提示: '请到管理员室使用《双重继承》交接材料。' };
  if (!回国前置完成(data)) return { 成功: false, 提示: '先完成母亲承接事件《回国》。' };
  const 错误 = 地点操作错误(data);
  if (错误) return { 成功: false, 提示: 错误 };
  const 索引 = data.背包.indexOf(双重继承场景票ID);
  if (索引 < 0) return { 成功: false, 提示: '《双重继承》交接材料已经不在背包里。' };

  data.背包.splice(索引, 1);
  当前路线.最早父亲到楼时段 = 对齐当前或下一个下午(data.系统._绝对时段);
  当前路线.已检查公共区域 = [];
  当前路线.最早早餐日 = -1;
  当前路线.最早视频时段 = -1;
  当前路线.启动楼层 = Number.isInteger(当前楼层) ? 当前楼层 : -1;
  当前路线.完成楼层 = -1;

  if (当前路线.最早父亲到楼时段 === data.系统._绝对时段 && 当前时段(data) === '下午') {
    当前路线.阶段 = '公共区域检查中';
    return {
      成功: true,
      变动: true,
      提示: '正式交接已经启动。父亲在这个安全下午来到公寓；接下来由你带他检查八个公共区域。',
    };
  }

  当前路线.阶段 = '待父亲回楼';
  return {
    成功: true,
    变动: true,
    提示: '正式交接材料已经整理并通知父亲。父亲会在下一个安全下午回到公寓；《回国》里提到的日期只保留为口头约定。',
  };
}

function 有总钥匙(data: SchemaType): boolean {
  return data.背包.includes(公寓楼总钥匙ID);
}

function 补唯一总钥匙(data: SchemaType): boolean {
  const 位置 = data.背包.reduce<number[]>((结果, id, index) => (id === 公寓楼总钥匙ID ? [...结果, index] : 结果), []);
  if (!位置.length) {
    data.背包.push(公寓楼总钥匙ID);
    return true;
  }
  for (let index = 位置.length - 1; index >= 1; index -= 1) data.背包.splice(位置[index], 1);
  return 位置.length > 1;
}

function 移除全部总钥匙(data: SchemaType): boolean {
  const 原数 = data.背包.length;
  data.背包 = data.背包.filter(id => id !== 公寓楼总钥匙ID);
  return data.背包.length !== 原数;
}

