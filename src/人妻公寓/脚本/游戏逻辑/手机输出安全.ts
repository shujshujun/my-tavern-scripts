const 双重继承余波禁入事实 =
  /(?:机场视频|视频通话|镜头下|镜头外|镜头死角|手机画面|成人动作|口交|肛交|乳交|性交|射精|精液|裸体|裸照|总钥匙.{0,12}(?:性|身体|下体)).{0,24}(?:知情|看穿|发现|默许|成全|故意|装作不知道)/i;

/** 生成后的逐条语义验收；格式合规不等于可以进入群聊。 */
export function 验收群聊隐私(消息: string, 模式: 群聊隐私模式): boolean {
  const 文 = String(消息 ?? '')
    .normalize('NFKC')
    .trim();
  if (!文) return false;
  if (模式 === '姐妹孕情') return !姐妹孕情禁入事实.test(文);
  // 本人孕情已告知的公开动态：仅增加孕情表达，其余公开渠道隐私条件保持有效。
  if (模式 === '朋友圈孕情') return !姐妹孕情禁入事实.test(文) && !楼务额外私密.test(文);
  if (模式 === '回国茶话会') return !回国茶话会禁入事实.test(文);
  if (模式 === '双重继承余波')
    return !双重继承余波禁入事实.test(文) && !父亲被写成已知关系(文, 文.startsWith('母亲:') ? '母亲' : '旁人');
  if (明确私密事实.test(文)) return false;
  return 模式 !== '楼务' || !楼务额外私密.test(文);
}

export type 父亲台词语义模式 = '普通审核' | '母亲机场视频' | '双重继承后家常';

function 父亲句中存在肯定语义(正文: string, 模式: RegExp): boolean {
  for (const 句 of String(正文 ?? '')
    .split(/[。！？；;\n]/u)
    .map(片段 => 片段.trim())
    .filter(Boolean)) {
    const 匹配 = 句.match(模式);
    if (!匹配 || 匹配.index === undefined) continue;
    const 前文 = 句.slice(Math.max(0, 匹配.index - 14), 匹配.index);
    if (
      /(?:没有|并未|尚未|还没|从未|不会|不再|无需|不用|不必|别|严禁|不能|并不知道|没看穿)(?:再|会|要|打算)?\s*$/u.test(
        前文,
      )
    ) {
      continue;
    }
    const 命中前段 = 匹配[0].slice(0, 20);
    if (/(?:不是|并非|不能|不得|不会)不(?:再|会)?(?:审核|审批|检查|考核|收回|拿回|换人|发给|交给|汇报)/u.test(命中前段))
      return true;
    if (
      /(?:不(?!管|论|只|止|光|但|妨)|没|未)(?:再|会|曾|替你|帮你|想|打算|准备)?(?:审核|审批|检查|考核|收回|拿回|换人|发给|交给|汇报)/u.test(
        命中前段,
      )
    )
      continue;
    if (
      /(?:没有|并未|尚未|还没|从未|不会|不再|无需|不用|不必|别|严禁|不能).{0,6}(?:知道|知情|看穿|发现|明白|默许|成全|审核|审批|收回|拿回|换人|发给|交给|汇报)/u.test(
        命中前段,
      )
    ) {
      continue;
    }
    return true;
  }
  return false;
}

/**
 * 格式安全之外的模式硬验收。普通审核电话仍可真实问楼务；机场视频与结局后家常只拒绝
 * 父亲主动恢复审核／知情共谋语义，玩家先谈公寓后的非命令式经验回应仍可通过。
 */
export function 验收父亲模式语义(台词: string, 模式: 父亲台词语义模式, 玩家说 = ''): boolean {
  const 文 = String(台词 ?? '')
    .normalize('NFKC')
    .trim();
  if (!文) return false;
  if (模式 === '普通审核') return true;

  if (父亲被写成已知关系(文, '父亲')) return false;

  const 主动审核 =
    /(?:把|将|先把|赶紧把).{0,16}(?:账本|上交|欠租|维修|租户|报修|胜任度|管理进度|审批|补救期限|报表).{0,16}(?:发给|交给|拿给|报给|汇报|说清|列出来|给我看)|(?:账本|上交|欠租|维修|租户|报修|胜任度|管理进度|审批|补救期限|报表).{0,16}(?:发给我|交上来|给我看看|逐项汇报|说清楚|处理了吗|进度如何|到底多少)|(?:我|爸|父亲).{0,8}(?:再|重新|继续)?(?:审核|审批|检查|考核).{0,16}(?:公寓|楼|管理|账|你)/u;
  if (父亲句中存在肯定语义(文, 主动审核)) return false;

  if (
    父亲句中存在肯定语义(
      文,
      /(?:重新|再).{0,8}(?:决定|考虑|审核).{0,12}(?:是否|要不要)?(?:交楼|交给你|让你管理)|(?:收回|拿回).{0,8}(?:总钥匙|钥匙|管理权)|(?:换人|另请人).{0,8}(?:管楼|管理)|(?:最后通牒|扣分|胜任度红线|滚去打工)/u,
    )
  ) {
    return false;
  }

  // 保留参数进入事实版本：玩家主动提到公寓时，诸如“按现行规矩留档就行”的被动经验回应可通过。
  void 玩家说;
  return true;
}

const 父亲旧固定兜底 = new Set([
  '这期楼里的账和事情，你照实一项项说。',
  '你妈已经替你说过话了，这期账我还是要逐项问清。',
]);

/** 旧版本曾把这两句确定性兜底当成有效 AI 回复落库；只用于阻止旧活动通话继续复读。 */
export function 是父亲旧固定兜底台词(原: string): boolean {
  return 父亲旧固定兜底.has(String(原 ?? '').trim());
}

function 引号配对(左: string, 右: string): boolean {
  return (
    (左 === '“' && 右 === '”') || (左 === '‘' && 右 === '’') || (左 === '"' && 右 === '"') || (左 === "'" && 右 === "'")
  );
}

/**
 * 只剥整条候选最外层、且说话人明确仍为父亲的常见模型包装。
 * 动作旁白、半截引语与包装外残留正文不在这里猜测，继续交给严格验收拒绝。
 */
function 剥父亲单一引语包装(原: string): string {
  const 文 = String(原 ?? '').trim();
  const 父亲引语 = 文.match(
    /^(?:父亲|爸爸|爸)\s*(?:说|问|答|道|训斥|叹道)\s*[，,:：]?\s*([“"‘'])([\s\S]*)([”"’'])\s*[。！？!?]?$/u,
  );
  if (父亲引语 && 引号配对(父亲引语[1], 父亲引语[3])) return 父亲引语[2].trim();
  const 直接引语 = 文.match(/^([“"‘'])([\s\S]*)([”"’'])\s*$/u);
  if (直接引语 && 引号配对(直接引语[1], 直接引语[3])) return 直接引语[2].trim();
  return 文;
}

/**
 * 父亲通话只接受单说话人的短句。空白或不合规候选返回空串，由通话层保留待回复令牌并显式重试；
 * 不得用固定本地文案冒充 AI 回复并写入记录，否则任何一次生成失败都会永久推进成重复台词。
 */
export function 安全父亲台词(原: string, 要求圆场首句: boolean): string {
  const 父亲标签 = ['父亲', '爸爸', '爸'];
  const 所有说话人 = [...父亲标签, '母亲', '妈妈', '妈', '儿子', '玩家', '管理员', '你妈', '你母亲', '你妈妈'];
  const 输出 =
    规范手机单气泡(剥父亲单一引语包装(原), {
      最大汉字: 150,
      可剥首标签: 父亲标签,
      已知说话人: 所有说话人,
      禁止多说话人: true,
      禁止任意说话人标签: true,
    }) ?? '';
  const 文 = 输出.normalize('NFKC');
  const 说话人标签 = /(?:父亲|爸爸|爸|母亲|妈妈|妈|儿子|玩家|管理员|你妈|你母亲|你妈妈)\s*[：:]/;
  const 旁白式父亲 = /(?:父亲|爸爸|爸)\s*(?:说|问|答|道|训斥|叹道)\s*[，,:：“"]/;
  const 旁白式换人 = /(?:^|[。！？!?，,\s])[\p{Script=Han}A-Za-z0-9_]{1,12}\s*(?:说|问|答|道|训斥|叹道)\s*[，,:：“"]/u;
  const 动作旁白 =
    /(?:^|[。！？!?，,\s])(?:父亲|爸爸|爸|他|电话那头)[^。！？!?\n]{0,24}(?:皱眉|抬眼|低头|翻(?:了)?翻|翻看|叹(?:了)?口气|沉默|顿(?:了)?顿|冷笑|摇(?:了)?摇头|点(?:了)?点头|看(?:了)?看|看着|望着)/u;
  const 格式安全 =
    !!文 &&
    !/[\r\n]/.test(文) &&
    !/[“”"‘’]/.test(文) &&
    !说话人标签.test(文) &&
    !旁白式父亲.test(文) &&
    !旁白式换人.test(文) &&
    !动作旁白.test(文) &&
    !/(?:母亲|妈妈|妈)(?:说|问|答|道|劝)[：:“"]/.test(文);
  const 已转述圆场 =
    /(?:你妈|你母亲|你妈妈).{0,12}(?:替你|帮你|为你).{0,12}(?:说|解释|缓和|求情)|(?:替你|帮你|为你).{0,12}(?:说|解释|缓和|求情).{0,12}(?:你妈|你母亲|你妈妈)/.test(
      文,
    );
  if (格式安全 && !是父亲旧固定兜底台词(输出) && (!要求圆场首句 || 已转述圆场)) return 输出;
  return '';
}
