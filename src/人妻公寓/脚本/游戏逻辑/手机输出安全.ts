export type 群聊隐私模式 = '楼务' | '姐妹' | '姐妹孕情';

const 明确私密事实 =
  /(?:私聊|单独发(?:给|了)|只发给|偷情|出轨|接吻|亲嘴|上床|做爱|开房|裸照|裸体|内衣照|床上|过夜|睡过|暧昧|不清不楚|有一腿|勾搭|眉来眼去|婚姻秘密|绿帽|情人|奸情|怀孕|避孕|体内|射精|口交|肛交|乳交|偷拍视频|摄像头).{0,24}|(?:昨晚|深夜|半夜).{0,16}(?:房里|房间|家里|家中|住处|门里|床上|接吻|亲热|过夜)|(?:管理员|房东|你).{0,12}(?:和|跟).{0,8}(?:她|太太|住户).{0,12}(?:亲热|接吻|上床|睡|偷情|暧昧)/i;

const 楼务额外私密 = /(?:私下|亲密行为|婚姻隐私|谁家夫妻|夫妻感情|只对你可见|仅你可见)/i;

/** 孕情已经公开后，姐妹小群只额外放行“怀孕／孩子父亲”这一项公开事实；其他私密事实照旧拦截。 */
const 姐妹孕情禁入事实 =
  /(?:私聊|单独发(?:给|了)|只发给|偷情|出轨|接吻|亲嘴|上床|做爱|开房|裸照|裸体|内衣照|床上|过夜|睡过|暧昧|不清不楚|有一腿|勾搭|眉来眼去|婚姻秘密|绿帽|情人|奸情|避孕|体内|射精|口交|肛交|乳交|偷拍视频|摄像头).{0,24}|(?:昨晚|深夜|半夜).{0,16}(?:房里|房间|家里|家中|住处|门里|床上|接吻|亲热|过夜)|(?:管理员|房东|你).{0,12}(?:和|跟).{0,8}(?:她|太太|住户).{0,12}(?:亲热|接吻|上床|睡|偷情|暧昧)/i;

/** 生成后的逐条语义验收；格式合规不等于可以进入群聊。 */
export function 验收群聊隐私(消息: string, 模式: 群聊隐私模式): boolean {
  const 文 = String(消息 ?? '').normalize('NFKC').trim();
  if (!文) return false;
  if (模式 === '姐妹孕情') return !姐妹孕情禁入事实.test(文);
  if (明确私密事实.test(文)) return false;
  return 模式 !== '楼务' || !楼务额外私密.test(文);
}

/** AI 输出全被拒绝时仍给一条不补充事实的本地消息，避免提示词失败后泄露或卡死节拍。 */
export function 群聊安全回退(合法发言人: readonly string[], 模式: 群聊隐私模式): string {
  const 发言人 = 合法发言人.find(Boolean)?.trim();
  if (!发言人) return '';
  return 模式 === '楼务'
    ? `${发言人}:收到，有楼务情况我再在群里说。`
    : `${发言人}:先聊点大家都看得见的吧。`;
}

/** 父亲通话只接受单说话人的短句；圆场首句缺少父亲转述时使用确定性本地台词。 */
export function 安全父亲台词(原: string, 要求圆场首句: boolean): string {
  const 父亲标签 = ['父亲', '爸爸', '爸'];
  const 所有说话人 = [...父亲标签, '母亲', '妈妈', '妈', '儿子', '玩家', '管理员', '你妈', '你母亲', '你妈妈'];
  const 输出 =
    规范手机单气泡(原, {
      最大汉字: 150,
      可剥首标签: 父亲标签,
      已知说话人: 所有说话人,
      禁止多说话人: true,
      禁止任意说话人标签: true,
    }) ?? '';
  const 文 = 输出.normalize('NFKC');
  const 说话人标签 = /(?:父亲|爸爸|爸|母亲|妈妈|妈|儿子|玩家|管理员|你妈|你母亲|你妈妈)\s*[：:]/;
  const 旁白式父亲 = /(?:父亲|爸爸|爸)\s*(?:说|问|答|道|训斥|叹道)\s*[，,:：“"]/;
  const 旁白式换人 = /(?:^|[。！？!?，,\s])[\p{Script=Han}A-Za-z0-9_]{1,12}\s*(?:说|问|答|道|训斥|叹道)\s*[，,:：“"]/u;
  const 动作旁白 =
    /(?:^|[。！？!?，,\s])(?:父亲|爸爸|爸|他|电话那头)[^。！？!?\n]{0,24}(?:皱眉|抬眼|低头|翻(?:了)?翻|翻看|叹(?:了)?口气|沉默|顿(?:了)?顿|冷笑|摇(?:了)?摇头|点(?:了)?点头|看(?:了)?看|看着|望着)/u;
  const 格式安全 =
    !!文 &&
    !/[\r\n]/.test(文) &&
    !/[“”"‘’]/.test(文) &&
    !说话人标签.test(文) &&
    !旁白式父亲.test(文) &&
    !旁白式换人.test(文) &&
    !动作旁白.test(文) &&
    !/(?:母亲|妈妈|妈)(?:说|问|答|道|劝)[：:“"]/.test(文);
  const 已转述圆场 = /(?:你妈|你母亲|你妈妈).{0,12}(?:替你|帮你|为你).{0,12}(?:说|解释|缓和|求情)|(?:替你|帮你|为你).{0,12}(?:说|解释|缓和|求情).{0,12}(?:你妈|你母亲|你妈妈)/.test(文);
  if (格式安全 && (!要求圆场首句 || 已转述圆场)) return 输出;
  return 要求圆场首句 ? '你妈已经替你说过话了，这期账我还是要逐项问清。' : '这期楼里的账和事情，你照实一项项说。';
}
