const 开发封顶表: readonly number[] = [0, 10, 25, 60, 85, 100];
/** 夫:AI 可写仅心理/情绪(双轴/状态/轨道全脚本) */
const 夫文本白名单 = ['当前心理想法', '当前情绪'] as const;

// ============================================
// 保护快照(模块内存;镜像在 chat 变量里持久兜底)
