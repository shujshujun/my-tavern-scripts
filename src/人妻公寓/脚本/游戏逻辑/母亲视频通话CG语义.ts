/**
 * 普通微信回合只在“接通入场＋通话主循环”中推进。
 * 入场只播放一次；入场末帧进入005；主循环末帧回到005，绝不回到001。
 */
export function 推进母亲视频通话普通CG(当前ID: string): 母亲视频通话CG语义 {
  const 入场序 = 母亲视频通话接通入场CG.findIndex(CG => CG.id === 当前ID);
  if (入场序 >= 0) {
    return 母亲视频通话接通入场CG[入场序 + 1] ?? 母亲视频通话主循环CG[0];
  }
  const 循环序 = 母亲视频通话主循环CG.findIndex(CG => CG.id === 当前ID);
  if (循环序 >= 0) {
    return 母亲视频通话主循环CG[(循环序 + 1) % 母亲视频通话主循环CG.length];
  }
  return 母亲视频通话接通入场CG[0];
}

/** 玩家请求结束通话时，按当前画面状态选一张衔接；三张不是固定连续播放。 */
export function 选择母亲视频通话结束衔接CG(当前连接状态: 母亲视频通话CG连接状态): 母亲视频通话CG语义 {
  if (当前连接状态 === '深喉') return 母亲视频通话结束衔接CG[1];
  if (
    当前连接状态 === '离口舔舐' ||
    当前连接状态 === '舌尖接触' ||
    当前连接状态 === '贴近' ||
    当前连接状态 === '未接触'
  ) {
    return 母亲视频通话结束衔接CG[2];
  }
  return 母亲视频通话结束衔接CG[0];
}

