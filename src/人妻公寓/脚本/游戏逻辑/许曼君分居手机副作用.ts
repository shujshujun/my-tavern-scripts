import { 读取许曼君分居状态 } from './许曼君分居系统';

export interface 许曼君分居手机展示 {
  id: string;
  类型: '私聊' | '系统通知';
  联系人: '许曼君' | '赵国强';
  标题: string;
  内容: string;
  绝对时段: number | null;
  权威性: '仅展示';
}

/** 手机只读展示四幕硬状态；消息失败、撤回或未读都不能改变路线检查点。 */
export function 读取许曼君分居手机展示(data: unknown): 许曼君分居手机展示[] {
  const state = 读取许曼君分居状态(data);
  const items: 许曼君分居手机展示[] = [];
  if (state.共同夜晚状态 === '待接受') {
    items.push({
      id: `manjun-four-act-joint-night-${state.封条修订}`,
      类型: '私聊',
      联系人: '许曼君',
      标题: '今晚回201吗',
      内容: '钥匙一直在管理员室。你要留下，就不是趁谁不在；今晚不来，也不影响我把自己的事说完。',
      绝对时段: state.最近观察绝对时段,
      权威性: '仅展示',
    });
  }
  if (state.预约.类型 === '取物' && state.预约.状态 === '待开始') {
    items.push({
      id: `manjun-four-act-pickup-${state.预约.开始绝对时段 ?? 'pending'}`,
      类型: '系统通知',
      联系人: '赵国强',
      标题: '201取物预约',
      内容: '赵国强只在这一次预约回201取完约定用品。个人钥匙仍封存在管理员室，由管理员陪同开门。',
      绝对时段: state.预约.开始绝对时段,
      权威性: '仅展示',
    });
  }
  if (state.预约.类型 === '最终交接' && state.预约.状态 === '待开始') {
    items.push({
      id: `manjun-four-act-final-handover-${state.预约.开始绝对时段 ?? 'pending'}`,
      类型: '系统通知',
      联系人: '赵国强',
      标题: '管理员室钥匙交接',
      内容: '这次只在管理员室确认是否进入离婚办理；赵国强不会再进入201，也不会取回个人钥匙。',
      绝对时段: state.预约.开始绝对时段,
      权威性: '仅展示',
    });
  }
  return items;
}
