import type { SchemaType } from '../../schema';
import type { 门牌 } from '../../stageConfig';
import { 角色结局后阶段 } from './结局后生活社交语义';

export interface 角色阶段体验 {
  标题: string;
  简介: string;
  继续方式: string;
  配偶称谓: '丈夫' | '前夫';
  配偶说明: string;
}

/** 玩家档案的当前状态说明；自由RP与已有入口共同承接，不签发进度或生成新约定。 */
export function 读取角色阶段体验(data: SchemaType, 门牌号: 门牌): 角色阶段体验 | null {
  if (!data.户[门牌号]) return null;
  const 阶段 = 角色结局后阶段(data, 门牌号);
  if (阶段 === '未进入后效') return null;
  const 基础 = { 配偶称谓: '丈夫' as const };
  switch (门牌号) {
    case '101':
      return { ...基础, 标题: '家庭中的新位置',
        简介: '夏乔与陆嘉明已经把你纳入知情的家庭安排，她会从这份关系继续与你相处。',
        继续方式: '可以直接到访、聊天或回应她的联系；家庭后续按下方已经出现的步骤继续。',
        配偶说明: '陆嘉明知情并继续参与家庭生活。' };
    case '102':
      return { ...基础, 标题: '明确的相处',
        简介: '沈静仪仍然克制，但会把想见、何时方便和自己的打算说清楚。',
        继续方式: '可以直接与她聊天；她在102且空闲时，可从“和她亲密”选择这次由谁开场。',
        配偶说明: '顾国栋已完成知情的结局收束，旧查岗不再触发。' };
    case '201': {
      const 法律已离 = 阶段 === '正式离婚' || 阶段 === '法律离婚待终幕';
      const 关系 = data.系统._许曼君分居.玩家最终关系选择;
      const 相处 = 关系 === '继续关系' ? '你们选择继续关系，201的日常与私人相处由此延续。'
        : 关系 === '暂不承诺' ? '你们仍是暂不承诺的关系，可以继续眼前的陪伴与相处。'
        : 关系 === '退出关系' ? '你已退出私人关系，往来以201住户事务为主。'
        : '当前未记录私人关系选择，先按201住户事务继续往来。';
      return { 标题: 阶段 === '正式离婚' ? '离婚后的生活' : 法律已离 ? '法律离婚已成立' : '分居后的过渡',
        简介: 相处,
        继续方式: 阶段 === '正式离婚' ? '可以直接与她说话；到201时，按她当前开放的生活与相处入口选择。' : '可以继续眼前的相处，并按下方当前步骤推进；完整结局仍待收束。',
        配偶称谓: 法律已离 ? '前夫' : '丈夫',
        配偶说明: 法律已离 ? '与赵国强的法律婚姻已经解除。' : '与赵国强已经分居，法律婚姻尚未解除。' };
    }
    case '202':
      return { ...基础, 标题: '她自己的生活节奏',
        简介: '周小满不再默认留门等人，会告诉你当下的安排，也会主动说想见。',
        继续方式: '可以直接聊天、邀约；她在202且空闲时，可从“和她亲密”选择这次开场。',
        配偶说明: '何俊生已完成知情的结局收束，旧调查与查岗不再触发。' };
    case '301':
      return { ...基础, 标题: '换照后的相处',
        简介: '你们已完成换照，安若妍会以已经确定的关系回应日常到访与亲近。',
        继续方式: '可以谈起照片、真实群消息或眼前的事，也可使用现有亲密入口。',
        配偶说明: '与江辰保留对外夫妻身份，私人生活互不干涉。' };
    case '302':
      return { ...基础, 标题: '留在302之后',
        简介: '她以自己的意志留在302，会主动表达与回应，也有自己的安排和判断。',
        继续方式: '当面聊天、私聊和现有亲密入口都可以继续这段相处。',
        配偶说明: '父亲已完成管理交接，仍不知道你们的私人关系。' };
  }
}
