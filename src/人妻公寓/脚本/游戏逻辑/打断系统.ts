/**
 * 丈夫打断系统(2026-07-19 用户提案拍板,顺序3>1>2的第一件):
 * 丈夫对妻子异常的主动表现——疑心值定打断级别,信任值压打断频率。
 *
 * 三级阶梯(全是排队事件,下一楼由 AI 演出;两值照分工表全脚本,AI 一字不写):
 *   一级·微信探问:她手机弹丈夫消息,不打断场景,只施压(她的演出变紧张)
 *   二级·电话查岗:场景中途丈夫来电,她必须当场接,当着{{user}}的面圆谎
 *   三级·强制中断:提前回家/勒令回去,这场戏被迫收尾
 *   反讽格(spec 2×2 钦定):高信任+高疑心 → 他不查妻子,反而私聊{{user}}
 *   "兄弟帮我留意下我老婆"——他亲手把门打开
 *
 * 纪律:
 * - 机制不可见:事件全是感知语剧情皮,不见数值不见规律
 * - 尊重运作窗口:_疑心冻结至 生效中(钓鱼券)不打断——玩家花钱买的清净必须兑现
 * - 频控:同户同时段最多一次(打断是调味料不是拦路虎);确定性种子,同楼重roll结果不变
 * - 302(母亲户)不走此系统:父亲永远不知道(spec 拍板),她的风险轴是风闻
 */

// ============================================
// 〔调参〕触发参数
// ============================================

/** 疑心低于此值丈夫毫无察觉,不打断 */
const 疑心门槛 = 25;
/** 触发概率:  (疑心-门槛)/此除数,上限0.5——疑心85≈50%/时段 */
const 概率除数 = 120;
/** 信任折扣:信任100时触发率×0.6(他信你,起了疑也先憋着) */
const 信任折扣除数 = 250;
/** 级别切分:疑心 <45=一级微信,45~70=二级电话,>70=三级中断 */
const 二级线 = 45;
const 三级线 = 70;
/** 反讽格门槛:信任≥60 且够二级 → "兄弟帮我留意下我老婆" */
const 反讽信任线 = 60;

// ============================================
// 事件文案(感知语剧情皮;她怎么圆谎由 AI 按性格补,不给示例——v2教训7)
// ============================================

function 一级文案(妻名: string, 夫名: string, 在她家: boolean): string {
  const 场 = 在她家 ? '她瞟了一眼门口的方向,' : '';
  return (
    `【手机亮了】${妻名}的手机在这时亮起——${夫名}发来的微信。${场}神色变了一瞬,回复时字斟句酌。` +
    `这条消息不中断当前场景,但压力渗进来了:让她看手机的小动作、语气里多出来的分寸感自然落进本轮演出`
  );
}

function 二级文案(妻名: string, 夫名: string, 在她家: boolean): string {
  const 圆法 = 在她家
    ? '她压低声音接起,一边说一边留意着屋里的动静'
    : '她只能当场接起,当着人的面把此刻圆成一个无懈可击的日常';
  return (
    `【查岗电话】${妻名}的手机响了,来电人:${夫名}。${圆法}。` +
    `这通电话必须在本轮接完:她怎么措辞、哪句是真哪句是编、挂断后落在脸上的余波,都按她的性格演。电话不终结这场戏,但空气变了`
  );
}

function 三级文案(妻名: string, 夫名: string, 在她家: boolean): string {
  const 收法 = 在她家
    ? `${夫名}来电说这就到家——留给她的时间只够把屋里恢复成"什么都没发生过"`
    : `${夫名}电话里语气不对,勒令她马上回家`;
  return (
    `【被迫收场】${收法}。${妻名}的这场戏被迫收尾:慌乱、抱歉、来不及说完的话,` +
    `在本轮内把告别演完,人必须走。不要拖到下一轮,也不要让{{user}}强行挽留成功`
  );
}

function 反讽文案(妻名: string, 夫名: string): string {
  return (
    `【兄弟拜托】${夫名}私下给{{user}}发来微信,语气犹豫又刻意随便:"兄弟,最近帮我留意下${妻名}……` +
    `她好像有点不对劲,我又说不上来。"他起了疑,却把钥匙递给了最不该托付的人。` +
    `让这条消息在本轮落地({{user}}看手机即可),他不在场,不要让他现身`
  );
}

