/**
 * 丈夫打断系统(2026-07-19 用户提案拍板,顺序3>1>2的第一件):
 * 丈夫对妻子异常的主动表现——疑心值定打断级别,信任值压打断频率。
 *
 * 三级阶梯(全是排队事件,下一楼由 AI 演出;两值照分工表全脚本,AI 一字不写):
 *   一级·微信探问:她手机弹丈夫消息,不打断场景,只施压(她的演出变紧张)
 *   二级·电话查岗:场景中途丈夫来电,她必须当场接,当着{{user}}的面圆谎
 *   三级·强制中断:提前回家/勒令回去,这场戏被迫收尾
 *   反讽格(spec 2×2 钦定):高信任+高疑心 → 他不查妻子,反而私聊{{user}}
 *   "兄弟帮我留意下我老婆"——他亲手把门打开
 *
 * 纪律:
 * - 机制不可见:事件全是感知语剧情皮,不见数值不见规律
 * - 尊重运作窗口:_疑心冻结至 生效中(钓鱼券)不打断——玩家花钱买的清净必须兑现
 * - 频控:同户同时段最多一次(打断是调味料不是拦路虎);确定性种子,同时段重roll结果不变
 * - 302(母亲户)不走此系统:父亲永远不知道(spec 拍板),她的风险轴是风闻
 */

