/** 疑心低于此值丈夫毫无察觉,不打断 */
const 疑心门槛 = 25;
/** 触发概率:  (疑心-门槛)/此除数,上限0.5——疑心85≈50%/时段 */
const 概率除数 = 120;
/** 信任折扣:信任100时触发率×0.6(他信你,起了疑也先憋着) */
const 信任折扣除数 = 250;
/** 级别切分:疑心 <45=一级微信,45~70=二级电话,>70=三级中断 */
const 二级线 = 45;
const 三级线 = 70;
/** 反讽格门槛:信任≥60 且够二级 → "兄弟帮我留意下我老婆" */
const 反讽信任线 = 60;

