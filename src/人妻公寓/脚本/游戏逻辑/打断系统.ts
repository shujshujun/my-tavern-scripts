/**
 * 打断检测:焦点户丈夫按 疑心×信任 决定是否/如何打断本场戏。
 * 只在"妻子在场与{{user}}互动 且 丈夫不在场"时有意义;排队走 系统._待发送事件。
 */
export function 打断检测(data: SchemaType, 焦点: 门牌[], 楼层: number): void {
  if (data.系统._待发送事件) return; // 事件通道已占用,不叠
  const 门牌号 = 焦点[0];
  if (!门牌号 || 门牌号 === '302') return; // 母亲户:父亲永远不知道(spec)
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配?.夫名) return;
  const 夫 = 节点.夫;

  const 钟 = 楼层 + data.系统._时段偏移楼;
  // 运作窗口兑现:钓鱼券冻结期他满脑子鱼塘,不查岗
  if (夫._疑心冻结至 >= 钟) return;
  // 他在家/在睡=没有"远程压力"的戏(在家撞见归撞见系统);出差/夜班在外才有查岗
  if (丈夫在楼(节点, 门牌号, 钟) !== '外出') return;
  // 频控:同户同时段最多一次
  const 档号 = Math.floor(钟 / 每时段楼数);
  if (夫._上次打断档 >= 档号) return;
  if (夫.疑心值 < 疑心门槛) return;

  // 确定性触发(档号为种子:同档内每楼同一判定,重roll不换命)
  const 触发率 = Math.min((夫.疑心值 - 疑心门槛) / 概率除数, 0.5) * (1 - 夫.信任值 / 信任折扣除数);
  if (seededRandom(档号, 门牌号, '丈夫打断') >= 触发率) return;

  const 在她家 = 读场景().房间id === 门牌号;
  const 反讽 = 夫.信任值 >= 反讽信任线 && 夫.疑心值 >= 二级线;
  const 文案 = 反讽
    ? 反讽文案(配.妻名, 配.夫名)
    : 夫.疑心值 > 三级线
      ? 三级文案(配.妻名, 配.夫名, 在她家)
      : 夫.疑心值 >= 二级线
        ? 二级文案(配.妻名, 配.夫名, 在她家)
        : 一级文案(配.妻名, 配.夫名, 在她家);

  夫._上次打断档 = 档号;
  data.系统._待发送事件 = 文案;
  console.info(
    `[人妻公寓·打断] ${门牌号} ${配.夫名} 疑心${夫.疑心值}/信任${夫.信任值} → ${反讽 ? '反讽格' : 夫.疑心值 > 三级线 ? '三级' : 夫.疑心值 >= 二级线 ? '二级' : '一级'}`,
  );
}

/** 供快照/手机系统查询:该户丈夫此刻是否处于"已拜托{{user}}留意"的反讽格(演出一致性) */
export function 处于反讽格(节点: 户节点Type): boolean {
  return 节点.夫.信任值 >= 反讽信任线 && 节点.夫.疑心值 >= 二级线;
}

// ============================================
// 父亲来电打断(P5② 母亲线强制联动1,spec拍板):她的"丈夫回家"=父亲的越洋电话——
// 亲热中随机来电,屏幕上是"老公";顶替别户"丈夫在家"的紧张感位
// ============================================

const 父亲来电概率 = 0.18; // 〔调参〕每时段档一掷

export function 父亲来电打断(data: SchemaType, 焦点: 门牌[], 楼层: number): void {
  if (data.系统._待发送事件) return;
  if (焦点[0] !== '302') return;
  const 节点 = data.户['302'];
  if (!节点 || 节点.妻.当前阶段 < 3) return; // 破了首夜那道坎,电话才有"打断"的意义
  const 钟 = 楼层 + data.系统._时段偏移楼;
  const 档号 = Math.floor(钟 / 每时段楼数);
  if (节点.夫._上次打断档 >= 档号) return; // 复用打断频控字段:同时段一次
  if (seededRandom(档号, '302', '父亲来电') >= 父亲来电概率) return;
  节点.夫._上次打断档 = 档号;
  data.系统._待发送事件 =
    '【越洋来电】就在这时,妈的手机在桌上震了起来——屏幕上两个字:老公。隔着七个时区,他挑了最不该打来的时刻。' +
    '接不接、当着{{user}}的面怎么接、声音里那份控制得住或控制不住的平稳,全按她此刻的状态与阶段演。' +
    '电话那头的他什么都不知道,永远不会知道——这通电话真正照亮的,是挂断后房间里的安静';
  console.info('[人妻公寓·打断] 302 父亲越洋来电');
}

// ============================================
// 母亲撞见系统(P5⑥;spec拍板:监督者撞见+入列后反转)——
// 与人妻的亲密推进(本楼堕落有增量)有小概率被妈"看见":入列前=胜任度小扣+暗账+1(她是父亲的眼睛);
// 入列后反转=场圆得天衣无缝不扣分,但她自己有反应(晚饭丰盛/一句不提/夜里敲门)——妈站你这边了,且她吃醋了
// ============================================

const 撞见基础概率 = 0.1; // 〔调参〕×难度表.撞见概率系数
const 撞见胜任度扣 = 3; // 〔调参〕入列前每次

export function 母亲撞见检测(
  data: SchemaType,
  门牌号: 门牌 | undefined,
  本楼堕落增量: number,
  楼层: number,
  难度系数: number,
): void {
  if (!门牌号 || 门牌号 === '302' || 本楼堕落增量 <= 0) return;
  if (data.系统._待发送事件) return;
  const 妻 = data.户[门牌号]?.妻;
  if (!妻 || 妻.当前阶段 < 2) return;
  const 钟 = 楼层 + data.系统._时段偏移楼;
  const 档号 = Math.floor(钟 / 每时段楼数);
  if (data.系统._上次撞见档 >= 档号) return;
  if (seededRandom(档号, 门牌号, '母亲撞见') >= 撞见基础概率 * 难度系数) return;

  data.系统._上次撞见档 = 档号;
  data.系统._母亲撞见次数 += 1;
  const 妻名 = 户静态表[门牌号].妻名;
  if (!data.系统._母亲入列) {
    data.胜任度 = _.clamp(data.胜任度 - 撞见胜任度扣, 0, 100);
    data.系统._待发送事件 =
      `【被看见了】就在与${妻名}气氛正暗涌的某个瞬间——妈出现在了不该出现的地方(楼道拐角/端着东西路过/来送吃的),` +
      '看见了不该看见的分寸。她什么都没说,一秒都没多停,转身走了。这份"什么都没说"比任何质问都重;' +
      '本楼把这次撞见自然织进场景(时机=最微妙处),之后的空气由它改变';
  } else {
    data.系统._待发送事件 =
      `【她看见了,然后】妈又一次看见了{{user}}和${妻名}之间的分寸——这一次她不再是转身就走:她把场面圆得天衣无缝` +
      '(一句家常把尴尬接走/顺手带上门),圆得像什么都没发生。但她自己有反应,选一样演:今晚的饭菜特别丰盛/她一整晚一句话不提/' +
      '深夜她来敲你的门,站在门口欲言又止。妈站在你这边了——而且,她在吃醋';
  }
  console.info(`[人妻公寓·撞见] 母亲撞见 ${门牌号}(第${data.系统._母亲撞见次数}次,${data.系统._母亲入列 ? '入列反转' : '监督者'})`);
}

// ============================================
// 换装起疑(换装余波扩展5,2026-07-19 用户拍板):她身上多了来路不明的显眼东西/
// 藏不住的异样,丈夫在家时段有小概率注意到——账(疑心+3)与戏(排队事件)一起走
// ============================================

const 换装疑心增量 = 3;
const 换装起疑概率 = 0.35;

export function 换装起疑(data: SchemaType, 楼层: number): void {
  if (data.系统._待发送事件) return; // 账与戏一起走:通道占用就等下一楼
  const 波 = 读余波(楼层);
  if (!波 || 波.疑记 || 楼层 - 波.起楼 < 2) return;
  const 节点 = data.户[波.门牌];
  const 配 = 户静态表[波.门牌];
  if (!节点 || !配?.夫名 || 波.门牌 === '302') return;
  const 钟 = 楼层 + data.系统._时段偏移楼;
  if (节点.夫._疑心冻结至 >= 钟) return; // 钓鱼券窗口:他满脑子鱼塘
  if (丈夫在楼(节点, 波.门牌, 钟) !== '在家') return;
  if (seededRandom(Math.floor(钟 / 每时段楼数), 波.门牌, '换装起疑') >= 换装起疑概率) return;
  节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 换装疑心增量, 0, 100);
  data.系统._待发送事件 = 波.私密
    ? `【丈夫起疑】${配.夫名}最近觉得${配.妻名}不太一样——说不上来哪里,像是有什么心事把她养得水灵。他多看了她两眼,没说什么。这份没说出口的注意,让她后背发紧`
    : `【丈夫起疑】${配.夫名}盯着${配.妻名}身上的新东西看了两眼:"这哪来的?"——她怎么圆由她的性格与心虚程度决定,这一问落在家里的空气里`;
  标余波({ 疑记: true });
  console.info(`[人妻公寓·打断] ${波.门牌} 换装起疑:疑心+${换装疑心增量}(${节点.夫.疑心值})`);
}
