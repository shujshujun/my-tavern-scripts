/**
 * 打断检测:焦点户丈夫按 疑心×信任 决定是否/如何打断本场戏。
 * 只在"妻子在场与{{user}}互动 且 丈夫不在场"时有意义;排队走 系统._待发送事件。
 */
function 取丈夫打断候选(data: SchemaType, 焦点: readonly 门牌[]) {
  if (data.系统._待发送事件) return; // 事件通道已占用,不叠
  const 门牌号 = 焦点[0];
  if (!门牌号 || 门牌号 === '302') return; // 母亲户:父亲永远不知道(spec)
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配?.夫名) return;
  const 夫 = 节点.夫;

  const 绝对时段 = 取绝对时段(data);
  // 运作窗口兑现:钓鱼券冻结期他满脑子鱼塘,不查岗
  if (疑心冻结中(夫, 绝对时段)) return;
  // 他在家/在睡=没有"远程压力"的戏(在家撞见归撞见系统);出差/夜班在外才有查岗
  if (丈夫在楼(节点, 门牌号, 绝对时段) !== '外出') return;
  // 频控:同户同时段最多一次
  const 档号 = 绝对时段;
  if (夫._上次打断档 >= 档号) return;
  return { 门牌号, 节点, 配, 夫, 档号 };
}

/** 变量重生成用：此时若疑心贡献改变，就可能改变已经掷过的一次性打断剧情。 */
export function 丈夫打断会读取疑心(data: SchemaType, 焦点: readonly 门牌[]): boolean {
  return Boolean(取丈夫打断候选(data, 焦点));
}

export function 打断检测(data: SchemaType, 焦点: 门牌[], _消息楼层: number): void {
  const 候选 = 取丈夫打断候选(data, 焦点);
  if (!候选) return;
  const { 门牌号, 配, 夫, 档号 } = 候选;
  if (夫.疑心值 < 疑心门槛) return;

  // 确定性触发(档号为种子:同档内每楼同一判定,重roll不换命)
  const 触发率 = Math.min((夫.疑心值 - 疑心门槛) / 概率除数, 0.5) * (1 - 夫.信任值 / 信任折扣除数);
  if (seededRandom(档号, 门牌号, '丈夫打断') >= 触发率) return;

  const 在她家 = 读场景().房间id === 门牌号;
  const 反讽 = 夫.信任值 >= 反讽信任线 && 夫.疑心值 >= 二级线;
  const 文案 = 反讽
    ? 反讽文案(配.妻名, 配.夫名)
    : 夫.疑心值 > 三级线
      ? 三级文案(配.妻名, 配.夫名, 在她家)
      : 夫.疑心值 >= 二级线
        ? 二级文案(配.妻名, 配.夫名, 在她家)
        : 一级文案(配.妻名, 配.夫名, 在她家);

  夫._上次打断档 = 档号;
  data.系统._待发送事件 = `${事件角色标记({ 在场妻: [门牌号], 关联夫: [门牌号] })}${文案}`;
  console.info(
    `[人妻公寓·打断] ${门牌号} ${配.夫名} 疑心${夫.疑心值}/信任${夫.信任值} → ${反讽 ? '反讽格' : 夫.疑心值 > 三级线 ? '三级' : 夫.疑心值 >= 二级线 ? '二级' : '一级'}`,
  );
}

/** 供快照/手机系统查询:该户丈夫此刻是否处于"已拜托{{user}}留意"的反讽格(演出一致性) */
export function 处于反讽格(节点: 户节点Type): boolean {
  return 节点.夫.信任值 >= 反讽信任线 && 节点.夫.疑心值 >= 二级线;
}

