import type { SchemaType } from '../../../schema';
import { 户静态表, type 门牌 } from '../../../stageConfig';
import { 解析姐妹群公开事实, type 姐妹群公开消息证据 } from './姐妹群公开事实';
import {
  构建角色结局后生活社交语义,
  角色结局后姐妹群长期方向,
  角色正式结局已完成,
} from '../结局后生活社交语义';
import { 母亲共居玩家私聊纪律 } from '../302共居系统';

export interface 结局期角色画像 {
  门牌: 门牌;
  姓名: string;
  当前阶段: number;
  已完成结局: string[];
  群内已公开关系: boolean;
  丈夫认知: string;
  群内口吻: string;
}

function 已完成(data: SchemaType, id: string): boolean {
  return data.系统._已完成特殊场景.includes(id);
}

export function 双重继承结局期(data: SchemaType): boolean {
  return data.系统._双重继承.阶段 === '已完成' || 已完成(data, '双重继承');
}

export function 角色结局期画像(
  data: SchemaType,
  门牌号: 门牌,
  消息: readonly 姐妹群公开消息证据[] = [],
): 结局期角色画像 {
  const 妻 = data.户[门牌号]?.妻;
  const 群内公开事实 = 解析姐妹群公开事实(消息);
  const 已完成结局: string[] = [];
  let 群内已公开关系 = false;
  let 丈夫认知 = '不得凭空推断丈夫知情';
  let 群内口吻 = '按当前阶段和群内真实消息自然发言，不得提前虚构尚未完成的结局';

  if (门牌号 === '101' && 已完成(data, '借种')) {
    已完成结局.push('借种');
    群内已公开关系 = 群内公开事实.借种家庭结构已公开;
    丈夫认知 = '陆嘉明已经知情并接受三人家庭安排，不得退回丈夫受骗或偷情曝光';
    群内口吻 = '夏乔已经完成借种结局；群里已公开的三人家庭事实不得失忆，但公开程度仍服从真实照片与朋友圈选择';
  }
  if (门牌号 === '302' && 双重继承结局期(data)) {
    已完成结局.push('双重继承');
    群内已公开关系 = 群内公开事实.母亲关系已公开;
    丈夫认知 = '父亲始终不知道母亲与玩家的真实关系，也不得出现早已看穿、默许或故意成全';
    群内口吻 = '母亲已经主动留在302，玩家是唯一实际管理员；她不参与雌竞，也不再替玩家向父亲圆场';
  }
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  if (后效.已开启 && !['101', '302'].includes(门牌号)) {
    if (角色正式结局已完成(data, 门牌号)) 已完成结局.push(后效.阶段);
    丈夫认知 = 后效.丈夫边界;
    群内口吻 = `${后效.姐妹群态度}${后效.群内可见后效}`;
    if (门牌号 === '301') {
      群内已公开关系 = 群内公开事实.安若妍换照已公开;
      if (群内已公开关系) 群内口吻 += '她已在本群晒出换好的301客厅照片，并说明江辰拍摄、玩家换照；后续接着这条真实消息交流。';
    }
  }

  return {
    门牌: 门牌号,
    姓名: 户静态表[门牌号].妻名,
    当前阶段: 妻?.当前阶段 ?? 0,
    已完成结局,
    群内已公开关系,
    丈夫认知,
    群内口吻,
  };
}

export function 角色结局期私聊补充(data: SchemaType, 门牌号: 门牌): string {
  const 画像 = 角色结局期画像(data, 门牌号);
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  const 主题 = 后效.主动私聊主题.length ? `可轮换方向：${后效.主动私聊主题.join('；')}。` : '';
  if (画像.已完成结局.includes('双重继承')) {
    return (
      '【结局后私聊】母亲已经主动选择留在302，玩家已经成为公寓唯一实际管理员。她不再用“等你爸回来决定”、替玩家向父亲圆场或突然退回普通母子边界；' +
      `私聊可以稳定承认已经成立的特殊关系，但仍保持她自己的成熟判断。父亲永远不知情。${后效.玩家私聊纪律}${母亲共居玩家私聊纪律(data)}${主题}`
    );
  }
  if (画像.已完成结局.includes('借种')) {
    return (
      '【结局后私聊】夏乔与陆嘉明已经建立知情的三人家庭安排。她可以自然说“我们三个”及已经真实发生的生活后果；' +
      `不得让陆嘉明失忆、把关系写回偷情试探，也不得虚构尚未发生的孕产节点。${后效.玩家私聊纪律}${主题}`
    );
  }
  if (后效.已开启) {
    return `【结局后私聊·${后效.阶段}】${后效.生活事实}${后效.玩家私聊纪律}${后效.丈夫边界}${主题}`;
  }
  if (画像.当前阶段 >= 5) {
    return '【高阶段私聊】她已经进入第五阶段，口吻可以稳定直接，不要退回低阶段反复试探；尚未完成的结局仍不得提前发生。';
  }
  return '';
}

export function 结局期姐妹群总纪律(
  data: SchemaType,
  消息: readonly 姐妹群公开消息证据[] = [],
  成员: readonly 门牌[] = Object.keys(data.户) as 门牌[],
): string {
  const 公开事实 = 解析姐妹群公开事实(消息);
  const 长期方向 = 成员
    .map(门牌号 => 角色结局后姐妹群长期方向(data, 门牌号))
    .filter(Boolean);
  if (!双重继承结局期(data) && !长期方向.length) {
    return '群成员只对真实在群里公开过的关系心知肚明；没有摊牌的内容仍不得直接点破。';
  }
  const 精确公开说明 =
    公开事实.借种家庭结构已公开 || 公开事实.母亲关系已公开 || 公开事实.安若妍换照已公开
      ? '当前分支已有脚本签发的群内公开事实，不得失忆后重新惊讶；'
      : '结局只会改变成熟口吻，当前分支没有稳定公开键的精确关系仍不得说破；';
  return (
    '【结局期姐妹群】每名成员按自己的当前阶段与经历回应同一话题；已完成者的变化不改变未完成者的进度与知情。' + 精确公开说明 +
    '争执和玩笑应更多围绕时间、陪伴、优先级、邀约、共同生活与已经发生的后果，而不是反复追问“你们是不是有关系”。' +
    `${长期方向.length ? `各成员长期方向：${长期方向.join('；')}` : ''}` +
    '丈夫私下决定、录像内容、外遇证据和未公开手续不能自动带进姐妹群。' +
    '未公开的其他角色剧情仍不可全知；不得把每轮都写成排班、比色情程度、全员争宠或母亲训话。'
  );
}

export function 结局期姐妹群成员画像(
  data: SchemaType,
  成员: readonly 门牌[],
  消息: readonly 姐妹群公开消息证据[] = [],
): 结局期角色画像[] {
  return 成员.map(门牌号 => 角色结局期画像(data, 门牌号, 消息));
}

export function 角色结局期公开朋友圈纪律(data: SchemaType, 门牌号: 门牌): string {
  const 画像 = 角色结局期画像(data, 门牌号);
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  if (画像.已完成结局.includes('双重继承')) {
    return (
      '【结局后公开朋友圈】可以把“父亲已经完成交接、玩家正式独立管理公寓”写成普通家庭近况；' +
      '后续应轮换饭桌、约定、分歧和社会上可解释的共同生活，不再只围绕照顾儿子或攻略升级；' +
      '绝不能公开母亲与玩家的真实关系、机场视频隐秘现场或让知情群友在评论区泄密。'
    );
  }
  if (画像.已完成结局.includes('借种')) {
    return '【借种结局公开层】公开朋友圈仍服从玩家已经作出的照片公开选择；不得因为姐妹群知情就自动公开完整三人关系。';
  }
  if (后效.已开启) return `【${后效.阶段}公开层】${后效.公开朋友圈纪律}`;
  return '';
}

export function 结局期称呼纪律(data: SchemaType, 门牌号: 门牌, 场景: '公开朋友圈' | '姐妹群' | '私聊'): string {
  const 画像 = 角色结局期画像(data, 门牌号);
  if (场景 === '公开朋友圈') return '公开层只使用玩家姓名、“管理员”或社会上可解释的普通称呼，不得用会暴露关系的称谓。';
  if (场景 === '姐妹群')
    return '群内可使用玩家姓名、“管理员”、真实群聊里已经出现过的昵称或符合本人性格的自然昵称；禁止所有人统一使用同一个亲密称呼。';
  if (门牌号 === '201' && 构建角色结局后生活社交语义(data, 门牌号).已开启) {
    const 选择 = data.系统._许曼君分居.玩家最终关系选择;
    if (选择 !== '继续关系' && 选择 !== '暂不承诺')
      return '称呼按当前住户与管理员关系，使用姓名或管理员；保留已经记录的私人关系选择。';
    if (选择 === '暂不承诺') return '称呼沿用两人实际使用过的名字或昵称，双方仍是暂不承诺的关系。';
  }
  return 画像.当前阶段 >= 5 || 画像.已完成结局.length
    ? '私聊可使用本人已经建立的稳定亲密称呼或名字自然衍生昵称；不能凭空换姓、统一叫法或复制其他角色的称呼。'
    : '私聊称呼继续服从当前攻略阶段，不得提前使用结局期亲密称呼。';
}
