/**
 * 普通微信私聊的文风去重纪律。
 *
 * 这里只根据已经真实落库的角色回复识别近期高频表达，不改变任何剧情事实、关系阶段或消息数量；
 * 生成模型仍可在玩家本轮明确提起对应话题时使用这些元素，但不能把人物资料逐项翻译成固定流程。
 */

const 最近角色消息上限 = 6;

export const 私聊固定模板链 =
  '“复述或改写玩家原话→提丈夫或婚姻作对照→脸红心跳等害羞反应→交代家务或当前位置→警告玩家安分”';

function 规范消息(消息: unknown): string {
  return typeof 消息 === 'string' ? 消息.trim() : '';
}

function 转义正则(文本: string): string {
  return 文本.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * 只看近期至多六条角色侧消息（通常覆盖两三轮回复），避免把很久以前的正常表达永久禁用。
 * 返回值只用于生成提示中的“近期已用元素”，不会作为内容硬过滤器。
 */
export function 识别最近私聊惯用元素(最近角色消息: readonly string[], 丈夫名?: string): string[] {
  const 最近 = 最近角色消息.map(规范消息).filter(Boolean).slice(-最近角色消息上限);
  if (!最近.length) return [];

  const 合并 = 最近.join('\n');
  const 命中: string[] = [];
  const 夫名 = 丈夫名?.trim();
  const 提到丈夫 = (夫名 ? new RegExp(转义正则(夫名)).test(合并) : false) || /(?:丈夫|老公|婚姻)/.test(合并);
  if (提到丈夫) 命中.push('丈夫或婚姻对照');

  if (/(?:心跳|心口|心乱|脸红|脸热|脸烫|脸上发烧|发烫|耳根|耳朵(?:红|烫)|害羞|羞得|慌得|冷汗|不敢抬头)/.test(合并)) {
    命中.push('脸红心跳式害羞');
  }

  if (/(?:做饭|晚饭|厨房|择菜|洗菜|洗碗|买菜|收拾|打扫|家务|晾衣|收衣|叠衣|琴盖|弹琴|练琴|备课|值班室)/.test(合并)) {
    命中.push('家务或当前位置过场');
  }

  const 警告式收尾 =
    /(?:不许|不准|别再|少来|安分(?:点|些)?|老实(?:点|些)?|别胡闹|别乱|再敢|再这样|小心我|不然我|听见没|听到没)/;
  if (最近.some(消息 => 警告式收尾.test(消息.slice(-48)))) 命中.push('警告或嘴硬收尾');

  return 命中;
}

/**
 * 普通手动私聊与自动主动私聊共用同一条纪律，避免两条入口分别长回同一种隐性模板。
 */
export function 构造私聊自然回复纪律(最近角色消息: readonly string[], 丈夫名?: string): string {
  const 近期元素 = 识别最近私聊惯用元素(最近角色消息, 丈夫名);
  const 近期避让 = 近期元素.length
    ? `近期几轮她已经明显用过：${近期元素.join('、')}。除非玩家本轮明确把对应话题重新提到台前，或当前硬事实确实要求，否则本轮优先避开这些元素；即使必须再用，也不能重新拼成相同顺序和相同收尾。`
    : '';

  return (
    '【私聊自然度·高优先】这不是把状态表、人设、丈夫资料和当前位置逐项翻译成台词。先判断本轮最值得回应的一件事，通常只抓一个主要反应，确有必要再补一个。' +
    `严禁把${私聊固定模板链}当成固定流程；除非玩家本轮消息或当前硬事实直接要求，通常最多从这些元素中选一至两项，而且开头、顺序和收尾不得照搬上一轮。` +
    '没有实际使用“「引用 原发送者: 被引用内容」”协议时，不要改写或复述玩家原话充当开场。' +
    '丈夫姓名和家庭资料只用于事实校验，不是每轮必写素材；只有玩家本轮主动提到丈夫、丈夫直接构成当前现场风险，或本轮事件主题确实涉及丈夫时，才主动提及或拿丈夫作对照。' +
    '不要默认用“不许、别再、安分点、再这样就……”收尾；可以直接接梗、反问、短答、转到一件具体小事、晚些再回、发一个表情，或自然停在半句，具体选择必须符合本人性格和当下关系。' +
    近期避让
  );
}
