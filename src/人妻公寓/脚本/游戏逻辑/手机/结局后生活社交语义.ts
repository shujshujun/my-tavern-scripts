import type { SchemaType } from '../../../schema';
import type { 门牌 } from '../../../stageConfig';
import { 构建角色结局后生活社交语义, 角色结局后姐妹群长期方向, 读取周小满承接生活事实 } from '../结局后生活社交语义';
import { 公开动态评论者方向 } from './结局后日常反馈';
import { 母亲共居主动私聊主题, 母亲共居玩家私聊纪律 } from '../302共居系统';

export interface 结局后生活社交画像 {
  成立: boolean;
  阶段: string;
  生活差分: string;
  私聊方向: string;
  丈夫差分: string;
  禁止: string;
}

function 有效门牌(门牌号: string): 门牌 | null {
  return ['101', '102', '201', '202', '301', '302'].includes(门牌号) ? (门牌号 as 门牌) : null;
}

function 画像阶段(门牌号: 门牌, 阶段: string): string {
  if (门牌号 === '102' && 阶段 === '录像带结局') return '102录像带后';
  if (门牌号 === '202' && 阶段 === '录像带结局') return '202录像带后';
  if (门牌号 === '201' && 阶段 === '分居完成') return '201分居后';
  if (门牌号 === '201' && 阶段 === '法律离婚待终幕') return '201法律离婚待终幕';
  if (门牌号 === '201' && 阶段 === '正式离婚') return '201离婚后';
  if (门牌号 === '301' && 阶段 === '名义夫妻') return '301名义夫妻后';
  if (门牌号 === '302' && 阶段 === '双重继承共居') return '302共居后';
  if (门牌号 === '101' && 阶段 === '借种家庭') return '101借种家庭后';
  return '未进入后效';
}

export function 构建结局后生活社交画像(data: SchemaType, 门牌文本: string): 结局后生活社交画像 {
  const 门牌号 = 有效门牌(门牌文本);
  if (!门牌号) {
    return { 成立: false, 阶段: '未进入后效', 生活差分: '', 私聊方向: '', 丈夫差分: '', 禁止: '' };
  }
  const 语义 = 构建角色结局后生活社交语义(data, 门牌号);
  const 生活差分 =
    门牌号 === '202' && 语义.已开启 && 读取周小满承接生活事实(data).停止默认等待
      ? `周小满不再把临时决定和无限等待当成默认，她会把自己的时间放回生活里。${语义.普通正文纪律}`
      : 语义.普通正文纪律;
  const 禁止 =
    门牌号 === '201' && 语义.阶段 === '分居完成'
      ? '禁止写成已离婚、称赵国强为前夫或让离婚证提前出现。'
      : 门牌号 === '201' && 语义.阶段 === '法律离婚待终幕'
        ? '法律离婚已经成立；禁止写回尚未离婚，也禁止提前完成或公开仍未收束的完整终幕。'
      : `禁止重演已经完成的结局；${语义.丈夫边界}`;
  return {
    成立: 语义.已开启,
    阶段: 画像阶段(门牌号, 语义.阶段),
    生活差分,
    私聊方向: 语义.主动私聊主题.join('；'),
    丈夫差分: 语义.丈夫边界,
    禁止,
  };
}

export function 角色结局后主动私聊补充(data: SchemaType, 门牌文本: string): string {
  const 门牌号 = 有效门牌(门牌文本);
  if (!门牌号) return '';
  if (门牌号 === '302') return 母亲共居主动私聊主题(data);
  const 语义 = 构建角色结局后生活社交语义(data, 门牌号);
  if (!语义.已开启) return '';
  return `【${画像阶段(门牌号, 语义.阶段)}主动私聊】只从这些长期方向中选择一项：${语义.主动私聊主题.join('；')}。${语义.丈夫边界}`;
}

export function 角色结局后玩家私聊补充(data: SchemaType, 门牌文本: string): string {
  const 门牌号 = 有效门牌(门牌文本);
  if (!门牌号) return '';
  const 语义 = 构建角色结局后生活社交语义(data, 门牌号);
  if (!语义.已开启) return '';
  const 私聊纪律 = 门牌号 === '302' ? 母亲共居玩家私聊纪律(data) : 语义.玩家私聊纪律;
  return (
    `${私聊纪律}${语义.丈夫边界}` +
    '玩家主动私聊只能回应问题、表达态度或建立合法计划，不能自动结算房间动作、地图移动、见面、吃饭、和解、留宿或结局推进。'
  );
}

export function 角色结局后公开朋友圈补充(data: SchemaType, 门牌文本: string): string {
  const 门牌号 = 有效门牌(门牌文本);
  if (!门牌号) return '';
  const 语义 = 构建角色结局后生活社交语义(data, 门牌号);
  return 语义.已开启 ? `${语义.公开朋友圈纪律}${语义.群内可见后效}` : '';
}

export function 母亲共居公开评论文案(data: SchemaType, 评论者文本: string, 事件类型: string): string {
  const 评论者 = 有效门牌(评论者文本);
  if (!评论者 || 评论者 === '302') return '';
  const 方向 = 公开动态评论者方向(data, 评论者);
  if (!方向) return '';
  return 事件类型 === '公开交接' ? `当前是正式交接公开动态。${方向}` : 方向;
}

export function 结局后姐妹群长期话题(data: SchemaType): string {
  const 方向 = (['102', '201', '202', '301', '302'] as const)
    .map(门牌号 => {
      const 文 = 角色结局后姐妹群长期方向(data, 门牌号);
      return 文 ? `【${门牌号}结局后群聊态度】${文}` : '';
    })
    .filter(Boolean);
  if (!方向.length) return '';
  return (
    '【结局后姐妹群长期变化】话题从重复确认关系转向现实生活边界、说到做到、时间、等待、住房与公开口径。' +
    方向.join('\n') +
    '私聊、仅你可见、录像画面和机场视频永远不能仅凭结局完成标记升级成全群事实。'
  );
}
