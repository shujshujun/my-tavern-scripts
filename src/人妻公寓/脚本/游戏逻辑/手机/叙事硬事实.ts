export type 邀约裁定结果 = '接受' | '拒绝' | '改口拒绝';
export type 住院叙事节点类型 = '恢复' | '近况' | '出院预告' | '出院';

export function 验收邀约裁定回复(文: string, 裁定结果: 邀约裁定结果, 计划?: 手机邀约计划): boolean {
  const 正文 = 文.normalize('NFKC').replace(/“[^”]*”|「[^」]*」|『[^』]*』|"[^"\n]*"/gu, '');
  const 陈述 = 正文.split(/[。！!；;\n]/u).filter(句 => !/[？?]|如果|要是|假如|有空的话|等有空/u.test(句));
  const 分句 = 陈述.flatMap(句 => 句.split(/[，,]|(?=但是|但(?!愿)|不过|可是)/u)).map(句 => 句.trim()).filter(Boolean);
  const 拒绝语义 = /不方便|去不了|来不了|见不了|没空|不行|取消|不答应|不赴约|不见(?!不散)|(?:不能|没法|无法|不会|不再|不|没)(?:去|来|过去|见面|赴约)|答应不(?:去|来|过去|见面|赴约)|改天|下次吧/u;
  const 有拒绝 = 分句.some(句 => 拒绝语义.test(句));
  const 有接受 = 分句.some(句 => !拒绝语义.test(句) && !/还没|尚未|没想好|原先|之前|刚才|本来/u.test(句) && (
    /^(?:好(?:的|啊|呀|吧)?|可以(?:的|啊)?|行(?:的|啊)?|没问题|我答应(?:了)?|答应了)[~～…]*$/u.test(句) ||
    /(?:我|我们)(?:会|一定会)?(?:按约|准时)?(?:去|过去|来|到)|到时见|不见不散|准时到|按约.{0,12}见|(?:今天|明天|今晚|周[一二三四五六日天]|星期[一二三四五六日天]|早上|中午|下午|傍晚|晚上|深夜|天台).{0,12}见/u.test(句)
  ));
  if (裁定结果 !== '接受') return 有拒绝 && !有接受;
  if (!有接受 || 有拒绝) return false;
  if (!计划) return true;

  const 目标 = 解析绝对时段(计划.目标绝对时段);
  const 创建 = 解析绝对时段(计划.创建绝对时段);
  const 地点们 = 房间表.flatMap(房间 => [房间.id, 房间.名称]).filter(Boolean);
  for (const 句 of 分句) {
    // 明确见面分句和承诺后的纯时地短语都属于安排；生活理由中的日期不改写计划。
    let 剩余 = 句.replace(/^(?:但是|但|不过|可是)/u, '')
      .replace(/今天|明天|后天|今晚|明晚|今早|明早|本周|这周|下周|本星期|这星期|下星期|下礼拜|(?:星期|周|礼拜)[一二三四五六日天]|早晨|上午|早上|中午|下午|傍晚|晚上|深夜/gu, '');
    for (const 名 of 地点们) 剩余 = 剩余.replaceAll(名, '');
    const 纯时地 = 剩余.replace(/[的在吧呀啊呢就好~～…\s]/gu, '') === '' && 剩余 !== 句;
    const 移动应约 = /^(?:我|我们)(?:会|一定会)?(?:过去|去|来|到)[的吧呀啊呢~～…\s]*$/u.test(剩余);
    if (!纯时地 && !移动应约 && !/见|赴约|等你|准时|按约|改到|改在|改成|换到|另约|挪到|推迟|提前/u.test(句)) continue;
    if (/改(?:到|在|成|去)|换(?:到|成|个)|另约|挪到|推迟|提前/u.test(句)) return false;
    for (const 房间 of 房间表) {
      if (房间.id !== 计划.地点 && [房间.id, 房间.名称].some(名 => 名 && 句.includes(名))) return false;
    }
    const 规范句 = 句.replace(/早晨|上午/gu, '早上').replace(/今晚/gu, '今天晚上').replace(/明晚/gu, '明天晚上').replace(/今早/gu, '今天早上').replace(/明早/gu, '明天早上');
    for (const 时段 of 六时段列表) if (规范句.includes(时段) && 时段 !== 目标.时段) return false;
    for (const [称呼, 日差] of [['今天', 0], ['明天', 1], ['后天', 2]] as const) {
      if (规范句.includes(称呼) && 目标.天数 !== 创建.天数 + 日差) return false;
    }
    for (const 星期 of 规范句.matchAll(/(?:星期|周|礼拜)([一二三四五六日天])/gu)) {
      if (`星期${星期[1] === '天' ? '日' : 星期[1]}` !== 目标.星期) return false;
    }
    if (/下周|下星期|下礼拜/u.test(规范句) && 目标.周数 !== 创建.周数 + 1) return false;
  }
  return true;
}

/** 只读取本人的事实分句；医生的当前说明可承接，问题、引用和其他家庭的消息不作本胎依据。 */
function 孕产事实分句(文: string): string[] {
  const 原 = 文.normalize('NFKC');
  const 文本 = 原.replace(/“[^”]*”|「[^」]*」|『[^』]*』|"[^"\n]*"/gu, (引用: string, 位置: number) => {
    const 前 = 原.slice(0, 位置).split(/[，,。！？?!；;\n]/u).at(-1) ?? '';
    return /引用|复述|想象|假设|你说|你问|问道|没.{0,6}说/u.test(前) ? '' : 引用.slice(1, -1);
  });
  return (文本.match(/[^。！？?!；;\n]+[。！？?!；;\n]?/gu) ?? [])
    .flatMap(句 => 句.split(/[，,]|(?=但是|但(?!愿)|现在)/u)).map(句 => 句.trim()).filter(句 =>
      句 && !/[？?]|是否|是不是/u.test(句) &&
      !/(?:姐姐|妹妹|朋友|邻居|嫂子)(?:的|家).{0,12}(?:儿子|女儿|宝宝|孩子)|上一胎|上一个孩子|大宝/u.test(句));
}

function 孕产未定表述(句: string): boolean {
  return /明天|后天|下周|准备|打算|计划|如果|要是|希望|可能|或许|预计|将要|将会|即将|就要|快要|快.{0,4}(?:出生|出院)|要(?:出生|生产|出院)/u.test(句);
}

function 孕产正向胎次(句们: readonly string[]): number[] {
  const 数字: Record<string, number> = { 头: 1, 一: 1, 二: 2, 三: 3, 1: 1, 2: 2, 3: 3 };
  return 句们.flatMap(句 => [...句.replace(/(?:不是|并非)(?:第[一二三123]|[头二三])胎/gu, '')
    .matchAll(/(?:第([一二三123])|([头二三]))胎/gu)].map(项 => 数字[项[1] ?? 项[2]]));
}

export function 验收报孕硬事实(文: string, 胎次: number, 必须提胎次 = true): boolean {
  const 句们 = 孕产事实分句(文);
  let 已怀孕 = false;
  for (const 句 of 句们) {
    if (!/怀孕|有了|验孕|检查/u.test(句) || 孕产未定表述(句)) continue;
    if (/(?:没有|没|并未|不是).{0,6}(?:怀孕|有了)|(?:怀孕|验孕|检查).{0,6}(?:还没|尚未|没有).{0,4}确认/u.test(句)) 已怀孕 = false;
    else if (/怀孕|有了|(?:验孕|检查).{0,8}确认/u.test(句)) 已怀孕 = true;
  }
  const 胎们 = 孕产正向胎次(句们);
  return 已怀孕 && 胎们.every(胎 => 胎 === 胎次) && (!必须提胎次 || 胎们.includes(胎次));
}

export function 验收孩子性别硬事实(文: string, 性别: string | undefined): boolean {
  const 肯定提及 = (词: RegExp, 否定词: RegExp): boolean => 词.test(文.replace(否定词, ''));
  if (性别 === '女') {
    return 肯定提及(/女儿|闺女|女孩|女宝宝/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:女儿|闺女|女孩|女宝宝)/gu);
  }
  if (性别 === '男') {
    return 肯定提及(/儿子|男孩|男宝宝/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:儿子|男孩|男宝宝)/gu);
  }
  return 肯定提及(/宝宝|孩子/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:宝宝|孩子)/gu);
}

export function 验收预产硬事实(文: string): boolean {
  const 否定到院 =
    /(?:不在|离开|没有去|没去|不去|还没去|尚未去|未去|还没到|尚未到|没到|未到|不能去|无法去).{0,4}医院|医院.{0,4}(?:不在|离开|没有去|没去|不去|还没到|尚未到|没到|未到)/u;
  const 句们 = 孕产事实分句(文);
  return 句们.some(句 => !孕产未定表述(句) && !否定到院.test(句) &&
    /(?:已经|刚刚?|我在|还在|正在|住进).{0,8}医院|到医院.{0,6}了/u.test(句)) &&
    句们.some(句 => /待产|预产|临盆|生产|要生/u.test(句));
}

export function 验收生产硬事实(文: string, 性别: string | undefined, 胎次?: number, 必须提性别 = true): boolean {
  const 句们 = 孕产事实分句(文);
  let 已出生 = false;
  const 完成句: string[] = [];
  for (const 句 of 句们) {
    if (!/出生|生产|生下|生了|待产/u.test(句)) continue;
    if (孕产未定表述(句) || /(?:还没|没有|尚未|并未).{0,6}(?:出生|生产|生下)|没生|(?:生产|出生).{0,6}(?:还没|尚未|没有|未).{0,4}(?:开始|结束|完成)|开始生产|正在生产|还在.{0,6}待产/u.test(句)) {
      if (!/之前|以前|先前|当时/u.test(句)) 已出生 = false;
      continue;
    }
    if (/(?:已经|已|刚刚?|顺利|平安).{0,8}(?:出生|生下)|出生(?:了|啦)|生了|生下(?:了|来)|生产.{0,4}(?:完成|完毕|结束)|生产完(?:了)?|(?:已经|已|刚刚?).{0,4}生产了[。！!]?$/u.test(句)) {
      已出生 = true;
      完成句.push(句);
    }
  }
  if (!已出生 || (胎次 !== undefined && 孕产正向胎次(句们).some(胎 => 胎 !== 胎次))) return false;
  const 性别句 = [...完成句, ...句们.filter(句 => /^(?:不是|并非|是|这次|这一胎|这胎|本胎|宝宝|孩子|她是|他是|生的是)/u.test(句))];
  const 性别文 = 性别句.join('，').replace(/(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:女儿|儿子|闺女|女孩|男孩|女宝宝|男宝宝)/gu, '');
  const 有女 = /女儿|闺女|女孩|女宝宝/u.test(性别文), 有男 = /儿子|男孩|男宝宝/u.test(性别文);
  if ((性别 === '女' && 有男) || (性别 === '男' && 有女)) return false;
  return (!必须提性别 && !有女 && !有男) || 验收孩子性别硬事实(性别文, 性别);
}

export function 验收合照硬事实(文: string, 结果: string): boolean {
  if (!/(?:照片|合照|拍|看看|看一眼)/u.test(文) || !/(?:宝宝|孩子|女儿|儿子|我们)/u.test(文)) return false;
  if (结果 === '陪产') return !/(?:没来|没有来|一次都没来|不在身边)/u.test(文);
  return !/(?:谢谢你一直陪着|还好你全程都在|你一直在身边|你全程陪产)/u.test(文);
}

export function 验收住院硬事实(文: string, 类型: 住院叙事节点类型): boolean {
  const 句们 = 孕产事实分句(文);
  let 状态: '未定' | '未出院' | '预告' | '已出院' = '未定';
  for (const 句 of 句们) {
    if (!/出院|回家|离开医院/u.test(句)) continue;
    if (/(?:还没有|还没|尚未|并未|没有|没|还不|暂时不|暂不|不能|不可以|无法).{0,5}(?:出院|回家)|(?:出院|回家).{0,5}(?:不行|不可以|取消|推迟)/u.test(句)) {
      if (!/之前|以前|先前|当时/u.test(句)) 状态 = '未出院';
    } else if (孕产未定表述(句) || /可以|获准|允许|快出院/u.test(句)) 状态 = '预告';
    else if (/(?:已经|今天|刚刚?|前天|昨天).{0,8}(?:出院|回家|离开医院)|(?:出院|回家).{0,8}(?:了|到家)/u.test(句)) 状态 = '已出院';
  }
  if (类型 === '出院') return 状态 === '已出院';
  if (类型 === '出院预告') return 状态 === '预告';
  if (状态 === '已出院') return false;
  return 类型 === '恢复' ? /恢复|身体|伤口|精神|休息|休养|睡/u.test(句们.join('，')) : /宝宝|孩子|女儿|儿子|医院/u.test(句们.join('，'));
}

export function 验收家庭计划硬事实(文: string): boolean {
  if (/(?:不想|不用|不必|不要|别).{0,6}(?:来|见|谈)|(?:不谈|别来|不用来)/u.test(文)) return false;
  return /101/u.test(文) && /孩子|生育|家庭计划/u.test(文) && /来|见|有空|谈/u.test(文) && /他|老公|丈夫|陆嘉明/u.test(文);
}
