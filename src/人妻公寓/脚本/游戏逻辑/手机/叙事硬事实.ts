export type 邀约裁定结果 = '接受' | '拒绝' | '改口拒绝';
export type 住院叙事节点类型 = '恢复' | '近况' | '出院预告' | '出院';

export function 验收邀约裁定回复(文: string, 裁定结果: 邀约裁定结果): boolean {
  const 拒绝语义 =
    /(?:不方便|不能|去不了|没空|改天|下次|恐怕|不行|有事|抱歉|算了|取消|来不了|见不了|没法|不答应|不赴约|不见(?!不散)|(?:不|没|不会|不再)(?:去|来|过去|见面)|答应不(?:去|来|过去|见面|赴约))/u;
  const 接受候选 = /(?:好|可以|行|没问题|答应|会去|过去|到时见|等你|准时|见面|约好|不见不散)/u;
  const 明确接受 = /(?:没问题|我会去|我过去|到时见|准时到|已经约好|不见不散)/u;
  if (裁定结果 === '接受') {
    return 接受候选.test(文) && !拒绝语义.test(文);
  }
  return 拒绝语义.test(文) && !明确接受.test(文);
}

export function 验收报孕硬事实(文: string, 胎次: number): boolean {
  if (/(?:没有|没|并未|不是).{0,4}(?:怀孕|有了)/u.test(文)) return false;
  const 已明确怀孕 = /怀孕|有了|验孕|检查.{0,8}确认/u.test(文);
  const 已明确胎次 =
    胎次 === 1 ? /头胎|第一胎/u.test(文) : 胎次 === 2 ? /二胎|第二胎/u.test(文) : /三胎|第三胎/u.test(文);
  return 已明确怀孕 && 已明确胎次;
}

export function 验收孩子性别硬事实(文: string, 性别: string | undefined): boolean {
  const 肯定提及 = (词: RegExp, 否定词: RegExp): boolean => 词.test(文.replace(否定词, ''));
  if (性别 === '女') {
    return 肯定提及(/女儿|闺女|女孩|女宝宝/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:女儿|闺女|女孩|女宝宝)/gu);
  }
  if (性别 === '男') {
    return 肯定提及(/儿子|男孩|男宝宝/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:儿子|男孩|男宝宝)/gu);
  }
  return 肯定提及(/宝宝|孩子/u, /(?:不是|并非|并不是|没有|并没有|并未|不算)(?:一个|个|这次的|我的|我们的)?(?:宝宝|孩子)/gu);
}

export function 验收预产硬事实(文: string): boolean {
  const 否定到院 =
    /(?:不在|离开|没有去|没去|不去|还没去|尚未去|未去|还没到|尚未到|没到|未到|不能去|无法去).{0,4}医院|医院.{0,4}(?:不在|离开|没有去|没去|不去|还没到|尚未到|没到|未到)/u;
  return /医院/u.test(文) && /待产|预产|临盆|生产|要生/u.test(文) && !否定到院.test(文);
}

export function 验收生产硬事实(文: string, 性别: string | undefined): boolean {
  if (/(?:还没|没有|尚未|并未).{0,6}(?:出生|生产|生下)|没生/u.test(文)) return false;
  return /出生|生了|生产|平安/u.test(文) && 验收孩子性别硬事实(文, 性别);
}

export function 验收合照硬事实(文: string, 结果: string): boolean {
  if (!/(?:照片|合照|拍|看看|看一眼)/u.test(文) || !/(?:宝宝|孩子|女儿|儿子|我们)/u.test(文)) return false;
  if (结果 === '陪产') return !/(?:没来|没有来|一次都没来|不在身边)/u.test(文);
  return !/(?:谢谢你一直陪着|还好你全程都在|你一直在身边|你全程陪产)/u.test(文);
}

export function 验收住院硬事实(文: string, 类型: 住院叙事节点类型): boolean {
  if (类型 === '恢复') return /恢复|身体|伤口|精神|休息|睡/u.test(文);
  if (类型 === '近况') return /宝宝|孩子|女儿|儿子/u.test(文);
  const 否定出院 =
    /(?:还没有|还没|尚未|并未|没有|没|还不|暂时不|暂不|不能|不可以|无法).{0,5}(?:出院|回家)|(?:出院|回家).{0,5}(?:不行|不可以|取消|推迟)/u;
  if (否定出院.test(文)) return false;
  if (类型 === '出院预告') return /出院/u.test(文) && /准备|快|就|观察|明天|之后|可以/u.test(文);
  return /(?:已经|今天|刚刚).{0,8}(?:出院|回家)|(?:出院|回家).{0,8}(?:了|到家)/u.test(文);
}

export function 验收家庭计划硬事实(文: string): boolean {
  if (/(?:不想|不用|不必|不要|别).{0,6}(?:来|见|谈)|(?:不谈|别来|不用来)/u.test(文)) return false;
  return /101/u.test(文) && /孩子|生育|家庭计划/u.test(文) && /来|见|有空|谈/u.test(文) && /他|老公|丈夫|陆嘉明/u.test(文);
}
