import type { SchemaType } from '../../../schema';
import { 户静态表, type 门牌 } from '../../../stageConfig';
import { 下一个回国茶话会后私聊成员 } from '../回国系统';
import { 创建手机时间线租约, 手机时间线租约仍有效 } from '../手机时间线租约';
import { 读库, 写库增量, 立即持久保存手机聊天变量 } from './数据层';
import { 小生成, 微信短文本, 称呼纪律 } from './生成引擎';
import { 当前手机绝对时段, 当前聊天ID, 末楼 } from './运行时上下文';
import { 请求手机重绘, 请求刷新手机红点 } from './UI刷新';
import { 构造回国提交凭据 } from './回国提交凭据';

/** 兜住“失败事件已发出、MVU 顺延尚未落库”与同拍补跑之间的窗口；世代变化后自然失效。 */
const 回国后私聊同拍暂缓 = new Set<string>();

export function 回国茶话会后私聊键(门牌号: 门牌): string {
  return `回国:茶话会后私聊:${门牌号}`;
}

/** 每个世界时段最多送达一名角色的茶话会后私聊；失败不消费，下一次手机节拍重试。 */
export async function 同步回国茶话会后私聊(data: SchemaType): Promise<boolean> {
  const 门牌号 = 下一个回国茶话会后私聊成员(data);
  if (!门牌号) return false;
  const 楼 = 末楼();
  const 时 = 当前手机绝对时段();
  const 租约 = 创建手机时间线租约(当前聊天ID(), 楼, SillyTavern.chat ?? [], 时);
  if (!租约) return false;
  const 暂缓键 = `${租约.聊天标识}:${租约.世代}:${时}:${门牌号}`;
  if (回国后私聊同拍暂缓.has(暂缓键)) return false;
  const 仍有效 = () => 手机时间线租约仍有效(租约, 当前聊天ID(), SillyTavern.chat ?? [], 当前手机绝对时段());
  const 暂缓本时段重试 = () => {
    if (!仍有效()) return;
    回国后私聊同拍暂缓.add(暂缓键);
    eventEmit('人妻公寓:回国茶话会后私聊暂缓', 门牌号, 构造回国提交凭据(租约, []));
  };
  const 库 = 读库();
  const 键 = 回国茶话会后私聊键(门牌号);
  if (库.消息.some(消息 => 消息.键 === 键)) {
    eventEmit('人妻公寓:回国茶话会后私聊已送达', 门牌号, 构造回国提交凭据(租约, 库.消息.filter(消息 => 消息.键 === 键)));
    return false;
  }
  const 户 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!户 || !配) return false;
  const 事件数据 = {
    发信人: 配.妻名,
    当前阶段: 户.妻.当前阶段,
    好感值: 户.妻.好感值,
    堕落值: 户.妻.堕落值,
    婚姻值: 户.妻.婚姻值,
    当前情绪: 户.妻.当前情绪,
    已有特殊关系事实: 户.妻.特殊.slice(-8),
    茶话会摘要: data.系统._回国.茶话会结构摘要,
    母亲已经在群里坦白与玩家的特殊关系: true,
    父亲即将回国: true,
  };
  let 原文 = '';
  try {
    原文 = await 小生成(
      '你替一款成人都市题材游戏生成一条姐妹茶话会结束后的角色私聊。只输出发信角色本人发送给管理员的微信正文，不写姓名、旁白、解释、引号或系统字段。' +
        '角色刚刚亲眼看见管理员的母亲加入姐妹群，并坦白自己与管理员已经不只是普通母子关系。' +
        '她可以按自身性格追问两人何时开始、父亲是否知道、拿管理员开玩笑、表达尴尬或重新确认自己的关系位置；只选最自然的一件事，不要把所有问题塞进一条消息。' +
        '不得编造未完成剧情、替玩家回答、声称父亲已经到楼或把母亲写成争宠对手。',
      `事件数据:${JSON.stringify(事件数据)}${称呼纪律()}`,
    );
  } catch (error) {
    暂缓本时段重试();
    throw error;
  }
  const 文 = await 微信短文本(原文, 220, `${配.妻名}的回国茶话会后私聊`, [配.妻名]);
  if (!文) {
    暂缓本时段重试();
    return false;
  }
  const 已写 = await 写库增量(
    { 新圈: [], 新消息: [{ 楼, 时, 会话: 门牌号, 发: '对方', 文, 类: '文本', 键 }], 节拍改: {} },
    仍有效,
  );
  if (!已写 || !仍有效()) return false;
  回国后私聊同拍暂缓.delete(暂缓键);
  请求刷新手机红点();
  请求手机重绘();
  await 立即持久保存手机聊天变量(租约.聊天标识);
  if (!仍有效()) return false;
  eventEmit('人妻公寓:回国茶话会后私聊已送达', 门牌号, 构造回国提交凭据(租约, 读库().消息.filter(消息 => 消息.键 === 键)));
  return true;
}

export const 回国口头安排纪律 = '【《回国》口头安排】父亲只说明近期会回国，正式交接等玩家准备好再通知；不得输出或计算可驱动世界钟的确切日期、倒计时或自动抵达。';
