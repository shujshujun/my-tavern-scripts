import { 户静态表, type 门牌 } from '../../../stageConfig';
import type { 微信消息 } from './数据层';
import type { 回国茶话会批次提交 } from '../回国系统';

export type 回国正事气泡 = Pick<微信消息, '会话' | '发' | '文' | '键'>;

/** 转正事必须由母亲交代回国安排和公共相处口径，不能以演员齐全代替任务完成。 */
export function 验收回国正事文本(消息们: readonly string[]): boolean {
  const 母亲句 = 消息们.flatMap(消息 => {
    const 匹配 = /^([^:：\n]+)[:：]\s*(.+)$/u.exec(消息);
    return 匹配?.[1].trim() === 户静态表['302'].妻名 ? 匹配[2].split(/[。；;\n]/u) : [];
  }).map(句 => 句.trim()).filter(Boolean);
  const 回国已说明 = 母亲句.some(句 =>
    /父亲|爸爸|你爸/u.test(句) && /回国|回来/u.test(句) &&
    /(?:一(?:个)?(?:周|星期|礼拜)|7天|七天).{0,6}后|再过.{0,4}(?:一周|一个星期|7天|七天)|下周|下个星期|下星期/u.test(句) &&
    !/[？?]|可能|也许|如果|假如|要是|举例|(?:只|仅)(?:是)?引用|(?:没|没有)说|上周|(?:还没|尚未|没有)(?:确定|确认|说定)|(?:不是|并非).{0,12}(?:一周|下周|回国|回来)|不是真的|并非事实|只是传闻|不一定|不(?:会|再|打算)?(?:在.{0,10})?(?:回国|回来)|(?:回国|回来).{0,8}(?:取消|未定)/u.test(句));
  const 公共口径已说明 = 母亲句.some(句 =>
    /公共(?:区域|场合|地方)|公区|楼道|大堂/u.test(句) &&
    /(?:普通|日常).{0,8}(?:住户|邻里|管理员)|(?:正常|照常|平常|平时|照旧).{0,14}(?:相处|住户|邻里|管理员|关系)|(?:相处|关系).{0,4}照旧/u.test(句) &&
    !/[？?]|(?:不必|不用|不需要|不要|不能|不再|别).{0,10}(?:普通|正常|照常|平常|日常).{0,12}(?:相处|关系|住户|邻里|管理员)/u.test(句));
  return 回国已说明 && 公共口径已说明;
}

/** 最终提交只接受同一转正事批次的实存气泡，不读取调用者自述的摘要作为凭证。 */
export function 验收回国正事实存(消息们: readonly 回国正事气泡[] = []): boolean {
  if (!消息们.length || 消息们.some(消息 => 消息.会话 !== '姐妹群' || 消息.发 !== '对方' ||
    !/^回国茶话会:转正事:-:(?:(?:[ab][^:]+):)?\d+$/u.test(消息.键 ?? ''))) return false;
  if (new Set(消息们.map(消息 => 消息.键!.replace(/:\d+$/u, ''))).size !== 1) return false;
  return 验收回国正事文本(消息们.map(消息 => 消息.文));
}

/** 任务内容由本次演员实际说出的文本承担，不从调用摘要或“送达成功”推断完成。 */
export function 验收回国茶话会文本(消息们: readonly string[], 提交: Pick<回国茶话会批次提交, '任务' | '目标'>, 玩家姓名 = ''): boolean {
  if (提交.任务 === '转正事') return 验收回国正事文本(消息们);
  if (提交.任务 !== '坦白' && 提交.任务 !== '点评') return true;
  const 气泡 = 消息们.flatMap(文 => {
    const 匹配 = /^([^:：\n]+)[:：]\s*(.+)$/u.exec(文);
    return 匹配 ? [{ 人: 匹配[1].trim(), 文: 匹配[2] }] : [];
  });
  const 母亲句 = 气泡.filter(项 => 项.人 === 户静态表['302'].妻名).flatMap(项 => 项.文.split(/[。！!；;\n]/u));
  if (提交.任务 === '坦白') {
    return 母亲句.some(句 => /我|我们/u.test(句) &&
      (/(?:不只是|不再只是|已经不是)(?:普通)?母子|母子之外/u.test(句) ||
        /伴侣|情人|恋人/u.test(句) && (/管理员|玩家|儿子/u.test(句) || !!玩家姓名 && 句.includes(玩家姓名))) &&
      !/[？?]|如果|假如|设想|举例|引用|你们|别人|(?:不是|并非|没有|不算).{0,6}(?:伴侣|情人|恋人)|不是说/u.test(句));
  }
  const 目标名 = 户静态表[提交.目标 as 门牌]?.妻名;
  if (!目标名 || !气泡.some(项 => 项.人 === 目标名 && 项.文.trim())) return false;
  return 母亲句.some(句 => 句.includes(目标名) && (/管理员|玩家|我儿子|他/u.test(句) || !!玩家姓名 && 句.includes(玩家姓名)) &&
    /眼神|心思|惦记|在意|亲近|关系|偷偷|藏|每次|总(?:是|爱|往)|主动|喜欢|在乎|关心|默契|牵挂|护着|对视/u.test(句) &&
    !/如果|假如|举例|引用|只是设想|没有说/u.test(句));
}

export function 验收回国茶话会实存(消息们: readonly 回国正事气泡[], 提交: 回国茶话会批次提交, 玩家姓名 = '', 成员: readonly string[] = []): boolean {
  if (!['改名反应', '坦白', '点评', '转正事', '回应回国', '收束'].includes(提交.任务)) return false;
  const 目标 = 提交.任务 === '点评' || 提交.任务 === '回应回国' ? String(提交.目标 || (提交.回应成员 ?? []).join(',') || '-') : '-';
  const 前缀 = `回国茶话会:${提交.任务}:${目标}:`;
  if (!消息们.length || 消息们.some(消息 => 消息.会话 !== '姐妹群' || 消息.发 !== '对方' ||
      !消息.键?.startsWith(前缀) || !/^(?:(?:[ab][^:]+):)?\d+$/u.test(消息.键.slice(前缀.length)))) return false;
  if (new Set(消息们.map(消息 => 消息.键!.replace(/:\d+$/u, ''))).size !== 1) return false;
  const 发言人 = 消息们.map(消息 => /^([^:：\n]+)[:：]/u.exec(消息.文)?.[1].trim() ?? '');
  const 母亲名 = 户静态表['302'].妻名;
  const 成员名 = 成员.map(m => 户静态表[m as 门牌]?.妻名).filter(Boolean);
  if (发言人.some(名 => 名 !== 母亲名 && !成员名.includes(名))) return false;
  if (提交.任务 === '改名反应') {
    const 母亲索引 = 发言人.indexOf(母亲名);
    if (母亲索引 < 0 || new Set(发言人.slice(0, 母亲索引).filter(名 => 成员名.includes(名))).size < Math.min(2, 成员名.length)) return false;
  } else if (提交.任务 === '回应回国') {
    if (!(提交.回应成员?.length) || 提交.回应成员.some(m => !成员.includes(m) || !发言人.includes(户静态表[m as 门牌]?.妻名))) return false;
  } else if (!发言人.includes(母亲名)) return false;
  return 验收回国茶话会文本(消息们.map(消息 => 消息.文), 提交, 玩家姓名);
}
