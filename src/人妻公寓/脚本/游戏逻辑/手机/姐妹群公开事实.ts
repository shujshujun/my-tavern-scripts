export interface 姐妹群公开消息证据 {
  会话?: string;
  键?: string;
  类?: string;
}

export interface 姐妹群公开事实 {
  /** 夏乔已经在姐妹群真实公开丈夫态度、孩子父亲或三人家庭结构。 */
  借种家庭结构已公开: boolean;
  /** 母亲已经在《回国》茶话会中由本人真实坦白与管理员的特殊关系。 */
  母亲关系已公开: boolean;
  /** 301换照照片与对应说明已经实际进入姐妹群。 */
  安若妍换照已公开: boolean;
}

function 当前姐妹群稳定键(消息: 姐妹群公开消息证据): string {
  if (消息.会话 !== '姐妹群' || 消息.类 === '撤回') return '';
  return typeof 消息.键 === 'string' ? 消息.键 : '';
}

function 是借种家庭结构公开键(键: string): boolean {
  if (/^父亲确认:姐妹群:101:.+/u.test(键)) return true;
  if (/^借种:产后家庭合照:姐妹群:101:\d+:.+/u.test(键)) return true;
  return /^姐妹生产:101:\d+:.+:确认(?::反应\d+)?$/u.test(键);
}

function 是母亲关系公开键(键: string): boolean {
  return /^回国茶话会:坦白:[^:]*:.+:\d+$/u.test(键);
}

/**
 * 姐妹群精确公开事实的唯一解析器。
 *
 * 调用方必须传入当前聊天、当前楼、当前分支已经裁剪后的消息。解析器只认脚本签发且仍
 * 存活的姐妹群稳定键；照片已拍、朋友圈发布、私聊知情、路线完成或AI正文都不能提升
 * 群内权限。撤回墓碑被明确排除，因此回档、删楼和切分支只需重传当前消息即可自然回退。
 */
export function 解析姐妹群公开事实(消息: readonly 姐妹群公开消息证据[]): 姐妹群公开事实 {
  let 借种家庭结构已公开 = false;
  let 母亲关系已公开 = false;
  let 安若妍换照已公开 = false;
  for (const 项 of 消息) {
    const 键 = 当前姐妹群稳定键(项);
    if (!键) continue;
    if (!借种家庭结构已公开 && 是借种家庭结构公开键(键)) 借种家庭结构已公开 = true;
    if (!母亲关系已公开 && 是母亲关系公开键(键)) 母亲关系已公开 = true;
    if (键 === '301结局:换照:姐妹群照片') 安若妍换照已公开 = true;
    if (借种家庭结构已公开 && 母亲关系已公开 && 安若妍换照已公开) break;
  }
  return { 借种家庭结构已公开, 母亲关系已公开, 安若妍换照已公开 };
}
