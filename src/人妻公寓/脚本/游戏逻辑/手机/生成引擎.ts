function 解析手机小生成原文(原: unknown): 手机小生成结果 {
  const 原文 = String(原 ?? '');
  const 封套状态 = 手机回复封套状态(原文);
  const 封套不完整 = 封套状态 !== '空' && 封套状态 !== '完整';
  return { 文: 封套不完整 ? '' : 净化消息(原文), 封套不完整 };
}

function 空手机小生成结果(): 手机小生成结果 {
  return { 文: '', 封套不完整: false };
}

