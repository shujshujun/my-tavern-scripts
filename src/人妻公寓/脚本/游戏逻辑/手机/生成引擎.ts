export async function 微信群文本(
  原: string,
  合法发言人: ReadonlySet<string>,
  最大字数: number,
  最多条数: number,
  语境: string,
  隐私模式?: 群聊隐私模式,
): Promise<string[]> {
  const 取合法 = (文本: string) =>
    解析微信群消息(文本, 合法发言人, 最大字数, Number.MAX_SAFE_INTEGER)
      .filter(行 => !隐私模式 || 验收群聊隐私(行, 隐私模式))
      .slice(0, 最多条数);
  const 直接 = 取合法(原);
  if (直接.length) return 直接;
  if (原.trim() && 合法发言人.size) {
    const 处理 = 隐私模式 ? '使用安全回退' : '已丢弃';
    console.warn(
      `[人妻公寓·手机] ${语境}未识别到合规的“发言人:内容”（每条不超过${最大字数}汉字），${处理}。`,
    );
  }
  if (隐私模式 && 原.trim()) {
    // 罐头回退只兜"AI 有输出但全被隐私验收拒绝"的场合;生成本身失败(原为空)时
    // 不得伪造一条"收到"式回复冒充群聊成功,让失败如实表现为无人接话(2026-08-03 审计 M3)
    const 回退 = 群聊安全回退([...合法发言人], 隐私模式);
    return 回退 ? [回退] : [];
  }
  return [];
}

