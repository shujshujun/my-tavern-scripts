import type { 门牌 } from '../../../stageConfig';
import { 门牌列表 } from '../../../stageConfig';
import {
  每日时段数,
  六时段列表,
  星期列表,
  每周时段数,
  解析绝对时段,
  type 星期名,
  type 周作息时段,
} from '../../../周作息';

/**
 * 手机定时定点邀约计划（v0.80）：玩家在微信单聊内安排本周某天、某时段、某地点见面。
 * 本模块是纯类型与纯函数——不读 getVariables、不写状态、不 import 内核/数据层，
 * 供业务接线、快照系统、客户端与行为测试共用同一套语义。
 *
 * 唯一持久真值存独立 chat 变量 `_手机邀约计划`（见 手机邀约计划键），不写入 MVU
 * schema，也绝不复用妻子的 `_阶段线路` 周期预约。星期/周数/时段文字一律由
 * `解析绝对时段` 从 `_绝对时段` 推导，本模块只保存不可由世界钟推导的真值。
 */

/** 新预约计划的独立 chat 变量键（v0.80 不兼容旧存档，不做迁移）。 */
export const 手机邀约计划键 = '_手机邀约计划';

export interface 手机邀约计划 {
  m: 门牌;
  /** 创建时所在消息楼；回档/原生删楼裁剪到创建楼之前时清掉。 */
  创建楼: number;
  /** 创建时的世界钟；时间推进不修改计划，由当前钟派生状态。 */
  创建绝对时段: number;
  /** 约定的目标绝对时段（本周内、不早于创建钟）。 */
  目标绝对时段: number;
  /** 约定地点（真实 `房间表` ID 白名单）。 */
  地点: string;
}

/** 私人地点白名单：`302`（你家）、`管理员室`、当前角色门牌（当前角色是 302 时与前者去重）。 */
export const 邀约私人地点列表 = ['302', '管理员室'] as const;

/** 公共场所白名单：不开放垃圾房、洗手间、晨跑公园、健身房。 */
export const 邀约公共地点列表 = ['大堂', '信箱区', '楼梯间', '天台', '公寓外部'] as const;

export type 邀约地点分组 = '私人地点' | '公共场所';

/** 地点分组；白名单外（含特殊玩法地点）返回 null。 */
export function 邀约地点分组(地点: string): 邀约地点分组 | null {
  if ((邀约私人地点列表 as readonly string[]).includes(地点)) return '私人地点';
  if ((邀约公共地点列表 as readonly string[]).includes(地点)) return '公共场所';
  return null;
}

/** 地点白名单校验：私人（302/管理员室/当前角色门牌）+ 公共五处；`房间表` 内但未开放的地点一律拒绝。 */
export function 邀约地点合法(地点: string, m: 门牌): boolean {
  return 邀约地点分组(地点) !== null || 地点 === m;
}

export interface 邀约日期选项 {
  星期: 星期名;
  星期序号: number;
  /** 该日第一个时段的目标绝对时段（本周内）。 */
  日起始绝对时段: number;
  /** 可选的时段：今天只列当前时段及之后，后续日给满六时段。 */
  时段选项: 周作息时段[];
}

/** 日期页只列当前星期从今天到星期日；不列过去日期，不列下周。 */
export function 邀约日期选项(当前绝对时段: number): 邀约日期选项[] {
  const 时间 = 解析绝对时段(当前绝对时段);
  const 周起始 = Math.floor(当前绝对时段 / 每周时段数) * 每周时段数;
  const 选项: 邀约日期选项[] = [];
  for (let 星期序号 = 时间.星期序号; 星期序号 < 星期列表.length; 星期序号++) {
    const 今天 = 星期序号 === 时间.星期序号;
    选项.push({
      星期: 星期列表[星期序号],
      星期序号,
      日起始绝对时段: 周起始 + 星期序号 * 每日时段数,
      时段选项: 今天 ? [...六时段列表].slice(时间.时段序号) : [...六时段列表],
    });
  }
  return 选项;
}

/**
 * 由 星期+时段 构造本周目标绝对时段；目标已过去或落出本周（下周）返回 null。
 * 今天只允许当前时段及之后（当前时段可选，用于立即去指定地点见面）。
 */
export function 构造目标绝对时段(星期: 星期名, 时段: 周作息时段, 创建绝对时段: number): number | null {
  const 星期序号 = 星期列表.indexOf(星期);
  const 时段序号 = 六时段列表.indexOf(时段);
  if (星期序号 < 0 || 时段序号 < 0 || !Number.isFinite(创建绝对时段)) return null;
  const 周起始 = Math.floor(创建绝对时段 / 每周时段数) * 每周时段数;
  const 目标 = 周起始 + 星期序号 * 每日时段数 + 时段序号;
  if (目标 < 创建绝对时段) return null;
  if (Math.floor(目标 / 每周时段数) !== Math.floor(创建绝对时段 / 每周时段数)) return null;
  return 目标;
}

export type 手机邀约计划状态 = '待赴约' | '赴约中' | '已过期' | '无效';

/**
 * 计划状态由世界钟派生，状态机：
 * - 当前钟 < 目标钟：待赴约，只占用“单例预约”，不改变人物位置。
 * - 当前钟 === 目标钟：赴约时段；人物地图位置是约定地点，只有玩家场景也等于
 *   该地点时才进入现场焦点/当面交互/入住占用（由消费侧校验房间等于约定地点）。
 * - 当前钟 > 目标钟：已错过/过期，不再占用，可被下一次接受覆盖。
 * - 创建点在当前时间线未来（回档到创建楼/创建钟之前）：无效；时间线裁剪时会清掉。
 */
export function 手机邀约计划状态(
  计划: 手机邀约计划 | null | undefined,
  当前绝对时段: number,
  当前楼 = 0,
): 手机邀约计划状态 {
  if (!计划 || typeof 计划 !== 'object') return '无效';
  if (!门牌列表.includes(计划.m)) return '无效';
  if (typeof 计划.地点 !== 'string' || !邀约地点合法(计划.地点, 计划.m)) return '无效';
  // 合法目标必须是整数时段：小数/NaN/Infinity/负数/畸形数值一律判无效，不崩溃。
  if (
    !Number.isSafeInteger(计划.创建楼) ||
    !Number.isSafeInteger(计划.创建绝对时段) ||
    !Number.isSafeInteger(计划.目标绝对时段)
  ) {
    return '无效';
  }
  if (计划.创建楼 < 0 || 计划.创建楼 > 当前楼) return '无效';
  if (计划.创建绝对时段 < 0 || 计划.创建绝对时段 > 当前绝对时段) return '无效';
  // 原始 chat 值也必须服从“创建时当前周”边界；否则损坏/手改值会以待赴约
  // 长期占用单例，尽管所有正规提交入口都不会创建跨周计划。
  if (!邀约目标合法(计划.目标绝对时段, 计划.创建绝对时段)) return '无效';
  if (当前绝对时段 < 计划.目标绝对时段) return '待赴约';
  if (当前绝对时段 === 计划.目标绝对时段) return '赴约中';
  return '已过期';
}

/** 待赴约/赴约中 = 占用单例预约；已过期/无效不阻塞下一次接受。 */
export function 手机邀约计划占用中(
  计划: 手机邀约计划 | null | undefined,
  当前绝对时段: number,
  当前楼 = 0,
): boolean {
  const 状态 = 手机邀约计划状态(计划, 当前绝对时段, 当前楼);
  return 状态 === '待赴约' || 状态 === '赴约中';
}

/**
 * 时间线裁剪到 楼层/目标钟 后，创建点在裁剪点之后（=计划在回档后的时间线里尚不存在）
 * 的计划应清掉；创建点仍存活的未来预约保留，由世界钟派生待赴约/赴约中/过期——
 * 时间撤销回到创建之后、目标之前时自然恢复为待赴约。
 */
export function 手机邀约计划需裁剪(计划: 手机邀约计划 | null | undefined, 楼层: number, 目标钟: number): boolean {
  return !!计划?.m && (Number(计划.创建楼) > 楼层 || Number(计划.创建绝对时段) > 目标钟);
}

/** 提交前与异步队列内重验：目标仍属于提交时当前周、且不早于当前钟；时间变化由现有手机租约令旧请求失效。 */
export function 邀约目标合法(目标绝对时段: number, 提交绝对时段: number): boolean {
  return (
    Number.isFinite(目标绝对时段) &&
    Number.isFinite(提交绝对时段) &&
    目标绝对时段 >= 提交绝对时段 &&
    Math.floor(目标绝对时段 / 每周时段数) === Math.floor(提交绝对时段 / 每周时段数)
  );
}

/**
 * 提交前完整校验（纯函数，业务层写玩家消息前与数据层最终 CAS 共用）：
 * 门牌有效、`计划.m === m`、地点对该角色合法、所有数值为安全整数且非负、
 * 创建锚不晚于提交时当前真值、目标时段属于提交时当前周且不早于提交钟。
 * 不满足时调用方必须整次拒绝：零消息、零冷却、零预约。
 */
export function 手机邀约计划可提交(
  计划: 手机邀约计划 | null | undefined,
  m: 门牌 | string | undefined,
  提交绝对时段: number,
  提交楼 = 0,
): boolean {
  if (!计划 || typeof 计划 !== 'object') return false;
  if (!m || !门牌列表.includes(m as 门牌)) return false;
  if (计划.m !== m) return false;
  if (typeof 计划.地点 !== 'string' || !邀约地点合法(计划.地点, 计划.m)) return false;
  if (
    !Number.isSafeInteger(计划.创建楼) ||
    !Number.isSafeInteger(计划.创建绝对时段) ||
    !Number.isSafeInteger(计划.目标绝对时段)
  ) {
    return false;
  }
  if (计划.创建楼 < 0 || 计划.创建绝对时段 < 0 || 计划.目标绝对时段 < 0) return false;
  if (!Number.isFinite(提交绝对时段) || 提交绝对时段 < 0 || 计划.创建绝对时段 > 提交绝对时段) return false;
  if (提交楼 > 0 && 计划.创建楼 > 提交楼) return false;
  // 目标必须属于提交时当前周且不早于提交钟；创建钟不晚于提交钟时，两者同周才算同一周。
  return 邀约目标合法(计划.目标绝对时段, 计划.创建绝对时段) && 邀约目标合法(计划.目标绝对时段, 提交绝对时段);
}
