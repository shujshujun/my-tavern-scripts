export async function 同步管理任务微信(data: SchemaType): Promise<boolean> {
  const 楼 = 末楼();
  const 时 = 取绝对时段(data);
  const 时间线租约 = 创建手机时间线租约(当前聊天ID(), 楼, SillyTavern.chat ?? [], 时);
  if (!时间线租约) return false;
  const 库 = 读库();
  const 已有键 = new Set(库.消息.flatMap(消息 => (消息.键 ? [消息.键] : [])));
  const 候选消息 = [
    ...编译管理任务微信通知(data, 楼, 时),
    ...编译怀孕微信通知(data, 楼, 时),
    ...编译许曼君分居手机通知(data, 楼, 时),
    ...编译许曼君离婚手机通知(data, 楼, 时),
    ...编译许曼君离婚后日常手机通知(data, 楼, 时),
  ];
  const 日常反馈待办 = 许曼君离婚后日常待发送反馈(data);
  const 时间线仍有效 = () =>
    手机时间线租约仍有效(时间线租约, 当前聊天ID(), SillyTavern.chat ?? [], 当前手机绝对时段());
  const 广播201持久送达收据 = (): void => {
    if (!时间线仍有效()) return;
    const 持久库 = 读库();
    if (
      许曼君离婚邀请待发送(data) &&
      持久库.消息.filter(
        消息 => 消息.会话 === '201' && 消息.发 === '对方' && 消息.键 === 许曼君离婚邀请消息键,
      ).length === 1
    ) {
      eventEmit('人妻公寓:许曼君离婚邀请已送达');
    }
    for (const 待办 of 日常反馈待办) {
      if (
        持久库.消息.filter(
          消息 => 消息.会话 === '201' && 消息.发 === '对方' && 消息.键 === 待办.消息键,
        ).length === 1
      ) {
        eventEmit('人妻公寓:许曼君离婚后日常反馈已送达', 待办.消息键);
      }
    }
  };
  const 新消息 = 候选消息.filter(消息 => !已有键.has(消息.键 as string));
  if (!新消息.length) {
    const 有待确认201消息 =
      (许曼君离婚邀请待发送(data) &&
        库.消息.filter(
          消息 => 消息.会话 === '201' && 消息.发 === '对方' && 消息.键 === 许曼君离婚邀请消息键,
        ).length === 1) ||
      日常反馈待办.some(
        待办 =>
          库.消息.filter(
            消息 => 消息.会话 === '201' && 消息.发 === '对方' && 消息.键 === 待办.消息键,
          ).length === 1,
      );
    if (!有待确认201消息) return false;
    const 已持久 = await 立即持久保存手机聊天变量(时间线租约.聊天标识);
    if (!已持久 || !时间线仍有效()) return false;
    广播201持久送达收据();
    return false;
  }
  const 已写 = await 写库增量({ 新圈: [], 新消息, 节拍改: {} }, 时间线仍有效);
  if (!已写 || !时间线仍有效()) return false;
  请求刷新手机红点();
  请求手机重绘();
  const 已持久 = await 立即持久保存手机聊天变量(时间线租约.聊天标识);
  if (!已持久 || !时间线仍有效()) return false;
  广播201持久送达收据();
  return true;
}

