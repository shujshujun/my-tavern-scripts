function 回国母亲邀请事务仍属于当前时间线(
  事务: 回国母亲邀请事务,
  允许刷新世代恢复: boolean,
): boolean {
  const 聊天 = SillyTavern.chat ?? [];
  if (!事务.聊天ID || 当前聊天ID() !== 事务.聊天ID) return false;
  if (!允许刷新世代恢复 && 读取当前手机时间线租约世代() !== 事务.时间线世代) return false;
  if (当前手机绝对时段() < 事务.绝对时段 || 末楼() < 事务.入群楼层) return false;
  if (事务.入群楼层 < 0 || 事务.入群楼层 >= 聊天.length) return false;
  return 手机锚消息签名(聊天[事务.入群楼层]) === 事务.锚签名;
}

function 回国母亲入群消息匹配事务(消息: 微信消息 | undefined, 事务: 回国母亲邀请事务): boolean {
  if (!消息) return false;
  const 群昵称 = 生成回国姐妹群昵称(事务.Persona名);
  return Boolean(
    消息.会话 === '姐妹群' &&
      消息.键 === 回国母亲入群消息键 &&
      消息.发 === '系统' &&
      消息.文 === 回国母亲入群系统文案 &&
      消息.楼 === 事务.入群楼层 &&
      消息.时 === 事务.绝对时段 &&
      消息.群昵称 === 群昵称 &&
      (!消息.标识 || 消息.标识 === 事务.事务ID),
  );
}

function 查找回国母亲入群消息(): 微信消息 | undefined {
  return [...读库().消息].reverse().find(消息 => 消息.键 === 回国母亲入群消息键);
}

