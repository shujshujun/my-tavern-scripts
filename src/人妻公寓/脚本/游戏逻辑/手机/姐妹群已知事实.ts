import { 户静态表 } from '../../../stageConfig';
import type { 微信消息 } from './数据层';
import { 解析姐妹群公开事实, type 姐妹群公开事实 } from './姐妹群公开事实';
import { 父亲被写成已知关系 } from '../父亲关系知情';

/** 调用方只传本发言人实际收到的消息；公开声明与世界硬事实分别处理。 */
export function 验收姐妹群跨线事实(
  消息: string,
  既有消息: readonly 微信消息[],
  本轮公开: Partial<姐妹群公开事实> = {},
): boolean {
  const 文 = 消息.normalize('NFKC').trim();
  const match = /^([^:：\n]+)[:：]\s*(.+)$/u.exec(文);
  if (!match) return false;
  const 发言人 = match[1].trim();
  const 正文 = match[2];
  const 公开 = 解析姐妹群公开事实(既有消息);
  for (const 键 of Object.keys(公开) as (keyof 姐妹群公开事实)[]) 公开[键] ||= 本轮公开[键] === true;
  // 玩家在群里实际提起的说法可以成为对话话题，但不签发世界书公开级或结局事实。
  const 玩家提起 = (模式: RegExp) =>
    既有消息.some(项 => 项.会话 === '姐妹群' && 项.发 === '我' && 项.类 !== '撤回' && 模式.test(项.文));
  // 只匹配传播其他记录／证据的具体表述；普通提及摄影、亲密或家庭成员不会单独触发拒收。
  if (
    /(?:公开|告诉大家|发到群里|给大家看).{0,24}(?:私聊记录|母带|外遇证据|CAM-?2录像|协议细节)|(?:私聊记录|母带|外遇证据|CAM-?2录像|协议细节).{0,24}(?:具体内容|原文是|写的是|告诉大家|发到群里|给大家看)/iu.test(
      正文,
    )
  )
    return false;
  if (
    !公开.借种家庭结构已公开 &&
    !玩家提起(
      /(?:夏乔|陆嘉明|101).{0,40}(?:生物学父亲|孩子.{0,4}父亲|三人.{0,4}家庭|家庭安排|知情|同意|接受)|(?:三人.{0,4}家庭|生物学父亲|家庭安排).{0,30}(?:夏乔|陆嘉明|101)/u,
    )
  ) {
    const 指向夏乔家庭 =
      /(?:陆嘉明.{0,24}(?:知情|知道|同意|接受|默许).{0,24}(?:管理员|玩家|关系|家庭安排|家庭结构)|夏乔.{0,24}(?:生物学父亲|孩子(?:的)?父亲|家庭安排))/u.test(
        正文,
      );
    const 夏乔自述家庭 =
      发言人 === 户静态表['101'].妻名 &&
      /(?:我(?:的)?(?:丈夫|老公)).{0,24}(?:知情|知道|同意|接受).{0,24}(?:管理员|玩家|关系|家庭安排|家庭结构)|(?:我们三个|我们(?:的家庭)|我(?:的)?孩子(?:的)?父亲).{0,24}(?:知情|同意|接受|管理员|玩家)/u.test(
        正文,
      );
    if (指向夏乔家庭 || 夏乔自述家庭) return false;
  }
  const 涉及母亲 = 发言人 === 户静态表['302'].妻名 || /母亲|妈妈|302/u.test(正文);
  if (涉及母亲) {
    if (/机场.{0,24}(?:隐秘现场|镜头死角|镜头外的|隐瞒父亲)/u.test(正文)) return false;
    if (父亲被写成已知关系(正文, 发言人 === 户静态表['302'].妻名 ? '母亲' : '旁人')) return false;
    if (
      !公开.母亲关系已公开 &&
      !玩家提起(
        /(?:母亲|妈妈|302).{0,32}(?:情人|恋人|伴侣|在一起|不只是母子|不是普通母子)|(?:情人|恋人|伴侣).{0,20}(?:母亲|妈妈|302)/u,
      ) &&
      /(?:母亲|妈妈|我).{0,8}(?:和|跟|与).{0,8}(?:儿子|管理员|玩家).{0,12}(?:恋人|爱人|伴侣|情人|在一起|同床|共枕)|(?:母亲|妈妈).{0,8}(?:真实关系|隐秘关系)/u.test(
        正文,
      )
    )
      return false;
  }
  return true;
}
