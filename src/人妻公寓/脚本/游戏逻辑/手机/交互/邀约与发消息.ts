function 群聊角色兜底(data: SchemaType, m: 门牌, 会话: '群' | '姐妹群', 是跟聊: boolean): string {
  const 配 = 户静态表[m];
  const 妻 = data.户[m].妻;
  if (会话 === '群') {
    if (/直接|强势|泼辣|爽快/u.test(`${配.初始?.气质描述 ?? ''}${配.雌竞}`)) return '我也看到了，这件事一起说清楚吧。';
    return 妻.当前阶段 >= 3 ? '我也留意到了，顺便补充一句。' : '我也看到了，先听听具体情况。';
  }
  if (!是跟聊) return 妻.当前阶段 >= 4 ? '怎么，特意点我呀？我听着呢。' : '我在，刚才那句我看见了。';
  if (妻.堕落值 >= 70 || 妻.当前阶段 >= 4) return '哟，你们这句我可听见了，也算我一个。';
  if (妻.婚姻值 <= 40 || 妻.好感值 >= 70) return '怎么只问她，我也有点想接这句话。';
  return /温柔|内敛|克制/u.test(配.初始?.气质描述 ?? '') ? '我本来不想插话，不过这句确实想问问。' : '等等，这句我也想接。';
}

/** 只有玩家确实引用了群成员才建立约束；跟聊低概率且最近十条命中过就硬冷却。 */
function 创建群聊引用响应约束(
  data: SchemaType,
  会话: '群' | '姐妹群',
  库: 微信库,
  批次消息: readonly 微信消息[],
  楼: number,
  时: number,
): 群聊引用响应约束 | undefined {
  const 成员 = 群聊成员门牌(data, 会话);
  const 名到门牌 = new Map(成员.map(m => [户静态表[m].妻名, m] as const));
  let 必答门牌: 门牌 | undefined;
  let 引用种子 = '';
  for (const 玩家消息 of [...批次消息].reverse()) {
    const 目标 = 定位微信消息(库.消息, 玩家消息.引用);
    if (!微信消息可引用(目标) || 目标.会话 !== 会话 || 目标.发 !== '对方') continue;
    const 名 = 微信消息发送者(目标, 玩家名());
    const m = 名到门牌.get(名);
    if (!m) continue;
    必答门牌 = m;
    引用种子 = 玩家消息.标识 || String(玩家消息.序 ?? '') || 玩家消息.文;
    break;
  }
  if (!必答门牌) return undefined;

  const 必答角色 = 户静态表[必答门牌].妻名;
  const 约束: 群聊引用响应约束 = {
    必答角色,
    必答兜底: 群聊角色兜底(data, 必答门牌, 会话, false),
  };
  const 最近群消息 = 库.消息.filter(m => m.会话 === 会话 && m.类 !== '撤回').slice(-10);
  if (最近群消息.some(m => m.键?.startsWith(`引用跟聊:${会话}:`))) return 约束;

  const 候选 = 成员.filter(m => m !== 必答门牌);
  if (!候选.length) return 约束;
  const 概率 = 计算微信引用跟聊概率(
    会话,
    候选.map(m => {
      const 妻 = data.户[m].妻;
      return { 阶段: 妻.当前阶段, 好感: 妻.好感值, 堕落: 妻.堕落值, 婚姻: 妻.婚姻值 };
    }),
  );
  if (seededRandom(楼, 时, 会话, 必答角色, 引用种子, '引用跟聊触发') >= 概率) return 约束;

  const 权重们 = 候选.map(m => {
    const 妻 = data.户[m].妻;
    const 性格扰动 = seededRandom(楼, 时, 会话, 户静态表[m].妻名, '引用跟聊人选') * 0.35;
    const 权重 =
      0.5 +
      妻.当前阶段 * 0.12 +
      限幅01(妻.好感值 / 100) * 0.45 +
      限幅01(妻.堕落值 / 100) * 0.55 +
      (1 - 限幅01(妻.婚姻值 / 100)) * 0.25 +
      性格扰动;
    return { m, 权重 };
  });
  const 总权重 = 权重们.reduce((和, 项) => 和 + 项.权重, 0);
  let 落点 = seededRandom(楼, 时, 会话, 必答角色, 引用种子, '引用跟聊轮盘') * 总权重;
  const 跟聊门牌 = 权重们.find(项 => (落点 -= 项.权重) <= 0)?.m ?? 权重们[权重们.length - 1].m;
  约束.跟聊角色 = 户静态表[跟聊门牌].妻名;
  约束.跟聊画像 = 群聊跟聊画像(data, 跟聊门牌);
  约束.跟聊兜底 = 群聊角色兜底(data, 跟聊门牌, 会话, true);
  约束.跟聊事件键 = `引用跟聊:${会话}:${楼}:${时}:${引用种子}`;
  return 约束;
}

async function 持久化玩家微信撤回(定位: 微信撤回定位): Promise<void> {
  let 已撤回 = false;
  await updateVariablesWith(
    vars => {
      const 原 = (_.get(vars, '_微信.消息') ?? []) as 微信消息[];
      const 结果 = 撤回微信玩家消息(原, 定位);
      if (!结果.已撤回) return vars;
      _.set(vars, '_微信.消息', 结果.消息);
      已撤回 = true;
      return vars;
    },
    { type: 'chat' },
  );
  if (!已撤回) {
    eventEmit('人妻公寓:提示', '这条消息已经撤回，或不在当前时间线上。');
    return;
  }
  for (const 键 of 会话待回复键列表()) {
    if (!手机聊天批次.含消息(键, 定位.标识)) continue;
    if (手机聊天批次.状态(键).灯 === '红') {
      // 请求提示中已经含有被撤回内容：整批定向终止，保留已经显示的回复，丢弃尚未显示的气泡。
      取消手机聊天批次键(键, false);
      continue;
    }
    手机聊天批次.移除消息(键, 定位.标识);
    const 状态 = 手机聊天批次.状态(键);
    if (状态.待回复数 === 0 && 状态.写入中数 === 0) {
      手机聊天批次.丢弃(键);
      释放会话待回复(键);
    }
  }
  请求手机重绘();
  请求刷新手机红点();
}

