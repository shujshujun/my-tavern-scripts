/** 同一聊天内所有妻子的邀约共用一条队列；不同存档互不等待，也不会共享单例判断。 */
const 手机邀约队列 = new Map<string, Promise<void>>();

function 排队手机邀约<T>(聊天ID: string, 手机租约世代: number, 任务: () => Promise<T>): Promise<T> {
  const 队列键 = `${聊天ID}${String.fromCharCode(0)}${手机租约世代}`;
  const 前序 = 手机邀约队列.get(队列键) ?? Promise.resolve();
  const 本次 = 前序.catch(() => undefined).then(任务);
  const 尾项 = 本次.then(
    () => undefined,
    () => undefined,
  );
  手机邀约队列.set(队列键, 尾项);
  const 清理 = () => {
    if (手机邀约队列.get(队列键) === 尾项) 手机邀约队列.delete(队列键);
  };
  void 尾项.then(清理, 清理);
  return 本次;
}

/**
 * 读赴约条(渲染层按钮状态用)：旧即时 `_赴约` 仍按原 起楼/至楼 生命周期读取；
 * 新 `_手机邀约计划` 待赴约/赴约中视为已约（待赴约带标记，按钮文案区分）。
 */
function 读赴约条(楼: number): { m: 门牌; 待赴约?: boolean } | null {
  const p = (_.get(getVariables({ type: 'chat' }), '_赴约') ?? null) as {
    m?: 门牌;
    起楼?: number;
    至楼?: number;
  } | null;
  if (p?.m && (p.起楼 ?? 0) <= 楼 && (p.至楼 ?? -1) >= 楼) return { m: p.m };
  const 计划 = 读手机邀约计划();
  const 状态 = 手机邀约计划状态(计划, 当前手机绝对时段(), 楼);
  if (状态 === '待赴约') return { m: 计划!.m, 待赴约: true };
  if (状态 === '赴约中') return { m: 计划!.m };
  return null;
}

