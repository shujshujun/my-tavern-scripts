import { 新建对话观察记录, 识别已保存对话, 自然对话可提交 } from '../自然对话观察';
import { 请求手机对话观察 } from './对话观察路由';
import { 当前聊天ID } from './运行时上下文';
import { 读取当前手机时间线租约世代 } from '../手机时间线租约';

/** 事实由业务确定。角色可以自由表达；格式或识别失败仍送达明确标注的事实通知。 */
export async function 自然通知回复(
  类别: '微信邀约' | '家庭通知', 文: string | null, 要求: string, 事实通知: string,
): Promise<string> {
  const 聊天 = 当前聊天ID(), 世代 = 读取当前手机时间线租约世代();
  const 仍有效 = () => 当前聊天ID() === 聊天 && 读取当前手机时间线租约世代() === 世代;
  if (文?.trim()) {
    const 批次 = `notice:${crypto.randomUUID()}`;
    const 记录 = 新建对话观察记录({
      版本: 1, 类别, 事件: 要求, 阶段: 事实通知, 分支: `${聊天}:${世代}`, 批次,
      要求: '对照业务已经确定的事实，判断角色消息是否准确传达本次通知、没有与事实矛盾或虚构玩家承诺。' +
        '不要求逐字复述、不要求特定措辞。邀请只是通知见面安排，不代表玩家已经到场或采取其他行动。' + 要求,
      消息: [{ id: `${批次}:notice`, 来源: '业务', 文本: 事实通知 }, { id: `${批次}:character`, 来源: '角色', 文本: 文 }],
    });
    await 识别已保存对话(记录, 请求手机对话观察, 仍有效);
    if (!仍有效()) return '';
    if (自然对话可提交(记录)) return 文;
  }
  if (!仍有效()) return '';
  return `［事件通知］${事实通知}\n角色回复暂未确认，已保留这次实际安排。`;
}
