export function 结局后公开日常(data: SchemaType, m: 门牌): { 主题: readonly 朋友圈主题[]; 方向: string } | null {
  if (!data.户[m] || !构建角色结局后生活社交语义(data, m).已开启) return null;
  return { 主题: 生活主题[m], 方向: 生活方向[m] };
}

/** 普通日常配图与专用事件分开选择；本函数不改变请求照片、亲密CG或剧情照片入口。 */
export function 结局后普通图策略(
  data: SchemaType,
  m: 门牌,
  渠道: '公开朋友圈' | '主动私聊' | '仅你可见',
  随机值: number,
): '沿用原图' | '主题图库' | '文字' {
  if (!结局后公开日常(data, m)) return '沿用原图';
  if (渠道 === '公开朋友圈') return '主题图库';
  if (m === '302' || 角色当前仅保留事务往来(data, m)) return '文字';
  // 已有私人图库继续用于偶尔分享照片；日常多数时候从真实见闻起话，不由旧图决定主题。
  return 随机值 < 0.3 ? '沿用原图' : '文字';
}

/** 只描述评论者自身的反应方式；不会给她补造发布者的私聊、场景或结局知识。 */
export function 公开动态评论者方向(data: SchemaType, m: 门牌): string {
  const 节点 = data.户[m];
  if (!节点) return '';
  const 后效 = 构建角色结局后生活社交语义(data, m);
  if (!后效.已开启) {
    return `${户静态表[m].妻名}仍处在本人的当前关系阶段${节点.妻.当前阶段}，按自己的性格接这条动态，不借用未来结局经历。`;
  }
  if (m === '201' && 角色当前仅保留事务往来(data, m)) {
    return '许曼君按自己已经决定的独立生活回应，可以关心实际安排、开玩笑或有不同意见，不把评论变成与管理员恢复私人关系。';
  }
  const 方向: Record<门牌, string> = {
    '101': '夏乔仍热闹直接，会关心怎么安排、谁来搭把手，也会开玩笑；她有自己的家庭经验，不要求别人采用同一种安排。',
    '102': '沈静仪仍克制，会注意对方说清了什么、实际怎么做，也会真诚欣赏，不把每条评论都变成规劝。',
    '201': '许曼君保留算账和打趣的习惯，会问具体安排或说出不同看法；她自己的选择不替对方作决定。',
    '202': '周小满仍温和，会直接说喜欢、不方便或自己的安排，也能接玩笑，不只附和别人。',
    '301': '安若妍会注意画面、表达和真实生活的细节，可以欣赏或调侃，不把所有人的日常都理解成摆拍。',
    '302': '母亲可以关心、调侃、欣赏或保留意见，不承担每一条动态的训话和收场。',
  };
  return 方向[m];
}
