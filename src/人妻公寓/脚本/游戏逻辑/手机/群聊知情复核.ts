import { 验收群聊隐私, 群聊隐私范围说明, type 群聊隐私模式 } from '../手机输出安全';
import { 新建对话观察记录, 识别已保存对话, 自然对话可提交 } from '../自然对话观察';
import { 请求手机对话观察 } from './对话观察路由';

/** 旧规则只提示待复核范围；否定、设想、引用或转开话题不会仅因出现某词而被删除。 */
export async function 复核群聊知情范围(消息: string[], 模式: 群聊隐私模式, 上下文: string, 仍有效 = () => true): Promise<{ 消息: string[]; 已确认: boolean }> {
  if (消息.every(文 => 验收群聊隐私(文, 模式))) return { 消息, 已确认: true };
  const 批次 = `privacy:${crypto.randomUUID()}`;
  const 记录 = 新建对话观察记录({
    版本: 1, 类别: '群聊进度', 事件: '群聊知情范围', 阶段: 模式, 分支: 批次, 批次,
    要求: '核对本批消息是否实际向当前群成员披露超出已公开范围的事实。' +
      '以下旧正则仅说明产品原有知情范围，不执行正则，不以出现词语判定泄露。必须理解否定、引用、假设与发言主体。' +
      '已经公开或当前事件允许本人公开的内容可自然交流。只是拒谈某话题且没有透露新事实可以保留。整批没有越界披露为完成，否则待续。' +
      '\n原有范围：' + 群聊隐私范围说明(模式) + '\n当前事件与已知上下文：' + 上下文,
    消息: 消息.map((文, i) => ({ id: `${批次}:character:${i}`, 来源: '角色', 文本: 文 })),
  });
  await 识别已保存对话(记录, 请求手机对话观察, 仍有效);
  return { 消息, 已确认: 仍有效() && 自然对话可提交(记录) };
}
