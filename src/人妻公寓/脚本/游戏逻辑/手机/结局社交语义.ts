import type { SchemaType } from '../../../schema';
import { 户静态表, type 门牌 } from '../../../stageConfig';
import { 解析姐妹群公开事实, type 姐妹群公开消息证据 } from './姐妹群公开事实';
import {
  构建角色结局后生活社交语义,
  角色结局后姐妹群长期方向,
  角色正式结局已完成,
} from '../结局后生活社交语义';

export interface 结局社交消息证据 extends 姐妹群公开消息证据 {
  文?: string;
}

export type 关系公开级 = '保持边界' | '心知肚明' | '群内摊牌' | '结局稳定' | '家庭结构已公开';

export interface 结局社交画像 {
  门牌: 门牌;
  姓名: string;
  当前阶段: number;
  关系公开级: 关系公开级;
  已完成结局: string;
  群内允许事实: string[];
  群聊口吻变化: string;
  私聊口吻变化: string;
  公开称呼纪律: string;
  群内称呼纪律: string;
  私聊称呼纪律: string;
}

export function 双重继承结局已成立(data: SchemaType): boolean {
  return data.系统._双重继承.阶段 === '已完成' || data.系统._已完成特殊场景.includes('双重继承');
}

function 已完成结局ID(data: SchemaType, 门牌号: 门牌): string {
  if (门牌号 === '302' && 双重继承结局已成立(data)) return '双重继承';
  if (门牌号 === '101' && data.系统._已完成特殊场景.includes('借种')) return '借种';
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  return 角色正式结局已完成(data, 门牌号) ? 后效.阶段 : '';
}

export function 构建结局社交画像(
  data: SchemaType,
  门牌号: 门牌,
  消息: readonly 结局社交消息证据[] = [],
): 结局社交画像 {
  const 节点 = data.户[门牌号];
  const 姓名 = 户静态表[门牌号].妻名;
  const 当前阶段 = 节点?.妻.当前阶段 ?? 0;
  const 结局ID = 已完成结局ID(data, 门牌号);
  const 群内允许事实: string[] = [];
  let 关系公开级: 关系公开级 = 当前阶段 >= 5 ? '心知肚明' : '保持边界';
  const 群内公开事实 = 解析姐妹群公开事实(消息);
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);

  if (门牌号 === '302') {
    const 已摊牌 = 群内公开事实.母亲关系已公开;
    if (已摊牌) {
      关系公开级 = 结局ID ? '结局稳定' : '群内摊牌';
      群内允许事实.push('母亲已经由本人在姐妹群承认与管理员不只是普通母子关系');
    } else if (结局ID) {
      // 结局成立只稳定本人生活口吻；没有当前分支坦白键时，不能把隐秘关系授予姐妹群。
      关系公开级 = '结局稳定';
    }
    if (结局ID) {
      群内允许事实.push('公开交接结果：父亲已经离开，管理员正式接管公寓，母亲以自己的意志继续留在302');
      群内允许事实.push('父亲始终不知道母亲与管理员的真实关系；机场视频及其隐秘现场不得进入群聊，只承接公开交接结果');
    }
  } else if (门牌号 === '101' && 结局ID === '借种') {
    const 已在群内公开 = 群内公开事实.借种家庭结构已公开;
    关系公开级 = 已在群内公开 ? '家庭结构已公开' : '结局稳定';
    if (已在群内公开) {
      群内允许事实.push('夏乔已经通过脚本签发的姐妹群消息亲自公开家庭结构，可以承接该公开消息里的丈夫态度与孩子父亲事实');
    } else {
      群内允许事实.push('夏乔的关系已经稳定，只用来调整她不再失忆的生活口吻；精确家庭结构尚未由本人在群内公开');
    }
  } else if (门牌号 === '301' && 结局ID && 群内公开事实.安若妍换照已公开) {
    关系公开级 = '群内摊牌';
    群内允许事实.push('安若妍已经在姐妹群亲自晒出换好的301客厅照片，并说明由江辰拍摄、玩家换照；只承接这条消息内的事实。');
  } else if (后效.已开启) {
    关系公开级 = 结局ID ? '结局稳定' : '心知肚明';
    群内允许事实.push(后效.群内可见后效);
    群内允许事实.push('结局后生活可以改变本人长期口吻，但丈夫私下决定、录像内容、外遇证据、手续细节和未公开关系不能由后效状态自动带进姐妹群。');
  } else if (当前阶段 >= 5) {
    群内允许事实.push('她与管理员的关系已经很深，成员可以心知肚明，但未真实摊牌的精确事实仍不能代她公开');
  } else {
    群内允许事实.push('只按当前阶段与真实群消息发言，不得提前使用未来结局口吻');
  }

  return {
    门牌: 门牌号,
    姓名,
    当前阶段,
    关系公开级,
    已完成结局:
      结局ID === '双重继承'
        ? '公寓交接已完成'
        : 结局ID === '借种'
          ? 关系公开级 === '家庭结构已公开'
            ? '家庭结构已公开'
            : '关系已稳定'
          : 结局ID,
    群内允许事实,
    群聊口吻变化: 后效.已开启
      ? `${后效.姐妹群态度 || '关系已经稳定，不得失忆后重新试探真假；可以直接争取时间、陪伴和现实安排，但仍保持本人性格。'}${
          后效.姐妹群长期话题.length ? `长期话题可轮换：${后效.姐妹群长期话题.join('、')}。` : ''
        }`
      : 当前阶段 >= 5
        ? '可以明显表现归属、占有或吃醋，但未摊牌内容仍留有本人边界。'
        : '继续服从当前阶段，不提前进入结局后的笃定口吻。',
    私聊口吻变化: 后效.已开启
      ? `${后效.玩家私聊纪律 || '可以直接承接已经成立的关系和共同生活，不再退回结局前的反复试探。'}${
          后效.主动私聊主题.length ? `可轮换生活方向：${后效.主动私聊主题.join('、')}。` : ''
        }`
      : '继续服从当前阶段与本人真实私聊记忆。',
    公开称呼纪律: '公开朋友圈只可使用玩家姓名、管理员或社会上可解释的普通称呼。',
    群内称呼纪律: '可使用真实在群里出现过、由玩家姓名自然衍生且符合本人性格的昵称；不得凭空统一叫主人或老公。',
    私聊称呼纪律: 后效.已开启
      ? 门牌号 === '201'
        ? '称呼沿用本人实际使用过的名字，以已经记录的继续、暂不承诺或退出选择为准。'
        : '可使用本人已经建立的亲密称呼，但必须符合本人性格，不能复制其他角色的称呼。'
      : '只使用玩家姓名、管理员或当前关系已经自然形成的昵称。',
  };
}

const 双重继承余波永久隐私 =
  /(?:机场视频|机场.*视频|视频通话|镜头下|镜头外|镜头死角|手机画面|成人动作|口交|肛交|乳交|性交|射精|精液|裸体|裸照)|(?:父亲|爸爸|他爸).{0,28}(?:知情|知道|看穿|发现|默许|成全|故意|装作不知道)|(?:知情|知道|看穿|发现|默许|成全).{0,28}(?:父亲|爸爸|他爸)/iu;

const 借种家庭精确事实 =
  /(?:借种|生物学父亲|孩子(?:的)?父亲.{0,16}(?:管理员|玩家)|(?:丈夫|陆嘉明).{0,18}(?:知情|知道|同意|接受|商量好|安排好)|(?:三人|我们三个).{0,12}(?:家庭|关系|一家人)|家庭安排.{0,18}(?:丈夫|陆嘉明|三人))/iu;

const 母亲共居公开关系泄漏 =
  /(?:母亲|妈妈|妈|我).{0,16}(?:和|跟|与).{0,12}(?:儿子|管理员|玩家|他).{0,16}(?:恋人|爱人|伴侣|夫妻|情人|在一起|同床|共枕|不是普通母子|不只是母子)|(?:儿子|管理员|玩家|他).{0,16}(?:是我(?:的)?男人|叫我老婆|把我当女人|与我同床|跟我共枕)|(?:我们|两个人).{0,16}(?:秘密关系|隐秘关系|母子关系变了)/iu;

const 母亲共居私密永久禁区 =
  /(?:机场.{0,12}(?:视频|通话|镜头)|(?:视频|通话|镜头).{0,12}机场|三日早餐|八区(?:检查|验收)|总钥匙.{0,12}(?:归位|挂钩)|(?:父亲|爸爸|他爸).{0,28}(?:知情|知道|看穿|发现|默许|成全|故意|装作不知道)|(?:知情|知道|看穿|发现|默许|成全).{0,28}(?:父亲|爸爸|他爸))/iu;

/**
 * 302结局后的手机内容分两层验收：私密层可以承认稳定关系，公开朋友圈仍需社会可解释；
 * 两层都不能让父亲知情，也不能把机场视频等已封存终幕重新带回手机日常。
 */
export function 验收母亲共居手机内容(消息: string, 场景: '公开朋友圈' | '私密'): boolean {
  const 文 = String(消息 ?? '').normalize('NFKC').trim();
  if (!文 || 母亲共居私密永久禁区.test(文)) return false;
  if (场景 === '私密') return true;
  return !双重继承余波永久隐私.test(文) && !母亲共居公开关系泄漏.test(文);
}

/**
 * 候选写入前只消费“候选生成之前”的画像。调用方不得把本次候选先塞进消息证据再验收，
 * 从而保证泄漏文本无法反向成为自己的公开证据。
 */
export function 验收双重继承余波公开事实(
  消息: string,
  画像: readonly 结局社交画像[],
): boolean {
  const 文 = String(消息 ?? '').normalize('NFKC').trim();
  if (!文 || 双重继承余波永久隐私.test(文)) return false;
  const 借种家庭已公开 = 画像.some(item => item.门牌 === '101' && item.关系公开级 === '家庭结构已公开');
  return 借种家庭已公开 || !借种家庭精确事实.test(文);
}

export function 结局期姐妹群纪律(
  data: SchemaType,
  画像: readonly 结局社交画像[],
): string {
  if (!双重继承结局已成立(data) && !画像.some(item => item.已完成结局)) {
    return '群内仍以心照不宣、拌嘴和试探为主；没有真实公开的关系不得由其他人代为说破。';
  }
  const 长期方向 = 画像
    .map(item => 角色结局后姐妹群长期方向(data, item.门牌))
    .filter(Boolean);
  return (
    '各成员按自身关系阶段回应。实际收到过公开说明的人不应失忆后重新震惊；尚未收到的人从本轮实际听到的内容继续了解；' +
    '对“保持边界／心知肚明／仅结局稳定”的角色仍不得强行公开。话题重点从猜测关系真假转为时间、陪伴、邀约、聚餐、承诺兑现、边界、分歧与和解；丈夫态度只在脚本稳定键已经公开时才能承接。' +
    `${长期方向.length ? `长期话题与态度差分：${长期方向.join('；')}` : ''}` +
    '丈夫私下决定、录像内容、外遇证据和未公开手续不能自动带进姐妹群。' +
    '争风吃醋仍可存在，但不要每轮排班、比色情或重复宣布所有人属于管理员。母亲不参加普通雌竞，也不是每轮必发言的纪律委员。'
  );
}

export function 结局期公开朋友圈纪律(data: SchemaType, 门牌号: 门牌): string {
  const 本人 = 构建结局社交画像(data, 门牌号);
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  if (!双重继承结局已成立(data) && !后效.已开启) return '';
  const 母亲交接层 = 双重继承结局已成立(data)
    ? '管理员已经正式接管公寓，但公开动态仍是社会可见层；姐妹群知情不等于朋友圈可以公开真实关系，机场视频隐秘现场绝不能出现。'
    : '';
  return `【结局后公开朋友圈】${母亲交接层}${后效.公开朋友圈纪律}${本人.公开称呼纪律}`;
}

export function 结局期私密手机纪律(data: SchemaType, 门牌号: 门牌): string {
  const 本人 = 构建结局社交画像(data, 门牌号);
  const 后效 = 构建角色结局后生活社交语义(data, 门牌号);
  if (!后效.已开启) return '';
  return `【当前私人关系】以本人已经成立的关系及已保存选择为准。${本人.私聊口吻变化}${后效.私密朋友圈纪律}${本人.私聊称呼纪律}`;
}
