/**
 * 把当前时间线的可见投影改动合回原始记录库。
 *
 * 旧投影必须直接来自原始数组的 filter（保留对象引用）。这样可以只删除当前投影里
 * 明确被压缩掉的记录、只追加本次新增记录，同时把其他分支、未来楼或刷新期间暂时
 * 失配的原始记录原样留在库中。物理裁枝只由明确 swipe／删楼／回档事务负责。
 */
export function 合并手机记录投影<T extends object>(
  原始记录: readonly T[],
  旧投影: readonly T[],
  新投影: readonly T[],
  新增位置: '前' | '后' = '后',
): T[] {
  const 旧投影集合 = new Set(旧投影);
  const 新投影集合 = new Set(新投影);
  const 新增记录 = 新投影.filter(记录 => !旧投影集合.has(记录));
  const 保留原始 = 原始记录.filter(记录 => !旧投影集合.has(记录) || 新投影集合.has(记录));
  return 新增位置 === '前' ? [...新增记录, ...保留原始] : [...保留原始, ...新增记录];
}
