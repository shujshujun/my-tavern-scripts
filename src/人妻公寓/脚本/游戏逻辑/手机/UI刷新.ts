/**
 * 手机 UI 刷新注册表（拆分方案 P3）：手机壳渲染与红点的真实实现只由内核持有，
 * 数据层/业务层不得反向 import 内核。本模块零依赖、无环——只保存两个函数引用，
 * 未注册时请求安全 no-op；内核模块初始化完成时经 `注册手机UI刷新实现` 安装实现。
 */

type 手机重绘实现 = () => void;
type 手机红点实现 = () => void;

let 已注册重绘: 手机重绘实现 | null = null;
let 已注册红点: 手机红点实现 | null = null;

/** 由内核在模块初始化完成时安装真实实现（渲染 与 刷新红点）。 */
export function 注册手机UI刷新实现(重绘: 手机重绘实现, 刷新红点: 手机红点实现): void {
  已注册重绘 = 重绘;
  已注册红点 = 刷新红点;
}

/** 请求手机壳重绘；未注册时安全 no-op。 */
export function 请求手机重绘(): void {
  已注册重绘?.();
}

/** 请求刷新手机红点；未注册时安全 no-op。 */
export function 请求刷新手机红点(): void {
  已注册红点?.();
}
