function 最近本人私聊(消息们: readonly 微信消息[], 门牌号: 门牌, 姓名: string): string[] {
  return 消息们
    .filter(消息 => 消息.会话 === 门牌号 && 消息.类 !== '撤回')
    .slice(-6)
    .map(消息 => `${消息.发 === '我' ? 玩家名() : 姓名}:${消息.文}`);
}

function 孕产硬事实(
  data: SchemaType,
  凭据: 生产通知凭据,
  事件主题: string,
  节点类型?: 住院微信节点类型,
  获知生产路径覆盖?: '姐妹群' | '私聊',
) {
  const 快照 = 读取生产事件快照(data, 凭据);
  if (!快照) return null;
  const 孩子 = 快照.孩子;
  const 事件数据 = 构建孕产事件数据(
    data,
    凭据.门牌,
    事件主题 === '到达预产并通知玩家'
      ? '预产'
      : 事件主题 === '发送产后母婴合照'
        ? '母婴合照'
        : 节点类型
          ? '住院'
          : '生产',
  );
  事件数据.胎次 = 凭据.胎次 as 1 | 2 | 3;
  事件数据.受孕场次标识 = 凭据.场次标识;
  事件数据.家庭计划知情 = 快照.家庭计划知情;
  const { 受孕场次标识: _内部场次, ...孕产 } = 事件数据;
  return {
    事件主题,
    孕产,
    生产事实: {
      本胎序号: 凭据.胎次,
      生产结果: 快照.结果,
      玩家产前看望: 快照.产前看望,
      玩家选择陪产: 快照.陪产已选择,
      获知生产路径: 获知生产路径覆盖 ?? 快照.获知生产路径,
      实际生产绝对时段: 快照.实际生产绝对时段,
      住院结束绝对时段: 快照.住院结束绝对时段,
      住院节点: 节点类型 ?? '',
    },
    孩子事实: 孩子
      ? {
          胎次: 孩子.胎次,
          性别: 孩子.性别,
          年龄阶段: 孩子.年龄阶段,
          玩家产后看望: 孩子.玩家产后看望,
        }
      : null,
  };
}

async function 生成孕产私聊(
  data: SchemaType,
  凭据: 生产通知凭据,
  事件主题: string,
  消息们: readonly 微信消息[],
  验收: (文: string) => boolean,
  节点类型?: 住院微信节点类型,
  获知生产路径覆盖?: '姐妹群' | '私聊',
): Promise<string> {
  const 姓名 = 户静态表[凭据.门牌].妻名;
  const 事件数据 = 孕产硬事实(data, 凭据, 事件主题, 节点类型, 获知生产路径覆盖);
  if (!事件数据) return '';
  const 最近私聊 = 最近本人私聊(消息们, 凭据.门牌, 姓名);
  const 原文 = await 小生成(
    '你替一款都市题材游戏生成一条孕产事件中的角色私聊。只输出母亲本人发送的微信正文，不写姓名、旁白、解释、引号或系统字段。' +
      '程序只提供事件主题、硬事实、角色阶段、性格、好感、堕落、婚姻、情绪、心理、胎次、既有孩子与玩家在场情况；你必须根据整份数据自行演绎，不能按头胎、二胎、三胎套固定反应。' +
      '必须表达事件主题要求的硬事实，不得改变胎次、孩子性别、生产结果、在场情况、关系或玩家行为，也不得声称玩家已经回复或作出新承诺。',
    `事件数据:\n${JSON.stringify(事件数据)}${最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''}`,
  );
  const 文 = await 微信短文本(原文, 手机可见单条硬上限, `${姓名}的${事件主题}微信`, [姓名]);
  return 文 && 验收(文) ? 文 : '';
}

async function 生成家庭计划邀请(data: SchemaType, 消息们: readonly 微信消息[]): Promise<string> {
  const 门牌号: 门牌 = '101';
  const 配 = 户静态表[门牌号];
  const 户 = data.户[门牌号];
  if (!户) return '';
  const 事件数据 = {
    事件主题: '家庭计划邀请微信',
    发信角色: 构建孕产角色数据(data, 门牌号, 户.妻._怀孕.状态 === '已告知'),
    丈夫: { 姓名: 配.夫名, 疑心值: 户.夫.疑心值, 信任值: 户.夫.信任值 },
    路线事实: {
      当前阶段: data.系统._家庭计划.阶段,
      丈夫已经选定玩家为双方信任的生育帮助人选: true,
      丈夫希望玩家来101当面谈孩子和家庭计划: true,
      发信人是妻子本人: true,
    },
  };
  const 最近私聊 = 最近本人私聊(消息们, 门牌号, 配.妻名);
  const 原文 = await 小生成(
    '你替一款都市题材游戏生成夏乔发给管理员的一条家庭计划邀请微信。只输出夏乔本人发送的正文，不写姓名、旁白、解释、引号或系统字段。' +
      '程序只提供事件主题、路线硬事实、夫妻数据、角色性格、阶段、好感、堕落、婚姻、情绪、心理与真实聊天；根据整份数据自行决定语气，不使用固定模板。' +
      '必须让玩家知道是丈夫提出见面、地点为101、要当面谈孩子或家庭计划；不得改变人选、地点、发信人或声称见面已经发生。',
    `事件数据:\n${JSON.stringify(事件数据)}${最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''}`,
  );
  const 文 = await 微信短文本(原文, 手机可见单条硬上限, '夏乔的家庭计划邀请微信', [配.妻名]);
  return 文 && 验收家庭计划硬事实(文) ? 文 : '';
}

/**
 * 孕产和家庭计划软叙事统一走“事件主题 + 结构化数据 → AI 演绎”。生成失败不落消息键，
 * 硬生产时钟、孩子账、已读解锁与路线阶段照常由脚本管理，下一次手机节拍可继续重试。
 */
export async function 同步孕产与家庭计划AI微信(data: SchemaType): Promise<boolean> {
  const 楼 = 末楼();
  const 时 = 取绝对时段(data);
  const 时间线租约 = 创建手机时间线租约(当前聊天ID(), 楼, SillyTavern.chat ?? [], 时);
  if (!时间线租约) return false;
  const 时间线仍有效 = () => 手机时间线租约仍有效(时间线租约, 当前聊天ID(), SillyTavern.chat ?? [], 当前手机绝对时段());
  const 库 = 读库();
  const 已有键 = new Set(库.消息.flatMap(消息 => (消息.键 ? [消息.键] : [])));
  const 新消息: 微信消息[] = [];
  const 当前消息 = () => [...库.消息, ...新消息];
  const 可追加 = (消息: 微信消息): void => {
    if (消息.键 && 已有键.has(消息.键)) return;
    新消息.push(消息);
    if (消息.键) 已有键.add(消息.键);
  };

  for (const 凭据 of 列出待告知孕情(data)) {
    const 键 = 怀孕微信键(凭据.门牌, 凭据.场次标识);
    if (已有键.has(键)) continue;
    const 冻结值 = data.户[凭据.门牌]?.妻._怀孕.告知文案.trim() ?? '';
    const 资料 = 解析报孕生成资料(冻结值);
    if (!资料) continue;
    const { 受孕场次标识: _内部场次, ...演绎数据 } = 资料;
    const 最近私聊 = 最近本人私聊(当前消息(), 凭据.门牌, 资料.母亲.姓名);
    const 原文 = await 小生成(
      '你替都市题材游戏中的角色生成她确认怀孕后主动发给玩家的一条微信。只输出角色本人发送的消息正文，不写姓名、旁白、解释或引号。' +
        '程序只提供事实和数值，你必须根据角色性格、当前阶段、好感、堕落、婚姻、情绪、心理、胎次、既有孩子和风险自行演绎；不得按头胎、二胎、三胎套固定句式。' +
        '必须明确让玩家知道她怀孕以及这是第几胎，但不得暴露系统字段、数值或场次标识。不得声称玩家已经回复、承诺或采取行动，也不得改变父亲、关系或生产事实。',
      `事件主题:确认怀孕后私聊报孕\n到期时冻结的报孕数据:\n${JSON.stringify(演绎数据)}${
        最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''
      }`,
    );
    if (!时间线仍有效()) return false;
    const 文 = await 微信短文本(原文, 手机可见单条硬上限, `${资料.母亲.姓名}的报孕微信`, [资料.母亲.姓名]);
    if (文 && 验收报孕硬事实(文, 资料.胎次)) 可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键 });
  }

  for (const 凭据 of 列出预产通知(data)) {
    const 键 = 预产微信键(凭据);
    if (已有键.has(键)) continue;
    const 生产 = data.户[凭据.门牌].妻._生产;
    const 孩子 = data.系统._家庭文档.孩子.find(项 => 项.id === 生产.生产结算标识);
    // 玩家可能一次跨过自动生产时点：仍用原预产键承担已读解锁，但生成内容必须承认当前已经生产，不能补发过时待产台词。
    const 已经生产 = 生产.状态 === '住院中';
    const 文 = await 生成孕产私聊(
      data,
      凭据,
      已经生产 ? '补发入院与已经生产的当前通知' : '到达预产并通知玩家',
      当前消息(),
      已经生产 ? 行 => /医院/u.test(行) && 验收生产硬事实(行, 孩子?.性别) : 验收预产硬事实,
    );
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键 });
  }

  for (const 凭据 of 列出产后通知(data)) {
    const 快照 = 读取生产事件快照(data, 凭据);
    if (!快照?.孩子) continue;
    const 由姐妹群承接 = 生产姐妹群前置已满足(data, 当前消息(), 凭据);
    const 生产群已落库 = 生产姐妹群已触发(当前消息(), 凭据.门牌, 凭据.胎次, 凭据.场次标识);
    const 获知键 = 产后微信键(凭据, '获知');
    // 已有真实孕情群历史时，完整的 5~8 句生产群专场由节拍引擎承接；这里不再抢先
    // 写一条随机成员报信，避免同一生产在同拍重复曝光。没有群前置才走必达私聊。
    if (快照.结果 !== '陪产' && !已有键.has(获知键) && !由姐妹群承接) {
      const 文 = await 生成孕产私聊(
        data,
        凭据,
        '生产完成并让玩家获知',
        当前消息(),
        候选 => 验收生产硬事实(候选, 快照.孩子?.性别),
        undefined,
        '私聊',
      );
      if (!时间线仍有效()) return false;
      if (文) 可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键: 获知键 });
    }

    const 合照键 = 产后微信键(凭据, '合照');
    if (!已有键.has(合照键)) {
      const 文 = await 生成孕产私聊(
        data,
        凭据,
        '发送产后母婴合照',
        当前消息(),
        候选 => 验收合照硬事实(候选, 快照.结果),
        undefined,
        生产群已落库 ? '姐妹群' : '私聊',
      );
      if (!时间线仍有效()) return false;
      if (文) {
        可追加({
          楼,
          时,
          会话: 凭据.门牌,
          发: '对方',
          文,
          类: '照片',
          图: `@production/${微信母婴图片键(凭据.门牌, 凭据.胎次)}`,
          键: 合照键,
        });
      }
    }
  }

  const 住院主题: Record<住院微信节点类型, string> = {
    恢复: '住院恢复近况',
    近况: '住院带娃近况',
    出院预告: '准备出院的近况',
    出院: '已经出院的近况',
  };
  for (const 节点 of 列出住院微信节点(data)) {
    const 键 = 产后微信键(节点, 节点.类型);
    if (已有键.has(键)) continue;
    const 文 = await 生成孕产私聊(
      data,
      节点,
      住院主题[节点.类型],
      当前消息(),
      候选 => 验收住院硬事实(候选, 节点.类型),
      节点.类型,
      生产姐妹群已触发(当前消息(), 节点.门牌, 节点.胎次, 节点.场次标识) ? '姐妹群' : '私聊',
    );
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时: Math.min(时, 节点.节点绝对时段), 会话: 节点.门牌, 发: '对方', 文, 类: '文本', 键 });
  }

  if (data.系统._家庭计划.阶段 === '待微信' && !已有键.has(家庭计划微信事件键)) {
    const 文 = await 生成家庭计划邀请(data, 当前消息());
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时, 会话: '101', 发: '对方', 文, 类: '文本', 键: 家庭计划微信事件键 });
  }

  if (!新消息.length || !时间线仍有效()) return false;
  const 已写 = await 写库增量({ 新圈: [], 新消息, 节拍改: {} }, 时间线仍有效);
  if (已写) {
    请求刷新手机红点();
    请求手机重绘();
  }
  return 已写;
}

/** 兼容旧调用名；新版同时同步同一条孕产/家庭计划叙事链。 */
export async function 同步孕情AI微信(data: SchemaType): Promise<boolean> {
  return 同步孕产与家庭计划AI微信(data);
}
