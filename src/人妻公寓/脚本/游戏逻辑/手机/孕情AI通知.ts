/**
 * 孕产和家庭计划软叙事统一走“事件主题 + 结构化数据 → AI 演绎”。生成失败不落消息键，
 * 硬生产时钟、孩子账、已读解锁与路线阶段照常由脚本管理，下一次手机节拍可继续重试。
 */
export async function 同步孕产与家庭计划AI微信(data: SchemaType): Promise<boolean> {
  const 楼 = 末楼();
  const 时 = 取绝对时段(data);
  const 时间线租约 = 创建手机时间线租约(当前聊天ID(), 楼, SillyTavern.chat ?? [], 时);
  if (!时间线租约) return false;
  const 时间线仍有效 = () => 手机时间线租约仍有效(时间线租约, 当前聊天ID(), SillyTavern.chat ?? [], 当前手机绝对时段());
  const 库 = 读库();
  const 已有键 = new Set(库.消息.flatMap(消息 => (消息.键 ? [消息.键] : [])));
  const 新消息: 微信消息[] = [];
  const 新圈: 朋友圈条[] = [];
  const 当前消息 = () => [...库.消息, ...新消息];
  const 可追加 = (消息: 微信消息): void => {
    if (消息.键 && 已有键.has(消息.键)) return;
    新消息.push(消息);
    if (消息.键) 已有键.add(消息.键);
  };

  for (const 凭据 of 列出待告知孕情(data)) {
    const 键 = 怀孕微信键(凭据.门牌, 凭据.场次标识);
    if (已有键.has(键)) continue;
    const 冻结值 = data.户[凭据.门牌]?.妻._怀孕.告知文案.trim() ?? '';
    const 资料 = 解析报孕生成资料(冻结值);
    if (!资料) continue;
    const { 受孕场次标识: _内部场次, ...演绎数据 } = 资料;
    const 最近私聊 = 最近本人私聊(当前消息(), 凭据.门牌, 资料.母亲.姓名);
    const 借种来源 = 凭据.门牌 === '101' && 是借种受孕场次(凭据.场次标识);
    const 原文 = await 小生成(
      借种来源
        ? '你替都市题材游戏中的夏乔生成一条发给管理员的微信。只输出夏乔本人发送的正文，不写姓名、旁白、解释或引号。' +
          '她已经拿到一个与此前家庭计划有关的确定检测结果，但这条消息只能邀请玩家亲自来101看，不能直接说怀孕、阳性、两条杠、孩子父亲或结果内容。' +
          '必须明确地点是101，并让玩家知道她有一样东西或一个结果要当面给他看；不得声称玩家已经回复、到达或作出承诺。'
        : '你替都市题材游戏中的角色生成她确认怀孕后主动发给玩家的一条微信。只输出角色本人发送的消息正文，不写姓名、旁白、解释或引号。' +
          '程序只提供事实和数值，你必须根据角色性格、当前阶段、好感、堕落、婚姻、情绪、心理、胎次、既有孩子和风险自行演绎；不得按头胎、二胎、三胎套固定句式。' +
          '必须明确让玩家知道她怀孕以及这是第几胎，但不得暴露系统字段、数值或场次标识。不得声称玩家已经回复、承诺或采取行动，也不得改变父亲、关系或生产事实。',
      `${借种来源 ? '事件主题:邀请玩家来101当面查看检测结果（消息中不得公开结果）' : '事件主题:确认怀孕后私聊报孕'}\n到期时冻结的报孕数据:\n${JSON.stringify(演绎数据)}${
        最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''
      }`,
    );
    if (!时间线仍有效()) return false;
    const 文 = await 微信短文本(原文, 手机可见单条硬上限, `${资料.母亲.姓名}的报孕微信`, [资料.母亲.姓名]);
    if (文 && (借种来源 ? 验收借种阳性邀约(文) : 验收报孕硬事实(文, 资料.胎次))) {
      可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键 });
    }
  }

  const 借种三人照场次 = 列出借种三人合照已拍场次(data);
  for (const 场次标识 of 借种三人照场次) {
    const 合照键 = 借种三人合照私聊键(场次标识);
    if (已有键.has(合照键)) continue;
    const 最近私聊 = 最近本人私聊(当前消息(), '101', 户静态表['101'].妻名);
    const 原文 = await 小生成(
      '你替夏乔生成一条发给管理员的微信照片消息文案。只输出夏乔本人发送的正文，不写姓名、旁白、解释或引号。' +
        '硬事实：她此前在101与丈夫陆嘉明、管理员三个人一起确认了借种结局带来的阳性结果，并由玩家亲手拍下三人合照；陆嘉明完全知情且接受，管理员是本胎生物学父亲。' +
        '这条消息可能因生成失败而延迟到孕期、产后甚至下一胎才补发，所以只说“这张照片”或“那天拍的照片”，不得写成刚刚发生。正文必须自然告诉管理员这是他们三个人的照片，不得复述系统、数值、场次标识或声称玩家已经回复。',
      `稳定照片事实:\n${JSON.stringify({ 场次标识, 三人合照已实拍: true, 陆嘉明知情: true })}\n夏乔当前角色数据:\n${JSON.stringify(
        构建孕产角色数据(data, '101', data.户['101']?.妻._怀孕.状态 === '已告知'),
      )}${最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''}`,
    );
    if (!时间线仍有效()) return false;
    const 文 = await 微信短文本(原文, 手机可见单条硬上限, '夏乔的借种三人合照私聊', [户静态表['101'].妻名]);
    if (文 && 验收借种三人合照私聊(文)) {
      可追加({
        楼,
        时,
        会话: '101',
        发: '对方',
        文,
        类: '照片',
        图: '@ending/夏乔借种/借种_三人镜面合照',
        键: 合照键,
      });
    }
  }

  const 公开裁切场次 = 借种三人照场次.find(场次标识 => 借种朋友圈选择状态(data, 场次标识) === '发布');
  const 已有安全动态 = 库.圈.some(动态 => 动态.谁 === 户静态表['101'].妻名 && 动态.图 === 借种朋友圈安全图);
  if (公开裁切场次 && !已有安全动态) {
    const 原文 = await 小生成(
      '你替夏乔生成一条公开朋友圈文案。只输出正文，不写姓名、旁白、解释、引号或图片说明。' +
        '配图是101家庭计划板一角、便签与生活用品的安全裁切，不含完整三人合照、检测结果、玩家身份或孩子父亲信息。' +
        '文案可以表达认真准备未来、把日子过好或家庭生活的新计划，但不得说怀孕、阳性、借种、生物学父亲、管理员或三人关系，也不得暗示公开完整原图。',
      `夏乔当前角色数据:\n${JSON.stringify(构建孕产角色数据(data, '101', false))}`,
    );
    if (!时间线仍有效()) return false;
    const 文 = await 微信短文本(原文, 手机可见单条硬上限, '夏乔的借种结局安全朋友圈', [户静态表['101'].妻名]);
    if (文 && 验收借种安全朋友圈(文)) {
      新圈.push({
        楼,
        时,
        谁: 户静态表['101'].妻名,
        文,
        评: [],
        图: 借种朋友圈安全图,
        长期记忆: {
          事件键: 构造朋友圈长期记忆事件键('家庭计划公开', '101', 公开裁切场次),
          事件: '夏乔公开发布家庭计划板的安全裁切动态',
          结果: '她公开表达正在认真筹划家庭未来，但仍隐去私密关系与检测结果',
        },
      });
    }
  }

  for (const 凭据 of 列出预产通知(data)) {
    const 键 = 预产微信键(凭据);
    if (已有键.has(键)) continue;
    const 生产 = data.户[凭据.门牌].妻._生产;
    const 孩子 = data.系统._家庭文档.孩子.find(项 => 项.id === 生产.生产结算标识);
    // 玩家可能一次跨过自动生产时点：仍用原预产键承担已读解锁，但生成内容必须承认当前已经生产，不能补发过时待产台词。
    const 已经生产 = 生产.状态 === '住院中';
    const 文 = await 生成孕产私聊(
      data,
      凭据,
      已经生产 ? '补发入院与已经生产的当前通知' : '到达预产并通知玩家',
      当前消息(),
      已经生产 ? 行 => /医院/u.test(行) && 验收生产硬事实(行, 孩子?.性别) : 验收预产硬事实,
    );
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键 });
  }

  for (const 凭据 of 列出产后通知(data)) {
    const 快照 = 读取生产事件快照(data, 凭据);
    if (!快照?.孩子) continue;
    const 由姐妹群承接 = 生产姐妹群前置已满足(data, 当前消息(), 凭据);
    const 生产群已落库 = 生产姐妹群已触发(当前消息(), 凭据.门牌, 凭据.胎次, 凭据.场次标识);
    const 获知键 = 产后微信键(凭据, '获知');
    // 已有真实孕情群历史时，完整的 5~8 句生产群专场由节拍引擎承接；这里不再抢先
    // 写一条随机成员报信，避免同一生产在同拍重复曝光。没有群前置才走必达私聊。
    if (快照.结果 !== '陪产' && !已有键.has(获知键) && !由姐妹群承接) {
      const 文 = await 生成孕产私聊(
        data,
        凭据,
        '生产完成并让玩家获知',
        当前消息(),
        候选 => 验收生产硬事实(候选, 快照.孩子?.性别),
        undefined,
        '私聊',
      );
      if (!时间线仍有效()) return false;
      if (文) 可追加({ 楼, 时, 会话: 凭据.门牌, 发: '对方', 文, 类: '文本', 键: 获知键 });
    }

    const 合照键 = 产后微信键(凭据, '合照');
    const 借种产后来源 = 凭据.门牌 === '101' && 是借种受孕场次(凭据.场次标识);
    const 照片硬事实已成立 =
      !借种产后来源 || 借种产后家庭合照已拍(data, 凭据.场次标识, 凭据.胎次);
    if (!已有键.has(合照键) && 照片硬事实已成立) {
      const 文 = await 生成孕产私聊(
        data,
        凭据,
        借种产后来源 ? '发送借种产后四人家庭合照' : '发送产后母婴合照',
        当前消息(),
        候选 =>
          借种产后来源 ? 验收借种产后家庭合照私聊(候选) : 验收合照硬事实(候选, 快照.结果),
        undefined,
        生产群已落库 ? '姐妹群' : '私聊',
      );
      if (!时间线仍有效()) return false;
      if (文) {
        可追加({
          楼,
          时,
          会话: 凭据.门牌,
          发: '对方',
          文,
          类: '照片',
          图: 借种产后来源
            ? '@ending/夏乔借种/借种_产后家庭合照'
            : `@production/${微信母婴图片键(凭据.门牌, 凭据.胎次)}`,
          键: 合照键,
        });
      }
    }
  }

  const 住院主题: Record<住院微信节点类型, string> = {
    恢复: '住院恢复近况',
    近况: '住院带娃近况',
    出院预告: '准备出院的近况',
    出院: '已经出院的近况',
  };
  for (const 节点 of 列出住院微信节点(data)) {
    const 键 = 产后微信键(节点, 节点.类型);
    if (已有键.has(键)) continue;
    const 文 = await 生成孕产私聊(
      data,
      节点,
      住院主题[节点.类型],
      当前消息(),
      候选 => 验收住院硬事实(候选, 节点.类型),
      节点.类型,
      生产姐妹群已触发(当前消息(), 节点.门牌, 节点.胎次, 节点.场次标识) ? '姐妹群' : '私聊',
    );
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时: Math.min(时, 节点.节点绝对时段), 会话: 节点.门牌, 发: '对方', 文, 类: '文本', 键 });
  }

  if (data.系统._家庭计划.阶段 === '待微信' && !已有键.has(家庭计划微信事件键)) {
    const 文 = await 生成家庭计划邀请(data, 当前消息());
    if (!时间线仍有效()) return false;
    if (文) 可追加({ 楼, 时, 会话: '101', 发: '对方', 文, 类: '文本', 键: 家庭计划微信事件键 });
  }

  if ((!新消息.length && !新圈.length) || !时间线仍有效()) return false;
  const 已写 = await 写库增量({ 新圈, 新消息, 节拍改: {} }, 时间线仍有效);
  if (已写) {
    请求刷新手机红点();
    请求手机重绘();
    await 立即持久保存手机聊天变量(时间线租约.聊天标识);
    排队同步朋友圈长期记忆(新圈, 时间线仍有效);
  }
  return 已写;
}

