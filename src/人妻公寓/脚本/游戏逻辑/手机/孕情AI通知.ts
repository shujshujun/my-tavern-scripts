function 借种三人合照私聊键(场次标识: string): string {
  return `借种:三人合照:私聊:${场次标识}`;
}

function 验收借种三人合照私聊(文: string): boolean {
  return /照片|合照|拍了一张/u.test(文) && /我们|三个|三个人|嘉明|老公/u.test(文);
}

function 验收借种产后家庭合照私聊(文: string): boolean {
  return /照片|合照|拍了/u.test(文) && /孩子|宝宝|儿子|女儿/u.test(文) && /嘉明|老公|四个|四个人|一家/u.test(文);
}

const 借种朋友圈安全图 = '@ending/夏乔借种/101_借种结局计划板';
function 验收借种安全朋友圈(文: string): boolean {
  return (
    /家|日子|生活|计划|准备|以后/u.test(文) &&
    !/怀孕|阳性|两条杠|借种|生物学|父亲|孩子是谁的|管理员|三个人|三人合照/u.test(文)
  );
}

function 验收借种阳性邀约(文: string): boolean {
  return (
    /101/u.test(文) &&
    /来|过来|回来|见面/u.test(文) &&
    /看|东西|结果|给你看/u.test(文) &&
    !/怀孕|有了|阳性|两条杠|当爸爸|当父亲/u.test(文)
  );
}

function 最近本人私聊(消息们: readonly 微信消息[], 门牌号: 门牌, 姓名: string): string[] {
  return 消息们
    .filter(消息 => 消息.会话 === 门牌号 && 消息.类 !== '撤回')
    .slice(-6)
    .map(消息 => `${消息.发 === '我' ? 玩家名() : 姓名}:${消息.文}`);
}

function 孕产硬事实(
  data: SchemaType,
  凭据: 生产通知凭据,
  事件主题: string,
  节点类型?: 住院微信节点类型,
  获知生产路径覆盖?: '姐妹群' | '私聊',
) {
  const 快照 = 读取生产事件快照(data, 凭据);
  if (!快照) return null;
  const 孩子 = 快照.孩子;
  const 事件数据 = 构建孕产事件数据(
    data,
    凭据.门牌,
    事件主题 === '到达预产并通知玩家'
      ? '预产'
      : 事件主题 === '发送产后母婴合照'
        ? '母婴合照'
        : 节点类型
          ? '住院'
          : '生产',
  );
  事件数据.胎次 = 凭据.胎次 as 1 | 2 | 3;
  事件数据.受孕场次标识 = 凭据.场次标识;
  事件数据.家庭计划知情 = 快照.家庭计划知情;
  事件数据.借种结局来源 =
    凭据.门牌 === '101' &&
    夏乔家庭计划后果有效(data, {
      场次标识: 凭据.场次标识,
      家庭计划知情: 快照.家庭计划知情,
      胎次: 凭据.胎次,
    });
  const { 受孕场次标识: _内部场次, ...孕产 } = 事件数据;
  return {
    事件主题,
    孕产,
    生产事实: {
      本胎序号: 凭据.胎次,
      生产结果: 快照.结果,
      玩家产前看望: 快照.产前看望,
      玩家选择陪产: 快照.陪产已选择,
      获知生产路径: 获知生产路径覆盖 ?? 快照.获知生产路径,
      实际生产绝对时段: 快照.实际生产绝对时段,
      住院结束绝对时段: 快照.住院结束绝对时段,
      住院节点: 节点类型 ?? '',
    },
    孩子事实: 孩子
      ? {
          胎次: 孩子.胎次,
          性别: 孩子.性别,
          年龄阶段: 孩子.年龄阶段,
          玩家产后看望: 孩子.玩家产后看望,
        }
      : null,
  };
}

async function 生成孕产私聊(
  data: SchemaType,
  凭据: 生产通知凭据,
  事件主题: string,
  消息们: readonly 微信消息[],
  验收: (文: string) => boolean,
  节点类型?: 住院微信节点类型,
  获知生产路径覆盖?: '姐妹群' | '私聊',
): Promise<string> {
  const 姓名 = 户静态表[凭据.门牌].妻名;
  const 事件数据 = 孕产硬事实(data, 凭据, 事件主题, 节点类型, 获知生产路径覆盖);
  if (!事件数据) return '';
  const 最近私聊 = 最近本人私聊(消息们, 凭据.门牌, 姓名);
  const 原文 = await 小生成(
    '你替一款都市题材游戏生成一条孕产事件中的角色私聊。只输出母亲本人发送的微信正文，不写姓名、旁白、解释、引号或系统字段。' +
      '程序只提供事件主题、硬事实、角色阶段、性格、好感、堕落、婚姻、情绪、心理、胎次、既有孩子与玩家在场情况；你必须根据整份数据自行演绎，不能按头胎、二胎、三胎套固定反应。' +
      '必须表达事件主题要求的硬事实，不得改变胎次、孩子性别、生产结果、在场情况、关系或玩家行为，也不得声称玩家已经回复或作出新承诺。' +
      (事件数据.孕产.借种结局来源
        ? '这是夏乔借种结局来源的本胎：陆嘉明始终知情并承担丈夫与社会父亲位置，管理员是明确的生物学父亲。住院、生产、合照和出院内容都必须承接三人关系，不得写成偷情曝光、丈夫受骗、父亲未知或普通质问。'
        : ''),
    `事件数据:\n${JSON.stringify(事件数据)}${最近私聊.length ? `\n最近本人私聊:\n${最近私聊.join('\n')}` : ''}`,
  );
  const 文 = await 微信短文本(原文, 手机可见单条硬上限, `${姓名}的${事件主题}微信`, [姓名]);
  return 文 && 验收(文) ? 文 : '';
}

