/**
 * 原生正文租约（纯状态机，无宿主依赖）。
 *
 * 语义：酒馆原生正文（玩家经原生输入框发起的 normal 正文）从“读取旧状态 → 注入公寓快照 →
 * 生成助手楼 → MVU 变量结算”是一个完整事务。本模块用“请求身份 + 精确聊天/时间线/楼层引用”
 * 的租约持有该事务，替代旧的无所有者布尔 `_isInAiCycle`。
 *
 * 旧布尔锁根因（BUG 语义排查协议·核心五问）：旧 `_isInAiCycle` 的真实用途不是“只要有任意
 * AI 请求就锁游戏”，而是保护原生正文事务不被时间推进/撤销中途改写。但任意
 * `CHAT_COMPLETION_PROMPT_READY` 都会把它设真；而后台 generateRaw、数据库插件主 API 路由等
 * 辅助生成同样触发该事件，却不建立游戏正文助手楼、也不会触发本卡期待的 MVU 正文结算。
 * 请求失败或静默结束后布尔锁无人释放，小憩/时间动作被误锁。现在只有“宿主 GENERATION_STARTED
 * 登记过的原生开始票”才能在 PROMPT_READY 认领正文租约，并只由匹配的
 * GENERATION_STOPPED / GENERATION_ENDED / VARIABLE_UPDATE_ENDED 精确释放。
 *
 * Owner 语义（2026-08-09 复审）：
 * 1. 开始票序号即租约 owner，不可复用。认领返回 owner；正常释放/失败释放必须携带并核对
 *    owner，旧 owner 对新票释放返回 false 且绝不清新票；停止/切聊天/切分支/删楼等宿主级
 *    作废走明确的全局作废入口 作废原生正文租约()。
 * 2. 认领必须核对票序号（防“读票→认领”之间票被替换）、阶段（等待 prompt）、聊天、时间线、
 *    用户楼层与用户消息对象引用；任一不符即拒绝（返回 null）且不改变当前代数。
 * 3. 同轮在途异步身份用 租约owner仍有效 校验：owner 仍是当前租约持有者，且聊天/时间线/
 *    用户楼层/用户消息引用仍与当前一致。
 *
 * 共享生成槽（rq0.75 生成通道互斥）：
 * 4. 登记开始票时同步尝试取得共享前台生成租约；前台/手机在途导致取得失败时返回 null、
 *    不建票（被拒请求绝不留下无租约的可认领票）。取得成功后共享前台 token 与票同生命周期：
 *    匹配 owner 的 释放正文租约、全局 作废原生正文租约、热 重置原生正文租约 都幂等释放它；
 *    错误 owner 释放不得释放共享 token。
 * 5. 新登记替换旧票（等待或已认领）时，先把旧票持有的共享前台租约归还，再为这张新票
 *    同步重新取得；全部在同一 JS 栈内完成，不存在检查后的并发窗口。
 */

import { 取得前台生成租约, type 生成通道租约 } from './生成通道互斥';

export type 原生正文阶段 = '等待prompt' | '正文结算';

export interface 原生正文开始票 {
  /** 单调令牌/序号：每一张新开始票唯一，也是租约 owner */
  序号: number;
  /** 阶段：等待prompt（已登记）→ 正文结算（已认领，生成与 MVU 结算期间） */
  阶段: 原生正文阶段;
  /** 登记时的聊天 ID */
  聊天ID: string;
  /** 登记时的时间线切换世代 */
  时间线世代: number;
  /** 宿主 GENERATION_STARTED 的开始类型（如 'normal'） */
  开始类型: string;
  /** 认领时的用户楼层与消息对象引用 */
  用户楼层: number;
  用户消息引用: unknown;
  /** 预期助手楼层（= 用户楼层 + 1） */
  预期助手楼层: number;
}

/** 认领/校验租约时核对的原生正文身份：聊天、时间线、用户楼层与用户消息对象引用。 */
export interface 原生正文租约校验 {
  聊天ID: string;
  时间线世代: number;
  用户楼层: number;
  用户消息引用: unknown;
}

let _原生开始票序号 = 0;
let _原生本轮令牌 = 0;
let _原生开始票: 原生正文开始票 | null = null;
/** 登记开始票时同步取得的共享前台生成租约；随票释放/作废/重置幂等释放。 */
let _原生共享前台租约: 生成通道租约 | null = null;

function 释放共享前台租约(): void {
  if (_原生共享前台租约) {
    _原生共享前台租约.释放();
    _原生共享前台租约 = null;
  }
}

/** 当前是否有生效中的原生正文租约（阶段为正文结算）。 */
export function 正文租约生效中(): boolean {
  return _原生开始票?.阶段 === '正文结算';
}

export function 读原生正文开始票(): 原生正文开始票 | null {
  return _原生开始票;
}

/** 当前生效正文租约的 owner（= 当前开始票序号）；无票或未认领时为 null。 */
export function 读当前租约owner(): number | null {
  return _原生开始票?.阶段 === '正文结算' ? _原生开始票.序号 : null;
}

export function 读原生正文令牌(): number {
  return _原生本轮令牌;
}

/**
 * 等待 prompt 的开始票是否与宿主 GENERATION_ENDED(messageCount) 精确匹配。
 *
 * 语义：等待阶段的开始票尚未形成正文锁。宿主 release 的 GENERATION_ENDED 广播 chat.length；
 * 若请求在 prompt 到达前就结束，chat 仍只有 user 尾楼，chat.length 恰好等于预期助手楼层
 * （= 用户楼层 + 1）。因此只有“票仍是等待prompt、消息数是整数、且消息数 === 预期助手楼层”
 * 的结束事件，才能证明属于这张等待票自己。
 *
 * 旧结束事件（如 messageCount = 用户楼层）在新票登记但尚未认领的窗口到达时，不得作废新票：
 * 否则当前请求异常结束后，后来的辅助 PROMPT_READY 可能在同一 user 尾楼上认领陈旧票，重新
 * 制造时间误锁。消息数缺失、非整数或大于预期值同样不能证明属于本票，保守不清票。
 *
 * 调用方须先保留现有聊天/时间线/user 消息引用校验；本判据只负责“等待票 ↔ 结束事件”归属。
 */
export function 等待票匹配结束事件(票: 原生正文开始票 | null, 消息数: unknown): boolean {
  if (!票 || 票.阶段 !== '等待prompt') return false;
  if (!Number.isInteger(消息数)) return false;
  // 精确命中（本等待票自己正常结束：chat 停在 user 尾楼，messageCount === 预期助手楼层）。
  if (消息数 === 票.预期助手楼层) return true;
  // 保守收口（失败/预停止的精确归属）：prompt 阶段就失败或中断的原生 normal 生成，宿主
  // release 的 GENERATION_ENDED 携带 messageCount <= 用户尾楼（= 预期助手楼层 - 1），与上面的
  // 精确预期值不符。但这类结束同样证明“本等待票自己没有形成正文”（chat 仍停在 user 尾楼，
  // 没有预期的 assistant 楼，不可能再被任何 PROMPT_READY 认领消费）。此处把严格“=== 预期助手
  // 楼层”放宽为“< 预期助手楼层”的提前结束，配合调用方已校验的 chat/时间线/用户楼层/引用，
  // 按精确身份作废本票——否则前台令牌会随等待票永久残留，使之后所有走 安全操作 入口的界面
  // 点击被「内容正在生成」门长期拦截。约定：只有 消息数 < 预期助手楼层 且 消息数 >= 用户楼层
  // （即确为等待票自身的提前结束，而非越界 0/负数等无意义值）才视作本票的失败；越界值与
  // >= 预期助手楼层的旧/错结束事件一律不命中，避免误清合法新票或落到正文结算失败分支。
  return typeof 消息数 === 'number' && 消息数 >= 票.用户楼层 && 消息数 < 票.预期助手楼层;
}

/**
 * 宿主 GENERATION_STARTED 登记一张等待 prompt 的原生开始票，替换旧票。
 * 登记前同步尝试取得共享前台生成租约；前台/手机在途导致取得失败时返回 null、不建票。
 * 只有本卡确认支持的原生正文请求（normal 玩家正文）才会调用本函数；
 * dryRun、quiet、自动后台触发、固定 0 楼主回合与兼容广播都不允许登记。
 */
export function 登记原生正文开始票(参数: {
  聊天ID: string;
  时间线世代: number;
  开始类型: string;
  用户楼层: number;
  用户消息引用: unknown;
}): 原生正文开始票 | null {
  // 先归还旧票（等待或已认领）持有的共享前台租约，再为这张新票同步取得共享前台租约；
  // 取得失败（手机批次/其他前台在途）时返回 null，绝不留下无租约的可认领票。
  释放共享前台租约();
  const 租约 = 取得前台生成租约();
  if (!租约) return null;
  _原生共享前台租约 = 租约;
  const 票: 原生正文开始票 = {
    序号: ++_原生开始票序号,
    阶段: '等待prompt',
    聊天ID: 参数.聊天ID,
    时间线世代: 参数.时间线世代,
    开始类型: 参数.开始类型,
    用户楼层: 参数.用户楼层,
    用户消息引用: 参数.用户消息引用,
    预期助手楼层: 参数.用户楼层 + 1,
  };
  _原生开始票 = 票;
  return 票;
}

/**
 * PROMPT_READY 认领正文租约：把“等待 prompt”开始票推进到“正文结算”，并递增本轮令牌
 * （作废更早一轮在途的 VARIABLE_UPDATE_ENDED 身份）。返回租约 owner（= 票序号）。
 *
 * 拒绝返回 null 且不改变当前代数：无票 / 序号不符（票已被替换）/ 票已被认领 / 聊天、时间线、
 * 用户楼层或用户消息引用与调用方校验不符。没有开始票的辅助/后台请求、以及正文租约已生效
 * 时后到的辅助 prompt，都不得递增正文令牌或改租约。
 */
export function 认领正文租约(参数: 原生正文租约校验 & { 序号: number }): number | null {
  const 票 = _原生开始票;
  if (!票) return null;
  if (票.序号 !== 参数.序号) return null;
  if (票.阶段 !== '等待prompt') return null;
  if (票.聊天ID !== 参数.聊天ID || 票.时间线世代 !== 参数.时间线世代) return null;
  if (票.用户楼层 !== 参数.用户楼层 || 票.用户消息引用 !== 参数.用户消息引用) return null;
  _原生本轮令牌 += 1;
  票.阶段 = '正文结算';
  return 票.序号;
}

/**
 * 释放正文租约：只有 owner 与当前开始票序号相符才清票（返回 true）。
 * 旧 owner 在票已被替换/作废后释放返回 false，绝不清新票；null 表示无租约可释放，
 * 同样返回 false（手动重处理/辅助模型事件等非正文结算路径的防御性调用）。
 * 释放不递增令牌，同轮在途回调仍可识别（如被拒原生正文的延迟 stopGeneration 仍能按
 * 其轮身份生效）。
 */
export function 释放正文租约(owner: number | null): boolean {
  if (!_原生开始票 || _原生开始票.序号 !== owner) return false;
  _原生开始票 = null;
  释放共享前台租约();
  return true;
}

/** 明确全局作废：停止/切聊天/切分支/删楼等宿主级作废入口。清票、递增令牌作废在途回调身份，并释放共享前台租约。 */
export function 作废原生正文租约(): void {
  _原生开始票 = null;
  _原生本轮令牌 += 1;
  释放共享前台租约();
}

/**
 * 同轮在途请求身份校验：owner 仍是当前生效租约持有者，且聊天、时间线、用户楼层与
 * 用户消息引用仍与当前一致。认领后的异步流程（注入、延迟停止）用它确认没有作废/
 * 替换/切聊天。`释放正文租约(owner)` 已按 owner 释放后本函数返回 false，调用方如需
 * 在“本轮刚被自己释放”后继续判定，须另行核对“无新票且令牌未变”。
 */
export function 租约owner仍有效(owner: number, 校验: 原生正文租约校验): boolean {
  const 票 = _原生开始票;
  if (!票 || 票.序号 !== owner || 票.阶段 !== '正文结算') return false;
  if (票.聊天ID !== 校验.聊天ID || 票.时间线世代 !== 校验.时间线世代) return false;
  if (票.用户楼层 !== 校验.用户楼层 || 票.用户消息引用 !== 校验.用户消息引用) return false;
  return true;
}

/** 热挂载/重入时重置状态（含幂等释放共享前台租约）。 */
export function 重置原生正文租约(): void {
  _原生开始票 = null;
  _原生本轮令牌 = 0;
  _原生开始票序号 = 0;
  释放共享前台租约();
}
