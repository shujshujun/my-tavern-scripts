/** 本模块只判断父亲是否被明确写成知道既定隐秘关系，不限制他了解房租、交接或普通家务。 */
export type 父亲知情叙述视角 = '父亲' | '母亲' | '旁人';

const 隐秘关系话题 =
  /(?:真实|隐秘|秘密|特殊|亲密)关系|(?:母子关系).{0,4}(?:变了|改变)|不只是母子|不是普通母子|你(?:和|跟|与)(?:你)?妈(?:的)?(?:那点事|那些事|关系)|我(?:和|跟|与)(?:你(?!爸)|管理员|玩家|儿子)(?:的)?(?:那点事|关系)|(?:母亲|妈妈|302).{0,12}(?:管理员|玩家|儿子).{0,12}(?:关系|情人|恋人|伴侣)|(?:情人|恋人|伴侣).{0,12}(?:母亲|妈妈|302)/u;
const 父亲称呼 = /父亲|爸爸|你爸|他爸/u;
const 知情谓语 = /知道|知情|得知|知晓|清楚|识破|察觉|看穿|发现|明白|默许|成全/gu;
const 普通事项 =
  /房租|交接|报修|维修|账本|物业|工作|行程|航班|吃饭|住在|住进|管理(?:公寓|事务|这栋楼)|公寓(?:管理|经营|事务|账)/u;

/** 否定、疑问和未发生的计划不签发知情事实；逐分句避免把后半句的否定套到前半句肯定上。 */
export function 父亲被写成已知关系(文本: string, 视角: 父亲知情叙述视角 = '旁人'): boolean {
  let 前句关系话题 = false;
  let 前句父亲主体 = false;
  for (const 原 of String(文本 ?? '')
    .normalize('NFKC')
    .split(/(?<=[，,。！？!?；;\n])/u)) {
    const 句 = 原.trim();
    if (!句) continue;
    const 本句话题 = 隐秘关系话题.test(句);
    const 父亲主体 = 父亲称呼.test(句) || (视角 === '父亲' && /我|(?:^|[:：])爸/u.test(句));
    const 谓语们 = [...句.matchAll(知情谓语)];
    for (const 匹配 of 谓语们) {
      const 之前 = 句.slice(0, 匹配.index);
      const 之后 = 句.slice(匹配.index + 匹配[0].length);
      const 其他人自述 =
        视角 !== '父亲' &&
        /(?:^|[:：])\s*我(?:也|才|早|已经|其实|一直|不|没|未|就|当然|只)?/u.test(之前) &&
        !父亲称呼.test(之前);
      const 父亲承接 =
        前句父亲主体 &&
        !其他人自述 &&
        /^(?:但|不过|而|其实|也|已经|早就|只是|他|就|还|一直|完全|确实|明明|不|没|未|并非|不是|\s)*$/u.test(之前);
      const 本人省略 = 视角 === '父亲' && /^(?:其实|已经|早就|一直|完全|确实|明明|不|没|未|\s)*$/u.test(之前);
      if (!父亲主体 && !父亲承接 && !本人省略) continue;
      const 装作 = /(?:装作|假装).{0,4}不(?:知道|知情)/u.exec(句);
      const 装作不知 = !!装作 && !/(?:没有|并非|不是|没|未)\s*$/u.test(句.slice(0, 装作.index));
      const 模糊共谋 =
        !普通事项.test(句) &&
        (匹配[0] === '默许' || 匹配[0] === '成全') &&
        /(?:我|你|我们|你们).{0,10}(?:管理员|玩家|儿子)|^(?:我|我们|你们)(?:了)?[。！!，,]?$/u.test(之后);
      if (!本句话题 && !(前句关系话题 && !普通事项.test(句)) && !装作不知 && !模糊共谋) continue;
      if (/[?？]\s*$/u.test(句) || /是否|会不会|是不是|知不知道|有没有/u.test(句)) continue;
      if (/(?:如果|假如|万一|要是|也许|可能|恐怕|担心|害怕)/u.test(之前)) continue;
      if (/(?:别|不要|不能|不想|希望|打算|准备|想|要).{0,5}(?:让|告诉).{0,12}$/u.test(之前)) continue;
      if (/(?:会|将|可能|也许|未必)\s*$/u.test(之前)) continue;
      const 双重否定 = /(?:不是|并非|不可能|不至于|不会|不能|没有)\s*(?:不|没|未)\s*$/u.test(之前);
      if (!双重否定 && !装作不知 && /(?:不|没|未)(?:曾|会|再)?\s*$/u.test(之前)) continue;
      if (!双重否定 && /(?:没有|从未|尚未|还没).{0,3}$/u.test(之前)) continue;
      return true;
    }
    前句关系话题 = 本句话题 && /[，,]\s*$/u.test(句);
    前句父亲主体 = 父亲主体 && /[，,]\s*$/u.test(句);
  }
  return false;
}
