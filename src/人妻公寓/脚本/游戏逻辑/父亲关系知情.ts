/** 本模块只判断父亲是否被明确写成知道既定隐秘关系，不限制他了解房租、交接或普通家务。 */
export type 父亲知情叙述视角 = '父亲' | '母亲' | '旁人';

const 隐秘关系话题 =
  /(?:真实|隐秘|秘密|特殊|亲密)关系|(?:母子关系).{0,4}(?:变了|改变)|不只是母子|不是普通母子|你(?:和|跟|与)(?:你)?妈(?:的)?(?:那点事|那些事|关系)|我(?:和|跟|与)(?:你(?!爸)|管理员|玩家|儿子)(?:的)?(?:那点事|关系)|(?:母亲|妈妈|302).{0,12}(?:管理员|玩家|儿子).{0,12}(?:关系|情人|恋人|伴侣)|(?:情人|恋人|伴侣).{0,12}(?:母亲|妈妈|302)/u;
const 机场隐秘现场 = /机场.{0,24}(?:隐秘现场|镜头死角|镜头外(?:的事|发生)|隐瞒父亲的事)/u;
const 父亲称呼 = /父亲|爸爸|你爸|他爸/u;
const 知情谓语 = /知道|知情|得知|知晓|清楚|识破|察觉|看穿|发现|明白|默许|成全|看见|看到/gu;
const 普通事项 =
  /房租|交接|报修|维修|账本|物业|工作|行程|航班|吃饭|住在|住进|管理(?:公寓|事务|这栋楼)|公寓(?:管理|经营|事务|账)/u;

/** 泛称的关系沿用本段话题；明确属于其他两人的关系不能借用本线对象。 */
function 本线知情话题(片段: string): boolean {
  const 文 = 片段.replace(
    /(?:房东|租客|经理|员工|朋友|同事|邻居)(?:和|跟|与)(?:房东|租客|经理|员工|朋友|同事|邻居)(?:的)?(?:真实|隐秘|秘密|特殊|亲密|工作)?关系/gu,
    '',
  );
  return 隐秘关系话题.test(文) || 机场隐秘现场.test(文);
}

type 知情主语归属 = '父亲' | '他人' | '代词' | '省略';

/** 只读本谓语前的主语区，不把“对……”的对象、比较对象或父亲的同事认作父亲。 */
function 读取知情主语(前文: string, 视角: 父亲知情叙述视角): 知情主语归属 {
  const 主语区 = 前文
    .replace(/(?:对于|关于|对)[\s\S]*$/u, '')
    .replace(/比(?:父亲|爸爸|你爸|他爸)/gu, '')
    // “爸爸问过同事但已经知道”里的同事是询问对象，不是后半句的省略主语。
    // 只隔离紧贴转折的明确询问宾语；转折后新出现的主语仍按原规则优先。
    .replace(/(?:询问|问过|问)(?:了)?(?:父亲|爸爸|你爸|他爸|母亲|妈妈|朋友|同事|我|你|她|他)(?=(?:但是|不过|而且|并且|但|却))/gu, '');
  const 主语 = [...主语区.matchAll(/(?:父亲|爸爸|你爸|他爸)(?:的(?!确)[\p{Script=Han}]+)?|母亲|妈妈|我(?!们)|你(?!们|爸)|她|他(?!们|爸)|朋友|同事/gu)].at(-1)?.[0];
  if (!主语) return 视角 === '父亲' && /(?:^|[:：])\s*爸/u.test(主语区) ? '父亲' : '省略';
  if (/^(?:父亲|爸爸|你爸|他爸)$/u.test(主语) || (主语 === '我' && 视角 === '父亲')) return '父亲';
  return 主语 === '他' ? '代词' : '他人';
}

/** 仅在分析副本中隔离被明确否认／劝止的引述；普通引号或转述不自动豁免真实知情。 */
function 知情断言分析副本(文本: string): string {
  const 文 = String(文本 ?? '').normalize('NFKC');
  return 文
    .replace(/“[^”]*”|「[^」]*」|『[^』]*』|"[^"]*"|‘[^’]*’/gu, (引文: string, 起点: number) => {
      const 前文 = 文.slice(0, 起点).split(/[，,。！？!?；;\n”」』"’]/u).at(-1) ?? '';
      const 后文 = 文.slice(起点 + 引文.length).replace(/^[\s，,。；;]+/u, '');
      const 否认 = /(?:没有|没|从未|并未)(?:说过|说|声称|表示)\s*[:：]?\s*$/u.exec(前文);
      const 否认引述 = !!否认 && !/(?:并非|不是|并不是|不可能)\s*$/u.test(前文.slice(0, 否认.index));
      const 劝止引述 = /(?:别|不要)(?:再)?(?:说|相信|信|误以为)\s*[:：]?\s*$/u.test(前文);
      const 明确辟谣 = /^(?:这句话|这种说法|的说法)?(?:是假的|不是真的|不属实|并不属实|只是一个假设)/u.test(后文);
      // 保留UTF-16长度供原文定位；引述内的标点不切断引号外的对象与指代。
      // 原消息与真实引用定位不作任何改写。
      return 否认引述 || 劝止引述 || 明确辟谣 ? ' '.repeat(引文.length) : 引文;
    })
    .replace(/[“”「」『』"‘’]/gu, ' ');
}

/** 否定、疑问和未发生的计划不签发知情事实；逐谓语区分主语、对象与嵌套层。 */
export function 父亲被写成已知关系(文本: string, 视角: 父亲知情叙述视角 = '旁人'): boolean {
  const 原文 = String(文本 ?? '').normalize('NFKC');
  let 前句关系话题 = false;
  let 前句父亲主体 = false;
  let 偏移 = 0;
  for (const 原 of 知情断言分析副本(原文).split(/(?<=[，,。！？!?；;\n])/u)) {
    const 原句 = 原文.slice(偏移, 偏移 + 原.length);
    偏移 += 原.length;
    const 句 = 原.trim();
    // 被否认的引述不签发事实，但仍可为随后“他早就知道了”提供对象和指代。
    const 引述上下文 = 原句 !== 原 && 本线知情话题(原句);
    const 本句话题 = 本线知情话题(句) || 引述上下文;
    const 谓语们 = [...句.matchAll(知情谓语)];
    const 前置主语 = 读取知情主语(句, 视角);
    let 本句父亲主体: boolean =
      前置主语 === '父亲' ||
      (引述上下文 && (父亲称呼.test(原句) || (视角 === '父亲' && /我/u.test(原句))));
    for (const [序, 匹配] of 谓语们.entries()) {
      const 上个 = 谓语们[序 - 1];
      const 前段 = 句.slice(上个 ? 上个.index + 上个[0].length : 0, 匹配.index);
      // 上一谓语的宾语不能充当这一谓语的主语；无逗号的转折同样在此划开。
      const 之前 = 上个 ? 前段.replace(/^[\s\S]*(?:但是|不过|而且|并且|但|却)/u, '') : 前段;
      const 之后 = 句.slice(匹配.index + 匹配[0].length, 谓语们[序 + 1]?.index);
      const 主语归属 = 读取知情主语(之前, 视角);
      const 父亲主体 = 主语归属 === '父亲';
      const 其他人自述 = 主语归属 === '他人';
      const 父亲承接: boolean =
        (本句父亲主体 || 前句父亲主体) &&
        !其他人自述 &&
        /^(?:但|不过|而|并|其实|也|已经|早就|早已|只是|他|就|还|一直|完全|十分|非常|相当|的确|确实|明明|不|没|未|并非|不是|\s)*$/u.test(之前);
      const 本人省略 = 视角 === '父亲' && /^(?:其实|已经|早就|早已|一直|完全|十分|非常|相当|的确|确实|明明|不|没|未|\s)*$/u.test(之前);
      本句父亲主体 = 父亲主体 || 父亲承接 || 本人省略;
      if (!本句父亲主体) continue;
      const 谓语片段 = `${之前}${匹配[0]}`;
      const 装作 = /(?:装作|假装).{0,4}不(?:知道|知情)/u.exec(谓语片段);
      const 装作不知 = !!装作 && !/(?:没有|并非|不是|没|未)\s*$/u.test(谓语片段.slice(0, 装作.index));
      const 模糊共谋 =
        !普通事项.test(句) &&
        (匹配[0] === '默许' || 匹配[0] === '成全') &&
        /(?:我|你|我们|你们).{0,10}(?:管理员|玩家|儿子)|^(?:我|我们|你们)(?:了)?[。！!，,]?$/u.test(之后);
      const 本谓语话题 = 本线知情话题(之后) || (!上个 && 本线知情话题(之前));
      if (!本谓语话题 && !(前句关系话题 && !普通事项.test(之后)) && !(装作不知 && !普通事项.test(之后)) && !模糊共谋) continue;
      if (/[?？]\s*$/u.test(句) || /是否|会不会|是不是|知不知道|有没有/u.test(句)) continue;
      if (/(?:如果|假如|万一|要是|也许|可能|恐怕|担心|害怕)/u.test(之前)) continue;
      if (/(?:别|不要|不能|不想|希望|打算|准备|想|要).{0,5}(?:让|告诉).{0,12}$/u.test(之前)) continue;
      if (/(?:会|将|可能|也许|未必)\s*$/u.test(之前)) continue;
      // 否定可隔着程度／方式副词修饰本谓语，例如“并未真正知道”“未曾实际察觉”。
      // 仅从判定副本末尾移除明确副词，不跨主语、转折或其他谓语吞掉前面的否定。
      // 双重否定与单重否定使用同一副本，保留“并非不真正知道”的肯定含义。
      const 否定之前 = 之前.replace(/(?:(?:真正|真的|实际|确实|完全|明确|直接|根本|丝毫|一点也)(?:地)?\s*)+$/u, '');
      const 双重否定 = /(?:不是|并非|不可能|不至于|不会|不能|没有)\s*(?:不|没|未)\s*$/u.test(否定之前);
      if (!双重否定 && !装作不知 && /(?:不|没|未)(?:曾|会|再)?\s*$/u.test(否定之前)) continue;
      if (!双重否定 && /(?:没有|从未|尚未|还没).{0,3}$/u.test(否定之前)) continue;
      return true;
    }
    前句关系话题 = 本句话题 && /[，,]\s*$/u.test(句);
    前句父亲主体 = 本句父亲主体 && /[，,]\s*$/u.test(句);
  }
  return false;
}
