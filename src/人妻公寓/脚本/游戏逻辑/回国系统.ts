  if (剧情等待) return [];
  if (地点 === '302' && 路线(data).阶段 === '待读回国消息' && 母亲在302(data))
    return [{ id: '阅读回国消息', kicker: 'RETURN', icon: 'story', 文案: '把父亲的回国消息给母亲看' }];
  if (地点 === '302' && 路线(data).阶段 === '待收纳' && data.背包.includes(回国私人物件箱ID) && 母亲在302(data))
    return [{ id: '收纳私人物件', kicker: 'PRIVATE', icon: 'home', 文案: '和母亲清点需要收起来的东西' }];
  if (地点 === '管理员室' && 路线(data).阶段 === '待看记录')
    return [{ id: '查看管理记录', kicker: 'RECORD', icon: 'edit', 文案: '和母亲看一次平常的管理记录' }];
