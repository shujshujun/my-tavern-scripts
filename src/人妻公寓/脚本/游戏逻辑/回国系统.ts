/**
 * `最早继续日` 只约束"再演一场母亲现场"的节奏，不代表整条路线停摆。
 * 纯硬操作（锁箱入柜）与打开父亲会话不占用当天的剧情额度，必须继续可见，
 * 否则玩家在等待日会看到一个动作也没有的空房间，误以为路线已经断掉。
 */
export function 回国剧情等待中(data: SchemaType): boolean {
  return 路线(data).最早继续日 >= 0 && 今日(data) < 路线(data).最早继续日;
}

