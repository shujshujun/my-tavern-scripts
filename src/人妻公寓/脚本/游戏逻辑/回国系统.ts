function 规范回国群名片段(原: string, 上限: number): string {
  const 单行 = [...String(原 ?? '')]
    .filter(字 => {
      const 码 = 字.codePointAt(0) ?? 0;
      return 码 >= 0x20 && 码 !== 0x7f && !(码 >= 0x80 && 码 <= 0x9f);
    })
    .join('')
    .replace(/\s+/gu, ' ')
    .trim();
  return [...单行].slice(0, 上限).join('').trim();
}

