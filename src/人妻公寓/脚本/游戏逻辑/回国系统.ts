export function 下一个回国茶话会后私聊成员(data: SchemaType): 门牌 | null {
  const 当前 = 路线(data);
  if (当前.茶话会状态 !== '已完成' || data.系统._绝对时段 < 当前.后续私聊最早时段) return null;
  return (
    当前.后续私聊待触发成员.find(
      (m): m is 门牌 =>
        门牌列表.includes(m as 门牌) &&
        m !== '302' &&
        Boolean(data.户[m as 门牌]) &&
        !当前.后续私聊已触发成员.includes(m),
    ) ?? null
  );
}

export function 提交回国茶话会后私聊已送达(data: SchemaType, 门牌号: 门牌): 回国结果 {
  const 当前 = 路线(data);
  if (!当前.后续私聊待触发成员.includes(门牌号)) return { 成功: false, 提示: '' };
  当前.后续私聊待触发成员 = 当前.后续私聊待触发成员.filter(m => m !== 门牌号);
  if (!当前.后续私聊已触发成员.includes(门牌号)) 当前.后续私聊已触发成员.push(门牌号);
  当前.后续私聊最早时段 = data.系统._绝对时段 + 1;
  return { 成功: true, 变动: true, 提示: '' };
}

/**
 * 可选后续私聊生成失败时只推进重试水位，不消费成员。这样临时空响应仍会在下个世界时段自愈，
 * 但不会在同一时段的每个手机节拍反复烧 API；迟到的其他成员失败票也不能延后当前队首。
 */
export function 暂缓回国茶话会后私聊(data: SchemaType, 门牌号: 门牌): 回国结果 {
  const 当前 = 路线(data);
  if (下一个回国茶话会后私聊成员(data) !== 门牌号) return { 成功: false, 提示: '' };
  当前.后续私聊最早时段 = Math.max(当前.后续私聊最早时段, data.系统._绝对时段 + 1);
  return { 成功: true, 变动: true, 提示: '' };
}

export function 提交回国茶话会批次(data: SchemaType, 提交: 回国茶话会批次提交): 回国结果 {
  const 当前 = 路线(data);
  if (当前.阶段 !== '姐妹茶话会进行中') return { 成功: false, 提示: '《回国》茶话会已经不在特殊演绎阶段。' };
  if (提交.玩家已发言) 当前.玩家已发言 = true;
  if (提交.任务 === '改名反应') {
    const 变动 = !当前.群名反应已完成;
    当前.群名反应已完成 = true;
    return { 成功: true, 变动, 提示: '' };
  }
  if (!当前.群名反应已完成) return { 成功: false, 提示: '群成员还没有完成对新群名的第一轮反应。' };
  if (提交.任务 === '坦白') {
    const 变动 = !当前.母亲已坦白;
    当前.母亲已坦白 = true;
    return { 成功: true, 变动, 提示: '' };
  }
  if (提交.任务 === '点评') {
    const 目标 = String(提交.目标 ?? '');
    if (!当前.茶话会成员快照.includes(目标)) return { 成功: false, 提示: '茶话会点评目标已经失效。' };
    if (!当前.已点评成员.includes(目标)) 当前.已点评成员.push(目标);
    if (!当前.已回应点评成员.includes(目标)) 当前.已回应点评成员.push(目标);
    return { 成功: true, 变动: true, 提示: '' };
  }
  if (提交.任务 === '转正事') {
    if (!当前.母亲已坦白 || 当前.已回应点评成员.length < 当前.茶话会成员快照.length)
      return { 成功: false, 提示: '茶话会还有成员尚未完成点评与回应。' };
    当前.茶话会状态 = '交代正事';
    当前.正事已说明 = true;
    return { 成功: true, 变动: true, 提示: '' };
  }
  if (提交.任务 === '回应回国') {
    for (const 原成员 of 提交.回应成员 ?? []) {
      const 成员 = String(原成员);
      if (当前.茶话会成员快照.includes(成员) && !当前.已回应回国成员.includes(成员)) 当前.已回应回国成员.push(成员);
    }
    return { 成功: true, 变动: true, 提示: '' };
  }
  if (!当前.正事已说明 || 当前.已回应回国成员.length < 当前.茶话会成员快照.length || !当前.玩家已发言)
    return { 成功: false, 提示: '父亲回国的正事还没有得到全部成员回应。' };
  return 提交回国茶话会完成(data, 提交.摘要 ?? '母亲已坦白并逐人调侃；群成员知道父亲即将回国，正事已经交代完。');
}

export function 提交回国父亲会话母亲气泡(data: SchemaType, 类型: '无需收尾' | '确认准备', 成功楼层: number): 回国结果 {
  if (类型 === '无需收尾') {
    if (路线(data).阶段 !== '待母亲回复父亲') return { 成功: false, 提示: '父亲询问已经不是当前《回国》步骤。' };
    路线(data).阶段 = '待父亲准备答复';
    路线(data).父亲最早回信时段 = data.系统._绝对时段 + 1;
    return {
      成功: true,
      变动: true,
      CG: '回国_09_302父亲会话协同回复',
      提示: '母亲已经明确回复父亲。等他口头确认近期回国与正式交接安排。',
    };
  }
  if (路线(data).阶段 !== '待确认交接意向') return { 成功: false, 提示: '父亲准备回楼交接的答复尚未就绪。' };
  路线(data).阶段 = '已完成';
  路线(data).完成楼层 = Number.isInteger(成功楼层) ? 成功楼层 : -1;
  if (!data.系统._已完成特殊场景.includes(回国完成ID)) data.系统._已完成特殊场景.push(回国完成ID);
  return { 成功: true, 变动: true, 提示: '《回国》完成。「双重继承」已经可以在商店购买；只有你使用场景票后，父亲才会真正回楼。' };
}

export function 回国父亲会话回复类型(data: SchemaType): '无需收尾' | '确认准备' | null {
  if (路线(data).阶段 === '待母亲回复父亲') return '无需收尾';
  if (路线(data).阶段 === '待确认交接意向') return '确认准备';
  return null;
}

