function 回国邀请短哈希(原: string): string {
  let 哈希 = 2166136261;
  for (const 字 of 原) {
    哈希 ^= 字.codePointAt(0) ?? 0;
    哈希 = Math.imul(哈希, 16777619);
  }
  return (哈希 >>> 0).toString(36);
}

export function 构造回国母亲邀请事务(参数: 构造回国母亲邀请事务参数): 回国母亲邀请事务 {
  const 冻结 = {
    聊天ID: String(参数.聊天ID ?? '').trim(),
    时间线世代: Number.isSafeInteger(参数.时间线世代) && 参数.时间线世代 >= 0 ? 参数.时间线世代 : -1,
    入群楼层: Number.isSafeInteger(参数.入群楼层) && 参数.入群楼层 >= 0 ? 参数.入群楼层 : -1,
    绝对时段: Number.isSafeInteger(参数.绝对时段) && 参数.绝对时段 >= 0 ? 参数.绝对时段 : -1,
    Persona名: 规范回国群名片段(参数.Persona名, 24) || '管理员',
    预期阶段: '待姐妹茶话会' as const,
    锚签名: String(参数.锚签名 ?? ''),
  };
  const 事务ID = `return-invite-${回国邀请短哈希(JSON.stringify(冻结))}`;
  return { 版本: 1, 事务ID, ...冻结 };
}

function 回国母亲邀请事务合法(事务: 回国母亲邀请事务): boolean {
  return Boolean(
    事务.版本 === 1 &&
      事务.事务ID &&
      事务.聊天ID &&
      事务.时间线世代 >= 0 &&
      事务.入群楼层 >= 0 &&
      事务.绝对时段 >= 0 &&
      事务.Persona名 &&
      事务.预期阶段 === '待姐妹茶话会' &&
      事务.锚签名,
  );
}

export function 读取回国母亲邀请事务(data: SchemaType): 回国母亲邀请事务 | null {
  const 原 = String(data.系统._回国.茶话会结构摘要 ?? '');
  if (!原.startsWith(回国母亲邀请事务前缀)) return null;
  try {
    const 候选 = JSON.parse(原.slice(回国母亲邀请事务前缀.length)) as 回国母亲邀请事务;
    return 回国母亲邀请事务合法(候选) ? 候选 : null;
  } catch {
    return null;
  }
}

function 写回国母亲邀请事务(data: SchemaType, 事务: 回国母亲邀请事务 | null): void {
  data.系统._回国.茶话会结构摘要 = 事务 ? `${回国母亲邀请事务前缀}${JSON.stringify(事务)}` : '';
}

export function 建立回国母亲邀请事务(data: SchemaType, 事务: 回国母亲邀请事务): 回国结果 {
  const 已有 = 读取回国母亲邀请事务(data);
  if (已有) {
    return 已有.事务ID === 事务.事务ID
      ? { 成功: true, 变动: false, 提示: '母亲入群邀请已经建立，正在继续提交。' }
      : { 成功: false, 提示: '另一笔母亲入群邀请仍在提交，不能重复建立。' };
  }
  const 当前路线 = data.系统._回国;
  if (
    当前路线.阶段 !== 事务.预期阶段 ||
    当前路线.茶话会状态 !== '入群演绎' ||
    !回国母亲邀请事务合法(事务)
  ) {
    return { 成功: false, 提示: '母亲入群邀请的阶段或时间线已经变化。' };
  }
  写回国母亲邀请事务(data, 事务);
  return { 成功: true, 变动: true, 提示: '母亲入群邀请已冻结，正在写入微信系统提示。' };
}

export function 确认回国母亲邀请消息已写(
  data: SchemaType,
  凭据: Pick<回国母亲邀请事务, '事务ID' | 'Persona名'>,
): 回国结果 {
  const 事务 = 读取回国母亲邀请事务(data);
  if (!事务 || 事务.事务ID !== 凭据.事务ID || 事务.Persona名 !== 凭据.Persona名) {
    return { 成功: false, 提示: '母亲入群消息不属于当前邀请事务。' };
  }
  const 结果 = 提交回国母亲加入姐妹群内部(data);
  if (!结果.成功) return 结果;
  写回国母亲邀请事务(data, null);
  return 结果;
}

