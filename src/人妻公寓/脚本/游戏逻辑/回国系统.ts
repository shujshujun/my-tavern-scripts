function 全局互斥错误(data: SchemaType, 当前地点: string | null = null, 当前事件 = ''): string {
  if (data.系统._坏结局) return '当前坏结局已经锁定，不能开始《回国》。';
  if (data.系统._性爱场景.状态 !== '空闲') return '当前亲密场景尚未结束。';
  if (data.系统._特殊场景.id || data.系统._荣耀洞拍 >= 0) return '当前特殊场景尚未结束。';
  if (回国普通强剧情冲突(data, 当前地点, 当前事件)) return '当前地点的场景剧情尚未结束。';
  if (data.系统._父亲通话.标识 || data.系统._父亲通话.状态 || data.系统._待接来电.期 >= 0) {
    return '当前父亲电话尚未处理。';
  }
  if (处于医院硬锁(data, '302')) return '母亲正在医院待产或恢复，《回国》从当前步骤暂停。';
  return '';
}

function 母亲互斥错误(data: SchemaType, 当前地点: string | null = null, 当前事件 = ''): string {
  const 错误 = 全局互斥错误(data, 当前地点, 当前事件);
  if (错误) return 错误;
  if (!data.户['302']) return '302母亲状态不存在。';
  return '';
}

