/**
 * 昵称只从带硬事件键的当前微信时间线读取，不扫描普通聊天内容，也不让模型或 SQLite 猜玩家姓名。
 * 调用方传入的消息已经由手机数据层完成回档、分支与时间线过滤。
 */
export function 读取回国姐妹群昵称(
  消息们: readonly { 会话?: string; 键?: string; 文?: string }[],
): string | null {
  for (let i = 消息们.length - 1; i >= 0; i -= 1) {
    const 消息 = 消息们[i];
    if (消息?.会话 !== '姐妹群' || 消息.键 !== 回国姐妹群改名消息键) continue;
    const 文 = String(消息.文 ?? '');
    if (!文.startsWith(回国姐妹群改名文案前缀) || !文.endsWith('”')) continue;
    const 昵称 = 规范回国群名片段(文.slice(回国姐妹群改名文案前缀.length, -1), 28);
    if (昵称.endsWith(回国姐妹群昵称后缀)) return 昵称;
  }
  return null;
}

