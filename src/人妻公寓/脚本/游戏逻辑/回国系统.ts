export function 解析回国剧情事件(事件: string): 回国剧情票 | null {
  const 匹配 = 事件.match(/【回国提交:([A-G]):([^:】]+):(\d+):(\d+)】/u);
  if (!匹配) return null;
  const 动作 = 回国代码动作[匹配[1]];
  const 预期阶段 = 匹配[2] as 回国阶段;
  const 请求时段 = Number(匹配[3]);
  const 拍 = Number(匹配[4]);
  if (!动作 || !Number.isInteger(请求时段) || !Number.isInteger(拍) || 拍 < 1 || 拍 > 回国剧情总拍[动作]) return null;
  return { 动作, 预期阶段, 请求时段, 拍 };
}

function 回国句中存在肯定事实(正文: string, 模式: RegExp): boolean {
  for (const 句 of String(正文 ?? '')
    .split(/[。！？；;\n]/u)
    .map(片段 => 片段.trim())
    .filter(Boolean)) {
    const 匹配 = 句.match(模式);
    if (!匹配 || 匹配.index === undefined) continue;
    const 前文 = 句.slice(Math.max(0, 匹配.index - 12), 匹配.index);
    const 命中局部 = `${前文}${匹配[0].slice(0, 18)}`;
    if (/(?:没有|并未|尚未|还没|未曾|不曾|并不|不能|不会|不打算|没有立刻|并没有|仍未)/u.test(命中局部)) continue;
    return true;
  }
  return false;
}

