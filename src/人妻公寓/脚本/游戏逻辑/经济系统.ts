function 按百元取整(金额: number): number {
  return Math.max(0, Math.round(金额 / 100) * 100);
}

function 上交不足扣分(完成率: number): number {
  if (完成率 >= 1) return 0;
  if (完成率 >= 0.8) return 2;
  if (完成率 >= 0.5) return 5;
  if (完成率 > 0) return 8;
  return 12;
}

function 胜任态度(胜任度: number, 红线: number, 通牒: boolean): string {
  if (通牒 || 胜任度 <= 红线) return '通牒';
  const 距离 = 胜任度 - 红线;
  return 距离 >= 30 ? '满意' : 距离 >= 20 ? '平淡' : 距离 >= 10 ? '不满' : '危险';
}

function 未结楼务报表(data: SchemaType, 当前绝对时段: number): string[] {
  const 级别序 = { 紧急: 3, 重要: 2, 日常: 1 } as const;
  const 排序 = [...data.系统._管理考核.活跃任务].sort((a, b) => {
    const a逾 = 当前绝对时段 > a.截止时段 ? 1 : 0;
    const b逾 = 当前绝对时段 > b.截止时段 ? 1 : 0;
    return b逾 - a逾 || 级别序[b.级别] - 级别序[a.级别] || a.截止时段 - b.截止时段;
  });
  const 展开 = 排序.slice(0, 3).map(任务 => {
    const 时差 = 当前绝对时段 - 任务.截止时段;
    return `${管理任务摘要(任务)}${时差 > 0 ? `已逾期${时差}时段` : `尚余${Math.max(0, -时差)}时段`}`;
  });
  if (排序.length > 3) 展开.push(`其余未结楼务${排序.length - 3}件`);
  return 展开;
}

/** 只在没有更高优先级未结责任时，把本期按期完成的重要事项编入父亲报表。 */
function 按期完成楼务报表(data: SchemaType, 期界时段: number, 有其他高优先问题: boolean): string[] {
  const 管理 = data.系统._管理考核;
  const 有高优先未结 = 管理.活跃任务.some(
    任务 => 期界时段 > 任务.截止时段 || 任务.级别 === '重要' || 任务.级别 === '紧急',
  );
  if (有其他高优先问题 || 有高优先未结) return [];
  return 管理.本期完成摘要
    .filter(项 => 项.按期 && (项.级别 === '重要' || 项.级别 === '紧急'))
    .map(项 => `本期按期完成重要楼务：${项.地点}${项.任务}（${项.级别}，${项.方式}）`);
}

function 逾期楼务原因(data: SchemaType, 任务ids: readonly string[], 当前时段: number, 允许旧逾期 = false): string {
  const ids = new Set(任务ids);
  const 新逾期 = data.系统._管理考核.活跃任务.find(任务 => ids.has(任务.id));
  if (新逾期) return 管理任务摘要(新逾期);
  if (!允许旧逾期) return '';
  const 旧逾期 = data.系统._管理考核.活跃任务.find(任务 => 任务.逾期已扣 && 当前时段 > 任务.截止时段);
  return 旧逾期 ? 管理任务摘要(旧逾期) : '';
}

function 合并父亲报表(旧报表: string, 新报表: string): string {
  if (!旧报表) return 新报表;
  if (!新报表 || 旧报表.includes(新报表)) return 旧报表;
  return `${旧报表};${新报表}`;
}

