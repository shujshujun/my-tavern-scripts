/**
 * 经济系统(P3:压力成型)——纪律:货币只走脚本结算,AI 不碰钱(变量分工表)。
 *
 * 结算入口:经济结算(每 AI 楼一次,主路径+逃生舱双挂,期号去重防重复入账)。
 * 时间读数一律钟楼(真实楼层+杀时间偏移);软计数(拾取/偷窃冷却)存 chat 变量 `_经济`,
 * 回档丢了也无害,且带"未来楼层作废"守卫(侦探系统回档陷阱同款)。
 */

// ── 软计数(chat 变量) ──

interface 经济计数 {
  拾取: Record<string, boolean>; // `${房间}:${period}` → 已拾取
  偷窃上次: Record<string, number>; // 门牌 → 上次翻找钟楼(冷却)
}

function 读计数(): 经济计数 {
  const v = (_.get(getVariables({ type: 'chat' }), '_经济') ?? {}) as Partial<经济计数>;
  return { 拾取: v.拾取 ?? {}, 偷窃上次: v.偷窃上次 ?? {} };
}

function 写计数(c: 经济计数): void {
  void Promise.resolve(insertOrAssignVariables({ _经济: c }, { type: 'chat' })).catch((e: unknown) =>
    console.error('[人妻公寓·经济] 计数写入失败', e),
  );
}

export interface 经济结果 {
  提示: string;
  事件?: string;
  变动?: boolean;
}

const 钟 = (data: SchemaType, 楼层: number) => 楼层 + data.系统._时段偏移楼;

// ============================================
// 收租日 + 上交日 + 父亲来电 + 最后通牒(每 AI 楼结算一次,期号去重)
// ============================================

/**
 * 经济结算:收租(每户,入住楼错开相位)→ 上交日(全局期:扣上交/胜任度记分/未接覆盖/通牒判定/
 * 生成待接来电)。返回 toast 短句列表(调用方转发 提示 事件)。
 */
export function 经济结算(data: SchemaType, 楼层: number): string[] {
  if (data.系统._坏结局) return [];
  const 现钟 = 钟(data, 楼层);
  const 期长 = 经济配置.收租周期;
  const 提示们: string[] = [];
  // 本次新产生的欠租要留给玩家一个账期处理；考核只追究进入结算前仍未解决的旧账。
  const 结算前欠租笔数 = Object.values(data.户).reduce((和, 节点) => 和 + Math.max(0, 节点._欠租笔数), 0);

  // ── 每户收租(期号=经过的完整周期数;杀时间跨期时惰性补收) ──
  for (const [m, 节点] of Object.entries(data.户)) {
    const 配 = 户静态表[m as 门牌];
    if (!配 || !配.月租) continue;
    const 期号 = Math.floor((现钟 - 节点._入住楼层) / 期长);
    if (期号 <= 0 || 期号 <= 节点._上次收租期) continue;
    const 笔数 = 期号 - Math.max(节点._上次收租期, 0);
    节点._上次收租期 = 期号;
    if (配.天生欠租) {
      节点._欠租笔数 += 笔数;
      提示们.push(`【房租】${配.妻名}家(${m})这期的房租又没动静——欠租 ${节点._欠租笔数} 笔,得上门催了。`);
    } else {
      const 到账 = 配.月租 * 笔数;
      data.现金 += 到账;
      提示们.push(`【房租】${m} ${配.妻名}家房租到账 ¥${到账}。`);
    }
  }

  // ── 上交日(全局期,从楼0起算;首期=第1期) ──
  const 全局期 = Math.floor(现钟 / 期长);
  if (全局期 >= 1 && 全局期 > data.系统._上次上交期) {
    data.系统._上次上交期 = 全局期;
    惰性结算全楼(data, 现钟); // 上交日全楼补被动账(审计 低危8:文档承诺过但从未接线,非焦点户轴值长期陈旧)
    const 报表行: string[] = [];
    const 难度 = 难度表[data.系统._难度] ?? 难度表['标准'];

    // 管楼不是“只要钱够就自动满分”：每期都有固定事务压力，足额交账与接听来电用于抵消。
    data.胜任度 = _.clamp(data.胜任度 - 难度.每期管理压力, 0, 100);
    报表行.push(`本期日常管理考核 -${难度.每期管理压力}`);

    // 上一通来电还挂着没接=被覆盖,失职扣分(不接爸的电话本身就是失职)
    if (data.系统._待接来电.期 >= 0) {
      data.胜任度 = _.clamp(data.胜任度 - 经济配置.未接覆盖扣分, 0, 100);
      报表行.push('上通电话你一直没接');
    }

    // 扣上交
    const 上交 = 经济配置.上交额;
    let 缺口 = 0;
    if (data.现金 >= 上交) {
      data.现金 -= 上交;
      data.胜任度 = _.clamp(data.胜任度 + 经济配置.足额上交加分, 0, 100);
      报表行.push(`本期足额上交 ¥${上交}`);
    } else {
      缺口 = 上交 - data.现金;
      data.现金 = 0;
      const 缺口扣分 = Math.min(
        经济配置.上交不足最高扣分,
        经济配置.上交不足基础扣分 + Math.ceil(缺口 / 500) * 经济配置.上交缺口每五百扣分,
      );
      data.胜任度 = _.clamp(data.胜任度 - 缺口扣分, 0, 100);
      报表行.push(`本期上交缺口 ¥${缺口}(-${缺口扣分})`);
    }

    // 上期欠租若到这次查账仍没处理，按笔追责；新欠租从下一期开始计入，给玩家明确处置窗口。
    if (结算前欠租笔数 > 0) {
      const 欠租扣分 = Math.min(经济配置.欠租最高扣分, 结算前欠租笔数 * 经济配置.欠租每笔扣分);
      data.胜任度 = _.clamp(data.胜任度 - 欠租扣分, 0, 100);
      报表行.push(`${结算前欠租笔数}笔旧欠租未处理(-${欠租扣分})`);
    }

    // 风闻从中低段就开始影响考核，不再等到 60 分才突然象征性扣一次。
    const 风闻扣分 =
      data.风闻 >= 经济配置.风闻重度线
        ? 经济配置.风闻重度扣分
        : data.风闻 >= 经济配置.风闻中度线
          ? 经济配置.风闻中度扣分
          : data.风闻 >= 经济配置.风闻轻度线
            ? 经济配置.风闻轻度扣分
            : 0;
    if (风闻扣分 > 0) {
      data.胜任度 = _.clamp(data.胜任度 - 风闻扣分, 0, 100);
      报表行.push(`楼里风声影响考核(-${风闻扣分})`);
    }

    // 通牒判定(唯一真 Game Over 的传动轴)
    const 红线 = 难度.胜任度红线;
    let 通牒 = false;
    if (data.系统._通牒期 >= 0 && 全局期 > data.系统._通牒期) {
      if (data.胜任度 <= 红线) {
        // 通牒期内没救回来:考验失败,按死法差分文案
        data.系统._坏结局 =
          缺口 > 0
            ? '考验失败·欠租烂账:父亲提前回国,账本摊在桌上,一页一页翻得很慢。"这楼是做慈善吗?"他没等你解释,钥匙已经收走了'
            : '考验失败·风闻满楼:父亲提前回国,他在楼下站了十分钟,听邻居说完了所有他不该听到的。他一句话没说,只让你妈进屋收拾东西';
        提示们.push('【考验失败】父亲回来了。');
        return 提示们;
      }
      data.系统._通牒期 = -1;
      报表行.push('上一期的账你救回来了');
    } else if (data.胜任度 <= 红线 && data.系统._通牒期 < 0) {
      data.系统._通牒期 = 全局期;
      通牒 = true;
    }

    // 生成待接来电(P4 手机接听;分数段只给标签不给裸数值——AI 数据隔离)
    const 分数段 = 通牒 ? '通牒' : data.胜任度 >= 70 ? '满意' : data.胜任度 >= 45 ? '平淡' : '不满';
    data.系统._待接来电 = { 期: 全局期, 分数段, 报表: 报表行.join(';'), 通牒 };
    提示们.push(通牒 ? '【来电】父亲的电话在响——这一通,最好接。' : '【来电】父亲来电话了。');
  }

  return 提示们;
}

// ============================================
// 催租三选(天生欠租户;硬催=钱到手关系崩/宽限=拿考验换攻略/垫上=钱你出她欠你人情)
// ============================================

export function 催租(data: SchemaType, 门牌号: 门牌, 选择: '硬催' | '宽限' | '垫上'): 经济结果 {
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配) return { 提示: '这户没有账要结。' };
  if (节点._欠租笔数 <= 0) return { 提示: '她家这期的账是清的。' };
  const 欠额 = 配.月租 * 节点._欠租笔数;
  const 妻名 = 配.妻名;
  节点._欠租笔数 = 0;

  if (选择 === '硬催') {
    data.现金 += 欠额;
    节点.妻.好感值 = _.clamp(节点.妻.好感值 - 10, 0, 100);
    return {
      提示: `¥${欠额} 到手。她关门的声音很轻,轻得像在忍着什么。`,
      事件: `【催租】{{user}}把${妻名}家欠的 ¥${欠额} 房租硬生生催了出来——她凑钱的窘迫、递钱时的难堪都被他看在眼里。演出这次不体面的收款,她之后见到他会绕着走一阵子`,
      变动: true,
    };
  }
  if (选择 === '宽限') {
    data.胜任度 = _.clamp(data.胜任度 - 3, 0, 100);
    节点.妻.好感值 = _.clamp(节点.妻.好感值 + 6, 0, 100);
    return {
      提示: `批条写好了:这期缓缓也行。报表上会难看一点。`,
      事件: `【宽限】{{user}}给${妻名}批了张缓交条:"这个月先缓缓,别跟别人说。"演出她接过那张纸时的神情——别人送她礼物,只有他送她喘息`,
      变动: true,
    };
  }
  // 垫上
  if (data.现金 < 欠额) {
    节点._欠租笔数 = Math.ceil(欠额 / 配.月租); // 钱不够,账退回去
    return { 提示: `想垫上这 ¥${欠额},你兜里的钱不够。` };
  }
  data.现金 -= 欠额;
  节点.妻.好感值 = _.clamp(节点.妻.好感值 + 8, 0, 100);
  return {
    提示: `¥${欠额} 从你口袋里出去了。账面干净,人情记下了。`,
    事件: `【垫租】${妻名}家的欠租被{{user}}悄悄垫上了,账本上什么都看不出来。她后来知道了这件事——演出她的五味杂陈:这个人情,她不知道该怎么还`,
    变动: true,
  };
}

// ============================================
// L4 要钱按钮(钱的流向反转=堕落可视化;榨取自带刹车)
// ============================================

export function 要钱(data: SchemaType, 门牌号: 门牌, 楼层: number): 经济结果 {
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配) return { 提示: '要不了。' };
  if (节点.妻.当前阶段 < 4) return { 提示: '你们的关系还没到伸手的地步。' };
  const 现钟 = 钟(data, 楼层);
  const 上次原 = 节点.妻._上次要钱楼层;
  const 上次 = 上次原 > 现钟 ? -999 : 上次原; // 回档陷阱守卫
  if (现钟 - 上次 < 经济配置.要钱冷却楼) return { 提示: '刚开过口,再等等——吃相别太难看。' };

  节点.妻._上次要钱楼层 = 现钟;
  节点.妻._要钱次数 += 1;
  data.现金 += 经济配置.要钱数额;

  // 刹车:累计≥N次,她自己的钱见底,只能向丈夫开口——丈夫心底觉得异样
  if (节点.妻._要钱次数 >= 经济配置.要钱触发疑心次数) {
    if (节点.夫._疑心冻结至 < 现钟) {
      节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 经济配置.要钱疑心增量, 0, 100);
    }
    return {
      提示: `¥${经济配置.要钱数额} 到手。她的私房钱早就见底了——这笔,是她跟丈夫开口要来的。`,
      事件: `【要钱】${配.妻名}又给了{{user}}一笔钱(¥${经济配置.要钱数额})。她自己的钱早花空了,这笔是她找丈夫要的——演出她跟丈夫开口的那一小段(借口、丈夫多看她的那一眼),以及她把钱递给{{user}}时不敢看他的手`,
      变动: true,
    };
  }
  return {
    提示: `她把钱塞过来,像怕你反悔似的。+¥${经济配置.要钱数额}`,
    事件: `【要钱】{{user}}向${配.妻名}开了口,她几乎没犹豫就把钱给了他(¥${经济配置.要钱数额})。演出这次给予——从他花钱开发她,到她倒贴他,钱的流向早就说明了一切`,
    变动: true,
  };
}

// ============================================
// 公共区金币(路过的小惊喜,不是可挂机副业:只挂钟楼种子,每K楼重掷)
// ============================================

const 金币房间: readonly string[] = ['大堂', '天台', '楼梯间'];

/** 此刻该房间有没有能捡的钱(UI 与脚本共用同一真值:纯种子+chat标记) */
export function 查金币(房间id: string, 现钟: number): number {
  if (!金币房间.includes(房间id)) return 0;
  const 期 = Math.floor(现钟 / 经济配置.金币刷新楼);
  if (seededRandom(期, 房间id, '金币') >= 经济配置.金币概率) return 0;
  if (读计数().拾取[`${房间id}:${期}`]) return 0;
  const 幅 = 经济配置.金币上限 - 经济配置.金币下限;
  return 经济配置.金币下限 + Math.floor(seededRandom(期, 房间id, '金币额') * (幅 + 1));
}

export function 捡金币(data: SchemaType, 房间id: string, 楼层: number): 经济结果 {
  const 现钟 = 钟(data, 楼层);
  const 数额 = 查金币(房间id, 现钟);
  if (!数额) return { 提示: '地上什么都没有。' };
  const c = 读计数();
  c.拾取[`${房间id}:${Math.floor(现钟 / 经济配置.金币刷新楼)}`] = true;
  写计数(c);
  data.现金 += 数额;
  return { 提示: `【拾获】${查房间名(房间id)}角落里捡到 ¥${数额}——谁掉的零钱,进了管理员的口袋。`, 变动: true };
}

function 查房间名(id: string): string {
  return ({ 大堂: '大堂', 天台: '天台', 楼梯间: '楼梯间' } as Record<string, string>)[id] ?? id;
}

// ============================================
// 空房偷窃(破门进外出住户家翻现金;概率低数额大,事后察觉几率=疑心+/风闻+)
// ============================================

export function 空房偷窃(data: SchemaType, 门牌号: 门牌, 楼层: number): 经济结果 {
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配) return { 提示: '这屋没什么可翻的。' };
  const { 房间id, 破门, 进房末楼 } = 读场景();
  if (房间id !== 门牌号 || !破门) return { 提示: '得先进得去,才翻得着。' };
  const 现钟 = 钟(data, 楼层);
  // 进房那刻已经确认是空屋，之后的演出冻结在该时点，不能因停留期间跨时段把住客瞬移回来。
  // 未来作废守卫(审计 低危11):酒馆原生删楼后 chat 变量不回滚,进房末楼可能停在"未来"
  const 进房钟 = 钟(data, 进房末楼 != null && 进房末楼 <= 楼层 ? 进房末楼 : 楼层);
  if (妻位置推算(门牌号, 进房钟) === 门牌号 || 丈夫在楼(节点, 门牌号, 进房钟) !== '外出') {
    return { 提示: '屋里有人,你的手缩了回来。' };
  }
  const c = 读计数();
  const 上次原 = c.偷窃上次[门牌号] ?? -999;
  const 上次 = 上次原 > 现钟 ? -999 : 上次原;
  if (现钟 - 上次 < 经济配置.偷窃同户冷却楼) return { 提示: '这家你翻过不久——明面上的钱不会自己长回来。' };
  c.偷窃上次[门牌号] = 现钟;
  写计数(c);

  if (seededRandom(现钟, 门牌号, '偷窃') >= 经济配置.偷窃现金概率) {
    return { 提示: '抽屉、床头、外套口袋……都翻了,没找到明面上的现金。' };
  }
  const 幅 = 经济配置.偷窃上限 - 经济配置.偷窃下限;
  const 数额 = 经济配置.偷窃下限 + Math.floor(seededRandom(现钟, 门牌号, '偷窃额') * (幅 + 1));
  data.现金 += 数额;

  // 事后察觉(支柱0:每件脏事汇入同一池子)
  if (seededRandom(现钟, 门牌号, '偷窃察觉') < 经济配置.偷窃察觉概率) {
    if (节点.夫._疑心冻结至 < 现钟) {
      节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 经济配置.偷窃察觉疑心, 0, 100);
    }
    data.风闻 = _.clamp(data.风闻 + 经济配置.偷窃察觉风闻, 0, 100);
    return {
      提示: `【偷窃】翻出 ¥${数额}。塞回口袋时,你听见楼道里有脚步声——不知道有没有人留意到你从这户出来。`,
      事件: `【失窃的家】${配.妻名}家最近丢了钱。她自己念叨"是不是我记错了",她丈夫没说话,但心里起了一笔账。这件事没人指向{{user}},但楼里的空气变了一点`,
      变动: true,
    };
  }
  return { 提示: `【偷窃】抽屉深处翻出 ¥${数额}。你把一切原样放好,没人会知道。`, 变动: true };
}

// ============================================
// 运作道具(机制不可见的道具版:效果脚本静默执行,AI 只看到剧情皮)
