// ============================================

export function 接听来电(data: SchemaType): { 成功: boolean; 分数段: string; 报表: string; 通牒: boolean } {
  const 电 = data.系统._待接来电;
  if (电.期 < 0) return { 成功: false, 分数段: '', 报表: '', 通牒: false };
  data.胜任度 = _.clamp(data.胜任度 + 经济配置.接听来电加分, 0, 100);
  const 出 = { 成功: true, 分数段: 电.分数段, 报表: 电.报表, 通牒: 电.通牒 };
  data.系统._待接来电 = { 期: -1, 分数段: '', 报表: '', 通牒: false };
  return 出;
}

export function 挂断来电(data: SchemaType): void {
  // 挂断不清状态:红点继续挂着,下一期被覆盖时照扣(不接爸的电话本身就是失职)
  void data;
}
