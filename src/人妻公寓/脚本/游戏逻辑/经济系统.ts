/**
 * 经营账仍按短周期逐期结算；普通父亲电话只在跨过独立联络周期时出现。
 * 两个周期不整除时，电话落在跨过周界后的首个经营期界，长期平均仍约一周一次。
 */
function 父亲例行来电到期(全局期: number, 经营期长: number): boolean {
  const 联络间隔 = Math.max(经营期长, 经济配置.父亲例行来电间隔时段);
  const 上一期界 = Math.max(0, (全局期 - 1) * 经营期长);
  const 本期界 = Math.max(0, 全局期 * 经营期长);
  return Math.floor(本期界 / 联络间隔) > Math.floor(上一期界 / 联络间隔);
}

function 例行联络报表(data: SchemaType): string {
  const 在办 = data.系统._管理考核.活跃任务.filter(任务 => !任务.逾期已扣).length;
  return `例行联络：近期账目已按经营周期结算；${在办 > 0 ? `${在办}件日常楼务仍在期限内推进` : '楼里没有需要立即追责的异常'}`;
}

/**
 * 完整期界之外刚逾期的重要／紧急楼务仍要即时通知父亲。这里只冻结本次新逾期事实：
 * 日常任务留到周报，正式通牒仍只能由期界考核启动，风闻专用 `紧急` 标志也不借用。
 */
function 合并严重楼务即时来电(
  data: SchemaType,
  任务ids: readonly string[],
  当前绝对时段: number,
  当前全局期: number,
): string {
  if (!任务ids.length) return '';
  const ids = new Set(任务ids);
  const 级别序 = { 紧急: 2, 重要: 1 } as const;
  const 报表 = data.系统._管理考核.活跃任务
    .filter(任务 => ids.has(任务.id) && (任务.级别 === '重要' || 任务.级别 === '紧急'))
    .sort(
      (a, b) =>
        级别序[b.级别 as keyof typeof 级别序] - 级别序[a.级别 as keyof typeof 级别序] ||
        a.截止时段 - b.截止时段 ||
        a.id.localeCompare(b.id),
    )
    .map(任务 => `${管理任务摘要(任务)}已逾期${Math.max(1, 当前绝对时段 - 任务.截止时段)}时段`)
    .join(';');
  if (!报表) return '';

  const 红线 = (难度表[data.系统._难度] ?? 难度表['标准']).胜任度红线;
  const 通牒中 = data.系统._通牒期 >= 0;
  // 跌破红线但尚未到期界，只能显示“危险”；不能在这里把分数段伪装成已正式通牒。
  const 分数段 = 通牒中 ? '通牒' : data.胜任度 <= 红线 ? '危险' : 胜任态度(data.胜任度, 红线, false);
  const 旧待接 = data.系统._待接来电;
  if (旧待接.期 >= 0) {
    const 原通牒 = 旧待接.通牒;
    data.系统._待接来电 = {
      期: 旧待接.期,
      分数段: 更严重父亲分数段(旧待接.分数段, 分数段),
      报表: 合并父亲报表(旧待接.报表, 报表),
      通牒: 原通牒 || 通牒中,
      紧急: 旧待接.紧急,
      母亲圆场: { ...旧待接.母亲圆场 },
    };
    return !原通牒 && 通牒中 ? '【来电】父亲原来那通电话已经升级为最后通牒。' : '';
  }

  data.系统._待接来电 = {
    期: 当前全局期,
    分数段,
    报表,
    通牒: 通牒中,
    紧急: false,
    母亲圆场: { 触发: false, 事件ID: '', 摘要: '', 仅剧情: false },
  };
  return 通牒中 ? '【来电】父亲的电话在响——这一通,最好接。' : '【来电】父亲来电话了，似乎有一件具体的事要问。';
}

function 风闻通牒原因(
  data: SchemaType,
  责任: readonly { 事件ID: string; 摘要: string; 扣分: number }[],
  延续紧急危机: boolean,
): string {
  const 有本期风闻扣分 = 责任.some(item => item.扣分 > 0);
  if (!有本期风闻扣分 && !延续紧急危机) return '';
  const 责任事件 = new Set(责任.filter(item => item.扣分 > 0).map(item => item.事件ID));
  const 候选事件 = data.系统._风闻账.最近事件.filter(
    event => 责任事件.has(event.id) || (延续紧急危机 && event.状态 === '活跃' && event.胜任责任 > 0),
  );
  const 母亲硬事件 = 候选事件.find(
    event =>
      event.门牌 === '302' &&
      (event.迹象 === '硬证据' || event.迹象 === '正式投诉' || event.胜任责任 >= 6),
  );
  if (母亲硬事件) return `母亲事发：${风闻事件安全摘要(母亲硬事件)}`;
  const 摘要 = 候选事件[0] ? 风闻事件安全摘要(候选事件[0]) : 责任.find(item => item.扣分 > 0)?.摘要;
  return `公开丑闻${摘要 ? `：${摘要}` : '：楼内风闻危机已经传到父亲那里'}`;
}

function 风闻责任类别(data: SchemaType, 事件ID: string): 胜任责任类别 {
  const event = data.系统._风闻账.最近事件.find(item => item.id === 事件ID);
  return event?.门牌 === '302' &&
    (event.迹象 === '硬证据' || event.迹象 === '正式投诉' || event.胜任责任 >= 6)
    ? '母亲事发'
    : '公开丑闻';
}

