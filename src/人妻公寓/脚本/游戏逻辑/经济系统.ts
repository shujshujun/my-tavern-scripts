// ============================================
// 公共区金币(路过的小惊喜,不是可挂机副业:按绝对时段挂种子,每K时段重掷)
// ============================================

const 金币房间: readonly string[] = ['大堂', '天台', '楼梯间'];

/** 此刻该房间有没有能捡的钱(UI 与脚本共用同一真值:纯种子+chat标记) */
export function 查金币(房间id: string, 绝对时段: number): number {
  if (!金币房间.includes(房间id)) return 0;
  const 期 = Math.floor(绝对时段 / 经济配置.金币刷新时段);
  if (seededRandom(期, 房间id, '金币') >= 经济配置.金币概率) return 0;
  // 标记与偷窃冷却同规:数字戳停在"未来"=回档遗留(钱已随 stat 回滚,标记却留在 chat 变量),
  // 作废掉让这枚金币能重捡;旧格式 true 无法判龄,保守视为已拾(2026-08-03 审计 L1)
  const 拾取记录 = 读计数().拾取[`${房间id}:${期}`];
  if (拾取记录 === true || (typeof 拾取记录 === 'number' && 拾取记录 <= 绝对时段)) return 0;
  const 幅 = 经济配置.金币上限 - 经济配置.金币下限;
  return 经济配置.金币下限 + Math.floor(seededRandom(期, 房间id, '金币额') * (幅 + 1));
}

export function 捡金币(data: SchemaType, 房间id: string, _消息楼层?: number): 经济结果 {
  const 现钟 = 取绝对时段(data);
  const 数额 = 查金币(房间id, 现钟);
  if (!数额) return { 提示: '地上什么都没有。' };
  const c = 读计数();
  c.拾取[`${房间id}:${Math.floor(现钟 / 经济配置.金币刷新时段)}`] = 现钟;
  data.现金 += 数额;
  return {
    提示: `【拾获】${查房间名(房间id)}角落里捡到 ¥${数额}——谁掉的零钱,进了管理员的口袋。`,
    变动: true,
    提交后: () => 写计数(c),
  };
}

function 查房间名(id: string): string {
  return ({ 大堂: '大堂', 天台: '天台', 楼梯间: '楼梯间' } as Record<string, string>)[id] ?? id;
}

// ============================================
// 空房偷窃(破门进外出住户家翻现金;概率低数额大,事后察觉几率=疑心+/风闻+)
// ============================================

export function 空房偷窃(data: SchemaType, 门牌号: 门牌, 楼层: number): 经济结果 {
  const 节点 = data.户[门牌号];
  const 配 = 户静态表[门牌号];
  if (!节点 || !配) return { 提示: '这屋没什么可翻的。' };
  const { 房间id, 破门, 非法进入, 进房末楼 } = 读场景();
  if (房间id !== 门牌号 || !(非法进入 || 破门)) return { 提示: '得先进得去,才翻得着。' };
  const 现钟 = 取绝对时段(data);
  // 真实消息楼只校验场景连续性；住客此刻是否在家读取当前绝对时段。
  if (进房末楼 != null && 进房末楼 > 楼层) return { 提示: '这段进房记录已经失效。' };
  if (妻位置推算(门牌号, 现钟, 节点) === 门牌号 || 丈夫在楼(节点, 门牌号, 现钟) !== '外出') {
    return { 提示: '屋里有人,你的手缩了回来。' };
  }
  const c = 读计数();
  const 上次原 = c.偷窃上次[门牌号] ?? -999;
  const 上次 = 上次原 > 现钟 ? -999 : 上次原;
  if (现钟 - 上次 < 经济配置.偷窃同户冷却时段) return { 提示: '这家你翻过不久——明面上的钱不会自己长回来。' };
  c.偷窃上次[门牌号] = 现钟;
  const 完成偷窃 = (结果: 经济结果): 经济结果 => ({
    ...结果,
    提交后: async () => {
      写计数(c);
      await 结果.提交后?.();
    },
  });

  if (seededRandom(现钟, 门牌号, '偷窃') >= 经济配置.偷窃现金概率) {
    return 完成偷窃({ 提示: '抽屉、床头、外套口袋……都翻了,没找到明面上的现金。', 变动: true });
  }
  const 幅 = 经济配置.偷窃上限 - 经济配置.偷窃下限;
  const 数额 = 经济配置.偷窃下限 + Math.floor(seededRandom(现钟, 门牌号, '偷窃额') * (幅 + 1));
  data.现金 += 数额;

  // 事后察觉(支柱0:每件脏事汇入同一池子)
  if (seededRandom(现钟, 门牌号, '偷窃察觉') < 经济配置.偷窃察觉概率) {
    if (!疑心冻结中(节点.夫, 现钟)) {
      节点.夫.疑心值 = _.clamp(节点.夫.疑心值 + 经济配置.偷窃察觉疑心, 0, 100);
    }
    登记风闻事件(data, {
      id: `偷窃察觉:${现钟}:${门牌号}`,
      类型: '偷窃察觉',
      目标增量: 经济配置.偷窃察觉风闻,
      门牌: 门牌号,
      地点: 门牌号,
      摘要: `${门牌号}住户发现家中失窃痕迹`,
      迹象: '硬证据',
      投诉: '严重',
    });
    return 完成偷窃({
      提示: `【偷窃】翻出 ¥${数额}。塞回口袋时,你听见楼道里有脚步声——不知道有没有人留意到你从这户出来。`,
      事件: `【失窃的家】${配.妻名}家最近丢了钱。她自己念叨"是不是我记错了",她丈夫没说话,但心里起了一笔账。这件事没人指向{{user}},但楼里的空气变了一点`,
      变动: true,
    });
  }
  return 完成偷窃({ 提示: `【偷窃】抽屉深处翻出 ¥${数额}。你把一切原样放好,没人会知道。`, 变动: true });
}

