export interface 接听来电结果 {
  成功: boolean;
  标识: string;
}

/**
 * 把“尚未接听”原子转成“通话中”。胜任度态度分与两个状态的交接由调用方在同一次
 * `脚本写入` 中落库，刷新绝不会再落入“待接已清、通话尚未建立”的空窗。
 */
export function 接听来电(data: SchemaType, 通话标识: string): 接听来电结果 {
  const 进行中 = data.系统._父亲通话;
  if (进行中.标识 && 进行中.期 >= 0) return { 成功: false, 标识: 进行中.标识 };
  const 电 = data.系统._待接来电;
  if (电.期 < 0 || !通话标识) return { 成功: false, 标识: '' };
  登记胜任变动(data, {
    id: `接听父亲来电:${电.期}:${通话标识}`,
    变动: 经济配置.接听来电加分,
    类别: '正向经营',
    原因: `按时接听第${电.期}期父亲来电`,
    数值上限: 80,
  });
  data.系统._父亲通话 = {
    ...空父亲通话(),
    标识: 通话标识,
    状态: '通话中',
    期: 电.期,
    分数段: 电.分数段,
    报表: 电.报表,
    通牒: 电.通牒,
    紧急: 电.紧急,
    母亲圆场: { ...电.母亲圆场 },
    待回复: { 序号: 1, 玩家说: '(通话接通,父亲先开口)' },
    下次回复序号: 2,
  };
  data.系统._待接来电 = {
    期: -1,
    分数段: '',
    报表: '',
    通牒: false,
    紧急: false,
    母亲圆场: { 触发: false, 事件ID: '', 摘要: '', 仅剧情: false },
  };
  return { 成功: true, 标识: 通话标识 };
}

