export function 使用运作(data: SchemaType, 道具id: string, 门牌号: 门牌 | null, 楼层: number): 经济结果 {
  const 配 = 查道具(道具id);
  if (!配 || 配.类别 !== '运作') return { 提示: '这不是能这么用的东西。' };
  const i = data.背包.indexOf(道具id);
  if (i < 0) return { 提示: '背包里没有这件东西。' };
  const 现钟 = 钟(data, 楼层);

  // 需要指定户的四件
  const 户向 = ['钓鱼团购券', '夜班内推', '外地项目介绍', '代订惊喜'].includes(道具id);
  const 节点 = 户向 && 门牌号 ? data.户[门牌号] : null;
  const 户配 = 户向 && 门牌号 ? 户静态表[门牌号] : null;
  if (户向 && (!节点 || !户配 || !户配.夫名)) return { 提示: '这份"心意"得有个明确的去处。' };

  const 用掉 = () => data.背包.splice(i, 1);

  switch (道具id) {
    case '钓鱼团购券': {
      用掉();
      节点!.夫._疑心冻结至 = 现钟 + 经济配置.钓鱼冻结楼;
      return {
        提示: `${户配!.夫名}收下了券,周末的日程定了。`,
        事件: `【钓鱼】{{user}}把一张钓鱼一日券送给了${户配!.夫名}("中奖送的,放着浪费")。他高兴地收下,满脑子都是周末的鱼塘——这阵子他顾不上琢磨别的`,
        变动: true,
      };
    }
    case '夜班内推': {
      用掉();
      节点!.夫._外出至 = Math.max(节点!.夫._外出至, 现钟 + 经济配置.夜班外出楼);
      return {
        提示: `${户配!.夫名}接了夜班的活。晚上的楼道,清净了。`,
        事件: `【夜班】经{{user}}介绍,${户配!.夫名}接了一段双倍工资的夜班。他为多出来的收入高兴,${户配!.妻名}晚上一个人在家的日子开始了`,
        变动: true,
      };
    }
    case '外地项目介绍': {
      const 上次原 = 节点!.夫._上次出差楼;
      const 上次 = 上次原 > 现钟 ? -999 : 上次原;
      if (现钟 - 上次 < 经济配置.出差每户冷却楼) return { 提示: '他刚回来没多久,再撮合一次出差太扎眼了。' };
      用掉();
      节点!.夫._上次出差楼 = 现钟;
      节点!.夫._外出至 = Math.max(节点!.夫._外出至, 现钟 + 经济配置.出差外出楼);
      return {
        提示: `行李箱轮子的声音,是这栋楼里最好听的声音。${户配!.夫名}出差去了。`,
        事件: `【出差】${户配!.夫名}接了{{user}}牵线的外地项目,一去要好一阵子。${户配!.妻名}在门口送他,挥手的弧度很标准`,
        变动: true,
      };
    }
    case '代订惊喜': {
      用掉();
      节点!.夫.疑心值 = _.clamp(节点!.夫.疑心值 - 经济配置.代订疑心直降, 0, 100);
      return {
        提示: `以她的名义订的小惊喜送到了${户配!.夫名}手上。他今天看谁都顺眼。`,
        事件: `【惊喜】${户配!.夫名}收到了一份"妻子订的"小惊喜,一整天心情都很好,看${户配!.妻名}的眼神都软了几分。没人知道下单的人是谁`,
        变动: true,
      };
    }
    case '全楼聚餐': {
      用掉();
      data.风闻 = _.clamp(data.风闻 - 经济配置.聚餐风闻直降, 0, 100);
      return {
        提示: '大排档两桌,酒过三巡。一顿饭下去,楼里的闲话淡了。',
        事件: '【聚餐】物业做东,全楼在楼下大排档吃了一顿。烟火气一上来,那些阳台对望的眼神和走廊里的窃语都被冲淡了不少',
        变动: true,
      };
    }
    case '粉刷翻新': {
      用掉();
      data.胜任度 = _.clamp(data.胜任度 + 经济配置.粉刷胜任度加, 0, 100);
      return {
        提示: '楼道焕然一新。这笔支出,账目上很漂亮。',
        事件: '【翻新】楼道重新粉刷,扶手除了锈。住户们进出都要摸一把新墙,交口称赞管理员会办事',
        变动: true,
      };
    }
    case '节日礼盒全员装': {
      用掉();
      for (const 节 of Object.values(data.户)) 节.妻.上次互动楼层 = 楼层;
      return {
        提示: '每户门口挂上了小礼盒。全楼太太们都记起了你的好。',
        事件: '【礼盒】每户门把手上都挂了一份管理处的节日小礼盒。这栋楼的太太们提起管理员,语气都热了几分',
        变动: true,
      };
    }
    case '物业巡检表': {
      用掉();
      const 行 = Object.keys(data.户)
        // 存在性守卫(审计 低危13):`!undefined?.隐身` 为 true,野门牌会放行到下面的裸取炸掉
        .filter(m => 户静态表[m as 门牌] && !户静态表[m as 门牌].隐身)
        .map(m => {
          const 配2 = 户静态表[m as 门牌];
          const 妻在 = 妻位置推算(m as 门牌, 现钟) === m ? '在家' : '不在';
          const 夫在 = 配2.夫名 ? 丈夫在楼(data.户[m as 门牌], m as 门牌, 现钟) : '—';
          return `${m}:${配2.妻名}${妻在}/${配2.夫名 || '—'}${夫在}`;
        })
        .join(' | ');
      return { 提示: `【巡检】${行}`, 变动: true };
    }
    default:
      return { 提示: '这件东西还没想好怎么用。' };
  }
}

