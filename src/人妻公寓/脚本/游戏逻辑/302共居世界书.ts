        '父亲是否已经到楼、暂住、离楼或退出审核，只服从当前剧情中已经成立的事实；不得提前宣布《双重继承》完成。',
        '母亲与玩家的关系只服从当前剧情进度，不得提前套用结局后的稳定共居生活。',
