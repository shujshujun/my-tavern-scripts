import { 解析绝对时段 } from '../../周作息';

export type 管理任务通知类型 = '报修' | '投诉';

export interface 管理任务通知输入 {
  类型: 管理任务通知类型;
  地点: string;
  事项: string;
  当前时段: number;
  截止时段: number;
}

const 报修口吻: Readonly<Record<string, string>> = {
  水龙头漏水: '水龙头漏水了',
  插座跳闸: '插座一用就跳闸',
  下水堵塞: '下水堵了',
  暖气阀漏水: '暖气阀漏水了',
  房内设施故障: '房里的设施出了故障',
};

function 相对日期时段(当前绝对时段: number, 截止绝对时段: number): string {
  const 当前 = 解析绝对时段(当前绝对时段);
  const 截止 = 解析绝对时段(截止绝对时段);
  const 相隔天数 = 截止.天数 - 当前.天数;

  if (相隔天数 === 0 && 截止.时段 === '晚上') return '今晚';
  if (相隔天数 === 0 && 截止.时段 === '深夜') return '今晚深夜';
  if (相隔天数 === 1 && 截止.时段 === '晚上') return '明晚';
  if (相隔天数 === 1 && 截止.时段 === '深夜') return '明天深夜';

  const 日期 =
    相隔天数 === 0
      ? '今天'
      : 相隔天数 === 1
        ? '明天'
        : 相隔天数 === 2
          ? '后天'
          : 截止.周数 === 当前.周数 + 1
            ? `下${截止.星期.replace('星期', '周')}`
            : 截止.星期.replace('星期', '周');
  return `${日期}${截止.时段}`;
}

/** 楼务硬通知使用住户会说的相对时间，不把内部“第几天”时钟直接露给玩家。 */
export function 管理任务期限口吻(当前时段: number, 截止时段: number): string {
  const 当前 = Math.max(0, Math.floor(Number(当前时段) || 0));
  const 截止 = Math.max(0, Math.floor(Number(截止时段) || 0));
  return 截止 < 当前 ? '尽快' : `最晚${相对日期时段(当前, 截止)}`;
}

export function 编译管理任务通知文案(输入: 管理任务通知输入): string {
  const 地点 = String(输入.地点 ?? '').trim() || '房里';
  const 事项 = String(输入.事项 ?? '').trim() || (输入.类型 === '报修' ? '房内设施故障' : '住户问题');
  const 期限 = 管理任务期限口吻(输入.当前时段, 输入.截止时段);

  if (输入.类型 === '报修') {
    const 问题 = 报修口吻[事项] ?? `${事项}需要处理`;
    return `管理员，${地点}这边${问题}，麻烦${期限}过来处理一下。`;
  }
  return `管理员，我已把“${事项}”投诉提交到管理员室，地点是${地点}，麻烦${期限}处理一下。`;
}
