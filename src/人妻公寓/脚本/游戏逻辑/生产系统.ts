export function 已生孩子(data: SchemaType, 门牌号: 门牌) {
  return data.系统._家庭文档.孩子
    .filter(孩子 => 孩子.母亲门牌 === 门牌号)
    .sort((a, b) => a.胎次 - b.胎次 || a.出生绝对时段 - b.出生绝对时段);
}

export function 已生产胎数(data: SchemaType, 门牌号: 门牌): number {
  return 已生孩子(data, 门牌号).length;
}

export function 已达生产上限(data: SchemaType, 门牌号: 门牌): boolean {
  return 已生产胎数(data, 门牌号) >= 每人最多胎数;
}

/** 成功受孕当刻冻结胎次与家庭计划知情事实；孕期时钟仍要等确认微信真正已读才启动。 */
export function 初始化本胎生产账(data: SchemaType, 门牌号: 门牌): boolean {
  const 节点 = data.户[门牌号];
  if (!节点 || 已达生产上限(data, 门牌号)) return false;
  const 本胎序号 = 已生产胎数(data, 门牌号) + 1;
  节点.妻._生产 = {
    ...空生产账(),
    本胎序号,
    家庭计划知情: 门牌号 === '101' && data.系统._家庭计划.阶段 === '已完成',
  };
  return true;
}

/** 微信前台已读后的唯一孕期起算口；重复、过期或其他胎次凭据均无副作用。 */
export function 开始已读孕期(data: SchemaType, 门牌号: 门牌, 场次标识: string): boolean {
  const 妻 = data.户[门牌号]?.妻;
  if (!妻 || 妻._怀孕.受孕场次标识 !== 场次标识 || 妻._怀孕.状态 !== '待告知') return false;
  const 当前绝对时段 = 读取世界时间(data).绝对时段;
  if (妻._生产.本胎序号 <= 0) {
    if (!初始化本胎生产账(data, 门牌号)) return false;
  }
  妻._怀孕.状态 = '已告知';
  妻._怀孕.告知绝对时段 = 当前绝对时段;
  妻._生产.状态 = '孕期';
  妻._生产.确认已读绝对时段 = 当前绝对时段;
  妻._生产.预产绝对时段 = 当前绝对时段 + 孕期时段数;
  return true;
}

