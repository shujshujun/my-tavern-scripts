function 失败(提示: string, 时间: 世界时间快照): 时间推进事务结果 {
  return {
    成功: false,
    提示,
    起始时间: 时间,
    结束时间: 时间,
    推进时段数: 0,
    线路提示: [],
    经济提示: [],
    资源提示: [],
  };
}

/** 只允许覆盖中央事务自己留下的一条时间文案，不能借标签吞掉其他强制事件。 */
export function 是单一时间流逝事件(事件: string): boolean {
  const 文本 = 事件.trim();
  const 标签 = 文本.match(/【[^】]+】/g) ?? [];
  return 文本.startsWith('【时间流逝】') && 标签.length === 1 && 标签[0] === '【时间流逝】' && !文本.includes('|');
}

function 刷新丈夫状态(data: SchemaType, 绝对时段: number): void {
  for (const [门牌字符串, 节点] of Object.entries(data.户)) {
    const 门牌号 = 门牌字符串 as 门牌;
    if (!节点 || !户静态表[门牌号]) continue;
    节点.夫.状态 = 丈夫在楼(节点, 门牌号, 绝对时段);
  }
}

function 构造时间流逝事件(方式: 时间推进方式, 结束时间: 世界时间快照, 地点: 时间推进地点): string {
  const 行动 =
    方式 === '睡到次日早晨'
      ? 地点 === '302'
        ? '在302家中睡下,一直休息到次日早晨;醒来后仍在302'
        : '在管理员室的值班床睡下,一直休息到次日早晨;醒来后仍在管理员室'
      : 方式 === '晨跑'
        ? '沿河畔公园完成了一次晨跑,让时间向前走过一个时段'
        : 方式 === '健身'
          ? '在公寓健身房完成了一次训练,让时间向前走过一个时段'
          : 方式 === '小憩'
            ? '停下手头的事小憩片刻,让时间向前走过一个时段'
            : '停下手头的事,让公寓里的钟向前走过一个时段';
  return (
    `【时间流逝】{{user}}${行动}。现在是第${结束时间.天数}天、${结束时间.星期}${结束时间.时段}。` +
    '上一场戏已经散了,请按此刻的公寓光景自然开启本轮,不要把推进时间前的场面原样续下去'
  );
}

function 推进候选(data: SchemaType, 方式: 时间推进方式): 时段推进结果 {
  return 方式 === '睡到次日早晨' ? 推进到次日早晨(data) : 推进时段(data, 1);
}

/**
 * 玩家主动推进世界时间的唯一原子事务。
 *
 * 所有业务结算先在深拷贝上按固定顺序完成，最后一次性替换传入数据；任何校验失败或
 * 运行时异常都不会改动原对象。消息楼只供入住事件定位，绝不参与时间、作息或结算。
 */
export function 执行时间推进事务(data: SchemaType, 请求: 时间推进请求): 时间推进事务结果 {
  const 起始时间 = 读取世界时间(data);

  // 乐观并发门必须最先检查：旧界面即使同时碰上坏结局/强事件，也只得到“状态已变化”。
  if (!Number.isInteger(请求?.预期绝对时段) || 请求.预期绝对时段 !== 起始时间.绝对时段) {
    return 失败('世界时间已经变化，请刷新当前状态后重试。', 起始时间);
  }
  if (data.系统._坏结局) return 失败('结局已经锁定，世界时间不能再推进。', 起始时间);

  const 原待发送事件 = data.系统._待发送事件;
  if (原待发送事件 && !是单一时间流逝事件(原待发送事件)) {
    return 失败('还有尚未演出的强制事件，请先完成这一幕。', 起始时间);
  }

  if (!['推进一时段', '睡到次日早晨', '小憩', '晨跑', '健身'].includes(请求.方式)) {
    return 失败('无法识别这次时间推进方式。', 起始时间);
  }
  if (!['管理员室', '302', '晨跑公园', '健身房'].includes(请求.当前地点)) {
    return 失败('当前地点不能执行这次时间推进。', 起始时间);
  }
  if (请求.方式 === '推进一时段' && 请求.当前地点 !== '管理员室') {
    return 失败('只有管理员室可以推进一个时段。', 起始时间);
  }
  if (请求.方式 === '睡到次日早晨' && 请求.当前地点 !== '管理员室' && 请求.当前地点 !== '302') {
    return 失败('只有管理员室或 302 可以睡到次日早晨。', 起始时间);
  }
  if (请求.方式 === '小憩' || 请求.方式 === '晨跑' || 请求.方式 === '健身') {
    const 活动校验 = 校验玩家时间活动(data, 请求.方式, 请求.当前地点);
    if (!活动校验.成功) return 失败(活动校验.提示, 起始时间);
  }
  if (!Number.isInteger(请求.当前消息楼) || 请求.当前消息楼 < 0) {
    return 失败('当前正文楼层无效，时间没有推进。', 起始时间);
  }

  try {
    const 候选 = _.cloneDeep(data) as SchemaType;
    // 已有时间文案只是尚未演出的旧提示，可以被本次更晚的同类事务覆盖。
    候选.系统._待发送事件 = '';

    const 推进结果 = 推进候选(候选, 请求.方式);
    const 结束时间 = 推进结果.新时间;
    const 资源提示: string[] = [];
    if (请求.方式 === '睡到次日早晨') {
      完全恢复玩家资源(候选);
      资源提示.push('睡眠完成：精力与体力已经按当前上限完全恢复。');
    } else if (请求.方式 === '小憩' || 请求.方式 === '晨跑' || 请求.方式 === '健身') {
      资源提示.push(结算玩家时间活动(候选, 请求.方式, 玩家当前日(data)));
    }

    // 固定事务顺序：所有后台被动账 → 作息栏 → 经济 → 冷落 → 阶段线路。
    惰性结算全楼(候选);
    刷新丈夫状态(候选, 结束时间.绝对时段);
    const 经济提示 = 经济结算(候选, 请求.当前消息楼);
    // 经济查账可能在本次事务内首次写入坏结局。Game Over 一旦成立，本笔后续人物账与
    // 关系线路必须立即冻结，不能在终局之后继续扣冷落或发放线路节点。
    const 线路提示: string[] = [];
    if (!候选.系统._坏结局) {
      结算全楼冷落(候选);
      线路提示.push(...上报时段推进(候选, 请求.方式));
    }

    const 无强事件 = () => !候选.系统._坏结局 && !候选.系统._待发送事件;

    // 首夜第二幕只在真正抵达早晨时抢占事件槽；其优先级高于新住户和普通时间文案。
    if (结束时间.时段 === '早上' && 候选.系统._母亲首夜第二幕 && 无强事件()) {
      候选.系统._待发送事件 = 构造母亲早饭桌事件(请求.当前地点);
    }

    // 时间事务已经收束连续人物，入住检测固定以 0 个持续人物运行；消息楼只用于事件定位。
    if (无强事件()) 入住检测(候选, 请求.当前消息楼, 0);

    // 没有更高优先级事件时只留一条可覆盖的时间文案，永不与强制事件用 `|` 拼接。
    if (无强事件()) 候选.系统._待发送事件 = 构造时间流逝事件(请求.方式, 结束时间, 请求.当前地点);

    Object.assign(data, 候选);
    const 动作提示 =
      请求.方式 === '睡到次日早晨'
        ? `已休息到第 ${结束时间.天数} 天${结束时间.时段}。`
        : `时间已推进到第 ${结束时间.天数} 天${结束时间.时段}。`;
    return {
      成功: true,
      提示: 动作提示,
      起始时间,
      结束时间,
      推进时段数: 推进结果.推进时段数,
      线路提示,
      经济提示,
      资源提示,
    };
  } catch (error) {
    console.error('[人妻公寓·时间] 原子推进失败，已放弃候选状态:', error);
    return 失败('时间推进失败，世界状态没有改变。', 起始时间);
  }
}
