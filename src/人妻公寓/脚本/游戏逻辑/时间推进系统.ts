export type 时间推进方式 = '推进一时段' | '睡到次日早晨' | 玩家时间活动;
export type 时间推进地点 = '管理员室' | '302' | '晨跑公园' | '健身房';

export interface 时间推进请求 {
  方式: 时间推进方式;
  /** UI 读到的世界时间版本；与存档不一致时失败关闭，防止连点和旧界面重复提交。 */
  预期绝对时段: number;
  /** 只交给仍以消息楼承担正文事件定位的入住系统，不参与任何世界时间计算。 */
  当前消息楼: number;
  /** 由脚本从当前聊天场景读取，不信任界面载荷；用于睡醒地点与早餐场景自洽。 */
  当前地点: 时间推进地点;
}

export interface 时间推进事务结果 {
  成功: boolean;
  提示: string;
  起始时间: 世界时间快照;
  结束时间: 世界时间快照;
  推进时段数: number;
  线路提示: string[];
  经济提示: string[];
  资源提示: string[];
}

