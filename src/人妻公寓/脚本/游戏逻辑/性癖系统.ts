import type { SchemaType } from '../../schema';
import type { 门牌 } from '../../stageConfig';
import { 户静态表, 查性癖 } from '../../stageConfig';
import { 当前时段 } from './楼层时钟';
import { 事件角色标记 } from './snapshotSystem';

/**
 * 性癖系统(P5;spec拍板槽位模型):
 * - 每妻 3 槽;装载对象须 ≥L4(个别深度项 L5);同款可装给不同人妻(各买各的)
 * - 装载贵(首装触发开幕正戏),卸载贱(点一下,免费即时无剧情),记忆不丢(曾开发永久档案)
 * - 重装免开幕正戏直接生效——她的身体记得,第一次是攻坚,以后是开关
 * - 快照只注入装载中的(数据隔离);感知语=演出语非标签(snapshotSystem 消费 性癖表.感知)
 */

export interface 性癖结果 {
  成功: boolean;
  提示: string;
  事件?: string;
  变动?: boolean;
}

export function 装载性癖(data: SchemaType, 道具id: string, 门牌号: 门牌): 性癖结果 {
  const 配 = 查性癖(道具id);
  const 节点 = data.户[门牌号];
  if (!配 || !节点) return { 成功: false, 提示: '装不上去。' };
  const i = data.背包.indexOf(道具id);
  if (i < 0) return { 成功: false, 提示: '背包里没有这一件。' };
  const 妻 = 节点.妻;
  const 妻名 = 户静态表[门牌号].妻名;
  if (配.限定户 && !配.限定户.includes(门牌号)) {
    return { 成功: false, 提示: `这一件……不是为${妻名}准备的。` };
  }
  const 母亲终局开幕窗口 =
    门牌号 === '302' &&
    道具id === 户静态表['302'].招牌性癖 &&
    妻.当前阶段 === 4 &&
    妻._阶段线路.目标阶段 === 5 &&
    妻._阶段线路.活跃节点 === 1;
  if (妻.当前阶段 < (配.档 === 5 ? 5 : 4) && !母亲终局开幕窗口) {
    return { 成功: false, 提示: `${妻名}还没到能接住它的时候(需要${配.档 === 5 ? '「归属」' : '「沉沦」'})。` };
  }
  if (妻.性癖装载.includes(道具id)) return { 成功: false, 提示: '她身上已经带着这一件了。' };
  if (妻.性癖装载.length >= 3) return { 成功: false, 提示: '她身上已经满了——先卸下一件。' };

  const 重装 = 妻.曾开发性癖.includes(道具id);
  if (!重装 && 配.开幕允许时段 && !配.开幕允许时段.includes(当前时段(data))) {
    return { 成功: false, 提示: `「${配.名称}」的第一次开幕只能在${配.开幕允许时段.join('或')}。` };
  }

  data.背包.splice(i, 1);
  妻.性癖装载.push(道具id);
  if (!重装) 妻.曾开发性癖.push(道具id);

  if (重装) {
    // 她的身体记得:免正戏直接生效
    return {
      成功: true,
      提示: `「${配.名称}」重新挂回了${妻名}身上——她的身体记得。`,
      事件: `${事件角色标记({ 在场妻: [门牌号] })}【重燃】{{user}}让${妻名}重新拾起了「${配.名称}」——不需要再教,她的身体一瞬间就想起来了;演出这份"想起来"的战栗(一个眼神/一次吞咽/膝盖发软),点到即止`,
      变动: true,
    };
  }
  return {
    成功: true,
    提示: `「${配.名称}」装载给了${妻名}——第一次开幕。`,
    事件: `${事件角色标记({ 在场妻: [门牌号] })}【性癖开幕·${配.名称}】对象:${妻名}。${配.开幕}。这场戏按她的性格与你们的关系走完整幕,堕落可小步上涨;完幕后这份性癖将常驻她身上`,
    变动: true,
  };
}

export function 卸载性癖(data: SchemaType, 门牌号: 门牌, 性癖id: string): 性癖结果 {
  const 节点 = data.户[门牌号];
  if (!节点) return { 成功: false, 提示: '没有这户。' };
  const i = 节点.妻.性癖装载.indexOf(性癖id);
  if (i < 0) return { 成功: false, 提示: '她身上没有这一件。' };
  节点.妻.性癖装载.splice(i, 1);
  // 卸载=管理动作:免费/即时/无剧情;档案卡"曾开发"永久保留。
  // 道具回背包(2026-07-26 审计 低危5,用户拍板"不该销毁"):文件头承诺"重装免开幕直接生效",
  // 旧版卸载只出槽不回包,"卸下→装回"每轮都要重买 900/1500,承诺形同虚设
  data.背包.push(性癖id);
  return {
    成功: true,
    提示: `「${查性癖(性癖id)?.名称 ?? 性癖id}」暂时卸下,收回了背包。她的身体不会忘。`,
    变动: true,
  };
}
