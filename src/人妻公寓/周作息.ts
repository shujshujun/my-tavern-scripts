/**
 * 公寓世界的固定周历与妻子基础作息。
 *
 * `_绝对时段` 是唯一输入：0 = 第 1 天（星期一）早上，之后每 +1 推进一个时段。
 * 本模块刻意不读取消息楼号，也不使用随机数；因此普通聊天不会推进日期，且同一星期、
 * 同一时段的位置每周稳定复现。特殊场景、赴约和连续对话的覆盖仍由调用方优先处理。
 */

export const 六时段列表 = ['早上', '中午', '下午', '傍晚', '晚上', '深夜'] as const;
export type 周作息时段 = (typeof 六时段列表)[number];

export const 星期列表 = ['星期一', '星期二', '星期三', '星期四', '星期五', '星期六', '星期日'] as const;
export type 星期名 = (typeof 星期列表)[number];

export const 作息门牌列表 = ['101', '102', '201', '202', '301', '302'] as const;
export type 作息门牌 = (typeof 作息门牌列表)[number];

export const 作息公共位置列表 = ['大堂', '信箱区', '天台', '垃圾房', '楼梯间', '外出'] as const;
export type 妻基础位置名 = 作息门牌 | (typeof 作息公共位置列表)[number];

export const 每日时段数 = 六时段列表.length;
export const 每周天数 = 星期列表.length;
export const 每周时段数 = 每日时段数 * 每周天数;

export interface 绝对时段信息 {
  绝对时段: number;
  天数: number;
  周数: number;
  星期: 星期名;
  星期序号: number;
  时段: 周作息时段;
  时段序号: number;
}

export function 规范绝对时段(值: number): number {
  return Number.isFinite(值) ? Math.max(0, Math.floor(值)) : 0;
}

/** 0-based 绝对时段 → 玩家可见周历。开局固定为第 1 周、星期一、早上。 */
export function 解析绝对时段(值: number): 绝对时段信息 {
  const 绝对时段 = 规范绝对时段(值);
  const 天序号 = Math.floor(绝对时段 / 每日时段数);
  const 时段序号 = 绝对时段 % 每日时段数;
  const 星期序号 = 天序号 % 每周天数;
  return {
    绝对时段,
    天数: 天序号 + 1,
    周数: Math.floor(天序号 / 每周天数) + 1,
    星期: 星期列表[星期序号],
    星期序号,
    时段: 六时段列表[时段序号],
    时段序号,
  };
}

/** “睡到次日早晨”应前进的时段数；即使当前就在早上，也会睡到下一天早上。 */
export function 到次日早晨间隔(值: number): number {
  return 每日时段数 - 解析绝对时段(值).时段序号;
}

export type 六时段位置表 = Readonly<Record<周作息时段, 妻基础位置名>>;
export type 星期位置覆盖 = Readonly<Partial<Record<星期名, Readonly<Partial<六时段位置表>>>>>;

export interface 妻周作息配置 {
  /** 大多数日子采用的六时段表。 */
  默认: 六时段位置表;
  /** 在默认表上按星期覆盖少量家务、办事和外出安排。 */
  星期覆盖: 星期位置覆盖;
}

function 宅家六时段(门牌: 作息门牌): 六时段位置表 {
  return {
    早上: 门牌,
    中午: 门牌,
    下午: 门牌,
    傍晚: 门牌,
    晚上: 门牌,
    深夜: 门牌,
  };
}

