/** 只负责基础日程；特殊场景、赴约、连续场景应在调用本函数前优先返回。 */
export function 妻基础位置(门牌: 作息门牌, 绝对时段: number): 妻基础位置名 {
  const 时间 = 解析绝对时段(绝对时段);
  const 作息: 妻周作息配置 = 妻周作息表[门牌];
  return 作息.星期覆盖[时间.星期]?.[时间.时段] ?? 作息.默认[时间.时段];
}
