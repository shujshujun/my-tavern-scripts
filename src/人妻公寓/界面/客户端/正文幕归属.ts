/**
 * 正文舞台的场景归属。
 *
 * 房间名只能说明上一幕在哪里发生，不能证明它在玩家走动后仍是“当前幕”；因此把
 * “归属房间”和“是否仍有效”分开保存。状态只属于客户端画面，不写入存档。
 */
export interface 正文幕归属 {
  房间: string | null;
  有效: boolean;
}

/** 回合完成默认沿用旧行为绑定当前房间；状态型回合可明确声明不更新正文幕。 */
export interface 回合完成正文选项 {
  更新正文幕?: boolean;
  /** 固定序章等本地演出不应立刻启动后台手机 AI，避免和玩家第一下引导操作争生成槽。 */
  跳过手机节拍?: boolean;
}

export function 创建正文幕归属(房间: string | null, 有效 = true): 正文幕归属 {
  return { 房间, 有效 };
}

/** 玩家一旦真实换场，旧幕永久失效；以后走回同名房间也不能靠字符串相等复活。 */
export function 作废正文幕归属(当前: 正文幕归属): 正文幕归属 {
  return 当前.有效 ? { ...当前, 有效: false } : 当前;
}

/**
 * 只有真正产生了新正文/独立演出的完成事件才认领当前房间。
 * 小憩、普通时间推进、撤销等只有状态结算的完成事件保持旧幕原状。
 */
export function 应用回合完成正文幕(当前: 正文幕归属, 当前房间: string | null, 选项?: 回合完成正文选项): 正文幕归属 {
  return 选项?.更新正文幕 === false ? 当前 : 创建正文幕归属(当前房间);
}

export function 正文幕属于当前房间(归属: 正文幕归属, 当前房间: string | null): boolean {
  return 归属.有效 && 归属.房间 === 当前房间;
}
