import type { SchemaType } from '../../../schema';
import type { 门牌 } from '../../../stageConfig';
import { 丈夫在楼 } from '../../../脚本/游戏逻辑/楼层时钟';
import { 读取丈夫线路风险阶段 } from '../../../脚本/游戏逻辑/丈夫线路风险策略';

export interface 配偶档案展示 {
  /** 长期居住安排不是作息中的“此刻外出”；空值时保留原作息展示。 */
  居住说明: string;
  旧风险已停用: boolean;
  风险说明: string;
}

/**
 * 只读展示投影：婚姻称谓仍由角色阶段体验负责，日程与风险门仍由原系统负责。
 * 不清疑心/信任，不写完成状态，也不以“旧随机查岗停用”代替专属/已排期事件规则。
 */
export function 读取配偶档案展示(data: SchemaType, 门牌号: 门牌, 绝对时段: number): 配偶档案展示 {
  const 户 = data.户[门牌号];
  let 居住说明 = '';
  switch (户?.夫._居住模式) {
    case '正式退居':
      居住说明 = `已正式退居，不再按日常作息返回${门牌号}。`;
      break;
    case '路线外住':
      居住说明 = '目前在外居住，回楼按线路安排，不按日常作息推断。';
      break;
    case '待离婚交接':
      居住说明 = '目前在外居住，等待离婚交接安排。';
      break;
    case '预约回楼':
      居住说明 = 丈夫在楼(户, 门牌号, 绝对时段) === '在家'
        ? '已按预约回楼。'
        : '目前在外居住，只在有效预约时段回楼。';
      break;
    case '提前通知':
      居住说明 = '回楼按提前通知约定，不按日常作息推断。';
      break;
  }
  const 风险阶段 = 读取丈夫线路风险阶段(data, 门牌号);
  const 旧风险已停用 = 风险阶段 !== '常规';
  const 风险说明 = 旧风险已停用
    ? `${风险阶段 === '承接保护' ? '承接剧情进行中，旧随机查岗暂停。' : '关系已变化，旧随机查岗已停用。'}疑心与信任读数继续保留；专属剧情和已排期事件仍按原流程处理。`
    : '';
  return { 居住说明, 旧风险已停用, 风险说明 };
}
