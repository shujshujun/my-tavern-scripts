/** 简单字符串哈希 → [0,1) 伪随机(确定性:同职位同楼号必得同结果) */
function 种子随机(键: string): number {
  let h = 2166136261;
  for (let i = 0; i < 键.length; i++) {
    h ^= 键.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return ((h >>> 0) % 10000) / 10000;
}

/**
 * 推算某修女当前所在(纯函数,楼号为种子;每回合楼号+2 → 位置轮换="她走动了")
 * 返回:房间id | '寝室:<职位>' | '巡逻'
 * - 纠察:巡逻(不定点,公共区游弋)
 * - 其余:60% 工作间 / 25% 自己寝室 / 15% 公共区
 * - 院长没有"工作间外"概念:60% 院长室 / 25% 礼拜堂 / 15% 寝室
 */
export function 推算位置(职位: 修女职位, 楼号: number): string {
  if (职位 === '巡查') return '巡逻'; // 登场前不在图上,登场后再细化
  const r = 种子随机(`${职位}#${楼号}`);
  if (职位 === '纠察') {
    return r < 0.5 ? '巡逻' : 公共房间ids[Math.floor(r * 100) % 公共房间ids.length];
  }
  if (职位 === '院长') {
    if (r < 0.6) return '院长室';
    if (r < 0.85) return '礼拜堂';
    return `寝室:院长`;
  }
  const 工作间 = 房间表.find(房 => 房.主人 === 职位)?.id ?? '庭院';
  if (r < 0.6) return 工作间;
  if (r < 0.85) return `寝室:${职位}`;
  return 公共房间ids[Math.floor(r * 100) % 公共房间ids.length];
}

/** 某房间当前在场的修女(含寝室;巡逻中的纠察不算进任何房间) */
export function 房内修女(房间id: string, 楼号: number, 可登场: readonly 修女职位[]): 修女职位[] {
  return 可登场.filter(职位 => 推算位置(职位, 楼号) === 房间id);
}

/**
 * 房间零钱(纯函数,与位置系统同一颗种子):约 30% 的房间掉落 2-6 奉献金——
 * 修女们遗落的什一税、蜡烛钱、私房钱。每过一回合(楼号+2)全院重掷;
 * 拾取记录存 chat 变量 _拾取(键=`种子:房间id`),同种子内不可重复捡。
 */
export function 房间奖励(房间id: string, 楼号: number): number {
  const r = 种子随机(`钱#${房间id}#${楼号}`);
  if (r >= 0.3) return 0;
  return 2 + Math.floor((r / 0.3) * 5); // 2-6
}
