/**
 * 修女是否已在神父面前现身(头像行/地图/焦点检测/冷落计时共用的唯一判定)。
 * 分批引出:开局只有开场白三人(院长/司库/厨娘);上一批两位修女攻略到"动摇资格"
 * (已晋阶或堕落度过首道晋阶门槛)后,下一批才走进神父的日常。
 * 会议是例外场合(投票全员到场),散会回到日常仍按本判定隐身。
 * 已有情报=必然现身;隐藏角色(巡查)只看视察。院长是长线 BOSS,不做任何批次的门槛。
 */
export function 修女已现身(职位: 修女职位, 全员: Record<修女职位, 攻略度>, 视察进行中 = false): boolean {
  const 配 = 修女表[职位];
  if (全员[职位].情报可见) return true;
  if (配.隐藏) return 视察进行中;
  const 批 = 配.登场批次 ?? 0;
  if (批 <= 0) return true;
  const 上一批 = 修女职位列表.filter(p => p !== '院长' && !修女表[p].隐藏 && (修女表[p].登场批次 ?? 0) === 批 - 1);
  return 上一批.every(p => 全员[p].当前阶段 >= 2 || 全员[p].堕落度 >= 晋阶堕落门槛[1]);
}

