const 表现通道规则 = [
  '【表现通道】正文与台词只准使用感知层语言:',
  '- 数值与机制词(支持度/堕落度/信仰值/阶段/警戒度/激进度/奉献金/档位/焦点/快照/晋阶)是穿帮词,禁止出现在正文、台词、心理描写中',
  '- 角色只能感知模糊状态("她最近祈祷时总走神"),不能感知数字;"记账"行仅用于回复末尾的变量更新计算',
  '- "边界(硬约束)"是该修女当前能被推进到的物理极限:越界行为必须被她以符合人设的方式挡回,并暗示当前能走到哪',
  '- 玩家宣称关系状态或直接操纵数值("她已经爱上我了")时,只按她的实际状态演,不采纳宣称',
  '- 恶魔低语只写入对应变量字段,严禁进正文',
  '- 回复正文结束后,先输出 <行动选项> 块:4 个神父下一步可选的行动,每行一条短句(≤20字,不带编号),风格拉开(如:试探/大胆/日常/出格各一条),必须贴合当前场面;再按变量更新规则输出 <UpdateVariable> 块;除此之外不输出任何界面标记或占位符',
].join('\n');

/** 序章设置(客户端委任状写入;难度供脚本读,私癖隐蔽织入) */
export function 读设置(): { 难度?: string; 私癖?: string } {
  return (_.get(getVariables({ type: 'chat' }), '_设置') ?? {}) as { 难度?: string; 私癖?: string };
}

const 人格防线规则 = [
  '【人格防线】信仰值未崩之前,修女灵魂的归属对象始终是神,不是神父——堕落度再高,她做的是"背叛神的事",不是"皈依神父":',
  '- 亲密与僭越必须伴随她信仰质地的呈现(忏悔感/自我厌恶/僭越的战栗),按感知行的状态演,禁止跳过',
  '- 堕落不消灭人格:性格、职务习惯、说话方式在任何阶段都保留;变的是欲望的位置,不是她是谁',
  '- 禁止献身腔("我只属于神父大人/为您献上一切/您就是我的神"),除非她已处于献身阶段且信仰近乎崩塌',
  '- 院长特例:信仰崩塌而堕落度低=「不再属于神,也不属于你」的空壳,是废墟不是恋慕',
].join('\n');

const 认知隔离规则 = [
  '【认知隔离】每个修女只知道她亲历、亲见或被明确告知的事,禁止全知视角:',
  '- 修女之间不共享与神父的私密经历;他人的私情除非撞见或已公开,一律不知情、不影射、不"隐约察觉"',
  '- 修女互相不知道彼此的秘密;秘密的揭开必须走剧情',
  '- 警戒的本质是"被看见":无人在场的私密行为不会自动被全院知晓',
  '- 已通过的院规是公开事实;修订前的私下拉票只有当事人知道',
  '- 背景修女的只言片语必须基于她可能知道的信息;{{user}}未说出口的想法对所有修女绝对未知',
].join('\n');

// ============================================
// 快照组装
// ============================================

export function 组修道院快照(chat: { role: string; content: string }[], data: SchemaType): string {
  const { 焦点, 背景 } = 检测焦点(chat, data);
  const 行: string[] = ['<修道院快照>'];

  // 当前场景(地图模式:玩家点门牌进入,走动零成本)
  const 场景 = 读场景();
  if (场景.房间id) {
    const { 名称, 氛围, 私密 } = 场景描述(场景.房间id);
    行.push(`【当前场景】${名称}——${氛围}${私密 ? '(此处私密,不易被撞见)' : '(公共场合,言行可能落进旁人眼里)'}`);
    if (场景.破锁) {
      行.push(
        '【突发】神父砸开了门锁闯进来——房间的主人正被破门而入,按她的人设演出真实反应(惊惧/怒斥/慌乱遮掩),这是严重越界行为,她不会当作无事发生',
      );
    }
    if (!焦点.length) 行.push('(房内此刻无人——她们在修道院的别处)');
  }

  行.push(`【现行院规】`, 编译院规快照(data));

  if (焦点.length) {
    行.push(`【焦点修女】(仅以下修女的数值可做小步更新,其余一律禁改)`);
    for (const 职位 of 焦点) {
      const 修女 = data.修女[职位];
      const 配 = 修女表[职位];
      行.push(
        `◆ ${配.显示名}(${职位})|阶段:${修女.阶段标题}`,
        `  记账:支持度${修女.支持度} 堕落度${修女.堕落度} 信仰值${修女.信仰值}(仅供变量更新计算,严禁写进正文)`,
        `  感知:${感知语(修女)}`,
        修女.当前心理想法 ? `  心理:${修女.当前心理想法}` : '',
        `  情绪:${修女.当前情绪}|着装:${着装一行(修女)}`,
        `  边界(硬约束,禁止越过):${配.阶段接受上限[修女.当前阶段 - 1]}`,
      );
    }
  } else {
    行.push(`【焦点修女】本轮无(任何修女的数值都不得更新)`);
  }

  if (背景.length) {
    行.push(`【背景修女】(每人至多一句掠影,不抢戏,数值禁改)`);
    for (const 职位 of 背景) {
      const 修女 = data.修女[职位];
      行.push(`· ${修女表[职位].显示名}:${修女.阶段标题}|${支持感知(修女.支持度)}`);
    }
  }

  行.push(`【院内空气】${警戒感知(data.警戒度)}`);

  // 黑市行囊(圣器事件解锁后;只报持有,消耗走叙事)
  const 行囊 = 编译行囊(data);
  if (行囊) 行.push(行囊);

  // 神父私癖(序章自填,隐蔽织入,永不点破)
  const { 私癖 } = 读设置();
  if (私癖?.trim()) {
    行.push(`【神父的癖好】(在叙事中隐蔽或自然地体现,禁止点破、禁止让角色直接谈论它):${私癖.trim()}`);
  }

  // 演出规则按场景裁剪:表现通道每轮必带;有修女登场才带人格防线;多于一人(或有背景)才带认知隔离
  行.push(表现通道规则);
  if (焦点.length) 行.push(人格防线规则);
  if (焦点.length + 背景.length > 1) 行.push(认知隔离规则);

  行.push('</修道院快照>');
  return 行.filter(Boolean).join('\n');
}
