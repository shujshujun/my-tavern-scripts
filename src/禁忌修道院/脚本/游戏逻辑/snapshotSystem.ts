const 焦点上限 = 2;

// ============================================
// 感知语编译(数值 → 模糊状态,查表零 AI 成本)
// ============================================

/** 罪恶感 = 堕落跑在信仰崩塌前面的差值 */
export function 罪恶感(修女: { 堕落度: number; 信仰值: number }): number {
  return Math.max(0, 修女.堕落度 - (100 - 修女.信仰值));
}

function 支持感知(支持度: number): string {
  if (支持度 >= 60) return '她已经站在你这边';
  if (支持度 >= 30) return '她愿意听你说话';
  if (支持度 >= 12) return '她开始对你另眼相看';
  return '她对你保持着分寸的距离';
}

function 罪恶感知(值: number): string {
  if (值 >= 30) return '她近来频繁出入忏悔室,祈祷时指节绞得发白';
  if (值 >= 15) return '她祈祷的时间变长了,却总是走神';
  if (值 > 0) return '偶尔,她会在祈祷中途睁开眼睛';
  return '';
}

/** 单个修女的感知语(表现通道,1-2 句) */
export function 感知语(修女: SchemaType['修女'][修女职位]): string {
  const 段 = [支持感知(修女.支持度), 阶段行为基调[修女.当前阶段 - 1]];
  const 罪 = 罪恶感知(罪恶感(修女));
  if (罪) 段.push(罪);
  return 段.join(';');
}

function 警戒感知(警戒度: number): string {
  if (警戒度 >= 75) return '院长的约谈只差一个由头,纠察的记档簿越来越厚';
  if (警戒度 >= 50) return '纠察的目光已经黏在神父身上';
  if (警戒度 >= 25) return '有人开始留意神父的行踪';
  return '院里风平浪静';
}

/** 着装一行编译(仅焦点注入) */
function 着装一行(修女: SchemaType['修女'][修女职位]): string {
  const 服 = 修女.服装;
  const 件 = [服.头纱, 服.上装, 服.下装, 服.袜足, 服.鞋, 服.配饰, 服.特殊装饰].filter(x => x && x !== '无');
  const 态 = [
    修女.暴露程度 !== '遮蔽' ? `暴露:${修女.暴露程度}` : '',
    修女.整洁度 !== '整洁' ? 修女.整洁度 : '',
  ].filter(Boolean);
  return [件.join('、'), ...态].join('|');
}

// ============================================
// 现行院规快照(AI 读现状不读 diff)
// ============================================

export function 编译院规快照(data: SchemaType): string {
  const 行: string[] = [];
  for (const 规则 of 院规表) {
    const 档号 = data.院规[规则.id] ?? 0;
    if (档号 <= 0) {
      行.push(`《${规则.名称}》:${规则.原规}`);
    } else {
      const 档 = 查档(规则.id, 档号)!;
      行.push(`《${规则.名称}》(已修订「${档.名称}」):${档.条文} —— ${档.全局效果}`);
    }
  }
  return 行.join('\n');
}

