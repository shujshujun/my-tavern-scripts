/** 玩家当前场景(客户端地图写入 chat 变量;走动零成本纯 UI,不产生楼层) */
export function 读场景(): { 房间id?: string; 破锁?: boolean; 进房末楼?: number } {
  return (_.get(getVariables({ type: 'chat' }), '_场景') ?? {}) as {
    房间id?: string;
    破锁?: boolean;
    进房末楼?: number;
  };
}

/** 场景显示名+氛围('寝室:职位' 特判) */
export function 场景描述(房间id: string): { 名称: string; 氛围: string; 私密: boolean } {
  if (房间id.startsWith('寝室:')) {
    const 职位 = 房间id.slice(3) as 修女职位;
    return {
      名称: `${修女表[职位]?.显示名 ?? 职位}的寝室`,
      氛围: '窄床、圣像、叠得一丝不苟的被褥——她全部的私人世界',
      私密: true,
    };
  }
  const 房 = 房间表.find(r => r.id === 房间id);
  return 房 ? { 名称: 房.名称, 氛围: 房.氛围, 私密: 房.私密 } : { 名称: 房间id, 氛围: '', 私密: false };
}

/**
 * 检测焦点:
 *   地图模式(有 _场景.房间id)→ 在场=位置系统决定,确定性焦点(prompt成本与阵容人数彻底脱钩)
 *   无场景(✠ 逃生舱原生玩法)→ 退回文本扫描
 */
export function 检测焦点(
  chat: { role: string; content: string }[],
  data: SchemaType,
): {
  焦点: 修女职位[];
  背景: 修女职位[];
} {
  const 可登场 = 修女职位列表.filter(职位 => 修女已现身(职位, data.修女, data.视察.状态 === '进行中'));

  const { 房间id, 进房末楼 } = 读场景();
  if (房间id) {
    // 位置种子冻结在进房那一刻:玩家在房内期间全院不重洗——否则楼号每回合+2,
    // 身边的修女下一轮就被"传送"走,AI 只能圆成"她起身要走"(必定离场事故)
    const 在房 = 房内修女(房间id, 进房末楼 ?? getLastMessageId(), 可登场);
    return { 焦点: 在房.slice(0, 3), 背景: [] };
  }

  const 尾部 = chat.slice(-4).reverse(); // 末条优先
  const 命中: 修女职位[] = [];
  for (const 楼 of 尾部) {
    for (const 职位 of 可登场) {
      if (命中.includes(职位)) continue;
      const { 显示名 } = 修女表[职位];
      if (楼.content.includes(显示名) || 楼.content.includes(职位)) 命中.push(职位);
    }
  }
  return { 焦点: 命中.slice(0, 焦点上限), 背景: 命中.slice(焦点上限) };
}

