import type { 修女职位 } from '../../schema';
import { 查档, 查规则, 修女表 } from '../../stageConfig';

/**
 * 双门槛算票引擎(纯函数,无副作用)
 *
 * 规则(见 设计spec.md 投票判定):
 *   支持门槛过 + 堕落门槛过 → 赞成
 *   支持门槛过 + 堕落门槛不过 → 弃权(喜欢你但说不出口);被把柄强制 → 弃权
 *   都不过 → 反对
 *   通过条件:赞成 > 反对(弃权不计);平票 → 院长裁决(按院长自己那票的立场)
 *
 * 同一套函数三处复用:会议结算 / 院规面板投票预测 / 院长抢案预判。
 */

export interface 票值 {
  支持度: number;
  堕落度: number;
}

/** 会议触发楼的全员票值快照(会议楼内数值变动不影响本次结果) */
export type 票值快照 = Record<修女职位, 票值>;

export type 投票立场 = '赞成' | '弃权' | '反对';

export interface 单票 {
  职位: 修女职位;
  显示名: string;
  投票: 投票立场;
  /** 差多少过支持门槛(≤0 即已过),预测面板"还差几点"用 */
  支持缺口: number;
  /** 差多少过堕落门槛(已含偏好修正) */
  堕落缺口: number;
  强制弃权: boolean;
}

export interface 投票结果 {
  规则id: string;
  规则名称: string;
  目标档: number;
  档名称: string;
  票: 单票[];
  赞成数: number;
  反对数: number;
  弃权数: number;
  平票: boolean;
  /** 平票时院长裁决的方向(非平票为 undefined) */
  院长裁决?: '通过' | '否决';
  通过: boolean;
}

/** 修女对某规则的堕落门槛修正:具体规则 id 优先,其次权重类别,都无则 0(负=更容易接受) */
export function 偏好修正(职位: 修女职位, 规则id: string): number {
  const 修正表 = 修女表[职位].偏好修正;
  if (规则id in 修正表) return 修正表[规则id];
  const 权重 = 查规则(规则id)?.权重;
  if (权重 && 权重 in 修正表) return 修正表[权重];
  return 0;
}

/** 单个修女对某议案的判定 */
export function 计算单票(
  职位: 修女职位,
  票值: 票值,
  规则id: string,
  目标档: number,
  强制弃权 = false,
): 单票 {
  const 档 = 查档(规则id, 目标档);
  if (!档) throw new Error(`[voteEngine] 未知议案:${规则id} 档${目标档}`);

  const 支持缺口 = 档.支持门槛 - 票值.支持度;
  const 堕落缺口 = 档.堕落门槛 + 偏好修正(职位, 规则id) - 票值.堕落度;

  let 投票: 投票立场;
  if (强制弃权) {
    投票 = '弃权'; // 把柄:她不投你,但她闭嘴
  } else if (支持缺口 <= 0 && 堕落缺口 <= 0) {
    投票 = '赞成';
  } else if (支持缺口 <= 0) {
    投票 = '弃权'; // 喜欢你但说不出口
  } else {
    投票 = '反对';
  }

  return { 职位, 显示名: 修女表[职位].显示名, 投票, 支持缺口, 堕落缺口, 强制弃权 };
}

/**
 * 全员算票 + 结果判定
 * @param 投票人 在院有投票权者(常态 7 人;巡查登场后视设计决定是否入席)
 * @param 强制弃权者 被把柄压住的席位
 */
export function 计算投票(
  快照: 票值快照,
  投票人: 修女职位[],
  规则id: string,
  目标档: number,
  强制弃权者: ReadonlySet<修女职位> = new Set(),
): 投票结果 {
  const 规则 = 查规则(规则id);
  const 档 = 查档(规则id, 目标档);
  if (!规则 || !档) throw new Error(`[voteEngine] 未知议案:${规则id} 档${目标档}`);

  const 票 = 投票人.map(职位 => 计算单票(职位, 快照[职位], 规则id, 目标档, 强制弃权者.has(职位)));

  const 赞成数 = 票.filter(t => t.投票 === '赞成').length;
  const 反对数 = 票.filter(t => t.投票 === '反对').length;
  const 弃权数 = 票.filter(t => t.投票 === '弃权').length;

  const 平票 = 赞成数 === 反对数;
  let 院长裁决: '通过' | '否决' | undefined;
  let 通过: boolean;
  if (!平票) {
    通过 = 赞成数 > 反对数;
  } else {
    // 平票院长裁决:按她自己那票的立场(她赞成才放行;她不在投票人列表时视为否决)
    const 院长票 = 票.find(t => t.职位 === '院长');
    院长裁决 = 院长票?.投票 === '赞成' ? '通过' : '否决';
    通过 = 院长裁决 === '通过';
  }

  return {
    规则id,
    规则名称: 规则.名称,
    目标档,
    档名称: 档.名称,
    票,
    赞成数,
    反对数,
    弃权数,
    平票,
    院长裁决,
    通过,
  };
}

/** 常态投票席(巡查未入席) */
export const 常规投票人: 修女职位[] = ['院长', '纠察', '司库', '医务', '图书', '厨娘', '见习'];
