/** 院长抢案:回退激进度最高的已篡改规则一档;无可回退则为训诫案 */
function 执行紧缩(): string {
  const { raw, data } = 读取();
  const 已篡改 = Object.entries(data.院规).filter(([, 档]) => 档 > 0);
  if (已篡改.length === 0) {
    return '重申《圣维罗妮卡院规》诸条,全院禁足静修三日,诵读会规。(无规则变动)';
  }
  const [规则id, 当前档] = _.maxBy(已篡改, ([id, 档]) => 查档(id, 档)?.激进度 ?? 0)!;
  const 档定义 = 查档(规则id, 当前档)!;
  const 规则 = 查规则(规则id)!;
  data.院规[规则id] = 当前档 - 1;
  data.激进度 = Math.max(0, data.激进度 - 档定义.激进度);
  脚本写入(raw, data);
  const 回到 = 当前档 - 1 > 0 ? `退回「${查档(规则id, 当前档 - 1)!.名称}」` : '恢复原规';
  return `废止《${规则.名称}》的「${档定义.名称}」修订,${回到},即刻生效。`;
}

/** 玩家在会议场景选定议程后由 UI eventEmit 调用 */
export async function 开始投票(规则id: string) {
  try {
    const 会议 = 读会议变量();
    const { raw, data } = 读取();
    if (data.会议.状态 !== '会议中' || !会议.票值快照 || 会议.结果) {
      console.warn('[禁忌修道院] 开始投票被忽略:不在可投票状态');
      return;
    }
    const 目标档 = (data.院规[规则id] ?? 0) + 1;
    if (!查档(规则id, 目标档)) {
      console.warn(`[禁忌修道院] 议案无效:${规则id} 档${目标档}`);
      return;
    }

    // 把柄强制弃权:玛利亚把柄在手且未倒戈 → 她不投你,但她闭嘴(倒戈后正常投票)
    const 强制弃权者 = new Set<修女职位>();
    const 纠察进度 = data.修女.纠察.专线进度;
    if (纠察进度['把柄'] && !纠察进度['倒戈']) 强制弃权者.add('纠察');
    const 票面 = 计算投票(会议.票值快照, 常规投票人, 规则id, 目标档, 强制弃权者);

    let 结果: 会议结果;
    if (票面.反对数 > 票面.赞成数) {
      // 票面明显不够 → 院长抢案(玩家原案不进入表决)
      const 紧缩动作 = 执行紧缩();
      结果 = {
        类型: '院长抢案',
        议程规则id: 规则id,
        议程档: 目标档,
        玩家原案: 票面,
        通过: false,
        紧缩动作,
        数据卡: '',
      };
    } else {
      结果 = {
        类型: '玩家议案',
        议程规则id: 规则id,
        议程档: 目标档,
        票面,
        通过: 票面.通过,
        数据卡: '',
      };
      if (票面.通过) {
        const 档 = 查档(规则id, 目标档)!;
        data.院规[规则id] = 目标档;
        data.激进度 += 档.激进度;
        脚本写入(raw, data);
      }
    }
    结果.数据卡 = 组数据卡(结果);
    写会议变量({ ...会议, 结果 });
    eventEmit('禁忌修道院:投票结果', 结果);

    // 自动推进一楼:AI 拿数据卡演会议现场
    await triggerSlash('/trigger');
  } catch (e) {
    console.error('[禁忌修道院] 开始投票失败:', e);
  }
}

/** 「离开会议厅」:回日常,倒计时重掷,通过案排队新规首夜 */
export function 离开会议厅() {
  try {
    const 会议 = 读会议变量();
    const { raw, data } = 读取();
    const 间隔 = 会议间隔();
    data.会议.状态 = '日常';
    data.会议.倒计时 = _.random(间隔[0], 间隔[1]);
    data.会议.已开届数 += 1;
    脚本写入(raw, data);

    if (会议.结果?.通过) {
      // 新规首夜:通过当晚自动触发(注入见 index.ts;遵守"event 绝不给示例")
      insertOrAssignVariables({ _首夜: { 规则id: 会议.结果.议程规则id, 档: 会议.结果.议程档 } }, { type: 'chat' });
    }
    写会议变量(undefined);
    console.info('[禁忌修道院] 离开会议厅,倒计时重置为', data.会议.倒计时);
  } catch (e) {
    console.error('[禁忌修道院] 离开会议厅失败:', e);
  }
}

