function 票面文本(票面: 投票结果): string {
  return 票面.票
    .map(t => `- ${t.显示名}(${修女表[t.职位].定位.split('/')[0]}):${t.强制弃权 ? '弃权(欲言又止)' : t.投票}`)
    .join('\n');
}

function 组数据卡(结果: 会议结果): string {
  const 规则 = 查规则(结果.议程规则id)!;
  const 行 = [`<会议结果数据卡>`];
  if (结果.类型 === '玩家议案' && 结果.票面) {
    const 档 = 查档(结果.议程规则id, 结果.议程档)!;
    行.push(
      `议程:《${规则.名称}》修订案「${档.名称}」(提案人:神父)`,
      `新条文:${档.条文}`,
      `投票实录(铁票,严禁改动,只演不改):`,
      票面文本(结果.票面),
      `结果:${结果.通过 ? '通过' : '否决'}(赞成${结果.票面.赞成数}/反对${结果.票面.反对数}/弃权${结果.票面.弃权数}${结果.票面.平票 ? ',平票由院长裁决' : ''})`,
    );
    if (结果.通过) 行.push(`新规即时生效,全院从此:${档.全局效果}`);
  } else {
    行.push(
      `议程:神父的《${规则.名称}》修订案未及宣读——院长特蕾莎行使主持权,换上她的紧缩案并当场裁可。`,
      `紧缩案:${结果.紧缩动作}`,
      `神父原案票面预判(供演出参考,不宣之于口):赞成${结果.玩家原案?.赞成数}/反对${结果.玩家原案?.反对数}/弃权${结果.玩家原案?.弃权数}`,
    );
  }
  行.push(
    `演出要求:用本楼完整演出这场修女会议——开场宣读、逐人表态时的神态与小动作(与上方票记严格一致:赞成者如何抬手、反对者何种神色、弃权者怎样垂目)、院长的反应、散会时的暗流。禁止改动任何一票,禁止出现数字与机制词。`,
    `</会议结果数据卡>`,
  );
  return 行.join('\n');
}

