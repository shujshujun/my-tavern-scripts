/** 会议结果待演:数据卡随生成注入(不清除,swipe 重 roll 也能重演;离开会议厅时清) */
export function 取待注入数据卡(): string | undefined {
  const 会议 = 读会议变量();
  if (会议.结果) return 会议.结果.数据卡;
  return undefined;
}

/** 新规首夜指令(零示例:只给要求不给模板,防固定化) */
export function 取首夜指令(): string | undefined {
  const 首夜 = _.get(getVariables({ type: 'chat' }), '_首夜') as { 规则id: string; 档: number } | undefined;
  if (!首夜) return undefined;
  const 规则 = 查规则(首夜.规则id);
  const 档 = 查档(首夜.规则id, 首夜.档);
  if (!规则 || !档) return undefined;
  return [
    `<新规首夜>`,
    `今晚是《${规则.名称}》「${档.名称}」生效后的第一夜。本楼直接演这条新规的首次执行:让全局改变落到具体的人和具体的画面上(${档.全局效果}),谁最先试探新边界、谁在旁观、谁口是心非,由当前各修女的处境自然决定。要求即时可感的奖励感——玩家立刻看到修道院真的变了。`,
    `</新规首夜>`,
  ].join('\n');
}

/** 首夜已演,清除标记(MESSAGE_RECEIVED 后由 index.ts 调用) */
export function 清首夜标记() {
  if (_.get(getVariables({ type: 'chat' }), '_首夜')) {
    insertOrAssignVariables({ _首夜: null }, { type: 'chat' });
  }
}
