/**
 * 会议系统:会议=结算画面,不是RP戏
 *
 * 流程(见 设计spec.md 会议流程):
 *   倒计时归零(index.ts)→ 状态=会议中 + 票值快照定格(chat 变量 _会议)
 *   → 客户端会议场景,玩家选议程 → eventEmit('禁忌修道院:开始投票')
 *   → 本模块结算(票面明显不够 → 院长抢案换紧缩案)→ 写 stat_data + 结果存 chat 变量
 *   → triggerSlash('/trigger') 自动推一楼,AI 拿数据卡演会议现场(只演不改票)
 *   → 「离开会议厅」→ 状态=日常,倒计时重掷,通过案排队"新规首夜"
 */

/** 会议间隔楼数(按序章选定的难度档;未配置回落到标准档) */
export function 会议间隔(): [number, number] {
  const { 难度 } = 读设置();
  return (难度 && 难度预设表[难度]?.会议间隔) || 难度预设表.忏悔者.会议间隔;
}

export interface 会议结果 {
  类型: '玩家议案' | '院长抢案';
  议程规则id: string;
  议程档: number;
  /** 抢案时:被预判否决的玩家原案票面(UI 展示"为什么被抢") */
  玩家原案?: 投票结果;
  /** 正式结算票面(抢案=紧缩案,无需投票,票面为空) */
  票面?: 投票结果;
  通过: boolean;
  /** 抢案的紧缩动作描述 */
  紧缩动作?: string;
  数据卡: string;
}

interface 会议变量 {
  票值快照?: 票值快照;
  触发楼层?: number;
  结果?: 会议结果;
}

function 读会议变量(): 会议变量 {
  return (_.get(getVariables({ type: 'chat' }), '_会议') ?? {}) as 会议变量;
}

function 写会议变量(v: 会议变量 | undefined) {
  insertOrAssignVariables({ _会议: v ?? null }, { type: 'chat' });
}

